using System.Collections.Generic;
using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate.Consoles.Statistics;

[GenerateTypedNameReferences]
public sealed partial class SWStatisticsConsoleMenu : FancyWindow
{
    private readonly (string Title, Control Panel)[] _tabs;
    private readonly Button[] _tabButtons;

    public SWStatisticsConsoleMenu()
    {
        RobustXamlLoader.Load(this);

        SWConsoleStyle.StyleRoot(RootPanel);
        SWConsoleStyle.StyleHeader(HeaderPanel);
        SWConsoleStyle.StyleTabBar(TabBarPanel);

        HeaderTitle.FontOverride = SWConsoleStyle.MonoBold;
        HeaderTitle.FontColorOverride = SWConsoleStyle.Accent;
        HeaderTitle.Text = "СТАТИСТИКА РЕСПУБЛИКИ";
        LiveDot.PanelOverride = new StyleBoxFlat { BackgroundColor = SWConsoleStyle.Good };
        HeaderClock.FontOverride = SWConsoleStyle.Mono;
        HeaderClock.FontColorOverride = SWConsoleStyle.TextBright;

        _tabs = new (string, Control)[]
        {
            ("РЕСПУБЛИКА", RepublicPanel),
            ("СЕКТОРА", SectorsPanel),
            ("КРИЗИСЫ", CrisesPanel),
            ("ЗАКОНЫ", LawsPanel),
        };

        _tabButtons = new Button[_tabs.Length];
        for (var i = 0; i < _tabs.Length; i++)
        {
            var idx = i;
            var btn = SWConsoleStyle.TabButton(_tabs[i].Title);
            btn.OnPressed += _ => ShowTab(idx);
            TabBar.AddChild(btn);
            _tabButtons[i] = btn;
        }

        ShowTab(0);
    }

    private void ShowTab(int index)
    {
        for (var i = 0; i < _tabs.Length; i++)
        {
            _tabs[i].Panel.Visible = i == index;
            SWConsoleStyle.StyleTabButton(_tabButtons[i], i == index);
        }
    }

    public void SetState(SWStatisticsConsoleState state)
    {
        HeaderClock.Text = string.IsNullOrEmpty(state.GameTime) ? "—" : state.GameTime;

        BuildRepublic(state);
        BuildSectors(state);
        BuildCrises(state);
        BuildLaws(state);
    }

    private void BuildRepublic(SWStatisticsConsoleState state)
    {
        RepublicStats.RemoveAllChildren();
        RepublicStats.AddChild(SWConsoleStyle.Section("ПОКАЗАТЕЛИ РЕСПУБЛИКИ"));
        RepublicStats.AddChild(new Control { MinHeight = 6 });

        foreach (var global in state.Globals)
            RepublicStats.AddChild(MakeGlobalBlock(global));
    }

    private Control MakeGlobalBlock(SWGlobalStatEntry global)
    {
        var panel = SWConsoleStyle.Row(SWConsoleStyle.BgPanel);
        panel.Margin = new Thickness(0, 0, 0, 6);

        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };

        var head = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        head.AddChild(SWConsoleStyle.Text(global.Name, global.Color, SWConsoleStyle.MonoBold));
        head.AddChild(new Control { HorizontalExpand = true });
        head.AddChild(SWConsoleStyle.Text($"ФАКТ {global.Actual:0}", SWConsoleStyle.ValueColor(global.Actual), SWConsoleStyle.Mono, 84, Control.HAlignment.Right));
        head.AddChild(SWConsoleStyle.Text($"ПОЛ. {global.Policy:0}", SWConsoleStyle.TextDim, SWConsoleStyle.Mono, 84, Control.HAlignment.Right));
        box.AddChild(head);

        box.AddChild(SWConsoleStyle.Bar(global.Actual, global.Min, global.Max, global.Color));

        var subs = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 0) };
        foreach (var sub in global.Subs)
        {
            var s = SWConsoleStyle.Text($"{sub.ShortName} {sub.Value:0}", SWConsoleStyle.ValueColor(sub.Value), SWConsoleStyle.MonoSmall);
            s.Margin = new Thickness(0, 0, 12, 0);
            subs.AddChild(s);
        }
        box.AddChild(subs);

        panel.AddChild(box);
        return panel;
    }

    private void BuildSectors(SWStatisticsConsoleState state)
    {
        SectorTable.RemoveAllChildren();
        SectorTable.AddChild(SWConsoleStyle.Section("СЕКТОРА"));
        SectorTable.AddChild(new Control { MinHeight = 6 });

        var grid = new GridContainer
        {
            Columns = 1 + state.Globals.Count,
            HSeparationOverride = 20,
            VSeparationOverride = 6,
        };

        grid.AddChild(SWConsoleStyle.Text("СЕКТОР", SWConsoleStyle.TextDim, SWConsoleStyle.MonoBold));
        foreach (var global in state.Globals)
            grid.AddChild(SWConsoleStyle.Text(global.ShortName, global.Color, SWConsoleStyle.MonoBold, 0, Control.HAlignment.Center));

        foreach (var sector in state.Sectors)
        {
            var nameColor = sector.Claimed ? sector.Color : SWConsoleStyle.TextDim;
            grid.AddChild(SWConsoleStyle.Text(sector.Name, nameColor, SWConsoleStyle.MonoBold));

            foreach (var stat in sector.Stats)
                grid.AddChild(SWConsoleStyle.Text($"{stat.Value:0}", SWConsoleStyle.ValueColor(stat.Value), SWConsoleStyle.Mono, 0, Control.HAlignment.Center));
        }

        var wrap = SWConsoleStyle.Row(SWConsoleStyle.BgPanel);
        wrap.AddChild(grid);
        SectorTable.AddChild(wrap);
    }

    private void BuildCrises(SWStatisticsConsoleState state)
    {
        CrisesList.RemoveAllChildren();
        CrisesList.AddChild(SWConsoleStyle.Section("АКТИВНЫЕ КРИЗИСЫ"));
        CrisesList.AddChild(new Control { MinHeight = 6 });

        if (state.Crises.Count == 0)
        {
            CrisesList.AddChild(SWConsoleStyle.Text("Активных кризисов нет.", SWConsoleStyle.TextDim, SWConsoleStyle.Mono));
            return;
        }

        foreach (var crisis in state.Crises)
        {
            var sev = SWConsoleStyle.SeverityColor(crisis.Severity);
            var panel = SWConsoleStyle.Row(SWConsoleStyle.BgPanel, sev);
            panel.Margin = new Thickness(0, 0, 0, 6);

            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };

            var head = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            head.AddChild(SWConsoleStyle.Text(crisis.Name, SWConsoleStyle.TextBright, SWConsoleStyle.MonoBold));
            head.AddChild(new Control { HorizontalExpand = true });
            head.AddChild(SWConsoleStyle.Pill(crisis.TypeLabel, SWConsoleStyle.Accent, SWConsoleStyle.PillDim));
            var sevLabel = SWConsoleStyle.Text($"{crisis.Severity:0}/100", sev, SWConsoleStyle.MonoBold);
            sevLabel.Margin = new Thickness(8, 0, 0, 0);
            sevLabel.VerticalAlignment = Control.VAlignment.Center;
            head.AddChild(sevLabel);
            box.AddChild(head);

            box.AddChild(SWConsoleStyle.Bar(crisis.Severity, 0, 100, sev));

            if (!string.IsNullOrWhiteSpace(crisis.AffectedLabel))
                box.AddChild(SWConsoleStyle.Text($"Очаг: {crisis.AffectedLabel}", SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));

            if (crisis.Impact.Count > 0)
                box.AddChild(EffectsRow(crisis.Impact));

            panel.AddChild(box);
            CrisesList.AddChild(panel);
        }
    }

    private void BuildLaws(SWStatisticsConsoleState state)
    {
        LawsList.RemoveAllChildren();
        LawsList.AddChild(SWConsoleStyle.Section("ДЕЙСТВУЮЩИЕ ЗАКОНЫ"));
        LawsList.AddChild(new Control { MinHeight = 6 });

        if (state.ActiveLaws.Count == 0)
        {
            LawsList.AddChild(SWConsoleStyle.Text("Действующих законов пока нет.", SWConsoleStyle.TextDim, SWConsoleStyle.Mono));
            return;
        }

        foreach (var law in state.ActiveLaws)
        {
            var panel = SWConsoleStyle.Row(SWConsoleStyle.BgPanel, SWConsoleStyle.Accent);
            panel.Margin = new Thickness(0, 0, 0, 6);

            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            box.AddChild(SWConsoleStyle.Text($"#{law.Id}  {law.Name}", SWConsoleStyle.TextBright, SWConsoleStyle.MonoBold));
            box.AddChild(SWConsoleStyle.Text($"автор: {law.Author}", SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));

            if (law.Effects.Count > 0)
                box.AddChild(EffectsRow(law.Effects));

            panel.AddChild(box);
            LawsList.AddChild(panel);
        }
    }

    private static Control EffectsRow(List<SWBillEffectEntry> effects)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 3, 0, 0) };
        foreach (var effect in effects)
        {
            var e = SWConsoleStyle.Text($"{effect.StatName} {effect.Delta:+0;-0}", effect.Color, SWConsoleStyle.MonoSmall);
            e.Margin = new Thickness(0, 0, 12, 0);
            row.AddChild(e);
        }
        return row;
    }
}
