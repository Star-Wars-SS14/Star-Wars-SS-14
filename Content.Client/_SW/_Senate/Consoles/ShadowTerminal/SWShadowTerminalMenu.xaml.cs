using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW._Senate.Consoles.ShadowTerminal;

[GenerateTypedNameReferences]
public sealed partial class SWShadowTerminalMenu : FancyWindow
{
    private readonly SWShadowTerminalBoundUserInterface _owner;
    private SWShadowTerminalState? _state;

    public SWShadowTerminalMenu(SWShadowTerminalBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        TitleClass = "LabelKeyText";
        _owner = owner;

        SWConsoleStyle.StyleRoot(RootPanel);
        SWConsoleStyle.StyleHeader(HeaderPanel);
        HeaderNetwork.FontOverride = SWConsoleStyle.Small;
        HeaderNetwork.FontColorOverride = SWConsoleStyle.Brass;
        HeaderTitle.FontOverride = SWConsoleStyle.Header;
        HeaderTitle.FontColorOverride = SWConsoleStyle.Bad;
        HeaderTitle.Text = "Теневой канал связи";
        BalanceLabel.FontOverride = SWConsoleStyle.Body;
        BalanceLabel.FontColorOverride = SWConsoleStyle.TextBright;
        StatusLabel.FontOverride = SWConsoleStyle.Body;
        NoticeLabel.FontOverride = SWConsoleStyle.Small;
        TargetCaption.FontOverride = SWConsoleStyle.Small;
        TargetCaption.FontColorOverride = SWConsoleStyle.TextDim;
        TargetCaption.Text = "Цель контракта (для защиты персоны, похищения, ликвидации):";

        TargetSelect.OnItemSelected += args =>
        {
            TargetSelect.SelectId(args.Id);
            RebuildContracts();
        };
    }

    public void SetState(SWShadowTerminalState state)
    {
        _state = state;

        BalanceLabel.Text = $"Оператор: {state.UserName}, личный счёт: {state.Balance} кр.";
        StatusLabel.Text = state.ContractActive ? state.ContractLabel : "Канал свободен. Синдикат ждёт предложений.";
        StatusLabel.FontColorOverride = state.ContractActive ? SWConsoleStyle.Warn : SWConsoleStyle.TextDim;

        NoticeLabel.Visible = state.Notice.Length > 0;
        NoticeLabel.Text = state.Notice;
        NoticeLabel.FontColorOverride = state.Notice.StartsWith("Контракт принят") ? SWConsoleStyle.Good : SWConsoleStyle.Bad;

        var previous = SelectedTarget();
        TargetSelect.Clear();
        for (var i = 0; i < state.Targets.Count; i++)
        {
            TargetSelect.AddItem(state.Targets[i], i);
            if (state.Targets[i] == previous)
                TargetSelect.SelectId(i);
        }

        RebuildContracts();
    }

    private string SelectedTarget()
    {
        if (_state == null || TargetSelect.ItemCount == 0)
            return string.Empty;

        var id = TargetSelect.SelectedId;
        return id >= 0 && id < _state.Targets.Count ? _state.Targets[id] : string.Empty;
    }

    private void RebuildContracts()
    {
        ContractsBox.RemoveAllChildren();
        if (_state == null)
            return;

        ContractsBox.AddChild(MakeRow("Собственная защита",
            "Наёмник следит, чтобы вы дожили до конца раунда.",
            _state.PriceProtectSelf, SWMercContractKind.ProtectSelf, false));
        ContractsBox.AddChild(MakeRow("Защита персоны",
            "Наёмник охраняет выбранную цель до конца раунда.",
            _state.PriceProtectOther, SWMercContractKind.ProtectOther, true));
        ContractsBox.AddChild(MakeRow("Похищение",
            "Цель будет доставлена на челнок синдиката живой.",
            _state.PriceKidnap, SWMercContractKind.Kidnap, true));
        ContractsBox.AddChild(MakeRow("Ликвидация",
            "Цель будет устранена, тело вывезено с планеты.",
            _state.PriceKill, SWMercContractKind.Kill, true));
    }

    private Control MakeRow(string title, string desc, int price, SWMercContractKind kind, bool needsTarget)
    {
        var row = SWConsoleStyle.Row(SWConsoleStyle.BgPanel, SWConsoleStyle.Bad);
        row.Margin = new Thickness(0, 0, 0, 5);

        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };

        var info = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        info.AddChild(SWConsoleStyle.Text(title, SWConsoleStyle.TextBright, SWConsoleStyle.Strong));
        info.AddChild(SWConsoleStyle.Text(desc, SWConsoleStyle.TextDim, SWConsoleStyle.Small));
        box.AddChild(info);

        var priceLabel = SWConsoleStyle.Text($"{price} кр.", SWConsoleStyle.Warn, SWConsoleStyle.Strong);
        priceLabel.VerticalAlignment = Control.VAlignment.Center;
        priceLabel.Margin = new Thickness(0, 0, 10, 0);
        box.AddChild(priceLabel);

        var btn = SWConsoleStyle.Action("Нанять", SWConsoleStyle.Bad);
        btn.VerticalAlignment = Control.VAlignment.Center;
        btn.Disabled = _state == null
            || _state.ContractActive
            || _state.Balance < price
            || (needsTarget && SelectedTarget().Length == 0);
        btn.OnPressed += _ => _owner.Hire(kind, needsTarget ? SelectedTarget() : string.Empty);
        box.AddChild(btn);

        row.AddChild(box);
        return row;
    }
}
