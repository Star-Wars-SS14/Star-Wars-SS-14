    private void BuildBudgetSection(SWSenateWorkConsoleState state)
    {
        BudgetSectionSummary.SetMessage(
            $"Бюджет дня: {state.BudgetTotal} кр.    Резерв: {state.BudgetReserve} кр.    " +
            (state.BudgetLocked ? "[зафиксирован]" : "[не зафиксирован]"));

        // Rebuild the input fields only when the sector set or lock state changes, so the periodic
        // refresh never wipes what the Chancellor is typing.
        var signature = (state.BudgetLocked ? "L:" : "U:");
        foreach (var sector in state.BudgetSectors)
            signature += sector.SectorId + ",";

        if (signature == _budgetSignature)
            return;

        _budgetSignature = signature;
        _budgetEdits.Clear();
        BudgetAllocPanel.RemoveAllChildren();

        if (state.BudgetLocked)
        {
            BudgetAllocPanel.AddChild(new Label { Text = "Распределение (зафиксировано):", StyleClasses = { "LabelKeyText" } });
            foreach (var sector in state.BudgetSectors)
                BudgetAllocPanel.AddChild(new Label { Text = $"{sector.Name}: {sector.Amount} кр.", FontColorOverride = sector.Color });
            return;
        }

        BudgetAllocPanel.AddChild(new Label { Text = "Распределение по секторам:", StyleClasses = { "LabelKeyText" } });
        foreach (var sector in state.BudgetSectors)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 1, 0, 1) };
            row.AddChild(new Label { Text = sector.Name, FontColorOverride = sector.Color, MinWidth = 180 });

            var edit = new LineEdit { Text = sector.Amount.ToString(), MinWidth = 100 };
            _budgetEdits[sector.SectorId] = edit;

            var id = sector.SectorId;
            var setButton = new Button { Text = "Задать", Margin = new Thickness(6, 0, 0, 0) };
            setButton.OnPressed += _ =>
            {
                if (int.TryParse(edit.Text, out var amount))
                    _owner.SetBudget(id, amount);
            };

            row.AddChild(edit);
            row.AddChild(setButton);
            BudgetAllocPanel.AddChild(row);
        }

        var lockButton = new Button { Text = "Зафиксировать бюджет", Margin = new Thickness(0, 6, 0, 0) };
        lockButton.OnPressed += _ =>
        {
            foreach (var (sectorId, edit) in _budgetEdits)
            {
                if (int.TryParse(edit.Text, out var amount))
                    _owner.SetBudget(sectorId, amount);
            }

            _owner.LockBudget();
        };
        BudgetAllocPanel.AddChild(lockButton);
    }

    private Control MakeDilemmaCard(SWDilemmaEntry dilemma)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(0, 2, 0, 10),
        };

        var head = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        head.AddChild(MakeTitle(dilemma.Name));
        head.AddChild(new Label { Text = dilemma.TimeLabel, FontColorOverride = Color.Goldenrod, Margin = new Thickness(6, 0, 0, 0) });
        box.AddChild(head);

        if (!string.IsNullOrWhiteSpace(dilemma.Description))
            box.AddChild(MakeWrap(dilemma.Description));

        for (var i = 0; i < dilemma.Options.Count; i++)
        {
            var option = dilemma.Options[i];
            var optionBox = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 1, 0, 4) };

            var optionRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            var index = i;
            var id = dilemma.Id;
            var label = option.Cost > 0 ? $"{option.Label} — {option.Cost} кр." : option.Label;
            if (dilemma.ChosenOption == i)
                label += " (выбрано)";
            var button = new Button
            {
                Text = label,
                Disabled = !dilemma.CanResolve || !option.Affordable,
                HorizontalExpand = true,
                HorizontalAlignment = Control.HAlignment.Left,
            };
            button.OnPressed += _ => _owner.ResolveDilemma(id, index);
            optionRow.AddChild(button);
            optionBox.AddChild(optionRow);

            var effects = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(8, 0, 0, 0) };
            foreach (var effect in option.Effects)
            {
                effects.AddChild(new Label
                {
                    Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                    FontColorOverride = effect.Color,
                    Margin = new Thickness(0, 0, 10, 0),
                });
            }
            optionBox.AddChild(effects);

            box.AddChild(optionBox);
        }

        if (dilemma.ChosenOption < 0 && (dilemma.FailEffects.Count > 0 || !string.IsNullOrWhiteSpace(dilemma.FailText)))
        {
            box.AddChild(MakeWrap("Срочно! При отсутствии решения наступит провал:", Color.IndianRed));
            if (!string.IsNullOrWhiteSpace(dilemma.FailText))
                box.AddChild(MakeWrap(dilemma.FailText, Color.IndianRed));
            if (dilemma.FailEffects.Count > 0)
                box.AddChild(MakeEffectsRow(dilemma.FailEffects));
        }

        return box;
    }

    // Wrapping helpers: plain Labels never word-wrap, so long sentences run off the edge and shove
    // sibling buttons out of view. RichTextLabel wraps to the available width, keeping rows tidy.
    private static RichTextLabel MakeWrap(string text, Color? color = null)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        var escaped = FormattedMessage.EscapeText(text);
        label.SetMessage(color is { } c ? $"[color={c.ToHex()}]{escaped}[/color]" : escaped);
        return label;
    }

    private static RichTextLabel MakeTitle(string text, Color? color = null)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        var escaped = FormattedMessage.EscapeText(text);
        label.SetMessage($"[bold][color={(color ?? Color.White).ToHex()}]{escaped}[/color][/bold]");
        return label;
    }

    private static Control MakeEffectsRow(List<SWBillEffectEntry> effects)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(8, 0, 0, 0) };
        foreach (var effect in effects)
        {
            row.AddChild(new Label
            {
                Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                FontColorOverride = effect.Color,
                Margin = new Thickness(0, 0, 10, 0),
            });
        }

        return row;
    }

    private Control MakeSummaryEntry(SWDilemmaEntry dilemma)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 1, 0, 2) };

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        header.AddChild(MakeTitle($"{dilemma.OwnerLabel}: {dilemma.Name}", dilemma.IsRepublic ? Color.Gold : Color.White));
        header.AddChild(new Label { Text = dilemma.Status, FontColorOverride = Color.Gray, Margin = new Thickness(6, 0, 8, 0) });

        var expanded = _expandedDilemmas.Contains(dilemma.Id);
        var details = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(12, 2, 0, 6), Visible = expanded };

        var id = dilemma.Id;
        var toggle = new Button { Text = expanded ? "Скрыть" : "Подробнее" };
        toggle.OnPressed += _ =>
        {
            if (!_expandedDilemmas.Add(id))
                _expandedDilemmas.Remove(id);
            var now = _expandedDilemmas.Contains(id);
            details.Visible = now;
            toggle.Text = now ? "Скрыть" : "Подробнее";
        };
        header.AddChild(toggle);
        box.AddChild(header);

        if (!string.IsNullOrWhiteSpace(dilemma.Description))
        {
            var desc = new RichTextLabel { Margin = new Thickness(0, 0, 0, 4) };
            desc.SetMessage(dilemma.Description);
            details.AddChild(desc);
        }

        for (var i = 0; i < dilemma.Options.Count; i++)
        {
            var option = dilemma.Options[i];
            details.AddChild(MakeWrap(
                dilemma.ChosenOption == i ? $"{option.Label} (выбрано)" : option.Label,
                dilemma.ChosenOption == i ? Color.LightGreen : Color.LightGray));
            details.AddChild(MakeEffectsRow(option.Effects));
        }

        if (dilemma.FailEffects.Count > 0 || !string.IsNullOrWhiteSpace(dilemma.FailText))
        {
            var failHeader = string.IsNullOrWhiteSpace(dilemma.FailText) ? "При провале:" : $"При провале: {dilemma.FailText}";
            details.AddChild(MakeWrap(failHeader, Color.IndianRed));
            if (dilemma.FailEffects.Count > 0)
                details.AddChild(MakeEffectsRow(dilemma.FailEffects));
        }

        box.AddChild(details);
        return box;
    }

