    /// <summary>
    /// The effects of a result. They grow with its rarity, and snowflakes, the usual result, stay a light dusting.
    /// </summary>
    private void PlayRevealEffects(SWBattlePassCaseEntry entry)
    {
        var legendary = entry.Cosmetic != null && entry.Rarity == SWCosmeticRarity.Legendary;
        var rare = entry.Cosmetic != null && entry.Rarity == SWCosmeticRarity.Rare;

        _controller.PlayCaseSound(entry.Cosmetic == null ? FlakesSound : legendary ? LegendarySound : rare ? RareSound : ItemSound);

        if (_reducedMotion)
            return;

        // The middle of the item. It became visible only this frame, so it has no position of its own yet.
        var origin = RevealCentre;
        var colors = entry.Cosmetic == null ? SnowPieces : legendary ? LegendaryPieces : rare ? RarePieces : CommonPieces;
        var count = entry.Cosmetic == null ? 26 : legendary ? 220 : rare ? 110 : 45;
        var speed = entry.Cosmetic == null ? 170f : legendary ? 760f : rare ? 560f : 360f;
        Confetti.Burst(origin, count, speed, colors);

        _popTime = 0;

        if (rare || legendary)
        {
            RevealFlash.PanelOverride = SWTerminalStyle.Fill(legendary ? LegendaryColor : RareColor);
            RevealFlash.Visible = true;
            _flashLeft = FlashTime;

            // Only the window moves. Under it the game goes on, and that must stay still.
            _shakeHome = Position;
            _shakeLeft = ShakeTime;
            _shakeForce = legendary ? 9f : 4f;
        }
    }

    private void UpdateRevealEffects(float delta)
    {
        if (_popTime < PopTime)
        {
            // A jump a little past the size, and back.
            _popTime += delta;
            var t = MathF.Min(1f, _popTime / PopTime);
            var scale = t < 0.7f
                ? PopFrom + (PopOver - PopFrom) * (t / 0.7f)
                : PopOver + (PopScale - PopOver) * ((t - 0.7f) / 0.3f);
            ResultView.Scale = new Vector2(scale, scale);
        }

        if (_flashLeft > 0)
        {
            _flashLeft -= delta;
            RevealFlash.Visible = _flashLeft > 0;
            RevealFlash.Modulate = new Color(1f, 1f, 1f, MathF.Max(0f, 0.3f * _flashLeft / FlashTime));
        }

        if (_shakeLeft > 0)
        {
            _shakeLeft -= delta;
            if (_shakeLeft <= 0)
            {
                LayoutContainer.SetPosition(this, _shakeHome);
            }
            else
            {
                var force = _shakeForce * (_shakeLeft / ShakeTime);
                var random = IoCManager.Resolve<IRobustRandom>();
                var jolt = new Vector2(random.NextFloat(-force, force), random.NextFloat(-force, force));
                LayoutContainer.SetPosition(this, _shakeHome + jolt);
            }
        }

        // The text arrives after the item: first how rare, then what it is, then what to do with it.
        if (_caseView == SWCaseView.Reveal)
        {
            _revealTime += delta;
            RevealRarity.Modulate = new Color(1f, 1f, 1f, _revealTime >= 0f ? 1f : 0f);
            RevealName.Modulate = new Color(1f, 1f, 1f, _revealTime >= 0.15f ? 1f : 0f);
            RevealNote.Modulate = new Color(1f, 1f, 1f, _revealTime >= 0.3f ? 1f : 0f);
        }
    }

    private void ShowReveal()
    {
        _revealAt = null;
        if (_result is not { } result || _state == null || !_proto.TryIndex(result.Case, out var proto))
            return;

        var entry = proto.Entries[result.Entry];
        var cosmetic = entry.Cosmetic != null;
        var color = cosmetic ? RarityColor(entry.Rarity) : IceColor;
        var legendary = cosmetic && entry.Rarity == SWCosmeticRarity.Legendary;
        var rare = cosmetic && entry.Rarity == SWCosmeticRarity.Rare;

        if (EntryEntity(entry) is { } entity)
            ResultView.SetPrototype(entity);

        ResultView.Visible = cosmetic;
        ResultIcon.Visible = !cosmetic;
        ResultIcon.Texture = EntryIcon();
        RevealLine.PanelOverride = SWTerminalStyle.Fill(color);

        // Light only where it means something: most cases give snowflakes, and those must not feel like a show.
        RevealGlow.Visible = rare || legendary;
        RevealGlow.ModulateSelfOverride = color.WithAlpha(legendary ? 0.5f : 0.4f);
        RevealRays.Visible = legendary;
        RevealRays.Texture = _sprite.Frame0(RaysA);
        RevealRays.ModulateSelfOverride = color.WithAlpha(0.3f);
        _raysFlipped = false;
        _rayFlipsLeft = legendary && !_reducedMotion ? RayFlips : 0;
        _nextRayFlip = _controller.Timing.RealTime + RayFlipTime;

        RevealRarity.Visible = cosmetic;
        RevealRarity.Text = cosmetic ? $"{RarityMark(entry.Rarity)} {RarityWord(entry.Rarity).ToUpperInvariant()}" : string.Empty;
        RevealRarity.FontColorOverride = color;
        RevealName.Text = cosmetic
            ? Capitalized(EntryName(entry))
            : Loc.GetString("sw-battlepass-case-flakes", ("flakes", result.Snowflakes));

        RevealNote.Text = !cosmetic
            ? Loc.GetString("sw-battlepass-case-flakes-total", ("count", _state.Snowflakes))
            : result.Duplicate
                ? Loc.GetString("sw-battlepass-case-repeat", ("flakes", result.Snowflakes))
                : Loc.GetString("sw-battlepass-case-in-items");
        RevealNote.FontColorOverride = result.Duplicate ? IceColor : null;

        WearResult.Visible = _resultCosmetic is { } won && _proto.TryIndex(won, out var loadout) && !_controller.IsBlockedForCharacter(loadout);

        var left = _state.Cases.GetValueOrDefault(proto.ID);
        MoreCases.Text = left > 0
            ? Loc.GetString("sw-battlepass-case-more", ("count", left))
            : Loc.GetString("sw-battlepass-case-back");
        MoreCases.Disabled = left > 0 && _state.InCombat;

        _revealButtonsAt = _controller.Timing.RealTime + RevealButtonsLock;
        _result = null;
        SetCaseView(SWCaseView.Reveal);
        UpdateCaseFooter(_state);
        _revealTime = 0;
        PlayRevealEffects(entry);
    }

    private void UpdateCaseMotion(float delta)
    {
        if (_revealAt is { } revealAt && _controller.Timing.RealTime >= revealAt)
            ShowReveal();

        UpdateRevealEffects(delta);

        // The world goes dark around the strip as it slows down.
        if (Reel.Spinning)
        {
            var light = 0.42f + (SpinDarkest - 0.42f) * Reel.Progress;
            SceneArt.ModulateSelfOverride = new Color(light, light, light);
            OddsTiles.Modulate = new Color(1f, 1f, 1f, 0.6f - 0.35f * Reel.Progress);
        }

        // The light behind the closed case breathes three times and then rests, so nothing nags from the corner of the eye.
        if (_caseView == SWCaseView.Closed)
        {
            _glowTime += delta;
            var breathing = !_reducedMotion && _glowTime < GlowPeriod * GlowBreaths;
            var wave = breathing ? 0.5f - 0.5f * MathF.Cos(_glowTime / GlowPeriod * MathF.Tau) : 0.5f;
            CaseGlow.ModulateSelfOverride = IceColor.WithAlpha(0.12f + 0.16f * wave);
        }

        if (_rayFlipsLeft > 0 && _controller.Timing.RealTime >= _nextRayFlip)
        {
            _rayFlipsLeft--;
            _raysFlipped = !_raysFlipped;
            _nextRayFlip = _controller.Timing.RealTime + RayFlipTime;
            RevealRays.Texture = _sprite.Frame0(_raysFlipped ? RaysB : RaysA);
        }
    }

    private void BuildItems(SWBattlePassState state)
    {
        ItemsGrid.RemoveAllChildren();
        WearHint.SetMarkup(_controller.GetCharacterName() is { } name
            ? Loc.GetString("sw-battlepass-items-hint", ("name", FormattedMessage.EscapeText(name)))
            : string.Empty);

        var any = false;
        foreach (var id in _owned.OrderBy(o => o))
        {
            if (!_proto.TryIndex<LoadoutPrototype>(id, out var loadout))
                continue;

            any = true;
            ItemsGrid.AddChild(BuildItemCard(loadout));
        }

        foreach (var title in state.Titles.OrderBy(t => t))
        {
            any = true;
            var card = new PanelContainer { HorizontalExpand = true, StyleClasses = { SWTerminalStyle.Card } };
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(8), SeparationOverride = 8 };
            box.AddChild(new TextureRect { Texture = _sprite.Frame0(TitleIcon), SetSize = new Vector2(32, 32), Stretch = TextureRect.StretchMode.KeepAspectCentered });
            box.AddChild(new Label
            {
                Text = Loc.GetString("sw-battlepass-reward-title", ("name", Loc.GetString(title))),
                HorizontalExpand = true,
                ClipText = true,
                VAlign = Label.VAlignMode.Center,
                StyleClasses = { SWTerminalStyle.Value },
            });
            card.AddChild(box);
            ItemsGrid.AddChild(card);
        }

        if (!any)
            ItemsGrid.AddChild(new Label { Text = Loc.GetString("sw-battlepass-items-empty"), StyleClasses = { SWTerminalStyle.Text } });

        // A short last row keeps its cards at half the width.
        while (ItemsGrid.ChildCount % ItemsGrid.Columns != 0)
        {
            ItemsGrid.AddChild(new Control { HorizontalExpand = true });
        }
    }

    private Control BuildItemCard(LoadoutPrototype loadout)
    {
        var card = new PanelContainer { HorizontalExpand = true, StyleClasses = { SWTerminalStyle.Card } };
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(6), SeparationOverride = 8 };

        var view = new EntityPrototypeView { SetSize = new Vector2(64, 48), Scale = new Vector2(3, 3), Stretch = SpriteView.StretchMode.None };
        view.SetPrototype(LoadoutEntity(loadout.ID));
        box.AddChild(view);

        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };
        text.AddChild(new Label
        {
            Text = LoadoutName(loadout.ID),
            ClipText = true,
            StyleClasses = { SWTerminalStyle.Value },
            ToolTip = LoadoutName(loadout.ID),
        });

        // Which jobs it is for: an item bought for one job must not look like it is missing on another.
        var jobs = _controller.JobsFor(loadout);
        text.AddChild(new Label
        {
            Text = jobs.Count switch
            {
                0 => string.Empty,
                1 => jobs[0],
                <= JobsNamedInFull => Loc.GetString("sw-battlepass-item-jobs", ("job", jobs[0]), ("more", jobs.Count - 1)),
                _ => Loc.GetString("sw-battlepass-item-jobs-many", ("count", jobs.Count)),
            },
            ClipText = true,
            ToolTip = string.Join("\n", jobs),
            StyleClasses = { SWTerminalStyle.Text },
        });
        box.AddChild(text);

        var worn = _controller.IsWorn(loadout.ID);
        var blocked = _controller.IsBlockedForCharacter(loadout);
        var button = new Button
        {
            Text = Loc.GetString(blocked ? "sw-battlepass-wear-blocked" : worn ? "sw-battlepass-take-off" : "sw-battlepass-wear"),
            MinWidth = 96,
            Disabled = blocked,
            VerticalAlignment = VAlignment.Center,
            StyleClasses = { SWTerminalStyle.Button },
            StyleBoxOverride = worn || blocked ? null : SWTerminalStyle.Box(SWTerminalStyle.ButtonFill, IceColor, 2, 8, 7),
            ToolTip = blocked ? Loc.GetString("sw-battlepass-cosmetic-species-blocked") : null,
        };
        button.OnPressed += _ =>
        {
            _controller.SetWorn(loadout.ID, !worn);
            if (_state != null)
                BuildItems(_state);
        };
        box.AddChild(button);

        card.AddChild(box);
        return card;
    }
