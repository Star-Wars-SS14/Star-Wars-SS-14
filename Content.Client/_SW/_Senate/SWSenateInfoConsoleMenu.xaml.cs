using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate;

[GenerateTypedNameReferences]
public sealed partial class SWSenateInfoConsoleMenu : FancyWindow
{
    public SWSenateInfoConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        Tabs.SetTabTitle(0, "Сектора");
        Tabs.SetTabTitle(1, "Руководство");
    }

    public void SetState(SWSenateInfoConsoleState state)
    {
        SectorList.RemoveAllChildren();
        foreach (var sector in state.Sectors)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 1, 0, 1),
            };

            row.AddChild(new Label
            {
                Text = sector.Name,
                FontColorOverride = sector.Color,
                MinWidth = 200,
            });

            row.AddChild(new Label
            {
                Text = sector.Holder == null ? "Свободен" : $"Занят: {sector.Holder}",
                FontColorOverride = sector.Holder == null ? Color.Gray : Color.White,
            });

            SectorList.AddChild(row);
        }

        ChancellorLabel.SetMessage($"Верховный Канцлер: {state.Chancellor ?? "Вакантно"}");
        SpeakerLabel.SetMessage($"Спикер Сената: {state.Speaker ?? "Вакантно"}");
    }
}
