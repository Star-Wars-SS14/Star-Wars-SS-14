using System.Linq;
using Content.Client._SW.UserInterface;
using Content.Shared._SW.TaskSystem;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.TaskSystem.UI;

[GenerateTypedNameReferences]
public sealed partial class TaskConsoleMenu : SWTerminalWindow
{
    public TaskConsoleMenu()
    {
        RobustXamlLoader.Load(this);
    }

    /// <summary>
    /// Colours the window for the console's faction and names it, because some accents look alike with colour blindness.
    /// </summary>
    public void SetOwner(string? faction)
    {
        SetFaction(faction);
        FactionName.Text = UserInterfaceManager.GetUIController<SWTerminalStyleUIController>().GetFactionName(faction);
    }

    public void PopulateTasks(List<TaskInfo> list)
    {
        var done = list.Count(task => task.Status.Float() >= 1f);
        Summary.Text = Loc.GetString("sw-task-console-summary", ("done", done), ("total", list.Count));

        TaskList.Children.Clear();

        // What still needs doing comes first: a finished task needs no action.
        foreach (var task in list.OrderBy(task => task.Status.Float() >= 1f))
        {
            TaskList.AddChild(new SWTaskControl(task, Accent));
        }
    }
}
