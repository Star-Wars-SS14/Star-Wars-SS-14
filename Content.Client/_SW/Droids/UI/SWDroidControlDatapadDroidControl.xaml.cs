using Content.Shared._SW.Droids;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.Droids.UI;

[GenerateTypedNameReferences]
public sealed partial class SWDroidControlDatapadDroidControl : PanelContainer
{
    public SWDroidControlDatapadDroidControl(
        SWDroidControlDatapadDroidEntry droid,
        Action<NetEntity> onFollowDatapadPressed,
        Action<NetEntity> onStopFollowDatapadPressed)
    {
        RobustXamlLoader.Load(this);

        DroidName.Text = droid.Name;
        DroidStatus.Text = Loc.GetString("sw-droid-control-datapad-droid-status", ("status", droid.Status));
        DroidCharge.Text = Loc.GetString("sw-droid-control-datapad-droid-charge", ("charge", droid.Charge));
        DroidCoordinates.Text = Loc.GetString(
            "sw-droid-control-datapad-droid-coordinates",
            ("coordinates", droid.CoordinatesText));
        FollowDatapadButton.Text = Loc.GetString(droid.FollowingDatapad
            ? "sw-droid-control-datapad-stop-following"
            : "sw-droid-control-datapad-follow-datapad");

        FollowDatapadButton.OnPressed += _ =>
        {
            if (droid.FollowingDatapad)
                onStopFollowDatapadPressed.Invoke(droid.DroidUid);
            else
                onFollowDatapadPressed.Invoke(droid.DroidUid);
        };
    }
}
