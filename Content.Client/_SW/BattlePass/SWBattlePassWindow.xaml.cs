    }

    private void BuildQuests(SWBattlePassSeasonPrototype season, SWBattlePassState state)
    {
        QuestList.RemoveAllChildren();

        QuestList.AddChild(new Label { Text = Loc.GetString("sw-battlepass-quests-daily"), StyleClasses = { SWTerminalStyle.Value } });
        foreach (var quest in state.Quests.Where(q => !q.Weekly))
        {
            var data = season.DailyQuests.FirstOrDefault(q => q.Id == quest.Id);
            if (data != null)
                QuestList.AddChild(BuildQuestRow(data, quest));
        }

        QuestList.AddChild(new Label { Text = Loc.GetString("sw-battlepass-quests-weekly"), StyleClasses = { SWTerminalStyle.Value } });
        foreach (var quest in state.Quests.Where(q => q.Weekly))
        {
            var data = season.WeeklyQuests.FirstOrDefault(q => q.Id == quest.Id);
            if (data != null)
