    public void SetState(SWSectorSelectConsoleState state)
    {
        var previous = _state;
        var wasPending = _pending;
        var previousSelection = _selected;
        var first = previous == null;
        var previousSector = previous?.CurrentSector;
        _updatingFilters = true;
        _state = state;
        _pending = false;
        if (state.CurrentSector != null && state.CurrentSector != previousSector)
        {
            _selected = state.CurrentSector;
            _revealSelected = true;
            FreeOnly.Pressed = false;
            Search.Text = string.Empty;
        }
        else if (first)
        {
            var initial = state.Sectors.FirstOrDefault(s => !s.Claimed);
            if (initial == null)
            {
                initial = state.Sectors.FirstOrDefault();
                FreeOnly.Pressed = false;
            }
            _selected = initial?.Id;
        }
        _updatingFilters = false;
        MySector.Disabled = state.CurrentSector == null;
        var sectorsChanged = previous == null || !SameSectors(previous, state);
        if (sectorsChanged || previousSelection != _selected || _revealSelected)
            RefreshList();
        if (sectorsChanged || previousSelection != _selected || previous == null ||
            previous.HasCard != state.HasCard || previous.IsSenatorCard != state.IsSenatorCard ||
            previous.CurrentSector != state.CurrentSector || previous.CurrentSectorName != state.CurrentSectorName ||
            previous.ModeActive != state.ModeActive || previous.DayActive != state.DayActive || wasPending)
            RefreshDetail();
    }

    private static bool SameSectors(SWSectorSelectConsoleState left, SWSectorSelectConsoleState right)
    {
        if (left.Sectors.Count != right.Sectors.Count)
            return false;
        for (var i = 0; i < left.Sectors.Count; i++)
        {
            var a = left.Sectors[i];
            var b = right.Sectors[i];
            if (a.Id != b.Id || a.Name != b.Name || a.Description != b.Description || a.Color != b.Color ||
                a.Claimed != b.Claimed || a.Representative != b.Representative || a.Shipyard != b.Shipyard)
                return false;
        }
        return true;
    }

    private void ShowMySector(string id)
    {
        _selected = id;
        _revealSelected = true;
        _updatingFilters = true;
        FreeOnly.Pressed = false;
        Search.Text = string.Empty;
        _updatingFilters = false;
        Select(id);
    }

    private void Select(string id)
    {
        _selected = id;
        RefreshList();
        RefreshDetail();
    }

    private void RefreshList()
    {
        if (_state == null) return;
        var scroll = ListScroll.GetScrollValue();
        SectorList.RemoveAllChildren();
        _revealRow = null;
        FreeCount.Text = $"Свободных мест: {_state.Sectors.Count(s => !s.Claimed)}";
        var search = Search.Text.Trim();
        var visible = 0;
        foreach (var sector in _state.Sectors)
        {
            if (FreeOnly.Pressed && sector.Claimed) continue;
            if (search.Length > 0 && sector.Name.IndexOf(search, StringComparison.OrdinalIgnoreCase) < 0 &&
                sector.Description.IndexOf(search, StringComparison.OrdinalIgnoreCase) < 0) continue;
            visible++;
            var button = new ContainerButton { HorizontalExpand = true };
            button.StyleBoxOverride = new StyleBoxFlat
            {
                BackgroundColor = sector.Id == _selected ? Color.FromHex("#19405A") : Color.FromHex("#101F2B"),
                BorderColor = sector.Id == _selected ? Color.FromHex("#7CC8E8") : SWConsoleStyle.Edge,
                BorderThickness = new Thickness(3, 0, 0, 0),
                ContentMarginLeftOverride = 8, ContentMarginRightOverride = 8,
                ContentMarginTopOverride = 3, ContentMarginBottomOverride = 3,
            };
            var contents = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            contents.AddChild(Wrap(sector.Name, SWConsoleStyle.TextBright, 180));
            contents.AddChild(Wrap(sector.Claimed ? "Место занято" : "Свободно", SWConsoleStyle.TextDim, 180));
            button.AddChild(contents);
            var id = sector.Id;
            button.OnPressed += _ => Select(id);
            SectorList.AddChild(button);
            if (_revealSelected && sector.Id == _selected)
                _revealRow = button;
        }
        if (visible == 0)
        {
            var message = FreeOnly.Pressed && !_state.Sectors.Any(s => !s.Claimed)
                ? "Свободных мест нет" : "Секторы не найдены";
            SectorList.AddChild(Wrap(message, SWConsoleStyle.TextDim, 180));
        }
        ListScroll.SetScrollValue(scroll);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        FitViewport(false);
        if (_revealRow == null || _revealRow.Height <= 0)
            return;
        ListScroll.VScroll = _revealRow.Position.Y;
        _revealRow = null;
        _revealSelected = false;
    }

    private void FitViewport(bool initial)
    {
        // WindowRoot.Size is in logical UI units (physical pixels / UI scale).
        var root = IoCManager.Resolve<IUserInterfaceManager>().WindowRoot;
        var viewport = root.Size;
        if (initial && (viewport.X <= 0 || viewport.Y <= 0) && root.UIScale > 0)
            viewport = (Vector2) IoCManager.Resolve<IClyde>().ScreenSize / root.UIScale;
        if (viewport.X <= 0 || viewport.Y <= 0 || !float.IsFinite(viewport.X) || !float.IsFinite(viewport.Y)) return;
        if (!initial && viewport == _viewport) return;
        _viewport = viewport;
        var limit = Vector2.Max(Vector2.One, viewport - new Vector2(24));
        MinSize = Vector2.Min(new Vector2(640, 460), limit);
        var current = initial ? new Vector2(1100, 780) : SetSize;
        if (!float.IsFinite(current.X) || !float.IsFinite(current.Y)) current = Size;
        SetSize = Vector2.Min(current, limit);
        if (!initial && IsOpen)
        {
            Measure(Vector2Helpers.Infinity);
            RecenterWindow(new Vector2(0.5f, 0.5f));
        }
    }

    private RichTextLabel Wrap(string text, Color color, float fallbackWidth)
    {
        var label = SWConsoleStyle.Wrap(text, color, fallbackWidth);
        label.Stylesheet = new Stylesheet(new StyleRule[]
        {
            StylesheetHelpers.Element<RichTextLabel>().Prop("font", _bodyFont),
        });
        return label;
    }
    private void RefreshWorldPreview(string? sectorId)
    {
        // Always clear the previous selection before resolving the new world.
        SectorWorldPreview.Texture = null;
        SectorWorldPreview.Visible = false;
        SectorWorldPreviewStatus.RemoveAllChildren();
        if (sectorId == null) return;
        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        if (!prototypes.TryIndex<SWGalacticMapPrototype>("SenateRepublic", out var map))
        {
            SectorWorldPreviewStatus.AddChild(Wrap("Сведения об опорном мире недоступны.", SWConsoleStyle.TextDim, 250));
            return;
        }
        var anchors = map.Worlds.Where(world => world.Sector?.Id == sectorId && world.Anchor).Take(2).ToArray();
        if (anchors.Length != 1)
        {
            SectorWorldPreviewStatus.AddChild(Wrap(anchors.Length == 0 ? "Опорный мир не определён." : "Опорный мир неоднозначен.", SWConsoleStyle.TextDim, 250));
            return;
        }
        var anchor = anchors[0];
        if (string.IsNullOrWhiteSpace(anchor.Id) || map.Worlds.Count(world => world.Id == anchor.Id) != 1)
        {
            SectorWorldPreviewStatus.AddChild(Wrap("Идентификатор опорного мира отсутствует или неоднозначен.", SWConsoleStyle.TextDim, 250));
            return;
        }
        var texture = SWStatisticsWorldArt.Get(anchor, true);
        if (texture == null)
        {
            SectorWorldPreviewStatus.AddChild(Wrap("Изображение опорного мира недоступно.", SWConsoleStyle.TextDim, 250));
            return;
        }
        SectorWorldPreview.Texture = texture;
        SectorWorldPreview.Visible = true;
        SectorWorldPreviewStatus.AddChild(Wrap("Условное изображение", SWConsoleStyle.TextDim, 250));
    }

    private void RefreshDetail()
    {
        if (_state == null) return;
        var scroll = _detailSelection == _selected ? DetailScroll.GetScrollValue() : Vector2.Zero;
        _detailSelection = _selected;
        Detail.RemoveAllChildren();
        DetailIntro.RemoveAllChildren();
        Infrastructure.RemoveAllChildren();
        Representative.RemoveAllChildren();
        FooterText.RemoveAllChildren();
        var sector = _state.Sectors.FirstOrDefault(s => s.Id == _selected);
        RefreshWorldPreview(sector?.Id);
        SectorMap.Select(sector?.Id);
        MapCaption.RemoveAllChildren();
        MapHeading.RemoveAllChildren();
        if (sector != null)
        {
            MapHeading.AddChild(Wrap($"Сектор {sector.Name}", SWConsoleStyle.Brass, 310));
            MapCaption.AddChild(Wrap(SectorMap.HasBoundary ? "Схематическая граница областей Республики и Империи" : "Общая граница областей не задана", SWConsoleStyle.TextDim, 310));
            MapCaption.AddChild(Wrap(SectorMap.Caption, SWConsoleStyle.TextDim, 310));
        }
        if (sector == null)
            Detail.AddChild(Wrap("Выберите сектор, чтобы узнать о нём больше.", SWConsoleStyle.TextDim, 350));
        else
        {
            var title = Wrap(sector.Name, SWConsoleStyle.TextBright, 350);
            title.Stylesheet = new Stylesheet(new StyleRule[]
            {
                StylesheetHelpers.Element<RichTextLabel>().Prop("font", _sectorTitleFont),
            });
            DetailIntro.AddChild(title);
            DetailIntro.AddChild(Wrap(sector.Claimed ? "Место занято" : "Свободно", sector.Claimed ? SWConsoleStyle.TextDim : SWConsoleStyle.Good, 350));
            Detail.AddChild(Wrap(sector.Description, SWConsoleStyle.TextBright, 350));
            Infrastructure.AddChild(Wrap("ИНФРАСТРУКТУРА", SWConsoleStyle.TextDim, 180));
            Infrastructure.AddChild(Wrap(sector.Shipyard ? "Верфи" : "Верфи отсутствуют", SWConsoleStyle.Brass, 180));
            Representative.AddChild(Wrap("ПРЕДСТАВИТЕЛЬ", SWConsoleStyle.TextDim, 180));
            Representative.AddChild(Wrap(!string.IsNullOrEmpty(sector.Representative) ? sector.Representative : sector.Claimed ? "Неизвестен" : "Место не занято", SWConsoleStyle.TextBright, 180));
        }
        var reason = !_state.HasCard ? "Вставьте карту сенатора" :
            !_state.IsSenatorCard ? "Нужна карта сенатора" :
            _state.CurrentSector != null ? $"Ваше представительство: {_state.CurrentSectorName ?? _state.CurrentSector}" :
            !_state.ModeActive ? "Сенат сейчас не работает" :
            !_state.DayActive ? "Занять место можно только днём" :
            sector == null ? "Выберите сектор" :
            sector.Claimed ? "Это место уже занято" : $"Выбрано: {sector.Name}";
        FooterText.AddChild(Wrap(reason, SWConsoleStyle.TextBright, 600));
        ClaimButton.Disabled = _pending || !_state.HasCard || !_state.IsSenatorCard || _state.CurrentSector != null ||
                               !_state.ModeActive || !_state.DayActive || sector == null || sector.Claimed;
        DetailScroll.SetScrollValue(scroll);
    }
}


// Measure the fixed header and footer before the flexible catalogue. BoxContainer
// otherwise gives a later footer only the height left by the expanding body.
public sealed class SWSectorSelectLayout : Container
{
    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        if (ChildCount != 3)
            return base.MeasureOverride(availableSize);

        var header = Children[0];
        var body = Children[1];
        var footer = Children[2];
        var fixedConstraint = new Vector2(availableSize.X, float.PositiveInfinity);
        header.Measure(fixedConstraint);
        footer.Measure(fixedConstraint);
        var remaining = Math.Max(0, availableSize.Y - header.DesiredSize.Y - footer.DesiredSize.Y);
        body.Measure(new Vector2(availableSize.X, remaining));
        return new Vector2(Math.Max(header.DesiredSize.X, Math.Max(body.DesiredSize.X, footer.DesiredSize.X)),
            header.DesiredSize.Y + body.DesiredSize.Y + footer.DesiredSize.Y);
    }

    protected override Vector2 ArrangeOverride(Vector2 finalSize)
    {
        if (ChildCount != 3)
            return base.ArrangeOverride(finalSize);

        var headerHeight = Math.Min(finalSize.Y, Children[0].DesiredSize.Y);
        var footerHeight = Math.Min(Math.Max(0, finalSize.Y - headerHeight), Children[2].DesiredSize.Y);
        var bodyHeight = Math.Max(0, finalSize.Y - headerHeight - footerHeight);
        Children[0].Arrange(UIBox2.FromDimensions(Vector2.Zero, new Vector2(finalSize.X, headerHeight)));
        Children[1].Arrange(UIBox2.FromDimensions(new Vector2(0, headerHeight), new Vector2(finalSize.X, bodyHeight)));
        Children[2].Arrange(UIBox2.FromDimensions(new Vector2(0, headerHeight + bodyHeight), new Vector2(finalSize.X, footerHeight)));
        return finalSize;
    }
}


/// <summary>Measure both columns at the same widths used during arrangement.</summary>
public sealed class SWSectorColumns : Container
{
    public float LeftFraction { get; set; } = 0.5f;
    public float RightWidth { get; set; }
    public float Gap { get; set; } = 12;
    private float _measuredWidth;

    private (float Left, float Right) Widths(float width)
    {
        var available = Math.Max(0, width - Gap);
        var right = RightWidth > 0 ? Math.Min(RightWidth, available) : available * (1 - Math.Clamp(LeftFraction, 0, 1));
        return (available - right, right);
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        if (ChildCount != 2) return base.MeasureOverride(availableSize);
        _measuredWidth = float.IsFinite(availableSize.X) ? Math.Max(0, availableSize.X) : 600;
        var (left, right) = Widths(_measuredWidth);
        Children[0].Measure(new Vector2(left, availableSize.Y));
        Children[1].Measure(new Vector2(right, availableSize.Y));
        return new Vector2(_measuredWidth, Math.Max(Children[0].DesiredSize.Y, Children[1].DesiredSize.Y));
    }

    protected override Vector2 ArrangeOverride(Vector2 finalSize)
    {
        if (ChildCount != 2) return base.ArrangeOverride(finalSize);
        // ScrollContainer can arrange wider than its measured constraint when its scrollbar is hidden.
        // Keep the measured widths so text and map heights remain valid on the first layout pass.
        var (left, right) = Widths(Math.Min(finalSize.X, _measuredWidth));
        Children[0].Arrange(UIBox2.FromDimensions(Vector2.Zero, new Vector2(left, finalSize.Y)));
        Children[1].Arrange(UIBox2.FromDimensions(new Vector2(left + Gap, 0), new Vector2(right, finalSize.Y)));
        return finalSize;
    }
}

