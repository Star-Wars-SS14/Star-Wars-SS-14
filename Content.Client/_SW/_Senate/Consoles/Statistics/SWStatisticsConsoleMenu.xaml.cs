    public void ShowTab(int index)
    {
        if (index < 0 || index >= _panels.Length) return;
        var changed = _active != index;
        _active = index;
        var headings = new[]
        {
            ("Глобальные показатели", "Фактическое состояние и политика Республики"),
            ("Сектора Республики", "Реестр, показатели и представительство"),
            ("Обстановка", "Сводки по направлениям"),
            ("Кризисы", "Действующие кризисы и связанные документы"),
            ("Действующие законы", "Реестр документов и полный текст"),
            ("Галактическая карта", "Миры, представительства и маршруты"),
            ("Товары", "Производственные связи и движение"),
        };
        PageTitle.Text = headings[index].Item1;
        PageSubtitle.Text = headings[index].Item2;
        FooterText.Text = index switch
        {
            GalaxyTab => "Сведения карты обновляются по опубликованным данным.",
            CommoditiesTab => "Выберите товар или участок производственной схемы.",
            3 => "Выберите кризис, чтобы открыть документ.",
            4 => "Чтение закона не запускает голосование.",
            _ => "Выберите показатель или раздел для просмотра сведений.",
        };
        if (changed) _tabReveal = 0;
        for (var i = 0; i < _panels.Length; i++)
        {
            _panels[i].Visible = i == index;
            StyleMainTab(_tabs[i], i == index);
        }
        RefreshActive();
    }

    private static void StyleMainTab(Button button, bool active)
    {
        button.StyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = active ? SWConsoleStyle.Selected : SWConsoleStyle.BgDark,
            BorderColor = active ? SWConsoleStyle.Brass : SWConsoleStyle.Edge,
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 12, ContentMarginRightOverride = 12,
            ContentMarginTopOverride = 7, ContentMarginBottomOverride = 7,
        };
        button.Label.FontColorOverride = active ? SWConsoleStyle.TextBright : SWConsoleStyle.TextDim;
    }

    private void FitViewport(bool initial)
    {
        var root = IoCManager.Resolve<IUserInterfaceManager>().WindowRoot;
        var viewport = root.Size;
        if (initial && (viewport.X <= 0 || viewport.Y <= 0) && root.UIScale > 0)
            viewport = (Vector2) IoCManager.Resolve<IClyde>().ScreenSize / root.UIScale;
        if (viewport.X <= 0 || viewport.Y <= 0 || !float.IsFinite(viewport.X) || !float.IsFinite(viewport.Y)) return;
        if (!initial && viewport == _viewport) return;
        _viewport = viewport;
        var limit = Vector2.Max(Vector2.One, viewport - new Vector2(24));
        MinSize = Vector2.Min(new Vector2(760, 620), limit);
        var current = initial ? new Vector2(1400, 860) : SetSize;
        if (!float.IsFinite(current.X) || !float.IsFinite(current.Y)) current = Size;
        SetSize = Vector2.Min(current, limit);
        if (!initial && IsOpen) { Measure(Vector2Helpers.Infinity); RecenterWindow(new Vector2(.5f)); }
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);
        if (args.Handled || args.Function != EngineKeyFunctions.CloseModals) return;
        if (_active == CommoditiesTab && _commodityLayout?.CloseDrawer() == true) { args.Handle(); return; }
        if (_active != GalaxyTab || !_galaxy.TryNavigateBack()) Close();
        args.Handle();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _windowReveal = 0;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!VisibleInTree) return;
        FitViewport(false);
        var visibleTabs = _tabs.Count(tab => tab.Visible);
        if (visibleTabs > 0 && TabBar.Width > 0)
        {
            var width = Math.Clamp(TabBar.Width / visibleTabs - 6, 90, 170);
            foreach (var tab in _tabs)
                if (!float.IsFinite(tab.SetWidth) || Math.Abs(tab.SetWidth - width) > .5f) tab.SetWidth = width;
        }
        var reduced = IoCManager.Resolve<IConfigurationManager>().GetCVar(CCVars.ReducedMotion);
        _windowReveal = reduced ? 1 : Math.Min(1, _windowReveal + Math.Max(0, args.DeltaSeconds) / .18f);
        _tabReveal = reduced ? 1 : Math.Min(1, _tabReveal + Math.Max(0, args.DeltaSeconds) / .12f);
        _filterReveal = reduced ? 1 : Math.Min(1, _filterReveal + Math.Max(0, args.DeltaSeconds) / .15f);
        _analysis.Modulate = Color.White.WithAlpha(_filterReveal);
        _ranking.Modulate = Color.White.WithAlpha(_filterReveal);
        _sectorDetail.Modulate = Color.White.WithAlpha(_filterReveal);
        AdvanceSectorRows(args.DeltaSeconds, reduced);
        ContentHost.Modulate = Color.White.WithAlpha(_windowReveal);
        _panels[_active].Modulate = Color.White.WithAlpha(_tabReveal);
    }

    public void SetState(SWStatisticsConsoleState state)
    {
        _state = state;
        var empire = state.Faction == "empire";
        _galaxy.SetViewerFaction(state.Faction);
        for (var i = 0; i < _tabs.Length; i++) _tabs[i].Visible = !empire || i is GalaxyTab or CommoditiesTab;
        Title = empire ? "Статистика Империи" : "Статистика Республики";
        HeaderNetwork.Text = empire ? "ИМПЕРИЯ / ГОЛОНЕТ" : "РЕСПУБЛИКА / ГОЛОНЕТ";
        HeaderTitle.Text = empire ? "Статистика Империи" : "Статистика Республики";
        RepublicSeal.Visible = !empire;
        if (empire && _active is not (GalaxyTab or CommoditiesTab)) ShowTab(GalaxyTab);
        HeaderClock.Text = state.GameTime.Length > 0 ? state.GameTime : "—";
        if (!state.Globals.Any(g => g.Id == _metricId)) _metricId = state.Globals.FirstOrDefault()?.Id;
        UpdateMetricNavigation();
        _tabs[3].Text = state.Crises.Count > 0 ? $"Кризисы ({state.Crises.Count})" : "Кризисы";
        RefreshActive();
    }

    public void SelectMetric(string id)
    {
        if (_state?.Globals.All(g => g.Id != id) != false) return;
        if (_metricId != id) _filterReveal = 0;
        _metricId = id;
        UpdateMetricNavigation();
        RefreshActive();
    }

    public void SelectSector(string id)
    {
        if (_state?.Sectors.All(s => s.Id != id) != false) return;
        _sectorId = id;
        RefreshSectors();
    }

    private void RefreshActive()
    {
        if (_state == null) return;
        switch (_active)
        {
            case 0: RefreshOverview(); break;
            case 1: RefreshSectors(); break;
            case 2: RefreshOperations(); break;
            case 3: RefreshCrises(); break;
            case 4: RefreshLaws(); break;
            case GalaxyTab: RefreshGalaxy(); break;
        }
    }

    private void UpdateMetricNavigation()
    {
        if (_state == null) return;
        var signature = string.Join("|", _state.Globals.Select(g => $"{g.Id}:{g.Name}"));
        if (signature != _metricSignature)
        {
            _metricSignature = signature;
            _metrics.RemoveAllChildren();
            _metricButtons.Clear();
            _sectorMetric.Clear();
            foreach (var (g, index) in _state.Globals.Select((g, i) => (g, i)))
            {
                var button = new SWConsoleButton { HorizontalExpand = true };
                button.Label.Visible = false;
                var text = VerticalStack(3);
                text.AddChild(SWStatisticsText.Wrap(g.Name, SWConsoleStyle.TextBright));
                var status = SWConsoleStyle.Text(string.Empty, SWConsoleStyle.TextDim, SWConsoleStyle.Small);
                text.AddChild(status);
                button.AddChild(text);
                button.OnPressed += _ => SelectMetric(g.Id);
                _metrics.AddChild(button);
                _metricButtons.Add(g.Id, (button, status));
                _sectorMetric.AddItem(g.Name, index);
            }
        }
        _sectorMetric.Disabled = _state.Globals.Count == 0;
        for (var i = 0; i < _state.Globals.Count; i++)
        {
            var g = _state.Globals[i];
            var row = _metricButtons[g.Id];
            row.Button.SetAppearance(SWConsoleStyle.TextBright, selected: g.Id == _metricId, quiet: true);
            row.Button.ToolTip = $"Факт: {SWStatisticsPresentation.Number(g.Actual)}, политика: {SWStatisticsPresentation.Number(g.Policy)}";
            row.Status.Text = SWStatisticsPresentation.Level(g.Actual, g.Min, g.Max);
            row.Status.FontColorOverride = SWStatisticsPresentation.LevelColor(g.Actual, g.Min, g.Max);
            if (g.Id == _metricId) _sectorMetric.SelectId(i);
        }
    }

    private void RefreshOperations()
    {
        if (_state == null) return;
        for (var i = 0; i < _operationButtons.Length; i++) SWConsoleStyle.StyleTabButton(_operationButtons[i], i == _operation);
        var signature = OperationSignature(_state);
        if (signature == _operationSignature) return;
        _operationSignature = signature;
        _operationDetail.RemoveAllChildren();
        _operationDetail.AddChild(SWConsoleDocument.Body(_operationButtons[_operation].Text ?? string.Empty, ""));
        if (_operation != 4)
        {
            _operationDetail.AddChild(Operations(_state, _operation));
            return;
        }
        var tabs = new WrapContainer { HorizontalExpand = true, SeparationOverride = 6, CrossSeparationOverride = 4 };
        var overview = SWConsoleStyle.TabButton(Loc.GetString("sw-statistics-finance-overview"));
        var taxes = SWConsoleStyle.TabButton(Loc.GetString("sw-statistics-finance-taxes"));
        SWConsoleStyle.StyleTabButton(overview, !_financeTaxesSelected);
        SWConsoleStyle.StyleTabButton(taxes, _financeTaxesSelected);
        overview.OnPressed += _ => { _financeTaxesSelected = false; RefreshOperations(); };
        taxes.OnPressed += _ => { _financeTaxesSelected = true; RefreshOperations(); };
        tabs.AddChild(overview); tabs.AddChild(taxes); _operationDetail.AddChild(tabs);
        if (!_financeTaxesSelected)
        {
            _operationDetail.AddChild(Operations(_state, _operation));
            return;
        }
        _operationDetail.AddChild(SWStatisticsText.Wrap(Loc.GetString("sw-statistics-finance-base-tax", ("rate", _state.FinanceBaseTaxRate)), SWConsoleStyle.TextBright));
        _operationDetail.AddChild(SWConsoleStyle.Section(Loc.GetString("sw-statistics-finance-active-taxes")));
        if (_state.FinanceActiveTaxes.Count == 0)
            _operationDetail.AddChild(SWStatisticsText.Wrap(Loc.GetString("sw-statistics-finance-no-taxes"), SWConsoleStyle.TextDim));
        else
            foreach (var entry in _state.FinanceActiveTaxes)
                _operationDetail.AddChild(SWStatisticsText.Wrap(Loc.GetString("sw-statistics-finance-tax-row", ("name", entry.Name), ("rate", entry.Rate)), SWConsoleStyle.TextBright));
        _operationDetail.AddChild(SWConsoleStyle.Section(Loc.GetString("sw-statistics-finance-active-reliefs")));
        if (_state.FinanceActiveReliefs.Count == 0)
            _operationDetail.AddChild(SWStatisticsText.Wrap(Loc.GetString("sw-statistics-finance-no-reliefs"), SWConsoleStyle.TextDim));
        else
            foreach (var entry in _state.FinanceActiveReliefs)
                _operationDetail.AddChild(SWStatisticsText.Wrap(Loc.GetString("sw-statistics-finance-relief-row", ("name", entry.Name), ("rate", entry.Rate)), SWConsoleStyle.TextBright));
    }

    private static string SituationSignature(IEnumerable<SWSituationalStatView> views) => string.Join("|", views.Select(x =>
        $"{x.SectorId}:{x.GlobalId}:{x.SubstatId}:{x.SubstatName}:{x.BaseValue}:{x.RawTotal}:{x.AppliedTotal}:{x.EffectiveValue}:" +
        string.Join(";", x.Sources.Select(source => $"{source.Source}:{source.SourceName}:{source.SectorId}:{source.SectorName}:{source.RawValue}"))));

    private string OperationSignature(SWStatisticsConsoleState s)
    {
        var effects = _operation == 0 ? s.DefconEffects : s.PostureEffects;
        var effectKey = string.Join(";", effects.Select(e => $"{e.StatName}:{e.Delta}:{e.PerHour}:{e.Color}"));
        var data = _operation switch
        {
            0 => $"{s.DefconName}|{s.DefconLevel}|{s.BorderPressure}|{s.BorderStatus}|{effectKey}",
            1 => $"{s.PostureName}|{s.Threat}|{s.ThreatStatus}|{s.Unrest}|{s.UnrestStatus}|{effectKey}",
            2 => $"{s.PandemicStatus}|{s.Immunity}|{s.PathogenActive}|{s.InfectionAvg}|{s.PathogenName}|{s.PathogenStrain}|{s.Research}",
            3 => $"{s.EconPhaseName}|{s.Growth}|{s.Overheat}|{s.OverheatStatus}",
            4 => $"{s.CreditRating}|{s.KeyRate}|{s.Inflation}|{s.InflationStatus}|{s.Debt}|{s.FinanceBaseTaxRate}|" +
                 string.Join(";", s.FinanceActiveTaxes.Select(x => $"{x.Id}:{x.Name}:{x.Rate}")) + "|" +
                 string.Join(";", s.FinanceActiveReliefs.Select(x => $"{x.Id}:{x.Name}:{x.Rate}")),
            5 => $"{s.JusticeStanceName}|{s.Backlog}|{s.BacklogStatus}|{s.CaseCount}|{s.CorruptionIndex}|{s.CorruptionStatus}",
            _ => $"{s.PowersActive}|{s.EmergencyLevelName}|{s.Authority}|{s.Legitimacy}",
        };
        return $"{_operation}|{_financeTaxesSelected}|{data}";
    }

    private void RefreshCrises()
    {
        var state = _state;
        if (state == null) return;
        var severe = state.Crises.Count(c => c.Severity >= 70);
        _crisisSummary.Visible = severe > 0 || state.Crises.Count == 0;
        _crisisSummary.SetMessage(state.Crises.Count == 0 ? "Кризисов нет" : $"Высокая тяжесть: {severe}", defaultColor: severe > 0 ? SWConsoleStyle.Bad : SWConsoleStyle.TextDim);
        _crises.SetDocuments(state.Crises.OrderByDescending(c => c.Severity).Select(c => new SWConsoleDocumentEntry(
            c.Id, c.Name, $"{c.TypeLabel}, {c.AffectedLabel}",
            $"{c.Name}|{c.Description}|{c.TypeLabel}|{c.AffectedLabel}|{c.Severity}|{c.SeverityLabel}|{c.EscalationThreat}|{c.ExitProgress}|" + string.Join(";", c.Impact.Select(e => $"{e.StatName}:{e.Delta}:{e.Color}")) + $"|map:{state.MapCrises.Any(m => m.Id == ("senate:" + c.Id))}",
            () =>
            {
                var body = SWConsoleDocument.Body(c.Name, c.Description);
                body.AddChild(Metric("Тяжесть кризиса", c.Severity, color: SWConsoleStyle.SeverityColor(c.Severity)));
                body.AddChild(SWStatisticsText.Wrap(c.SeverityLabel, SWConsoleStyle.TextDim));
                body.AddChild(SWStatisticsText.Wrap($"{c.TypeLabel}, {c.AffectedLabel}", SWConsoleStyle.TextDim));
                if (c.EscalationThreat.Length > 0) body.AddChild(SWStatisticsText.Wrap(c.EscalationThreat, SWConsoleStyle.Warn));
                if (c.ExitProgress.Length > 0) body.AddChild(SWStatisticsText.Wrap(c.ExitProgress, SWConsoleStyle.Good));
                StatEffects(body, c.Impact);
                var mapId = $"senate:{c.Id}";
                if (_state?.MapCrises.Any(m => m.Id == mapId) == true)
                {
                    var locate = SWConsoleStyle.TabButton("Открыть место на карте");
                    locate.OnPressed += _ => { ShowTab(GalaxyTab); _galaxy.FocusCrisis(mapId); };
                    body.AddChild(locate);
                }
                return body;
            })));
    }

    private void RefreshLaws()
    {
        if (_state == null) return;
        _laws.SetDocuments(_state.ActiveLaws.Select(law => new SWConsoleDocumentEntry(law.Id, law.Name,
            $"№ {law.Id}, {law.Author}", SWConsoleDocument.Revision(law), () => SWConsoleDocument.Bill(law))));
    }
}

/// <summary>Clipped frame shared by the statistics console's pages.</summary>
public sealed class SWStatisticsFrame : StyleBox
{
    private readonly Vector2[] _vertices = new Vector2[8];
    protected override float GetDefaultContentMargin(Margin margin) => 0;

    protected override void DoDraw(DrawingHandleScreen handle, UIBox2 box, float uiScale)
    {
        var cut = MathF.Min(14 * uiScale, MathF.Min(box.Width, box.Height) / 4);
        _vertices[0] = new Vector2(box.Left + cut, box.Top);
        _vertices[1] = new Vector2(box.Right - cut, box.Top);
        _vertices[2] = new Vector2(box.Right, box.Top + cut);
        _vertices[3] = new Vector2(box.Right, box.Bottom - cut);
        _vertices[4] = new Vector2(box.Right - cut, box.Bottom);
        _vertices[5] = new Vector2(box.Left + cut, box.Bottom);
        _vertices[6] = new Vector2(box.Left, box.Bottom - cut);
        _vertices[7] = new Vector2(box.Left, box.Top + cut);
        handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, _vertices, Color.ToSrgb(SWConsoleStyle.BgDark));
        for (var i = 0; i < _vertices.Length; i++)
            handle.DrawLine(_vertices[i], _vertices[(i + 1) % _vertices.Length], SWConsoleStyle.Edge);
    }
}
