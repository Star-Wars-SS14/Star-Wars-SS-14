using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate.Consoles.Info;

[GenerateTypedNameReferences]
public sealed partial class SWSenateInfoConsoleMenu : FancyWindow
{
    public SWSenateInfoConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        Tabs.SetTabTitle(0, "Сектора");
        Tabs.SetTabTitle(1, "Руководство");
        Tabs.SetTabTitle(2, "Расписание дня");
        Tabs.SetTabTitle(3, "Действующие законы");
    }

    public void SetState(SWSenateInfoConsoleState state)
    {
        SectorList.RemoveAllChildren();
        foreach (var sector in state.Sectors)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 1, 0, 1),
            };

            row.AddChild(new Label
            {
                Text = sector.Name,
                FontColorOverride = sector.Color,
                MinWidth = 200,
            });

            row.AddChild(new Label
            {
                Text = sector.Holder == null ? "Свободен" : $"Занят: {sector.Holder}",
                FontColorOverride = sector.Holder == null ? Color.Gray : Color.White,
            });

            SectorList.AddChild(row);
        }

        ChancellorLabel.SetMessage($"Верховный Канцлер: {state.Chancellor ?? "Вакантно"}");
        SpeakerLabel.SetMessage($"Спикер Сената: {state.Speaker ?? "Вакантно"}");

        Title = string.IsNullOrEmpty(state.GameTime)
            ? "Информационная консоль Сената"
            : $"Информационная консоль Сената — {state.GameTime}";

        ScheduleGrid.RemoveAllChildren();
        foreach (var row in state.Schedule)
        {
            var rowBox = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 1, 0, 1) };
            rowBox.AddChild(new Label
            {
                Text = row.IsNow ? $"> {row.TimeLabel}" : row.TimeLabel,
                FontColorOverride = row.IsNow ? Color.White : Color.Gray,
                MinWidth = 70,
            });
            rowBox.AddChild(new Label { Text = row.Text, FontColorOverride = row.Color });
            ScheduleGrid.AddChild(rowBox);
        }

        ActiveLawsList.RemoveAllChildren();
        if (state.ActiveLaws.Count == 0)
        {
            ActiveLawsList.AddChild(new Label { Text = "Действующих законов пока нет." });
        }
        else
        {
            foreach (var law in state.ActiveLaws)
            {
                var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 2, 0, 6) };
                box.AddChild(new Label { Text = $"#{law.Id}  {law.Name}", StyleClasses = { "LabelKeyText" } });
                box.AddChild(new Label { Text = $"Автор: {law.Author}", FontColorOverride = Color.Gray });

                if (!string.IsNullOrWhiteSpace(law.Description))
                {
                    var desc = new RichTextLabel { Margin = new Thickness(0, 2, 0, 2) };
                    desc.SetMessage(law.Description);
                    box.AddChild(desc);
                }

                var effects = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
                foreach (var effect in law.Effects)
                {
                    effects.AddChild(new Label
                    {
                        Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                        FontColorOverride = effect.Color,
                        Margin = new Thickness(0, 0, 12, 0),
                    });
                }

                box.AddChild(effects);
                ActiveLawsList.AddChild(box);
            }
        }
    }
}
