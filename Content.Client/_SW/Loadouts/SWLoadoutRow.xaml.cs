using Content.Client._SW.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._SW.Loadouts;

/// <summary>
/// One choice in a loadout group. A closed one stays visible and says why it is closed.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SWLoadoutRow : ContainerButton
{
    private const float LockedAlpha = 0.65f;

    public SWLoadoutRow(EntProtoId? icon, string name, int cost, bool selected, string accent, FormattedMessage? lockReason)
    {
        RobustXamlLoader.Load(this);

        Icon.SetPrototype(icon);
        NameLabel.Text = name;

        if (cost > 0)
        {
            CostLabel.Text = Loc.GetString("sw-loadout-cost", ("cost", cost));
            CostLabel.Visible = true;
        }

        TickIcon.Visible = selected;
        Stripe.Visible = selected;
        if (selected)
            Stripe.SetOnlyStyleClass(SWTerminalStyle.AccentLine + accent);

        if (lockReason == null)
            return;

        Disabled = true;
        LockIcon.Visible = true;
        Icon.Modulate = Color.White.WithAlpha(LockedAlpha);
        NameLabel.Modulate = Color.White.WithAlpha(LockedAlpha);
        ReasonLabel.Visible = true;
        ReasonLabel.SetMessage(lockReason);
    }
}
