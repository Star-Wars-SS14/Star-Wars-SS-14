public sealed partial class SWGlobalWarMarketConsoleMenu : SWGlobalWarWindow
{
    private readonly IPrototypeManager _prototypes;
    private readonly List<ProtoId<SWGlobalWarCommodityPrototype>> _commodities = new();
    private readonly List<ProtoId<SWGlobalWarPlanetPrototype>> _searchPlanets = new();
    private readonly Dictionary<ProtoId<SWGlobalWarCommodityPrototype>, SWGlobalWarMarketGoodRow> _goodsRows = new();
    private readonly Dictionary<string, SWGlobalWarShipmentRow> _shipmentRows = new();
    private readonly Dictionary<RichTextLabel, string> _displayedText = new();
    private readonly Dictionary<ProtoId<SWGlobalWarPlanetPrototype>, string> _planetNames = new();
    private readonly List<(string Key, SWGlobalWarShipmentView Shipment)> _visibleShipments = new();
    private SWGlobalWarMarketConsoleState? _state;
    private ProtoId<SWGlobalWarPlanetPrototype>? _selected;
    private (ProtoId<SWGlobalWarPlanetPrototype> From, ProtoId<SWGlobalWarPlanetPrototype> To)? _route;
    private ProtoId<SWGlobalWarCommodityPrototype>? _commodity;
    private SWGlobalWarMarketMapMode _mode;
    private bool _showTraffic = true;
    private bool _freightPage;
    private readonly SWGlobalWarMarketStats _mapStats = new(false);
    private readonly SWGlobalWarMarketStats _wideStats = new(true);
    private ProtoId<SWGlobalWarCommodityPrototype>? _openGood;
    private bool _deliveryAvailable;
    public event Action<SWGlobalWarFreightQuery>? PageRequested;

    public SWGlobalWarMarketConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        UseChartSize();
        _prototypes = IoCManager.Resolve<IPrototypeManager>();
        StyleInterface();
        InitializeFilters();
        InitializeFlowEditor();
        InitializeGrowth();
        InitializeForms();
        InitializeReturns();
        InitializeLanthanum();
        InitializeSupply();
        InitializeSupplyWork();
        InitializeMarketLayout();
        Map.PlanetSelected += id =>
        {
            _selected = id;
            _route = null;
            RequestPage();
            RefreshDetails();
        };
        Map.RouteSelected += (from, to) =>
        {
            _selected = null;
            _route = (from, to);
            RequestPage();
            ShowPage(true);
        };
        PlanetSearch.OnItemSelected += args =>
        {
            if (args.Id >= 0 && args.Id < _searchPlanets.Count)
            {
                PlanetSearch.SelectId(args.Id);
                Map.SelectPlanet(_searchPlanets[args.Id]);
            }
        };
        Overview.OnPressed += _ =>
        {
            _selected = null;
            _route = null;
            Map.ClearSelection();
            RequestPage();
            RefreshDetails();
        };
        TrafficToggle.OnPressed += _ =>
        {
            _showTraffic = !_showTraffic;
            RefreshFilters();
        };
        GoodsTab.OnPressed += _ => ShowPage(false);
        FreightTab.OnPressed += _ => ShowPage(true);
        PreviousPage.OnPressed += _ => RequestPage((_state?.Query.Page ?? 0) - 1);
        NextPage.OnPressed += _ => RequestPage((_state?.Query.Page ?? 0) + 1);
        ShowPage(false);
    }

    private void InitializeFilters()
    {
        CommodityFilter.AddItem(Loc.GetString("sw-global-war-market-all-goods"), 0);
        foreach (var prototype in _prototypes.EnumeratePrototypes<SWGlobalWarCommodityPrototype>()
                     .OrderBy(prototype => Loc.GetString(prototype.Name)).ThenBy(prototype => prototype.ID))
        {
            _commodities.Add(prototype.ID);
            CommodityFilter.AddItem(Loc.GetString(prototype.Name), _commodities.Count);
        }
        CommodityFilter.SelectId(0);
        CommodityFilter.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id > _commodities.Count)
                return;
            CommodityFilter.SelectId(args.Id);
            _commodity = args.Id == 0 ? (ProtoId<SWGlobalWarCommodityPrototype>?) null : _commodities[args.Id - 1];
            RequestPage();
            RefreshFilters();
        };
        var modes = new[] { "demand", "supply", "stock", "consumption", "incoming", "coverage", "balance" };
        for (var i = 0; i < modes.Length; i++)
            MetricFilter.AddItem(Loc.GetString($"sw-global-war-market-{modes[i]}"), i);
        MetricFilter.SelectId(0);
        MetricFilter.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= modes.Length)
                return;
            MetricFilter.SelectId(args.Id);
            _mode = (SWGlobalWarMarketMapMode) args.Id;
            RefreshFilters();
        };
    }

    public void UpdateState(SWGlobalWarMarketConsoleState state)
    {
        if (_state != null && (_state.Generation != state.Generation || _state.Assignment != state.Assignment ||
            _state.AssignmentRevision != state.AssignmentRevision))
        {
            _selected = null;
            _route = null;
            _commodity = null;
            CommodityFilter.SelectId(0);
            if (PlanetSearch.ItemCount > 0)
                PlanetSearch.SelectId(-1);
            Map.ClearSelection();
            Map.SetMarketFilter(null, _mode, _showTraffic);
            ResetFlowEditor();
        }
        PrepareFlowDraft(state);
        _state = state;
        _planetNames.Clear();
        foreach (var planet in state.Planets)
            _planetNames[planet.Planet] = planet.Name;
        RefreshFlowEditor();
        RefreshGrowth();
        RefreshReturns();
        RefreshLanthanum();
        RefreshSupply();
        RefreshSupplyWork();
        if (_selected is { } selected && !_planetNames.ContainsKey(selected))
            _selected = null;
        if (_route is { } route && !state.Connections.Any(link => SameLane(link.From, link.To, route.From, route.To)))
            _route = null;
        Map.SetMarketState(state);
        RefreshSearch();
        RefreshDetails();
        RefreshStatus();
    }

    private void RefreshStatus()
    {
        if (_state == null)
            return;
        // A working network needs no line of its own: the sums wait in the map's tooltip.
        StatusPanel.Visible = !_state.Ready;
        if (!_state.Ready)
        {
            SetText(NetworkStatus, Loc.GetString("sw-global-war-market-offline"));
            return;
        }
        var moving = _state.FreightTotals.Sum(total => total.Moving);
        var waiting = _state.FreightTotals.Sum(total => total.Waiting);
        TransitLegend.Text = Loc.GetString("sw-global-war-market-foot-moving", ("count", moving.ToString("0.###")));
        WaitingLegend.Text = Loc.GetString("sw-global-war-market-foot-waiting", ("count", waiting.ToString("0.###")));
        var commodityName = _commodity is { } selected ? Loc.GetString(_prototypes.Index(selected).Name)
            : Loc.GetString("sw-global-war-market-all-goods");
        SetText(NetworkStatus, Loc.GetString("sw-global-war-market-status-filtered", ("commodity", commodityName),
            ("planets", _state.Planets.Count), ("moving", moving.ToString("0.###")), ("waiting", waiting.ToString("0.###"))));
    }

    private void RefreshSearch()
    {
        if (_state == null || _searchPlanets.Count == _state.Planets.Count && _state.Planets.All(planet => _searchPlanets.Contains(planet.Planet))
            && PlanetSearch.ItemCount > 0)
            return;
        _searchPlanets.Clear();
        PlanetSearch.Clear();
        PlanetSearch.AddItem(Loc.GetString("sw-global-war-travel-search"), -1);
        PlanetSearch.SetItemDisabled(0, true);
        foreach (var planet in _state.Planets.OrderBy(planet => planet.Name))
        {
            PlanetSearch.AddItem(planet.Name, _searchPlanets.Count);
            _searchPlanets.Add(planet.Planet);
        }
        PlanetCount.Text = Loc.GetString("sw-global-war-travel-planet-count", ("count", _state.Planets.Count));
    }

    private void RefreshFilters()
    {
        Map.SetMarketFilter(_commodity, _mode, _showTraffic);
        TrafficToggle.SetAppearance(SWGlobalWarConsoleStyle.TextBright, selected: _showTraffic);
        RefreshDetails();
        RefreshStatus();
    }

    private void ShowPage(bool freight)
    {
        FlowsScroll.Visible = false;
        GrowthScroll.Visible = false;
        FlowsTab.SetAppearance(SWGlobalWarConsoleStyle.TextBright, selected: false, tab: true);
        GrowthTab.SetAppearance(SWGlobalWarConsoleStyle.TextBright, selected: false, tab: true);
        _freightPage = freight;
        GoodsScroll.Visible = !freight;
        FreightScroll.Visible = freight;
        GoodsTab.SetAppearance(SWGlobalWarConsoleStyle.TextBright, selected: !freight, tab: true);
        FreightTab.SetAppearance(SWGlobalWarConsoleStyle.TextBright, selected: freight, tab: true);
        RefreshDetails();
    }

    /// <summary>Updates stable market cards and filtered freight rows while retaining the selected planet and scroll containers.</summary>
    private void RefreshDetails()
    {
        if (_state == null)
            return;
        RefreshLanthanum();
        RefreshSupply();
        GoodsTab.Disabled = _route != null;
        var planet = _state.Planets.FirstOrDefault(entry => entry.Planet == _selected);
        var bidirectional = _route is { } path && _state.Connections.Any(link => link.From == path.To && link.To == path.From);
        CardName.Text = _route is { } route ? $"{PlanetName(route.From)} {(bidirectional ? "↔" : "→")} {PlanetName(route.To)}"
            : planet?.Name ?? Loc.GetString("sw-global-war-market-overview");
        RefreshCard(planet);
        var goods = (planet != null ? planet.Goods : _state.Planets.SelectMany(entry => entry.Goods))
            .Where(good => _commodity == null || good.Commodity == _commodity).ToArray();
        SetText(MarketSummary, planet is { Availability: not SWGlobalWarMarketAvailability.Ready }
            ? SWGlobalWarMarketPresentation.Availability(planet.Availability)
            : SWGlobalWarMarketPresentation.Summary(SWGlobalWarMarketTotals.From(goods)));
        var unavailable = planet is { Availability: not SWGlobalWarMarketAvailability.Ready };
        MarketSummary.Visible = unavailable;
        var totals = SWGlobalWarMarketTotals.From(goods);
        _mapStats.Update(totals);
        _wideStats.Update(totals);
        SetText(EmptyGoods, planet is { Availability: not SWGlobalWarMarketAvailability.Ready }
            ? SWGlobalWarMarketPresentation.Availability(planet.Availability)
            : Loc.GetString("sw-global-war-market-empty-goods"));
        var groups = goods.GroupBy(good => good.Commodity).OrderBy(group => Loc.GetString(_prototypes.Index(group.Key).Name)).ToArray();
        var activeGoods = groups.Select(group => group.Key).ToHashSet();
        foreach (var id in _goodsRows.Keys.Where(id => !activeGoods.Contains(id)).ToArray())
        {
            GoodsRows.RemoveChild(_goodsRows[id]);
            _goodsRows.Remove(id);
        }
        for (var index = 0; index < groups.Length; index++)
        {
            var group = groups[index];
            if (!_goodsRows.TryGetValue(group.Key, out var row))
            {
                row = new SWGlobalWarMarketGoodRow(_prototypes.Index(group.Key));
                var commodity = group.Key;
                row.OnPressed += _ =>
                {
                    _openGood = _openGood == commodity ? (ProtoId<SWGlobalWarCommodityPrototype>?) null : commodity;
                    RefreshDetails();
                };
                row.SetShape(!MarketLayout.ShowMap);
                row.SetNarrow(Size.X < NarrowTableWidth);
                _goodsRows.Add(group.Key, row);
                GoodsRows.AddChild(row);
            }
            if (GoodsRows.GetChild(index) != row)
                row.SetPositionInParent(index);
            row.Update(SWGlobalWarMarketTotals.From(group));
            row.SetOpen(_openGood == group.Key);
            row.SetShape(!MarketLayout.ShowMap);
        }
        RefreshDelivery(groups.FirstOrDefault(group => group.Key == _openGood));
        EmptyGoods.Visible = groups.Length == 0;
        RefreshShipments();
    }

    /// <summary>The planet's card: what it does, its name and the world itself. A route and the overview have no world to show.</summary>
    private void RefreshCard(SWGlobalWarPlanetMarketView? planet)
    {
        CardPlanet.Visible = planet != null;
        CardKind.Visible = planet != null;
        CardStateRow.Visible = planet != null && (MarketLayout.ShowMap || planet.Availability != SWGlobalWarMarketAvailability.Ready);
        PlanetCard.ToolTip = planet != null ? _prototypes.Index(planet.Planet).Description
            : Loc.GetString(_route != null ? "sw-global-war-market-link-hint" : "sw-global-war-market-select-hint");
        if (planet == null)
            return;

        var prototype = _prototypes.Index(planet.Planet);
        CardKind.Text = Loc.GetString("sw-global-war-travel-kind-" + prototype.Kind.ToString().ToLowerInvariant());
        CardKind.FontColorOverride = SWGlobalWarConsoleStyle.SideText(planet.Owner ?? prototype.InitialOwner);

        var ready = planet.Availability == SWGlobalWarMarketAvailability.Ready;
        CardState.Text = ready ? Loc.GetString("sw-global-war-market-card-ready") : SWGlobalWarMarketPresentation.Availability(planet.Availability);
        CardState.FontColorOverride = ready ? SWGlobalWarConsoleStyle.Good : SWGlobalWarConsoleStyle.Bad;
        CardStateIcon.Visible = !ready;
        if (!ready)
            CardStateIcon.Texture = SWGlobalWarConsoleStyle.Art("status", SWGlobalWarMarketPresentation.AvailabilityIcon(planet.Availability));

        // Beside the map the card is the atlas's, with the world half out of it. In the table it is small.
        var art = SWGlobalWarConsoleStyle.ArtScale / UIScale;
        var large = MarketLayout.ShowMap;
        CardPlanet.Texture = SWGlobalWarMapControl.PlanetTexture(planet.Planet.Id, large ? "planets_large" : "planets_small");
        CardPlanet.TextureScale = new Vector2(art);
        CardPlanet.SetSize = new Vector2((large ? 80 : 28) * art);
        CardPlanet.Margin = large ? new Thickness(0, 0, -24 * art, 0) : new Thickness(0, 0, 4, 0);
    }

    /// <summary>One order button under the list. Beside the map it comes only for a good that runs short.</summary>
    private void RefreshDelivery(IGrouping<ProtoId<SWGlobalWarCommodityPrototype>, SWGlobalWarMarketGoodView>? good)
    {
        _deliveryAvailable = false;
        if (good == null)
            return;

        var totals = SWGlobalWarMarketTotals.From(good);
        var name = Loc.GetString(_prototypes.Index(good.Key).Name);
        _deliveryAvailable = _selected != null && _state?.Assignment != Guid.Empty
            && (!MarketLayout.ShowMap || totals.Uncovered > 0);
        Delivery.Text = Loc.GetString("sw-global-war-market-order-delivery", ("name", name));
        DeliveryLine.Text = totals.Uncovered > 0
            ? Loc.GetString("sw-global-war-market-short-line", ("name", name), ("count", totals.Uncovered.ToString("0.###")))
            : string.Empty;
        DeliveryLine.Visible = MarketLayout.ShowMap == false;
    }

    private void RefreshShipments()
    {
        if (_state == null)
            return;
        var shipments = _state.Shipments.Where(shipment => (_commodity == null || shipment.Commodity == _commodity)
            && (_selected == null || shipment.Route.Contains(_selected.Value))
            && (_route is not { } route || SameLane(shipment.From, shipment.To, route.From, route.To)))
            .GroupBy(ShipmentKey).Select(group => (Key: group.Key, Shipment: group.First() with { Quantity = group.Sum(shipment => shipment.Quantity) }))
            .OrderBy(entry => entry.Shipment.ArrivesAt != null).ThenBy(entry => entry.Shipment.ArrivesAt).ToArray();
        var active = shipments.Select(entry => entry.Key).ToHashSet();
        foreach (var key in _shipmentRows.Keys.Where(key => !active.Contains(key)).ToArray())
        {
            ShipmentRows.RemoveChild(_shipmentRows[key]);
            _shipmentRows.Remove(key);
        }
        _visibleShipments.Clear();
        for (var index = 0; index < shipments.Length; index++)
        {
            var entry = shipments[index];
            if (!_shipmentRows.TryGetValue(entry.Key, out var row))
            {
                row = new SWGlobalWarShipmentRow(_prototypes.Index(entry.Shipment.Commodity));
                var shipmentId = entry.Shipment.Id;
                row.ReturnRequested += () => SelectReturn(shipmentId);
                _shipmentRows.Add(entry.Key, row);
                ShipmentRows.AddChild(row);
            }
            if (ShipmentRows.GetChild(index) != row)
                row.SetPositionInParent(index);
            _visibleShipments.Add(entry);
            row.SetReturnAvailable(_state.ReturnCandidates.Any(c => c.Part.Shipment == entry.Shipment.Id),
                FlowDraft.PendingReturn == null);
        }
        EmptyShipments.Visible = shipments.Length == 0;
        FreightSummary.Visible = !MarketLayout.ShowMap;
        PreviousPage.Parent!.Visible = _state.TotalShipments > SWGlobalWarMarketConsoleState.ShipmentPageSize;
        SetText(FreightSummary, Loc.GetString("sw-global-war-market-freight-summary",
            ("moving", _state.FreightTotals.Sum(total => total.Moving).ToString("0.###")),
            ("waiting", _state.FreightTotals.Sum(total => total.Waiting).ToString("0.###"))));
        PreviousPage.Disabled = _state.Query.Page == 0;
        NextPage.Disabled = (_state.Query.Page + 1) * SWGlobalWarMarketConsoleState.ShipmentPageSize >= _state.TotalShipments;
        FreightPage.Text = Loc.GetString("sw-global-war-market-page", ("page", _state.Query.Page + 1),
            ("pages", Math.Max(1, (_state.TotalShipments + SWGlobalWarMarketConsoleState.ShipmentPageSize - 1) /
                SWGlobalWarMarketConsoleState.ShipmentPageSize)), ("count", _state.TotalShipments));
        var link = _route is { } selectedRoute ? _state.Connections.FirstOrDefault(connection => connection.From == selectedRoute.From
            && connection.To == selectedRoute.To) : null;
        LinkInfo.Visible = LinkLoad.Visible = link != null;
        if (link != null)
        {
            SetText(LinkInfo, Loc.GetString(link.OccupancyComplete ? "sw-global-war-market-link-info" : "sw-global-war-market-link-visible", ("used", link.InFlightVolume.ToString("0.##")),
                ("capacity", link.Capacity.ToString("0.##")), ("seconds", link.TravelTime.TotalSeconds.ToString("0.##"))));
            LinkLoad.Value = link.InFlightVolume;
            LinkLoad.Maximum = link.Capacity;
            LinkLoad.Fill = link.InFlightVolume >= link.Capacity && link.Capacity > 0 ? SWGlobalWarConsoleStyle.Brass : SWGlobalWarConsoleStyle.Accent;
        }
        RefreshShipmentTimes();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateMarketLayout();
        if (_freightPage)
            RefreshShipmentTimes();
        // The other tabs hide this scroll without telling the goods page.
        DeliveryFoot.Visible = GoodsScroll.Visible && _deliveryAvailable;
        Delivery.Disabled = FlowPending;
    }

    private void RefreshShipmentTimes()
    {
        if (_state == null)
            return;
        foreach (var (key, shipment) in _visibleShipments)
        {
            var duration = _state.Connections.FirstOrDefault(link => link.From == shipment.From && link.To == shipment.To)?.TravelTime
                ?? TimeSpan.FromSeconds(1);
            _shipmentRows[key].Update(shipment, Map.MarketDisplayTime, PlanetName, duration);
        }
    }

    private void RequestPage(int page = 0)
    {
        PageRequested?.Invoke(new(_selected, _commodity, _route?.From, _route?.To, Math.Max(0, page),
            SupplyKind: FlowDraft.SupplyKind));
    }

    private string PlanetName(ProtoId<SWGlobalWarPlanetPrototype> id) => _planetNames.GetValueOrDefault(id, id.Id);

    private static bool SameLane(ProtoId<SWGlobalWarPlanetPrototype> from, ProtoId<SWGlobalWarPlanetPrototype> to,
        ProtoId<SWGlobalWarPlanetPrototype> a, ProtoId<SWGlobalWarPlanetPrototype> b) => from == a && to == b || from == b && to == a;

    private static string ShipmentKey(SWGlobalWarShipmentView shipment) =>
        $"{shipment.Id}|{shipment.Origin}|{shipment.Owner}|{shipment.Captured}|{shipment.Returning}|{shipment.HoldReason}|{shipment.Commodity.Id}|{string.Join('>', shipment.Route.Select(planet => planet.Id))}|{shipment.Leg}|{shipment.DepartedAt.Ticks}|{shipment.ArrivesAt?.Ticks}";

    private void SetText(RichTextLabel label, string text)
    {
        if (_displayedText.TryGetValue(label, out var previous) && previous == text)
            return;
        _displayedText[label] = text;
        label.SetMessage(SWGlobalWarConsoleStyle.MoneyMessage(text));
    }

