using Content.Shared._SW.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Content.Client._SW.Economy.UI;
[GenerateTypedNameReferences]
public sealed partial class SWWithdrawalWindow : DefaultWindow
{
    public SWWithdrawalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void PopulateCurrencies (List<ProtoId<SWCurrencyPrototype>> currencies)
    {
        RequestsList.Children.Clear();
        foreach (var currency in currencies)
        {
            var cntrl = new SWWithdrawalControl(currency);
            RequestsList.AddChild(cntrl);
        }
    }

    public override void Close()
    {
        base.Close();

    }
}
