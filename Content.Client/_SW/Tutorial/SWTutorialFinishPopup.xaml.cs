using Content.Client._SW.UserInterface;
using Content.Shared._SW.Tutorial;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.Tutorial;

/// <summary>
/// The last screen: what to do first in a real round, and the choice of a side. The smaller side says so in words and
/// is the one main button; the colour stays neutral, because this window belongs to no faction.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SWTutorialFinishPopup : Control
{
    public event Action<SWTutorialSide>? OnSide;
    public event Action? OnClose;

    public SWTutorialFinishPopup(SWTutorialFinishedEvent ev)
    {
        RobustXamlLoader.Load(this);

        RepublicButton.Visible = ev.RoundStarted;
        EmpireButton.Visible = ev.RoundStarted;
        WaitLabel.Visible = !ev.RoundStarted;

        SetSide(RepublicButton, "sw-tutorial-finish-republic", ev.RepublicAlive, ev.RepublicAlive < ev.EmpireAlive);
        SetSide(EmpireButton, "sw-tutorial-finish-empire", ev.EmpireAlive, ev.EmpireAlive < ev.RepublicAlive);

        RepublicButton.OnPressed += _ => OnSide?.Invoke(SWTutorialSide.Republic);
        EmpireButton.OnPressed += _ => OnSide?.Invoke(SWTutorialSide.Empire);
        CloseButton.OnPressed += _ => OnClose?.Invoke();
    }

    private static void SetSide(Button button, string text, int alive, bool weaker)
    {
        button.Text = Loc.GetString(text, ("alive", alive), ("weaker", weaker ? "true" : "false"));
        button.AddStyleClass(weaker ? SWTerminalStyle.MainButton + SWTerminalStyle.NeutralAccent : SWTerminalStyle.Button);
    }
}
