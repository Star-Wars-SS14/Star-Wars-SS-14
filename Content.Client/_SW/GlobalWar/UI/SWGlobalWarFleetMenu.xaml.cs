using System.Numerics;
using Content.Shared._SW.GlobalWar.Combat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarFleetMenu : SWGlobalWarWindow
{
    public event Action<SWGlobalWarShipClass, Guid, bool>? Requested;
    private const int CardsInRow = 3;
    private SWGlobalWarFleetView? _view;

    public SWGlobalWarFleetMenu()
    {
        RobustXamlLoader.Load(this);
        ContentsContainer.Margin = new Thickness(0);
        HelpMark.ToolTip = Loc.GetString("sw-global-war-fleet-instructions");
        BudgetWord.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        BudgetWord.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        BudgetValue.FontOverride = SWGlobalWarConsoleStyle.Bold(22);
        BudgetValue.FontColorOverride = SWGlobalWarConsoleStyle.Money;
        EmptyOrders.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        HeadDecision.OnToggled += _ => { if (_view != null) UpdateState(_view); };
    }

    public void UpdateState(SWGlobalWarFleetView view)
    {
        _view = view;
        Budget.SetMessage(SWGlobalWarConsoleStyle.MoneyMessage(Loc.GetString("sw-global-war-fleet-budget", ("amount", view.Available))));
        BudgetValue.Text = Loc.GetString("sw-global-war-finance-sum", ("sum", view.Available));
        Reason.SetMessage(Loc.GetString($"sw-global-war-fleet-{view.Reason}"));
        HeadDecision.Visible = view.Head;
        var allowed = view.Authorized && (!view.Head || HeadDecision.Pressed);
        var side = SWGlobalWarConsoleStyle.SideLetter();
        Scene.Scene = SWGlobalWarConsoleStyle.Picture("fleet_" + side);
        Offers.RemoveAllChildren();
        BoxContainer? shelf = null;
        foreach (var offer in view.Offers)
        {
            if (shelf == null || shelf.ChildCount >= CardsInRow)
            {
                shelf = new BoxContainer { SeparationOverride = 8, HorizontalExpand = true };
                Offers.AddChild(shelf);
            }

            shelf.AddChild(Card(offer, view, allowed, side));
        }

        Orders.RemoveAllChildren();
        EmptyOrders.Visible = view.Orders.Length == 0;
        foreach (var order in view.Orders)
        {
            // A status can be a whole sentence, so it goes under the name and is given whole in the tooltip.
            var status = Loc.GetString($"sw-global-war-fleet-status-{order.Status}");
            var (row, line) = Row(ShipName(order.Class), Loc.GetString("sw-global-war-travel-time-short", ("seconds", order.Seconds)) + ". " + status);
            row.ToolTip = status;
            line.AddChild(Hull(order.Class, side, new Vector2(56, 36)));
            line.GetChild(line.ChildCount - 1).SetPositionFirst();
            var cancel = new SWGlobalWarConsoleButton { Text = Loc.GetString("sw-global-war-fleet-cancel-short"), ToolTip = Loc.GetString("sw-global-war-fleet-cancel"), Disabled = !allowed || !order.CanCancel };
            cancel.OnPressed += _ => Requested?.Invoke(order.Class, order.Id, HeadDecision.Pressed);
            line.AddChild(cancel);
            Orders.AddChild(row);
        }
    }

    /// <summary>The ship on the yard's drawing board. Its shape comes from the real ship's map.</summary>
    private PanelContainer Card(SWGlobalWarFleetOffer offer, SWGlobalWarFleetView view, bool allowed, string side)
    {
        var enough = view.Available >= offer.Price;
        var open = allowed && offer.Available && enough;
        var board = new Control { SetHeight = 92, RectClipContent = true, HorizontalExpand = true };
        board.AddChild(new TextureRect { Texture = SWGlobalWarConsoleStyle.Picture("yard_" + side), Stretch = TextureRect.StretchMode.KeepAspectCovered, HorizontalExpand = true, VerticalExpand = true });
        var hull = Hull(offer.Class, side, new Vector2(200, 84));
        hull.Modulate = offer.Available ? Color.White : Color.White.WithAlpha(.35f);
        hull.HorizontalAlignment = HAlignment.Center;
        hull.VerticalAlignment = VAlignment.Center;
        board.AddChild(hull);

        var words = new BoxContainer { SeparationOverride = 8, Margin = new Thickness(10, 6, 10, 0) };
        words.AddChild(new Label { Text = ShipName(offer.Class), HorizontalExpand = true, ClipText = true, FontOverride = SWGlobalWarConsoleStyle.Strong, FontColorOverride = Color.White });
        words.AddChild(new Label { Text = Loc.GetString("sw-global-war-finance-sum", ("sum", offer.Price)), FontOverride = SWGlobalWarConsoleStyle.Strong, FontColorOverride = enough ? SWGlobalWarConsoleStyle.Money : SWGlobalWarConsoleStyle.TextDim });

        var foot = new BoxContainer { SeparationOverride = 8, Margin = new Thickness(10, 2, 10, 8) };
        foot.AddChild(new Label { Text = Loc.GetString("sw-global-war-travel-time-short", ("seconds", offer.Seconds)), VAlign = Label.VAlignMode.Center, FontOverride = SWGlobalWarConsoleStyle.Small, FontColorOverride = SWGlobalWarConsoleStyle.TextDim });
        var buy = new SWGlobalWarConsoleButton
        {
            Text = Loc.GetString(!offer.Available ? "sw-global-war-fleet-buy-closed" : !enough ? "sw-global-war-fleet-buy-poor" : "sw-global-war-fleet-buy"),
            Disabled = !open,
            HorizontalExpand = true,
            MinHeight = 36,
        };
        buy.SetAppearance(SWGlobalWarConsoleStyle.TextBright, money: true);
        buy.OnPressed += _ => Requested?.Invoke(offer.Class, Guid.Empty, HeadDecision.Pressed);
        foot.AddChild(buy);

        var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 0 };
        body.AddChild(board);
        body.AddChild(words);
        body.AddChild(foot);
        var card = new PanelContainer { HorizontalExpand = true, PanelOverride = SWGlobalWarConsoleStyle.RowBox(false), Margin = new Thickness(0) };
        card.AddChild(body);
        return card;
    }

    private static TextureRect Hull(SWGlobalWarShipClass shipClass, string side, Vector2 size) => new()
    {
        Texture = SWGlobalWarConsoleStyle.Picture($"ship_{shipClass}_{side}"),
        Stretch = TextureRect.StretchMode.KeepCentered,
        SetSize = size,
        VerticalAlignment = VAlignment.Center,
        RectClipContent = true,
    };

    private static (PanelContainer Row, BoxContainer Line) Row(string name, string time)
    {
        var line = new BoxContainer { SeparationOverride = 8, HorizontalExpand = true, Margin = new Thickness(10, 4), MinHeight = 38 };
        var words = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
        words.AddChild(new Label { Text = name, ClipText = true, FontOverride = SWGlobalWarConsoleStyle.Strong, FontColorOverride = Color.White });
        words.AddChild(new Label { Text = time, ClipText = true, FontOverride = SWGlobalWarConsoleStyle.Small, FontColorOverride = SWGlobalWarConsoleStyle.TextDim });
        line.AddChild(words);
        var row = new PanelContainer { HorizontalExpand = true, PanelOverride = SWGlobalWarConsoleStyle.RowBox(false) };
        row.AddChild(line);
        return (row, line);
    }

    private static string ShipName(SWGlobalWarShipClass shipClass) =>
        Loc.GetString($"sw-global-war-fleet-class-{shipClass.ToString().ToLowerInvariant()}");
}
