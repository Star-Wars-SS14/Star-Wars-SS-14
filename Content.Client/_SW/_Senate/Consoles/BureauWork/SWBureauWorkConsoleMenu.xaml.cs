using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate.Consoles.BureauWork;

[GenerateTypedNameReferences]
public sealed partial class SWBureauWorkConsoleMenu : FancyWindow
{
    private readonly SWBureauWorkConsoleBoundUserInterface _owner;

    public SWBureauWorkConsoleMenu(SWBureauWorkConsoleBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        _owner = owner;

        SWConsoleStyle.StyleRoot(RootPanel);
        SWConsoleStyle.StyleHeader(HeaderPanel);
        HeaderTitle.FontOverride = SWConsoleStyle.MonoBold;
        HeaderTitle.FontColorOverride = SWConsoleStyle.Accent;
        HeaderTitle.Text = "РАБОЧАЯ КОНСОЛЬ БЮРО";
        LiveDot.PanelOverride = new StyleBoxFlat { BackgroundColor = SWConsoleStyle.Good };
        HeaderClock.FontOverride = SWConsoleStyle.Mono;
        HeaderClock.FontColorOverride = SWConsoleStyle.TextBright;
    }

    public void SetState(SWBureauWorkConsoleState state)
    {
        HeaderClock.Text = string.IsNullOrEmpty(state.GameTime) ? "—" : state.GameTime;
        BureauList.RemoveAllChildren();

        if (!state.HasCard)
        {
            BureauList.AddChild(SWConsoleStyle.Text("Вставьте ID-карту министра в консоль.", SWConsoleStyle.TextDim, SWConsoleStyle.Mono));
            return;
        }

        if (!state.HasBureau)
        {
            BureauList.AddChild(SWConsoleStyle.Text("Эта карта не закреплена ни за одним бюро. Займите бюро на консоли назначения.", SWConsoleStyle.TextDim, SWConsoleStyle.Mono));
            return;
        }

        BuildHeader(state);
        BuildDilemma(state);

        if (state.IsShips)
            BuildShips(state);

        BuildRequests(state);
    }

    private void BuildRequests(SWBureauWorkConsoleState state)
    {
        BureauList.AddChild(new Control { MinHeight = 12 });
        BureauList.AddChild(SWConsoleStyle.Section("ЗАЯВКИ СЕНАТОРОВ"));
        BureauList.AddChild(SWConsoleStyle.Text($"Админ-ресурс: {state.Admin}  ·  аудит: {state.AuditCost}", SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
        BureauList.AddChild(new Control { MinHeight = 4 });

        if (state.Requests.Count == 0)
        {
            BureauList.AddChild(SWConsoleStyle.Text("Обращений в бюро нет.", SWConsoleStyle.TextDim, SWConsoleStyle.Mono));
            return;
        }

        foreach (var req in state.Requests)
        {
            var card = SWConsoleStyle.Row(SWConsoleStyle.BgPanel, SWConsoleStyle.Accent);
            card.Margin = new Thickness(0, 0, 0, 6);
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            box.AddChild(SWConsoleStyle.Text(req.ProblemName, SWConsoleStyle.TextBright, SWConsoleStyle.MonoBold));
            box.AddChild(SWConsoleStyle.Text($"{req.OwnerLabel}  ·  {req.DeadlineLabel}", SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
            if (!string.IsNullOrWhiteSpace(req.ProblemDescription))
            {
                var desc = new RichTextLabel { Margin = new Thickness(0, 2, 0, 0) };
                desc.SetMessage(req.ProblemDescription);
                box.AddChild(desc);
            }

            box.AddChild(SWConsoleStyle.Text($"Проверка: {req.AuditLabel}", req.Audited ? SWConsoleStyle.Good : SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
            if (req.Audited && !string.IsNullOrWhiteSpace(req.IssueDescription))
                box.AddChild(SWConsoleStyle.Text(req.IssueDescription, SWConsoleStyle.Warn, SWConsoleStyle.MonoSmall));

            var id = req.Id;
            var top = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 3, 0, 0) };
            var audit = SWConsoleStyle.Action("Проверить", SWConsoleStyle.Warn, !req.CanAudit);
            if (req.CanAudit)
                audit.OnPressed += _ => _owner.AuditRequest(id);
            top.AddChild(audit);
            var refuse = SWConsoleStyle.Action("Отказать", SWConsoleStyle.Bad);
            refuse.Margin = new Thickness(6, 0, 0, 0);
            refuse.OnPressed += _ => _owner.RefuseRequest(id);
            top.AddChild(refuse);
            box.AddChild(top);

            for (var i = 0; i < req.Options.Count; i++)
            {
                var opt = req.Options[i];
                var idx = i;
                var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 3, 0, 0) };
                row.AddChild(EffectsRow(opt.Effects));
                var label = opt.Cost > 0 ? $"{opt.Label}  ({opt.Cost} кр)" : opt.Label;
                var btn = SWConsoleStyle.Action(label, opt.Affordable ? SWConsoleStyle.Good : SWConsoleStyle.TextDim, !opt.Affordable);
                btn.HorizontalAlignment = Control.HAlignment.Left;
                if (opt.Affordable)
                    btn.OnPressed += _ => _owner.ResolveRequest(id, idx);
                row.AddChild(btn);
                box.AddChild(row);
            }

            card.AddChild(box);
            BureauList.AddChild(card);
        }
    }

    private void BuildHeader(SWBureauWorkConsoleState state)
    {
        var card = SWConsoleStyle.Row(SWConsoleStyle.BgPanel, state.BureauColor);
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        box.AddChild(SWConsoleStyle.Text(state.BureauName, state.BureauColor, SWConsoleStyle.MonoLarge));
        box.AddChild(SWConsoleStyle.Text(state.BureauTitle, SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
        if (!string.IsNullOrWhiteSpace(state.BureauDescription))
            box.AddChild(SWConsoleStyle.Text(state.BureauDescription, SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
        card.AddChild(box);
        BureauList.AddChild(card);

        var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 0) };
        line.AddChild(SWConsoleStyle.Text($"Бюджет: {state.Budget} кр", SWConsoleStyle.Warn, SWConsoleStyle.MonoBold));
        line.AddChild(new Control { HorizontalExpand = true });
        if (state.CanResign)
        {
            var resign = SWConsoleStyle.Action("Сложить полномочия", SWConsoleStyle.Bad);
            resign.OnPressed += _ => _owner.Resign();
            line.AddChild(resign);
        }
        BureauList.AddChild(line);
    }

    private void BuildDilemma(SWBureauWorkConsoleState state)
    {
        BureauList.AddChild(new Control { MinHeight = 12 });
        BureauList.AddChild(SWConsoleStyle.Section("ТЕКУЩАЯ ДИЛЕММА"));
        BureauList.AddChild(new Control { MinHeight = 4 });

        if (state.Dilemma is not { } dil)
        {
            BureauList.AddChild(SWConsoleStyle.Text("Сейчас нет активной дилеммы. Ожидайте следующую.", SWConsoleStyle.TextDim, SWConsoleStyle.Mono));
            return;
        }

        var card = SWConsoleStyle.Row(SWConsoleStyle.BgPanel, SWConsoleStyle.Warn);
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        box.AddChild(SWConsoleStyle.Text(dil.Name, SWConsoleStyle.TextBright, SWConsoleStyle.MonoBold));
        if (!string.IsNullOrWhiteSpace(dil.Description))
        {
            var desc = new RichTextLabel { Margin = new Thickness(0, 2, 0, 0) };
            desc.SetMessage(dil.Description);
            box.AddChild(desc);
        }
        box.AddChild(SWConsoleStyle.Text(dil.TimeLabel, SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
        card.AddChild(box);
        BureauList.AddChild(card);

        for (var i = 0; i < dil.Options.Count; i++)
        {
            var opt = dil.Options[i];
            var idx = i;
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 3, 0, 0) };
            row.AddChild(EffectsRow(opt.Effects));
            if (!string.IsNullOrWhiteSpace(opt.Description))
                row.AddChild(SWConsoleStyle.Text(opt.Description, SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
            var btn = SWConsoleStyle.Action(opt.Label, opt.Affordable ? SWConsoleStyle.Accent : SWConsoleStyle.TextDim, !opt.Affordable);
            btn.HorizontalAlignment = Control.HAlignment.Left;
            btn.Margin = new Thickness(0, 2, 0, 0);
            if (opt.Affordable)
                btn.OnPressed += _ => _owner.ResolveDilemma(idx);
            row.AddChild(btn);
            BureauList.AddChild(row);
        }
    }

    private void BuildShips(SWBureauWorkConsoleState state)
    {
        BureauList.AddChild(new Control { MinHeight = 12 });
        BureauList.AddChild(SWConsoleStyle.Section("ТРАНСПОНДЕРНЫЙ РЕЕСТР"));
        BureauList.AddChild(new Control { MinHeight = 4 });

        BureauList.AddChild(SWConsoleStyle.Text($"Торговый поток: {state.TradeFlow}/100 — {state.TradeFlowStatus}",
            SWConsoleStyle.ValueColor(state.TradeFlow), SWConsoleStyle.MonoBold));
        BureauList.AddChild(SWConsoleStyle.Bar(state.TradeFlow, 0, 100, SWConsoleStyle.ValueColor(state.TradeFlow)));
        if (state.ForgedActive > 0)
            BureauList.AddChild(SWConsoleStyle.Text($"Фальшивые транспондеры в обороте: {state.ForgedActive}", SWConsoleStyle.Bad, SWConsoleStyle.MonoSmall));

        BureauList.AddChild(new Control { MinHeight = 6 });
        BureauList.AddChild(SWConsoleStyle.Text($"Режим реестра: {state.PolicyLabel}", SWConsoleStyle.TextBright, SWConsoleStyle.MonoBold));
        var policyRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 2, 0, 0) };
        AddPolicyButton(policyRow, state, 0, "Свободный");
        AddPolicyButton(policyRow, state, 1, "Баланс");
        AddPolicyButton(policyRow, state, 2, "Строгий");
        BureauList.AddChild(policyRow);

        BureauList.AddChild(new Control { MinHeight = 8 });
        BureauList.AddChild(SWConsoleStyle.Text("Заявки на регистрацию", SWConsoleStyle.Accent, SWConsoleStyle.MonoBold));
        BureauList.AddChild(SWConsoleStyle.Text("Досмотр вскрывает истинный риск. Одобрение поддельного транспондера сеет контрабанду.",
            SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
        BureauList.AddChild(new Control { MinHeight = 4 });

        if (state.Applications.Count == 0)
        {
            BureauList.AddChild(SWConsoleStyle.Text("Очередь заявок пуста.", SWConsoleStyle.TextDim, SWConsoleStyle.Mono));
            return;
        }

        var alt = false;
        foreach (var app in state.Applications)
        {
            var row = SWConsoleStyle.Row(alt ? SWConsoleStyle.BgRowAlt : SWConsoleStyle.BgPanel);
            alt = !alt;
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };

            var top = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            var name = SWConsoleStyle.Text($"{app.Name} · {app.Origin}", SWConsoleStyle.TextBright, SWConsoleStyle.MonoBold);
            name.HorizontalExpand = true;
            top.AddChild(name);
            top.AddChild(SWConsoleStyle.Text(app.RiskLabel, app.RiskColor, SWConsoleStyle.MonoSmall));
            box.AddChild(top);

            var id = app.Id;
            var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 3, 0, 0) };
            var approve = SWConsoleStyle.Action("Одобрить", SWConsoleStyle.Good);
            approve.OnPressed += _ => _owner.ProcessApp(id, 0);
            buttons.AddChild(approve);
            var inspect = SWConsoleStyle.Action(app.Inspected ? "Проверено" : $"Досмотр ({app.InspectCost})", SWConsoleStyle.Warn, !app.CanInspect);
            inspect.Margin = new Thickness(6, 0, 0, 0);
            if (app.CanInspect)
                inspect.OnPressed += _ => _owner.ProcessApp(id, 1);
            buttons.AddChild(inspect);
            var deny = SWConsoleStyle.Action("Отказать", SWConsoleStyle.Bad);
            deny.Margin = new Thickness(6, 0, 0, 0);
            deny.OnPressed += _ => _owner.ProcessApp(id, 2);
            buttons.AddChild(deny);
            box.AddChild(buttons);

            row.AddChild(box);
            BureauList.AddChild(row);
        }
    }

    private void AddPolicyButton(BoxContainer row, SWBureauWorkConsoleState state, int level, string label)
    {
        var btn = SWConsoleStyle.Action(label, state.Policy == level ? SWConsoleStyle.Accent : SWConsoleStyle.Neutral, state.Policy == level);
        btn.Margin = new Thickness(0, 0, 6, 0);
        if (state.Policy != level)
            btn.OnPressed += _ => _owner.SetPolicy(level);
        row.AddChild(btn);
    }

    private static Control EffectsRow(System.Collections.Generic.List<SWBillEffectEntry> effects)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        foreach (var e in effects)
        {
            var label = SWConsoleStyle.Text($"{e.StatName} {e.Delta:+0;-0}", e.Color, SWConsoleStyle.MonoSmall);
            label.Margin = new Thickness(0, 0, 10, 0);
            row.AddChild(label);
        }
        return row;
    }
}
