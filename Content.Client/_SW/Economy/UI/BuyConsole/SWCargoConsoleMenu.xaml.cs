using System.Linq;
using Content.Client.Cargo.Systems;
using Content.Client.Cargo.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._SW.Economy;
using Content.Shared.Cargo;
using Content.Shared.Cargo.Components;
using Content.Shared.Cargo.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Toolshed.TypeParsers;
using static Robust.Client.UserInterface.Controls.BaseButton;

namespace Content.Client._SW.Economy.UI.BuyConsole;

[GenerateTypedNameReferences]
public sealed partial class SWCargoConsoleMenu : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    private readonly SWSharedBankSystem _swBankSystem = default!;

    private readonly IEntityManager _entityManager;
    private readonly IPrototypeManager _protoManager;
    private readonly SpriteSystem _spriteSystem;
    private EntityUid _owner;

    private List<SWCurrencyPrototype> _currencyPrototypes = new();
    private List<string> _currencyPrototypeIds = new();

    public event Action<ButtonEventArgs>? OnItemSelected;

    private readonly List<string> _categoryStrings = new();
    private string? _category;
    public Dictionary<ProtoId<SWCurrencyPrototype>, float> Balance = new();
    public List<ProtoId<SWCargoProductPrototype>> ProductCatalogue = new();

    public event Action? OnWithdrawalButtonPressed;
    public event Action? OnAddMoneyButtonPressed;

    public SWCargoConsoleMenu(EntityUid owner, IEntityManager entMan, IPrototypeManager protoManager, SpriteSystem spriteSystem)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _entityManager = entMan;
        _protoManager = protoManager;
        _spriteSystem = spriteSystem;
        _swBankSystem = entMan.System<SWSharedBankSystem>();
        _owner = owner;

        _currencyPrototypes = _protoManager.EnumeratePrototypes<SWCurrencyPrototype>().ToList();
        _currencyPrototypeIds = _currencyPrototypes.Select(c => c.ID).ToList();
        Title = entMan.GetComponent<MetaDataComponent>(owner).EntityName;

        SearchBar.OnTextChanged += OnSearchBarTextChanged;
        Categories.OnItemSelected += OnCategoryItemSelected;

        TabContainer.SetTabTitle(0, Loc.GetString("cargo-console-menu-tab-title-orders"));
        TabContainer.SetTabTitle(1, Loc.GetString("cargo-console-menu-tab-title-pay"));

        MoneyOutButton.OnPressed += (_) => OnWithdrawalButtonPressed?.Invoke();
        MoneyInButton.OnPressed += (_) => OnAddMoneyButtonPressed?.Invoke();
    }

    private void OnCategoryItemSelected(OptionButton.ItemSelectedEventArgs args)
    {
        SetCategoryText(args.Id);
        PopulateProducts();
    }

    private void OnSearchBarTextChanged(LineEdit.LineEditEventArgs args)
    {
        PopulateProducts();
    }

    private void SetCategoryText(int id)
    {
        _category = id == 0 ? null : _categoryStrings[id];
        Categories.SelectId(id);
    }

    public void PopulateBalance(Dictionary<ProtoId<SWCurrencyPrototype>, float> balance)
    {
        Balance = balance;
        BalanceContainer.Children.Clear();
        foreach (var (currency, amount) in Balance)
        {
            var cntrl = new SWCurrencyControl(currency, amount, false);
            BalanceContainer.AddChild(cntrl);
        }
    }
    private IEnumerable<SWCargoProductPrototype> ProductPrototypes
    {
        get
        {
            foreach (var cargoPrototypeId in ProductCatalogue)
            {
                var cargoPrototype = _protoManager.Index(cargoPrototypeId);
                yield return cargoPrototype;
            }
        }
    }

    /// <summary>
    ///     Populates the list of products that will actually be shown, using the current filters.
    /// </summary>
    public void PopulateProducts()
    {
        Products.RemoveAllChildren();
        var products = ProductPrototypes.ToList();
        products.Sort((x, y) =>
            string.Compare(x.Name, y.Name, StringComparison.CurrentCultureIgnoreCase));

        var search = SearchBar.Text.Trim().ToLowerInvariant();
        foreach (var prototype in products)
        {
            if (search.Length == 0 && _category == null ||
                search.Length != 0 && prototype.Name.ToLowerInvariant().Contains(search) ||
                search.Length != 0 && prototype.Description.ToLowerInvariant().Contains(search) ||
                search.Length == 0 && _category != null && Loc.GetString(prototype.Category).Equals(_category))
            {
                var button = new SWProductRow
                {
                    Product = prototype,
                    ProductName = { Text = prototype.Name },
                    MainButton = { ToolTip = prototype.Description },
                    PointCost = { Text = GetCostText(prototype) },
                    Icon = { Texture = _spriteSystem.Frame0(prototype.Icon) },
                };
                button.MainButton.OnPressed += args =>
                {
                    OnItemSelected?.Invoke(args);
                };
                Products.AddChild(button);
            }
        }
    }

    private string GetCostText(SWCargoProductPrototype prototype)
    {
        var costs = prototype.Cost;
        _swBankSystem.FillCurrencies(_currencyPrototypeIds, ref costs);
        string res = "";
        foreach (var (curProtoId, amount) in costs)
        {
            var curProto = _protoManager.Index(curProtoId);
            res += $"{curProto.ShortName} {amount}/";
        }
        res = res.Remove(res.Length - 1);
        return res;
    }

    /// <summary>
    ///     Populates the list of products that will actually be shown, using the current filters.
    /// </summary>
    public void PopulateCategories()
    {
        _categoryStrings.Clear();
        Categories.Clear();

        foreach (var prototype in ProductPrototypes)
        {
            if (!_categoryStrings.Contains(Loc.GetString(prototype.Category)))
            {
                _categoryStrings.Add(Loc.GetString(prototype.Category));
            }
        }

        _categoryStrings.Sort();

        // Add "All" category at the top of the list
        _categoryStrings.Insert(0, Loc.GetString("cargo-console-menu-populate-categories-all-text"));

        foreach (var str in _categoryStrings)
        {
            Categories.AddItem(str);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        BalanceContainer.Children.Clear();
        foreach (var (currency, amount) in Balance)
        {
            var cntrl = new SWCurrencyControl(currency, amount, false);
            BalanceContainer.AddChild(cntrl);
        }
    }
}
