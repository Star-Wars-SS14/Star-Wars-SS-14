        {
            BackgroundColor = PremiumFill,
            BorderColor = PremiumLine,
            BorderThickness = new Thickness(0, 2, 0, 2),
        };

        QuestsLink.OnPressed += _ => SelectTab(QuestsTab);

        TabTrack.OnPressed += _ => SelectTab(TrackTab);
        TabQuests.OnPressed += _ => SelectTab(QuestsTab);
        TabCases.OnPressed += _ => SelectTab(CasesTab);
