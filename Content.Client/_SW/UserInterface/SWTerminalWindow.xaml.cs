using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.UserInterface;

/// <summary>
/// A console window in the SW terminal style. Children declared in XAML go into its contents.
/// </summary>
[GenerateTypedNameReferences]
[Virtual]
public partial class SWTerminalWindow : BaseWindow
{
    private const int DragMarginSize = 7;

    public SWTerminalWindow()
    {
        RobustXamlLoader.Load(this);

        CloseButton.OnPressed += _ => Close();
        XamlChildren = ContentsContainer.Children;
    }

    public string? Title
    {
        get => WindowTitle.Text;
        set => WindowTitle.Text = value;
    }

    /// <summary>
    /// The accent name of the window's faction, see <see cref="SWTerminalStyle.AccentOf"/>.
    /// </summary>
    public string Accent { get; private set; } = SWTerminalStyle.NeutralAccent;

    /// <summary>
    /// Colours the window for a faction prototype ID. No faction leaves it neutral.
    /// </summary>
    public void SetFaction(string? faction)
    {
        Accent = SWTerminalStyle.AccentOf(faction);
        AccentLine.SetOnlyStyleClass(SWTerminalStyle.AccentLine + Accent);
    }

    /// <summary>
    /// A row with a name on the left and an amount of money on the right, for the card of a terminal window.
    /// </summary>
    public static BoxContainer CreateValueRow(string name, string value)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(14, 8),
        };

        var nameLabel = new Label { Text = name, HorizontalExpand = true, ClipText = true };
        nameLabel.AddStyleClass(SWTerminalStyle.Text);
        row.AddChild(nameLabel);

        var valueLabel = new Label { Text = value };
        valueLabel.AddStyleClass(SWTerminalStyle.Money);
        row.AddChild(valueLabel);

        return row;
    }

    /// <summary>
    /// A small filled tag. It is read-only, so unlike a button it has no hover and no pressed look.
    /// </summary>
    public static PanelContainer CreateChip(string text, string kind)
    {
        var chip = new PanelContainer { VerticalAlignment = VAlignment.Center };
        chip.AddStyleClass(SWTerminalStyle.Chip);
        chip.AddStyleClass(kind);

        chip.AddChild(new Label { Text = text });

        return chip;
    }

    public static PanelContainer CreateDivider()
    {
        // The game truncates sizes at a UI scale below 1, so a height of 1 draws nothing at 1280x720.
        var divider = new PanelContainer { MinHeight = 2 };
        divider.AddStyleClass(SWTerminalStyle.Divider);
        return divider;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = DragMode.Move;

        if (!Resizable)
            return mode;

        if (relativeMousePos.Y < DragMarginSize)
            mode = DragMode.Top;
        else if (relativeMousePos.Y > Size.Y - DragMarginSize)
            mode = DragMode.Bottom;

        if (relativeMousePos.X < DragMarginSize)
            mode |= DragMode.Left;
        else if (relativeMousePos.X > Size.X - DragMarginSize)
            mode |= DragMode.Right;

        return mode;
    }
}
