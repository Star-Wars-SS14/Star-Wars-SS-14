using System.Text.RegularExpressions;
using Content.Client._SW.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._SW.Tutorial;

/// <summary>
/// One short small line in the corner, off the middle of the screen where the character and the world are. A note about a mistake takes its place for a few seconds. A step done keeps the old
/// line green for a moment, or the success goes unnoticed.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SWTutorialPrompt : UIWidget
{
    /// <summary>
    /// Just above the row of slots, so the line stays in one place when they come on. At the top it would run into the menu
    /// bar and the chat as soon as they appear.
    /// </summary>
    public const float AboveBottom = 72;

    public const float FromLeft = 8;

    private const float NoteTime = 4f;
    private const float HoldTime = 0.6f;

    private static readonly Regex KeyCap = new(@"(\[[^\]]+\])", RegexOptions.Compiled);
    private static readonly Color NoteColor = Color.FromHex("#FFB84D");
    private static readonly Color DoneColor = Color.FromHex("#5CE65C");

    private readonly StyleBoxFlat _keyCapBox = new()
    {
        BorderColor = Color.White,
        BorderThickness = new Thickness(1),
        ContentMarginLeftOverride = 3,
        ContentMarginRightOverride = 3,
    };

    private float _noteLeft;
    private float _holdLeft;
    private string _shown = string.Empty;
    private Color? _shownColor;

    public event Action? OnReturnPressed;

    public Control ReturnControl => ReturnButton;

    public string PromptText { get; private set; } = string.Empty;

    public string NoteText { get; private set; } = string.Empty;

    public SWTutorialPrompt()
    {
        RobustXamlLoader.Load(this);

        // A plain plate: nothing to hover and nothing that looks like a button, readable on any floor.
        Pill.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#0C0E0F").WithAlpha(0.85f) };
        ReturnButton.OnPressed += _ => OnReturnPressed?.Invoke();
    }

    /// <param name="text">The line. Null hides the plate.</param>
    /// <param name="note">What just went wrong, if anything.</param>
    public void SetText(string? text, string? note)
    {
        var newNote = note ?? string.Empty;
        if (newNote != NoteText && newNote.Length > 0)
            _noteLeft = NoteTime;

        PromptText = text ?? string.Empty;
        NoteText = newNote;
        Show();
    }

    public void SetReturnButton(bool visible)
    {
        ReturnButton.Visible = visible;
        Show();
    }

    /// <summary>
    /// Marks the line on screen as done and holds it there before the next one comes.
    /// </summary>
    public void Done()
    {
        _holdLeft = HoldTime;
        Build(_shown, DoneColor);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_holdLeft > 0f)
        {
            _holdLeft -= args.DeltaSeconds;
            if (_holdLeft <= 0f)
                Show();
        }

        if (_noteLeft > 0f)
        {
            _noteLeft -= args.DeltaSeconds;
            if (_noteLeft <= 0f)
                Show();
        }
    }

    private void Show()
    {
        if (_holdLeft > 0f)
            return;

        var showNote = _noteLeft > 0f && NoteText.Length > 0;
        Build(showNote ? NoteText : PromptText, showNote ? NoteColor : null);
        Pill.Visible = _shown.Length > 0 || ReturnButton.Visible;
    }

    /// <summary>
    /// Text and key caps side by side: "Drop: [Q]" becomes a label and a framed key.
    /// </summary>
    private void Build(string text, Color? color)
    {
        if (_shown == text && _shownColor == color)
            return;

        _shown = text;
        _shownColor = color;
        Line.RemoveAllChildren();

        foreach (var part in KeyCap.Split(text))
        {
            if (string.IsNullOrWhiteSpace(part))
                continue;

            var isKey = part.StartsWith('[') && part.EndsWith(']');
            var label = new Label
            {
                Text = isKey ? part[1..^1] : part.Trim(),
                FontColorOverride = color,
                StyleClasses = { SWTerminalStyle.Value },
            };

            if (!isKey)
            {
                Line.AddChild(label);
                continue;
            }

            var cap = new PanelContainer { PanelOverride = _keyCapBox };
            cap.AddChild(label);
            Line.AddChild(cap);
        }
    }
}
