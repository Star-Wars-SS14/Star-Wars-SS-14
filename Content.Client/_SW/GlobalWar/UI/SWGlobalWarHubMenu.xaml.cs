using System.Globalization;
using System.Linq;
using Content.Shared._SW.GlobalWar;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarHubMenu : SWGlobalWarWindow
{
    public SWGlobalWarHubDraft Draft = new();
    private SWGlobalWarHubView? _state;
    private readonly List<Guid> _grants = new();
    private readonly List<Guid> _orders = new();
    private bool _restoring;
    public event Action<SWGlobalWarHubCommand>? StartRequested;
    public event Action<Guid, long, Guid>? CancelRequested;
    public event Action<SWGlobalWarHubGrantCommand>? GrantRequested;
    public event Action<SWGlobalWarHubRevokeRequest>? RevokeRequested;

    public SWGlobalWarHubMenu()
    {
        RobustXamlLoader.Load(this);
        Start.SetAppearance(SWGlobalWarConsoleStyle.TextBright, money: true);
        HelpMark.ToolTip = Loc.GetString("sw-global-war-hub-instructions");
        Start.MainFont = SWGlobalWarConsoleStyle.MainButton;
        HubWord.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        HubWord.FontColorOverride = Color.FromHex("#E9C17E");
        StepValue.FontOverride = SWGlobalWarConsoleStyle.Bold(26);
        StepValue.FontColorOverride = Color.White;
        StepPrice.FontOverride = SWGlobalWarConsoleStyle.Bold(18);
        StepPrice.FontColorOverride = SWGlobalWarConsoleStyle.Money;
        HeadDecision.OnToggled += _ => { Draft.HeadDecision = HeadDecision.Pressed; Refresh(); };
        Maximum.OnTextChanged += _ => { if (!_restoring) Draft.Maximum = Maximum.Text; };
        Minutes.OnTextChanged += _ => { if (!_restoring) Draft.Minutes = Minutes.Text; };
        GrantPicker.OnItemSelected += args =>
        {
            GrantPicker.SelectId(args.Id);
            Draft.Grant = _grants[args.Id];
            Draft.SelectionLost = false;
            Refresh();
        };
        OrderPicker.OnItemSelected += args =>
        {
            OrderPicker.SelectId(args.Id);
            Draft.Order = _orders[args.Id];
            Refresh();
        };
        Start.OnPressed += _ =>
        {
            if (_state is not { Ready: true } state || Draft.Pending)
                return;
            var grant = state.Grants.FirstOrDefault(g => g.Id == Draft.Grant);
            Draft.Start = new(state.Generation, Guid.NewGuid(), state.AssignmentRevision, state.Capacity,
                grant?.MoneyOrder ?? Guid.Empty, grant?.Id ?? Guid.Empty, Draft.HeadDecision);
            Draft.LastAttempt = Draft.Start.Request;
            Draft.Feedback = string.Empty;
            SendPending();
        };
        Cancel.OnPressed += _ =>
        {
            if (_state?.Active is not { } active || Draft.Pending)
                return;
            Draft.Cancel = active.Request;
            Draft.LastCancellation = active.Request;
            Draft.Feedback = string.Empty;
            SendPending();
        };
        Grant.OnPressed += _ =>
        {
            if (_state is not { Ready: true } state || Draft.Pending ||
                state.Orders.FirstOrDefault(o => o.Id == Draft.Order) is not { } order ||
                !int.TryParse(Maximum.Text, out var maximum) || !int.TryParse(Minutes.Text, out var minutes) ||
                minutes <= 0 || minutes > 15)
            {
                Draft.Feedback = Loc.GetString("sw-global-war-hub-input");
                Refresh();
                return;
            }
            Draft.GrantCommand = new(state.Generation, Guid.NewGuid(), state.AssignmentRevision,
                order.Employee, order.EmployeeRevision, order.Id, maximum, TimeSpan.FromMinutes(minutes), Draft.HeadDecision);
            Draft.Feedback = string.Empty;
            SendPending();
        };
        Revoke.OnPressed += _ =>
        {
            if (_state is not { Ready: true } state || Draft.Grant == Guid.Empty || Draft.Pending)
                return;
            Draft.Revoke = new(state.Generation, Guid.NewGuid(), state.AssignmentRevision, Draft.Grant,
                Draft.HeadDecision, Guid.Empty);
            Draft.Feedback = string.Empty;
            SendPending();
        };
        Retry.OnPressed += _ => SendPending();
    }

    public void UpdateState(SWGlobalWarHubView state)
    {
        var initial = _state == null;
        Scene.Scene = SWGlobalWarConsoleStyle.Picture("hub_" + SWGlobalWarConsoleStyle.SideLetter());
        var changed = Draft.Generation != state.Generation || Draft.Assignment != state.Assignment ||
            Draft.Revision != state.AssignmentRevision;
        if (state.Generation == Guid.Empty || changed)
        {
            Draft.Clear();
            Set(Result, string.Empty);
        }
        Draft.Generation = state.Generation;
        Draft.Assignment = state.Assignment;
        Draft.Revision = state.AssignmentRevision;
        _state = state;
        var confirmed = Draft.LastAttempt == Guid.Empty ? state.OwnResults.LastOrDefault() :
            state.OwnResults.LastOrDefault(r => r.Request == Draft.LastAttempt);
        if (confirmed != null && !(Draft.Confirmed is { Status: not SWGlobalWarHubStatus.Working } terminal &&
                terminal.Request == confirmed.Request && confirmed.Status == SWGlobalWarHubStatus.Working))
            Draft.Confirmed = confirmed;
        if (initial || changed)
        {
            _restoring = true;
            Maximum.Text = string.IsNullOrEmpty(Draft.Maximum)
                ? state.NextCapacity.ToString(CultureInfo.InvariantCulture) : Draft.Maximum;
            Minutes.Text = Draft.Minutes;
            HeadDecision.Pressed = Draft.HeadDecision;
            _restoring = false;
        }
        if (Draft.Start is { } start && state.OwnResults.Any(r => r.Request == start.Request) ||
            Draft.Cancel is { } cancel && state.OwnResults.Any(r => r.Request == cancel && r.Status != SWGlobalWarHubStatus.Working))
        {
            Draft.Feedback = null;
            Draft.ClearPending();
        }
        UpdatePicker(GrantPicker, _grants, state.Grants.Select(g => g.Id).ToArray(), Draft.Grant,
            state.CanManage ? Loc.GetString("sw-global-war-hub-direct") : Loc.GetString("sw-global-war-hub-select-grant"),
            id =>
            {
                var grant = state.Grants.Single(g => g.Id == id);
                return Loc.GetString("sw-global-war-hub-grant-option", ("employee", grant.Employee),
                    ("maximum", grant.MaximumCapacity), ("purpose", grant.Purpose));
            });
        if (!_grants.Contains(Draft.Grant))
        {
            Draft.Grant = Guid.Empty;
            Draft.SelectionLost = true;
            Draft.Feedback = Loc.GetString("sw-global-war-hub-selection-lost");
        }
        UpdatePicker(OrderPicker, _orders, state.Orders.Select(o => o.Id).ToArray(), Draft.Order,
            Loc.GetString("sw-global-war-hub-select-order"), id =>
            {
                var order = state.Orders.Single(o => o.Id == id);
                return Loc.GetString("sw-global-war-hub-order-option", ("employee", order.Name),
                    ("remaining", order.Remaining), ("purpose", order.Purpose));
            });
        if (!_orders.Contains(Draft.Order))
            Draft.Order = Guid.Empty;
        Refresh();
    }

    private static void UpdatePicker(OptionButton picker, List<Guid> ids, Guid[] choices, Guid selected,
        string empty, Func<Guid, string> label)
    {
        var next = new[] { Guid.Empty }.Concat(choices).ToArray();
        if (!ids.SequenceEqual(next))
        {
            ids.Clear();
            ids.AddRange(next);
            picker.Clear();
            for (var i = 0; i < ids.Count; i++)
                picker.AddItem(i == 0 ? empty : label(ids[i]), i);
        }
        else
            for (var i = 0; i < ids.Count; i++)
                picker.SetItemText(i, i == 0 ? empty : label(ids[i]));
        picker.SelectId(Math.Max(0, ids.IndexOf(selected)));
    }

    public void ReceiveReply(SWGlobalWarHubReply reply)
    {
        if (_state is not { Ready: true } ||
            !(Draft.Start?.Request == reply.Request || Draft.Cancel == reply.Request ||
                Draft.GrantCommand?.Request == reply.Request || Draft.Revoke?.Request == reply.Request))
            return;
        if (reply.Result is { } confirmed)
            Draft.Confirmed = confirmed;
        Draft.Feedback = reply.Result != null ? null : reply.Success
            ? Loc.GetString("sw-global-war-hub-action-ok") : FailureText(reply.Failure);
        Draft.ClearPending();
        Refresh();
    }

    private void SendPending()
    {
        if (_state is not { Ready: true } state || state.Assignment != Draft.Assignment || state.Generation != Draft.Generation)
            return;
        if (Draft.Start is { } start)
            StartRequested?.Invoke(start);
        else if (Draft.Cancel is { } cancel)
            CancelRequested?.Invoke(state.Generation, state.AssignmentRevision, cancel);
        else if (Draft.GrantCommand is { } grant)
            GrantRequested?.Invoke(grant);
        else if (Draft.Revoke is { } revoke)
            RevokeRequested?.Invoke(revoke);
        Refresh();
    }

    private void Refresh()
    {
        var receipt = Draft.Confirmed;
        var currentReceipt = Draft.Feedback == null && receipt != null &&
            (Draft.LastAttempt == Guid.Empty || receipt.Request == Draft.LastAttempt);
        Set(Result, Draft.Feedback ?? (currentReceipt ? ResultText(receipt!, Draft.LastCancellation == receipt!.Request) : string.Empty));
        Set(Receipt, receipt == null ? string.Empty : Loc.GetString("sw-global-war-hub-result-funding",
            ("result", ResultText(receipt, Draft.LastCancellation == receipt.Request)), ("funding", FundingText(receipt))));
        Receipt.Visible = receipt != null && !currentReceipt;
        if (_state is not { Ready: true } state)
        {
            Set(Overview, Loc.GetString("sw-global-war-hub-unavailable"));
            Set(Funding, string.Empty);
            Set(Reason, string.Empty);
            Set(Progress, string.Empty);
            Start.Disabled = Cancel.Disabled = Retry.Disabled = true;
            Management.Visible = HeadDecision.Visible = false;
            if (Draft.Confirmed is { } own)
            {
                Set(Funding, FundingText(own));
            }
            return;
        }
        HeadDecision.Visible = state.Head;
        Management.Visible = state.CanManage;
        Set(Overview, Loc.GetString("sw-global-war-hub-overview", ("planet", state.Planet), ("capacity", state.Capacity),
            ("next", state.NextCapacity), ("price", state.Price),
            ("orbit", Faction(state.Orbit)), ("surface", Faction(state.Surface))));
        StepRow.Visible = true;
        StepValue.Text = Loc.GetString("sw-global-war-hub-step-value", ("capacity", state.Capacity), ("next", state.NextCapacity));
        StepPrice.Text = Loc.GetString("sw-global-war-finance-sum", ("sum", state.Price));
        var grant = state.Grants.FirstOrDefault(g => g.Id == Draft.Grant);
        var authority = !state.HeadDecisionRequired || Draft.HeadDecision;
        var failure = Draft.SelectionLost || state.CanManage && grant != null ? SWGlobalWarHubFailure.Denied :
            state.Failure != SWGlobalWarHubFailure.None ? state.Failure : grant?.Failure ??
            (state.CanManage && authority ? SWGlobalWarHubFailure.None : SWGlobalWarHubFailure.Denied);
        Set(Funding, state.Active is { } funded && state.OwnResults.Any(r => r.Request == funded.Request)
            ? FundingText(funded) : grant == null ? Loc.GetString("sw-global-war-hub-direct-info") :
            Loc.GetString("sw-global-war-hub-grant-info", ("remaining", grant.Remaining), ("maximum", grant.MaximumCapacity),
                ("seconds", Math.Max(0, (int) (grant.Expires - state.Time).TotalSeconds)),
                ("moneySeconds", Math.Max(0, (int) ((grant.MoneyExpires ?? state.Time) - state.Time).TotalSeconds)),
                ("purpose", grant.Purpose)));
        Set(Reason, Draft.Pending ? Loc.GetString(Draft.Cancel != null ? "sw-global-war-hub-pending-cancel" :
            "sw-global-war-hub-pending") : FailureText(failure));
        Start.Text = Loc.GetString("sw-global-war-hub-start-price", ("price", state.Price));
        Start.Disabled = Draft.Pending || failure != SWGlobalWarHubFailure.None || grant == null && !state.CanManage;
        Cancel.Disabled = Draft.Pending || state.Active == null || !state.OwnResults.Any(r => r.Request == state.Active.Request);
        Retry.Disabled = !Draft.Pending;
        Grant.Disabled = Draft.Pending || Draft.Order == Guid.Empty || !authority;
        Revoke.Disabled = Draft.Pending || grant == null || grant.Revoked || !authority;
        if (state.Active is { } active)
        {
            var seconds = Math.Max(0, (int) Math.Ceiling((active.Finishes - state.Time).TotalSeconds));
            Set(Progress, seconds == 0 ? Loc.GetString("sw-global-war-hub-await-completion") :
                Loc.GetString("sw-global-war-hub-working", ("executor", state.Executor), ("seconds", seconds), ("price", active.Price)));
        }
        else
            Set(Progress, state.Executor.Length > 0 ? Loc.GetString("sw-global-war-hub-other-working",
                ("executor", state.Executor)) : string.Empty);
        if (currentReceipt && receipt is { } result)
            Set(Result, Loc.GetString("sw-global-war-hub-result-funding",
                ("result", ResultText(result, Draft.LastCancellation == result.Request)), ("funding", FundingText(result))));
    }

    private static string ResultText(SWGlobalWarHubResult result, bool cancelling)
    {
        return result.Status switch
        {
            SWGlobalWarHubStatus.Completed => Loc.GetString(cancelling ? "sw-global-war-hub-already-completed" :
                "sw-global-war-hub-completed", ("capacity", result.Capacity), ("price", result.Price)),
            SWGlobalWarHubStatus.Cancelled => Loc.GetString("sw-global-war-hub-cancelled",
                ("reason", FailureText(result.Failure)), ("capacity", result.Capacity),
                ("funding", Loc.GetString(result.FundingState switch
                {
                    SWGlobalWarHubFundingState.DirectReleased => "sw-global-war-hub-direct-released",
                    SWGlobalWarHubFundingState.OrderAvailable => "sw-global-war-hub-order-released",
                    SWGlobalWarHubFundingState.ParentClosed => "sw-global-war-hub-parent-closed",
                    SWGlobalWarHubFundingState.ParentUnavailable => "sw-global-war-hub-parent-unavailable",
                    _ => "sw-global-war-hub-cleanup-pending",
                }, ("price", result.Price)))),
            _ => Loc.GetString("sw-global-war-hub-started"),
        };
    }

    private static string FundingText(SWGlobalWarHubResult result) => result.Direct
        ? Loc.GetString("sw-global-war-hub-confirmed-direct", ("price", result.Price))
        : Loc.GetString("sw-global-war-hub-confirmed-order", ("price", result.Price), ("purpose", result.Purpose));

    private static string Faction(SWGlobalWarFaction faction) => Loc.GetString(faction switch
    {
        SWGlobalWarFaction.Republic => "sw-global-war-hub-republic",
        SWGlobalWarFaction.Empire => "sw-global-war-hub-empire",
        _ => "sw-global-war-hub-neutral",
    });

    private static string FailureText(SWGlobalWarHubFailure failure) => failure == SWGlobalWarHubFailure.None
        ? string.Empty : Loc.GetString("sw-global-war-hub-failure-" + failure.ToString().ToLowerInvariant());

    private static void Set(RichTextLabel label, string text) =>
        label.SetMessage(label.Name is "Result" or "Receipt" ? FormattedMessage.FromUnformatted(text) : SWGlobalWarConsoleStyle.MoneyMessage(text));
}
