    private void BuildCases(SWBattlePassState state)
    {
        if (_case == null || _season == null)
            return;

        var count = state.Cases.GetValueOrDefault(_case.ID);

        if (SceneArt.Texture == null && _season.Banner != null)
        {
            var banner = _sprite.Frame0(_season.Banner);
            SceneArt.Texture = new AtlasTexture(banner, UIBox2.FromDimensions(SceneRegionLeft, 0, SceneRegionWidth, SceneRegionHeight));
        }

        CaseIcon.Texture = _sprite.Frame0(_case.Icon);
        CaseIcon.ModulateSelfOverride = count > 0 ? Color.White : new Color(1f, 1f, 1f, 0.45f);
        CaseGlow.Visible = count > 0;
        CaseName.Text = Loc.GetString(_case.Name);
        CaseCount.Text = $"×{count}";
        CaseCountChip.Visible = count > 0;

        // The first case is known in advance. Without this line the reel would act out a chance that is not there.
        CaseFirst.Visible = !state.FirstCaseOpened && _case.FirstEntry != null && count > 0;
        if (_case.FirstEntry is { } firstEntry)
            CaseFirst.Text = Loc.GetString("sw-battlepass-case-first-line", ("name", EntryName(_case.Entries[firstEntry])));

        OpenCase.Visible = count > 0;
        OpenCase.Disabled = state.InCombat;
        OpenCase.ToolTip = state.InCombat ? Loc.GetString("sw-battlepass-refused-combat") : null;

        var nextTier = NextCaseTier(_season, SWBattlePassRules.TierOf(_season, state.Xp));
        CaseNote.Text = count > 0
            ? state.InCombat ? Loc.GetString("sw-battlepass-case-in-combat") : string.Empty
            : nextTier is { } tier ? Loc.GetString("sw-battlepass-case-next-tier", ("tier", tier)) : string.Empty;
        CaseNote.Visible = CaseNote.Text != string.Empty;

        var rules = Loc.GetString("sw-battlepass-case-rules", ("next", _case.PityAfter + 1));
        if (!state.FirstCaseOpened && _case.FirstEntry is { } first)
            rules += "\n" + Loc.GetString("sw-battlepass-case-first", ("name", EntryName(_case.Entries[first])));

        CaseRules.SetMarkup(rules);

        // While the reel runs these would tell the result first.
        if (!Reel.Spinning && _revealAt == null)
            UpdateCaseFooter(state);

        OddsList.RemoveAllChildren();
        var longRun = SWBattlePassRules.ShownLongRunShares(_case);
        for (var i = 0; i < _case.Entries.Count; i++)
        {
            OddsList.AddChild(BuildOddsRow(_case, i, longRun[i], state));
        }

        if (!_tilesBuilt)
        {
            _tilesBuilt = true;
            foreach (var entry in _case.Entries)
            {
                OddsTiles.AddChild(BuildOddsTile(entry));
            }
        }

        Reel.SetCase(_case, this);
    }

    private static int? NextCaseTier(SWBattlePassSeasonPrototype season, int tier)
    {
        for (var i = tier + 1; i <= season.Tiers.Count; i++)
        {
            if (season.Tiers[i - 1].Free?.Case != null)
                return i;
        }

        return null;
    }

