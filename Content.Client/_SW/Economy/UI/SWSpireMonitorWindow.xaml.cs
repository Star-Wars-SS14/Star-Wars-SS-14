namespace Content.Client._SW.Economy;

[GenerateTypedNameReferences]
public sealed partial class SWSpireMonitorWindow : SWTerminalWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;

    // EntitySystems are NOT in the IoC container: resolve via the system manager.
    private SpriteSystem _sprite = default!;

    private readonly SWSpireMonitorBoundUserInterface _owner;
    private List<SWSpireMonitorRowData> _rows = new();
    private readonly List<Button> _rowButtons = new();
    private int _selected = -1;

    // Faction -> job-icon state used as the faction emblem in the spire list.
    private static readonly Dictionary<string, string> FactionIconState = new()
    {
        { "RepublicFaction", "RepublicGeneral" },
        { "EmpireFaction", "EmpireMajor" },
        { "ExchangeFaction", "ExchangeCaptain" },
        { "BlackSunFaction", "Blacksun" },
        { "MandalorianFaction", "MandalorianVeteran" },
    };

    private static readonly Dictionary<string, string> FactionHex = new()
    {
        { "RepublicFaction", "#2e6bd6" },
        { "EmpireFaction", "#d63a3a" },
        { "ExchangeFaction", "#8a5a2b" },
        { "BlackSunFaction", "#8a3ad6" },
        { "MandalorianFaction", "#d6c23a" },
    };

    private const string NeutralHex = "#8a8a8a";

    // state name -> resolved icon specifier (null = not found), filled lazily once.
    private readonly Dictionary<string, SpriteSpecifier?> _factionIconCache = new();

    // Seamless marquee: the Margin is applied to the BOX with two copies, never
    // to the measured label (Margin on the measured label shrinks DesiredSize and
    // causes an early reset). Step = first copy width + inter-copy gap.
    private const float TickerSpeed = 40.0f;
    private const float TickerGap = 60.0f;
    private float _tickerOffset;

    public SWSpireMonitorWindow(SWSpireMonitorBoundUserInterface owner)
    {
        _owner = owner;
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _sysMan.GetEntitySystem<SpriteSystem>();

        // Static (non-lagging) mascot in the corner.
        MascotRect.Texture = _sprite.GetFrame(
            new SpriteSpecifier.Rsi(new ResPath("/Textures/_SW/Economy/control_spire/calicomp.rsi"), "calicomp"),
            TimeSpan.Zero);

        Title = Loc.GetString("sw-spire-monitor-title");

        // Details are hidden until a spire row is selected.
        DetailPanel.Visible = false;
    }

    public void UpdateState(SWSpireMonitorBoundUserInterfaceState state)
    {
        _rows = state.Rows;
        if (_selected >= _rows.Count)
            _selected = -1;

        RebuildList();
        ShowDetail(_selected);
        SetTicker(Loc.GetString("sw-spire-ticker"));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTicker(args.DeltaSeconds);
    }

    private void RebuildList()
    {
        SpireListBox.RemoveAllChildren();
        _rowButtons.Clear();

        for (var i = 0; i < _rows.Count; i++)
        {
            var row = _rows[i];
            var index = i;
            var color = Color.FromHex(FactionHex.GetValueOrDefault(row.OwnerFaction, NeutralHex));

            var button = new Button
            {
                ToggleMode = true,
                HorizontalExpand = true,
                Pressed = index == _selected,
            };

            // Default BoxContainer orientation is Horizontal in this engine,
            // so we intentionally do not touch Orientation (enum name differs).
            var box = new BoxContainer
            {
                SeparationOverride = 6,
            };

            // Faction emblem (job-icon); hidden for neutral spires or missing icons.
            var icon = new TextureRect
            {
                MinSize = new Vector2(24, 24),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Center,
            };
            var iconSpec = row.OwnerFaction == string.Empty
                ? null
                : ResolveFactionIcon(FactionIconState.GetValueOrDefault(row.OwnerFaction, string.Empty));
            if (iconSpec != null)
            {
                icon.Texture = _sprite.GetFrame(iconSpec, TimeSpan.Zero);
            }
            else
            {
                icon.Visible = false;
            }

            var name = new Label
            {
                Text = row.SpireName,
                FontColorOverride = color,
                HorizontalExpand = true,
                ClipText = true,
            };
            var ownerName = new Label { Text = row.OwnerName, StyleClasses = { "SWTermText" } };

            box.AddChild(icon);
            box.AddChild(name);
            box.AddChild(ownerName);
            button.AddChild(box);
            button.OnPressed += _ => OnRowPressed(index);

            _rowButtons.Add(button);
            SpireListBox.AddChild(button);
        }
    }

    /// <summary>
    /// Resolves a faction emblem via the job-icon prototype id convention
    /// ("JobIcon" + state name). Returns null when the prototype is missing so the
    /// row simply renders without an icon instead of crashing.
    /// </summary>
    private SpriteSpecifier? ResolveFactionIcon(string state)
    {
        if (state == string.Empty)
            return null;

        if (_factionIconCache.TryGetValue(state, out var cached))
            return cached;

        var found = _prototype.TryIndex<JobIconPrototype>("JobIcon" + state, out var icon)
            ? icon.Icon
            : null;

        _factionIconCache[state] = found;
        return found;
    }

    private void OnRowPressed(int index)
    {
        // Ping the server so row selection plays the standard console beep.
        _owner.SendSelect();

        _selected = _selected == index ? -1 : index;

        for (var i = 0; i < _rowButtons.Count; i++)
        {
            _rowButtons[i].Pressed = i == _selected;
        }

        ShowDetail(_selected);
    }

    private void UpdateTicker(float deltaSeconds)
    {
        // Measured label carries no Margin, so DesiredSize is the true text width.
        var copyWidth = TickerTextA.DesiredSize.X;
        if (copyWidth <= 0f)
            return;

        var step = copyWidth + TickerGap;
        _tickerOffset -= deltaSeconds * TickerSpeed;
        if (_tickerOffset <= -step)
            _tickerOffset += step;

        TickerBox.Margin = new Thickness(_tickerOffset, 0, 0, 0);
    }

    private void SetTicker(string text)
    {
        if (TickerTextA.Text == text)
            return;

        TickerTextA.Text = text;
        TickerTextB.Text = text;
        _tickerOffset = 0f;
    }

    /// <summary>
    /// The detail panel only exists while a spire row is selected; deselecting
    /// (second click on the same row) hides it again.
    /// </summary>
    private void ShowDetail(int index)
    {
        if (index < 0 || index >= _rows.Count)
        {
            DetailPanel.Visible = false;
            return;
        }

        DetailPanel.Visible = true;
        var row = _rows[index];
        var color = Color.FromHex(FactionHex.GetValueOrDefault(row.OwnerFaction, NeutralHex));

        DetailNameLabel.Text = row.SpireName;
        DetailNameLabel.FontColorOverride = color;
        DetailOwnerLabel.Text = Loc.GetString("sw-spire-monitor-owner", ("faction", row.OwnerName));
        DetailOwnerLabel.FontColorOverride = color;

        DetailCapturingLabel.Visible = row.IsCapturing;
        if (row.IsCapturing)
        {
            DetailCapturingLabel.Text = Loc.GetString("sw-spire-monitor-capturing",
                ("faction", row.CapturingName));
        }

        DetailCaptureBar.Value = row.CaptureProgress;
        DetailPayoutBar.Value = row.PayoutProgress;
        DetailCaptureTimerLabel.Text = Loc.GetString("sw-spire-monitor-capture",
            ("value", row.IsCapturing ? FormatClock(row.CaptureRemainingSeconds) : Loc.GetString("sw-spire-none")));
        DetailPayoutTimerLabel.Text = Loc.GetString("sw-spire-monitor-payout",
            ("value", row.OwnerFaction != string.Empty ? FormatClock(row.PayoutRemainingSeconds) : Loc.GetString("sw-spire-none")));
    }

    private static string FormatClock(float seconds)
    {
        var span = TimeSpan.FromSeconds(seconds);
        return span.Minutes.ToString("D2") + ":" + span.Seconds.ToString("D2");
    }
}