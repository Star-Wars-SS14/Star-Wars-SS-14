using Content.Shared._SW.GlobalWar.Combat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.GlobalWar.UI;

/// <summary>Droids of this side here, in all and in reach, the four commands, and an order for one more.</summary>
[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarDefenceMenu : SWGlobalWarWindow
{
    public event Action<SWGlobalWarDefenceCommand>? Requested;

    public SWGlobalWarDefenceMenu()
    {
        RobustXamlLoader.Load(this);
        foreach (var value in new[] { HereValue, SideValue, NearbyValue })
        {
            value.FontOverride = SWGlobalWarConsoleStyle.Bold(28);
            value.FontColorOverride = SWGlobalWarConsoleStyle.TextBright;
        }
        foreach (var label in new[] { HereLabel, SideLabel, NearbyLabel })
        {
            label.FontOverride = SWGlobalWarConsoleStyle.Small;
            label.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        }
        HelpMark.ToolTip = Loc.GetString("sw-global-war-defence-ui-instructions");
        Order.MainFont = SWGlobalWarConsoleStyle.MainButton;
        Order.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true, money: true);
        Hold.OnPressed += _ => Requested?.Invoke(SWGlobalWarDefenceCommand.Hold);
        Objective.OnPressed += _ => Requested?.Invoke(SWGlobalWarDefenceCommand.Objective);
        Retreat.OnPressed += _ => Requested?.Invoke(SWGlobalWarDefenceCommand.Retreat);
        Follow.OnPressed += _ => Requested?.Invoke(SWGlobalWarDefenceCommand.Follow);
        Order.OnPressed += _ => Requested?.Invoke(SWGlobalWarDefenceCommand.Order);
    }

    public void UpdateState(SWGlobalWarDefenceView view)
    {
        var known = view.Reason.Length == 0;
        HereValue.Text = known ? $"{view.Here}/{view.HereLimit}" : "-";
        SideValue.Text = known ? $"{view.Side}/{view.SideLimit}" : "-";
        NearbyValue.Text = known ? view.Nearby.ToString() : "-";
        Hold.Disabled = Objective.Disabled = Retreat.Disabled = Follow.Disabled = !view.CanCommand;
        Order.Text = Loc.GetString("sw-global-war-defence-ui-order", ("price", view.Price), ("seconds", view.BuildSeconds));
        Order.Disabled = !view.CanOrder;
        var lines = new List<string>();
        if (!known)
            lines.Add(Loc.GetString(view.Reason));
        else if (!view.CanOrder)
            lines.Add(Loc.GetString("sw-global-war-defence-ui-no-budget"));
        if (view.Ordered > 0)
            lines.Add(Loc.GetString("sw-global-war-defence-ui-ordered", ("count", view.Ordered)));
        if (view.Result.Length > 0)
            lines.Add(view.Result);
        Status.SetMessage(string.Join("\n", lines));
    }
}
