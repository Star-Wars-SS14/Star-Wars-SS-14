[GenerateTypedNameReferences]
public sealed partial class SWMinistrySelectConsoleMenu : FancyWindow
{
    private readonly SWMinistrySelectConsoleBoundUserInterface _owner;
    private readonly Font _titleFont;
    private SWMinistrySelectConsoleState? _state;
    private string? _selected;
    private string? _detailSelection;
    private int _group;
    private bool _pending;
    private Vector2 _viewport;

    public SWMinistrySelectConsoleMenu(SWMinistrySelectConsoleBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        _owner = owner;
        _titleFont = new VectorFont(IoCManager.Resolve<IResourceCache>().GetResource<FontResource>("/Fonts/NotoSans/NotoSans-Regular.ttf"), 24);
        SWConsoleStyle.StyleRoot(RootPanel);
        FitViewport(true);
        RootPanel.PanelOverride = Panel("#172733", "#537A91", 6);
        HeaderPanel.PanelOverride = Panel("#0A131D", "#35586E", 0);
        ListPanel.PanelOverride = Panel("#0A131D", "#2C4659", 0);
        FooterPanel.PanelOverride = Panel("#0A131D", "#2C4659", 0);
        Seal.Texture = IoCManager.Resolve<IResourceCache>().GetResource<TextureResource>("/Textures/_SW/Interface/Senate/republic-seal.png").Texture;
        HeaderTitle.FontOverride = SWConsoleStyle.Strong;
        HeaderTitle.FontColorOverride = SWConsoleStyle.TextBright;
        ListTitle.FontOverride = SWConsoleStyle.Small;
        ListTitle.FontColorOverride = SWConsoleStyle.TextDim;
        MinistriesTab.OnPressed += _ => ChangeGroup(0);
        DepartmentsTab.OnPressed += _ => ChangeGroup(1);
        BureausTab.OnPressed += _ => ChangeGroup(2);
        ClaimButton.OnPressed += _ =>
        {
            if (_selected == null || _pending || ClaimButton.Disabled) return;
            _pending = true;
            ClaimButton.Disabled = true;
            _owner.SelectMinistry(_selected);
        };
    }

    private static StyleBoxFlat Panel(string background, string border, int padding) => new()
    {
        BackgroundColor = Color.FromHex(background), BorderColor = Color.FromHex(border),
        BorderThickness = new Thickness(1), ContentMarginLeftOverride = padding, ContentMarginRightOverride = padding,
        ContentMarginTopOverride = padding, ContentMarginBottomOverride = padding,
    };

    public void SetState(SWMinistrySelectConsoleState state)
    {
        var old = _state;
        var pending = _pending;
        _pending = false;
        _state = state;
        if (_selected == null || !state.Ministries.Any(m => m.Id == _selected))
        {
            var initial = state.Ministries.FirstOrDefault(m => m.KindGroup == _group);
            _selected = initial?.Id;
        }
        var changed = old == null || !SameEntries(old, state);
        if (changed) RefreshList();
        if (changed || pending || old == null || old.HasCard != state.HasCard || old.IsMinisterCard != state.IsMinisterCard ||
            old.Current != state.Current || old.CurrentName != state.CurrentName || old.ModeActive != state.ModeActive || old.DayActive != state.DayActive)
            RefreshDetail();
    }

    private static bool SameEntries(SWMinistrySelectConsoleState a, SWMinistrySelectConsoleState b)
    {
        if (a.Ministries.Count != b.Ministries.Count) return false;
        for (var i = 0; i < a.Ministries.Count; i++)
        {
            var x = a.Ministries[i]; var y = b.Ministries[i];
            if (x.Id != y.Id || x.Name != y.Name || x.Description != y.Description || x.Color != y.Color ||
                x.KindGroup != y.KindGroup || x.KindLabel != y.KindLabel || x.ParentId != y.ParentId || x.ParentName != y.ParentName ||
                x.Claimed != y.Claimed || x.Holder != y.Holder || x.Locked != y.Locked || x.LockedReason != y.LockedReason) return false;
        }
        return true;
    }

    private void ChangeGroup(int group)
    {
        _group = group;
        _selected = _state?.Ministries.FirstOrDefault(m => m.KindGroup == group)?.Id;
        ListScroll.SetScrollValue(Vector2.Zero);
        RefreshList(); RefreshDetail();
    }

    private void Select(SWMinistryEntry entry)
    {
        var changedGroup = _group != entry.KindGroup;
        _group = entry.KindGroup; _selected = entry.Id;
        if (changedGroup) ListScroll.SetScrollValue(Vector2.Zero);
        RefreshList(); RefreshDetail();
    }

    private void RefreshList()
    {
        if (_state == null) return;
        var scroll = ListScroll.GetScrollValue();
        MinistryList.RemoveAllChildren();
        var tabs = new[] { MinistriesTab, DepartmentsTab, BureausTab };
        for (var i = 0; i < tabs.Length; i++) tabs[i].StyleBoxOverride = Panel(i == _group ? "#1D4864" : "#101D29", "#41657A", 6);
        foreach (var entry in _state.Ministries.Where(m => m.KindGroup == _group))
        {
            var button = new ContainerButton { HorizontalExpand = true };
            button.StyleBoxOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex(entry.Id == _selected ? "#1A4050" : "#101C27"),
                BorderColor = entry.Color, BorderThickness = new Thickness(3, 0, 0, 0), ContentMarginLeftOverride = 10,
                ContentMarginRightOverride = 8, ContentMarginTopOverride = 6, ContentMarginBottomOverride = 6 };
            var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            text.AddChild(SWConsoleStyle.Wrap(entry.Name, SWConsoleStyle.TextBright, 180));
            text.AddChild(SWConsoleStyle.Wrap(Status(entry), entry.Claimed || entry.Locked ? SWConsoleStyle.TextDim : SWConsoleStyle.Good, 180));
            button.AddChild(text);
            button.OnPressed += _ => Select(entry);
            MinistryList.AddChild(button);
        }
        ListScroll.SetScrollValue(scroll);
    }

    private static string Status(SWMinistryEntry entry) => entry.Claimed ? "Занято" : entry.Locked ? "Недоступно" : "Свободно";
    private PanelContainer Section(string title, out BoxContainer contents)
    {
        var panel = new PanelContainer { HorizontalExpand = true, PanelOverride = Panel("#0B1722", "#2C4659", 12) };
        contents = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 8 };
        contents.AddChild(SWConsoleStyle.Wrap(title, SWConsoleStyle.TextDim, 400));
        panel.AddChild(contents);
        return panel;
    }

    private void RefreshDetail()
    {
        if (_state == null) return;
        var scroll = _detailSelection == _selected ? DetailScroll.GetScrollValue() : Vector2.Zero;
        _detailSelection = _selected;
        Dossier.RemoveAllChildren(); FooterText.RemoveAllChildren();
        var entry = _state.Ministries.FirstOrDefault(m => m.Id == _selected);
        if (entry != null)
        {
            var top = Section("ДОСЬЕ ВЕДОМСТВА", out var intro);
            var title = SWConsoleStyle.Wrap(entry.Name, SWConsoleStyle.TextBright, 440);
            title.Stylesheet = new Stylesheet(new StyleRule[] { StylesheetHelpers.Element<RichTextLabel>().Prop("font", _titleFont) });
            intro.AddChild(title);
            intro.AddChild(SWConsoleStyle.Wrap($"Портфель: {Status(entry).ToLowerInvariant()}", entry.Claimed || entry.Locked ? SWConsoleStyle.TextDim : SWConsoleStyle.Good, 440));
            if (entry.Claimed) intro.AddChild(SWConsoleStyle.Wrap($"Занимает: {entry.Holder ?? "неизвестно"}", SWConsoleStyle.TextBright, 440));
            if (entry.Locked && !string.IsNullOrEmpty(entry.LockedReason)) intro.AddChild(SWConsoleStyle.Wrap(entry.LockedReason, SWConsoleStyle.TextDim, 440));
            if (entry.ParentName != null) intro.AddChild(SWConsoleStyle.Wrap($"Подчинение: {entry.ParentName}", SWConsoleStyle.TextDim, 440));
            Dossier.AddChild(top);
            var description = Section("ОБЛАСТЬ ОТВЕТСТВЕННОСТИ", out var body);
            body.AddChild(SWConsoleStyle.Wrap(entry.Description, SWConsoleStyle.TextBright, 440));
            Dossier.AddChild(description);
            var children = _state.Ministries.Where(m => m.ParentId == entry.Id).ToArray();
            if (children.Length > 0)
            {
                var section = Section("ПОДЧИНЁННЫЕ ВЕДОМСТВА", out var list);
                foreach (var child in children)
                {
                    var card = Section(child.Name, out var info);
                    info.AddChild(SWConsoleStyle.Wrap(child.Description, SWConsoleStyle.TextBright, 400));
                    info.AddChild(SWConsoleStyle.Wrap(Status(child), child.Claimed || child.Locked ? SWConsoleStyle.TextDim : SWConsoleStyle.Good, 400));
                    if (child.Locked && child.LockedReason.Length > 0) info.AddChild(SWConsoleStyle.Wrap(child.LockedReason, SWConsoleStyle.TextDim, 400));
                    var open = new Button { Text = "Открыть досье", HorizontalAlignment = HAlignment.Right };
                    open.OnPressed += _ => Select(child);
                    info.AddChild(open); list.AddChild(card);
                }
                Dossier.AddChild(section);
            }
        }
        else Dossier.AddChild(SWConsoleStyle.Wrap("Выберите ведомство", SWConsoleStyle.TextDim, 400));
        var reason = !_state.HasCard ? "Вставьте карту министра" : !_state.IsMinisterCard ? "Нужна карта министра" :
            _state.Current != null ? $"Назначение закреплено: {_state.CurrentName ?? _state.Current}" :
            !_state.ModeActive ? "Сенат сейчас не работает" : !_state.DayActive ? "Назначение доступно только днём" :
            entry == null ? "Выберите ведомство" : entry.Claimed ? "Портфель занят" : entry.Locked ? entry.LockedReason : $"Выбрано: {entry.Name}";
        FooterText.AddChild(SWConsoleStyle.Wrap("КАРТА МИНИСТРА", SWConsoleStyle.TextDim, 400));
        FooterText.AddChild(SWConsoleStyle.Wrap(reason, SWConsoleStyle.TextBright, 400));
        ClaimButton.Disabled = _pending || !_state.HasCard || !_state.IsMinisterCard || _state.Current != null ||
            !_state.ModeActive || !_state.DayActive || entry == null || entry.Claimed || entry.Locked;
        ClaimButton.StyleBoxOverride = Panel(ClaimButton.Disabled ? "#273640" : "#205A80", "#4A90B7", 9);
        ClaimButton.Label.FontColorOverride = ClaimButton.Disabled ? SWConsoleStyle.TextDim : SWConsoleStyle.TextBright;
        DetailScroll.SetScrollValue(scroll);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        FitViewport(false);
    }

    private void FitViewport(bool initial)
    {
        var root = IoCManager.Resolve<IUserInterfaceManager>().WindowRoot;
        var viewport = root.Size;
        if (initial && (viewport.X <= 0 || viewport.Y <= 0) && root.UIScale > 0)
            viewport = (Vector2) IoCManager.Resolve<IClyde>().ScreenSize / root.UIScale;
        if (viewport.X <= 0 || viewport.Y <= 0 || !float.IsFinite(viewport.X) || !float.IsFinite(viewport.Y)) return;
        if (!initial && viewport == _viewport) return;
        _viewport = viewport;
        var limit = Vector2.Max(Vector2.One, viewport - new Vector2(24));
        MinSize = Vector2.Min(new Vector2(640, 460), limit);
        var current = initial ? new Vector2(1100, 780) : SetSize;
        if (!float.IsFinite(current.X) || !float.IsFinite(current.Y)) current = Size;
        SetSize = Vector2.Min(current, limit);
        if (!initial && IsOpen) { Measure(Vector2Helpers.Infinity); RecenterWindow(new Vector2(.5f)); }
    }
}

public sealed class SWMinistryLayout : Container
{
    protected override Vector2 MeasureOverride(Vector2 size)
    {
        if (ChildCount != 3) return base.MeasureOverride(size);
        Children[0].Measure(new Vector2(size.X, float.PositiveInfinity));
        Children[2].Measure(new Vector2(size.X, float.PositiveInfinity));
        Children[1].Measure(new Vector2(size.X, Math.Max(0, size.Y - Children[0].DesiredSize.Y - Children[2].DesiredSize.Y)));
        return new Vector2(Math.Max(Children[0].DesiredSize.X, Math.Max(Children[1].DesiredSize.X, Children[2].DesiredSize.X)),
            Children[0].DesiredSize.Y + Children[1].DesiredSize.Y + Children[2].DesiredSize.Y);
    }
    protected override Vector2 ArrangeOverride(Vector2 size)
    {
        if (ChildCount != 3) return base.ArrangeOverride(size);
        var header = Math.Min(size.Y, Children[0].DesiredSize.Y);
        var footer = Math.Min(Math.Max(0, size.Y - header), Children[2].DesiredSize.Y);
        var body = Math.Max(0, size.Y - header - footer);
        Children[0].Arrange(UIBox2.FromDimensions(Vector2.Zero, new Vector2(size.X, header)));
        Children[1].Arrange(UIBox2.FromDimensions(new Vector2(0, header), new Vector2(size.X, body)));
        Children[2].Arrange(UIBox2.FromDimensions(new Vector2(0, header + body), new Vector2(size.X, footer)));
        return size;
    }
}

public sealed class SWMinistryColumns : Container
{
    public bool Footer { get; set; }
    public float Gap { get; set; } = 10;
    private float _measuredWidth;
    private (float Left, float Right) Widths(float width)
    {
        var available = Math.Max(0, width - Gap);
        var right = Footer ? Math.Min(210, available) : available * .75f;
        return (available - right, right);
    }
    protected override Vector2 MeasureOverride(Vector2 size)
    {
        if (ChildCount != 2) return base.MeasureOverride(size);
        _measuredWidth = float.IsFinite(size.X) ? Math.Max(0, size.X) : 600;
        var (left, right) = Widths(_measuredWidth);
        Children[0].Measure(new Vector2(left, size.Y)); Children[1].Measure(new Vector2(right, size.Y));
        return new Vector2(_measuredWidth, Math.Max(Children[0].DesiredSize.Y, Children[1].DesiredSize.Y));
    }
    protected override Vector2 ArrangeOverride(Vector2 size)
    {
        if (ChildCount != 2) return base.ArrangeOverride(size);
        var (left, right) = Widths(Math.Min(size.X, _measuredWidth));
        Children[0].Arrange(UIBox2.FromDimensions(Vector2.Zero, new Vector2(left, size.Y)));
        Children[1].Arrange(UIBox2.FromDimensions(new Vector2(left + Gap, 0), new Vector2(right, size.Y)));
        return size;
    }
}
