using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using System;
using Robust.Client.AutoGenerated;

namespace Content.Client._SW.Vehicle.UI;

[GenerateTypedNameReferences]
public sealed partial class SWVehicleRoleControl : Control
{

    public SWVehicleRoleControl(string roleName, string roleId, Action<string> onTake, bool occupied)
    {
        RobustXamlLoader.Load(this);

        RoleLabel.Text = roleName;
        TakeButton.OnPressed += _ => onTake?.Invoke(roleId);
        TakeButton.Disabled = occupied;
    }
}
