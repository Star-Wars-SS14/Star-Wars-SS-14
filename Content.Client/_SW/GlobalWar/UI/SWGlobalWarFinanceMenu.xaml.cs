[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarFinanceMenu : SWGlobalWarWindow
{
    public event Action<BoundUserInterfaceMessage>? Send;
    private SWGlobalWarFinanceView? _view;
    private SWGlobalWarFinanceRequest? _pending;
    private readonly HashSet<Guid> _retiredGenerations = new();
    private readonly List<SWGlobalWarAccount> _accounts = new();
    private List<SWGlobalWarEmployeeView> _employees = new();
    private List<SWGlobalWarOrderView> _orders = new();
    private SWGlobalWarAccount _account;
    private SWGlobalWarAccount _destination = SWGlobalWarAccount.War;
    private SWGlobalWarAccount _orderAccount;
    private bool _orderFormOpen;
    private NetUserId? _employee;
    private Guid? _selectedOrder;
    private SWGlobalWarFinancePageRequest? _ordersRequest;
    private SWGlobalWarFinancePageRequest? _journalRequest;
    private bool _latestOrders = true;
    private bool _latestJournal = true;
    private long _oldestEntry = long.MaxValue;
    private long _seenRevision = -1;
    private long _journalRevision = -1;
    private readonly Stack<Guid> _newerOrders = new();
    private readonly Stack<(SWGlobalWarFinancePage Page, float Scroll)> _newerJournal = new();
    private SWGlobalWarFinancePage? _currentOrders;
    private SWGlobalWarFinancePage? _currentJournal;
    private readonly SWGlobalWarGovernmentDraftSystem _drafts = IoCManager.Resolve<IEntityManager>().System<SWGlobalWarGovernmentDraftSystem>();
    private SWGlobalWarGovernmentDraftSystem.Scope? _scope;
    private sealed record EditingState(string Amount, string Purpose, SWGlobalWarAccount Account,
        SWGlobalWarAccount Destination, NetUserId? Employee, Guid? Order, SWGlobalWarFinanceRequest? Pending, string Result);
    private string _resultText = string.Empty;

    public SWGlobalWarFinanceMenu()
    {
        RobustXamlLoader.Load(this);
        ContentsContainer.Margin = new Thickness(0);
        OnResized += FitWidth;
        Reserve.SetAppearance(SWGlobalWarConsoleStyle.TextBright, money: true);
        TreasuryBand.Scene = SWGlobalWarConsoleStyle.Picture("finance_" + SWGlobalWarConsoleStyle.SideLetter());
        TreasuryWord.FontOverride = ShareWord.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        TreasuryWord.FontColorOverride = ShareWord.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        TreasuryFree.FontOverride = SWGlobalWarConsoleStyle.Bold(26);
        TreasuryFree.FontColorOverride = Color.FromHex("#E9C17E");
        TreasuryTotals.FontOverride = SWGlobalWarConsoleStyle.Small;
        TreasuryTotals.FontColorOverride = SWGlobalWarConsoleStyle.TextBright;
        NewOrderTitle.FontOverride = SWGlobalWarConsoleStyle.Strong;
        NewOrderTitle.FontColorOverride = Color.White;
        JournalPanel.PanelOverride = SWGlobalWarConsoleStyle.RowBox(false);
        Add10.OnPressed += _ => AddAmount(10000);
        Add50.OnPressed += _ => AddAmount(50000);
        Add100.OnPressed += _ => AddAmount(100000);
        AddAll.OnPressed += _ =>
        {
            if (_view?.Budgets.FirstOrDefault(b => b.Account == _account) is { } source)
                Amount.Text = (source.Balance - source.Reserved).ToString(CultureInfo.InvariantCulture);
        };
        TreasuryOrder.OnPressed += _ =>
        {
            TreasurySlot.Visible = true;
            ToggleOrderForm(SWGlobalWarAccount.Treasury, TreasurySlot);
        };
        AccountSelector.OnItemSelected += args =>
        {
            AccountSelector.SelectId(args.Id);
            _account = (SWGlobalWarAccount) args.Id;
            RefreshControls();
        };
        EmployeeSelector.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= _employees.Count)
                return;
            EmployeeSelector.SelectId(args.Id);
            _employee = _employees[args.Id].User;
            RefreshControls();
        };
        Amount.OnTextChanged += _ => RefreshControls();
        Purpose.OnTextChanged += _ => RefreshControls();
        Reserve.OnPressed += _ => Request(SWGlobalWarFinanceAction.Reserve);
        Retry.OnPressed += _ => { if (_pending != null) Send?.Invoke(_pending); };
        LatestOrders.OnPressed += _ => { _newerOrders.Clear(); LoadPage(false); };
        OlderOrders.OnPressed += _ =>
        {
            if (_orders.Count == 0 || _currentOrders == null)
                return;
            _newerOrders.Push(_currentOrders.BeforeOrder);
            LoadPage(false, beforeOrder: _orders[0].Id);
        };
        NewerOrders.OnPressed += _ => { if (_newerOrders.TryPop(out var before)) LoadPage(false, beforeOrder: before); };
        LatestJournal.OnPressed += _ => { _newerJournal.Clear(); LoadPage(true); };
        OlderJournal.OnPressed += _ =>
        {
            if (_currentJournal != null)
                _newerJournal.Push((_currentJournal, JournalScroll.VScroll));
            LoadPage(true, _oldestEntry);
        };
        NewerJournal.OnPressed += _ =>
        {
            if (!_newerJournal.TryPop(out var saved))
                return;
            _journalRequest = new SWGlobalWarFinancePageRequest(saved.Page.Generation, saved.Page.AssignmentRevision,
                true, saved.Page.BeforeRevision, saved.Page.BeforeOrder);
            UpdatePage(saved.Page);
            UserInterfaceManager.DeferAction(() =>
            {
                if (!Disposed && _currentJournal == saved.Page)
                    JournalScroll.VScrollTarget = saved.Scroll;
            });
        };
    }

    public void UpdateView(SWGlobalWarFinanceView view)
    {
        if (view.Generation != Guid.Empty && _retiredGenerations.Contains(view.Generation) ||
            _view is { } previous && previous.Generation == view.Generation && previous.Revision > view.Revision)
            return;
        if (_view is { } old && old.Generation != Guid.Empty && old.Generation != view.Generation)
            _retiredGenerations.Add(old.Generation);
        if (_view?.Generation != view.Generation || _view?.Assignment != view.Assignment ||
            _view?.AssignmentRevision != view.AssignmentRevision || view.Availability != SWGlobalWarViewAvailability.Ready)
            ClearPrivateData();
        _view = view;
        if (view.Availability == SWGlobalWarViewAvailability.Ready)
        {
            var scope = _drafts.Authorize(SWGlobalWarGovernmentConsoleKind.Finance,
                view.Generation, view.Assignment, view.AssignmentRevision);
            if (_scope == null && scope is { } authorized &&
                _drafts.Restore<EditingState>(SWGlobalWarGovernmentConsoleKind.Finance, authorized) is { } saved)
            {
                Amount.Text = saved.Amount;
                Purpose.Text = saved.Purpose;
                _account = saved.Account;
                _destination = saved.Destination;
                _employee = saved.Employee;
                _selectedOrder = saved.Order;
                _pending = saved.Pending;
                _resultText = saved.Result;
                Plain(Result, _resultText);
            }
            _scope = scope;
        }
        else
        {
            _scope = null;
            _drafts.Revoke(SWGlobalWarGovernmentConsoleKind.Finance);
        }
        Content.Visible = view.Availability == SWGlobalWarViewAvailability.Ready;
        Plain(Status, Loc.GetString(view.Availability switch
        {
            SWGlobalWarViewAvailability.Ready => "sw-global-war-finance-authorized",
            SWGlobalWarViewAvailability.Forbidden => "sw-global-war-government-forbidden",
            _ => "sw-global-war-government-unavailable",
        }));
        if (!Content.Visible)
            return;
        ShowBalances(view.Budgets);
        var accounts = view.Budgets.Where(b => view.CanTransfer || b.CanManage).Select(b => b.Account).ToList();
        if (!_accounts.SequenceEqual(accounts))
        {
            _accounts.Clear();
            _accounts.AddRange(accounts);
            AccountSelector.Clear();
            foreach (var account in accounts)
                AccountSelector.AddItem(AccountName(account), (int) account);
            if (!accounts.Contains(_account) && accounts.Count != 0)
                _account = accounts[0];
            if (accounts.Count != 0)
                AccountSelector.SelectId((int) _account);
        }
        RefreshEmployees();
        if (_seenRevision != view.Revision)
        {
            _seenRevision = view.Revision;
            if (_latestOrders && _ordersRequest == null)
                LoadPage(false);
            if (_currentJournal == null && _journalRequest == null)
                LoadPage(true);
        }
        NewEntries.Visible = _journalRevision >= 0 && view.Revision != _journalRevision;
        if (_pending is { } pending && view.RecentResults.FirstOrDefault(r => r.Request == pending.Request) is { } result)
            UpdateResult(result);
        RefreshControls();
    }

    public void UpdateResult(SWGlobalWarFinanceResultView result)
    {
        if (_pending is not { } pending || pending.Request != result.Request)
            return;
        _pending = null;
        _resultText = result.Accepted ? Loc.GetString("sw-global-war-finance-result-" + pending.Action.ToString().ToLowerInvariant(),
            ("amount", result.EffectAmount), ("account", AccountName(pending.Account)),
            ("destination", AccountName(pending.Destination))) : FailureText(result.Failure);
        Plain(Result, _resultText);
        RefreshControls();
    }

    public void UpdatePage(SWGlobalWarFinancePage page)
    {
        var expected = page.Journal ? _journalRequest : _ordersRequest;
        if (_view is not { Availability: SWGlobalWarViewAvailability.Ready } view || expected == null ||
            page.Generation != view.Generation || page.AssignmentRevision != view.AssignmentRevision ||
            page.BeforeOrder != expected.BeforeOrder || page.BeforeRevision != expected.BeforeRevision)
            return;
        if (page.Journal)
        {
            _journalRequest = null;
            _currentJournal = page;
            _latestJournal = page.BeforeRevision == long.MaxValue;
            _oldestEntry = page.Entries.Count == 0 ? long.MaxValue : page.Entries[0].Revision;
            OlderJournal.Disabled = !page.Allowed || !page.HasOlder;
            NewerJournal.Disabled = _newerJournal.Count == 0;
            ShowJournal(page);
        }
        else
        {
            _ordersRequest = null;
            _currentOrders = page;
            _latestOrders = page.BeforeOrder == Guid.Empty;
            _orders = page.Allowed ? page.Orders : [];
            ShowOrders();
            OlderOrders.Disabled = !page.Allowed || !page.HasOlder;
            NewerOrders.Disabled = _newerOrders.Count == 0;
            OrdersPages.Visible = !OlderOrders.Disabled || !NewerOrders.Disabled;
            if (!page.Allowed)
                Plain(Result, Loc.GetString("sw-global-war-finance-page-expired"));
        }
        RefreshControls();
    }

    private void LoadPage(bool journal, long beforeRevision = long.MaxValue, Guid beforeOrder = default)
    {
        if (_view is not { Availability: SWGlobalWarViewAvailability.Ready } view)
            return;
        var request = new SWGlobalWarFinancePageRequest(view.Generation, view.AssignmentRevision, journal, beforeRevision, beforeOrder);
        if (journal && beforeRevision == long.MaxValue)
        {
            _journalRevision = view.Revision;
            NewEntries.Visible = false;
        }
        if (journal) _journalRequest = request;
        else _ordersRequest = request;
        Send?.Invoke(request);
    }

    private void AddAmount(long sum)
    {
        long.TryParse(Amount.Text, NumberStyles.None, CultureInfo.InvariantCulture, out var amount);
        Amount.Text = (amount + sum).ToString(CultureInfo.InvariantCulture);
    }

    private void RequestTransfer(SWGlobalWarAccount from, SWGlobalWarAccount to)
    {
        if (_view is not { Availability: SWGlobalWarViewAvailability.Ready } view || _pending != null || from == to)
            return;
        long.TryParse(Amount.Text, NumberStyles.None, CultureInfo.InvariantCulture, out var amount);
        _destination = to;
        _pending = new SWGlobalWarFinanceRequest(view.Generation, Guid.NewGuid(), view.AssignmentRevision,
            SWGlobalWarFinanceAction.Transfer, from, amount, to);
        Plain(Result, Loc.GetString("sw-global-war-government-pending"));
        Send?.Invoke(_pending);
        RefreshControls();
    }

    private void Request(SWGlobalWarFinanceAction action, SWGlobalWarOrderView? order = null)
    {
        if (_view is not { Availability: SWGlobalWarViewAvailability.Ready } view || _pending != null)
            return;
        long.TryParse(Amount.Text, NumberStyles.None, CultureInfo.InvariantCulture, out var amount);
        if (action == SWGlobalWarFinanceAction.Release && order?.CanRelease != true)
            return;
        _pending = new SWGlobalWarFinanceRequest(view.Generation, Guid.NewGuid(), view.AssignmentRevision, action,
            action == SWGlobalWarFinanceAction.Release && order != null ? order.Account : _orderAccount,
            action == SWGlobalWarFinanceAction.Release ? 0 : amount, _destination,
            action == SWGlobalWarFinanceAction.Release ? order?.Id ?? Guid.Empty : Guid.Empty,
            action == SWGlobalWarFinanceAction.Reserve ? _employee : null,
            action == SWGlobalWarFinanceAction.Reserve ? Purpose.Text : string.Empty);
        Plain(Result, Loc.GetString("sw-global-war-government-pending"));
        Send?.Invoke(_pending);
        RefreshControls();
    }

    private void RefreshEmployees()
    {
        var employees = _view?.Employees.Where(e => e.Account == _orderAccount).ToList() ?? [];
        if (_employees.SequenceEqual(employees))
            return;
        _employees = employees;
        EmployeeSelector.Clear();
        for (var i = 0; i < employees.Count; i++)
            EmployeeSelector.AddItem(employees[i].Name, i);
        if (!employees.Any(e => e.User == _employee))
            _employee = employees.Count == 0 ? null : employees[0].User;
        if (_employee != null)
            EmployeeSelector.SelectId(employees.FindIndex(e => e.User == _employee));
    }

    private void RefreshControls()
    {
        if (_view is not { } view)
            return;
        var transferProblem = false;
        var source = view.Budgets.FirstOrDefault(b => b.Account == _account);
        var budget = view.Budgets.FirstOrDefault(b => b.Account == _orderAccount);
        var canManage = view.Budgets.Any(b => b.CanManage);
        JournalPanel.Visible = view.Budgets.Count != 0;
        JournalRestricted.Visible = view.Budgets.Count == 0;
        OrdersTitle.Text = Loc.GetString(canManage ? "sw-global-war-finance-orders" : "sw-global-war-finance-my-orders");
        TreasuryOrder.Visible = view.Budgets.Any(b => b.Account == SWGlobalWarAccount.Treasury && b.CanManage);
        // While the budget shows, this line lives under the question mark.
        var who = Loc.GetString(view.CanTransfer || canManage ? "sw-global-war-finance-authorized" : "sw-global-war-finance-reader");
        Plain(Status, who);
        Status.Visible = !Content.Visible;
        HelpMark.ToolTip = who + "\n" + Loc.GetString("sw-global-war-finance-balance-hint");
        Result.Visible = _resultText.Length != 0 || _pending != null;
        var amountValid = long.TryParse(Amount.Text, NumberStyles.None, CultureInfo.InvariantCulture, out var amount) && amount > 0;
        var transferFailure = !view.CanTransfer ? SWGlobalWarFinanceFailure.Denied :
            !amountValid ? SWGlobalWarFinanceFailure.InvalidAmount :
            source == null ? SWGlobalWarFinanceFailure.Denied :
            amount > source.Balance - source.Reserved ? SWGlobalWarFinanceFailure.InsufficientFunds :
            SWGlobalWarFinanceFailure.None;
        var spendFailure = !amountValid ? SWGlobalWarFinanceFailure.InvalidAmount :
            budget == null ? SWGlobalWarFinanceFailure.Denied :
            amount > budget.Balance - budget.Reserved ? SWGlobalWarFinanceFailure.InsufficientFunds :
            SWGlobalWarFinanceFailure.None;
        var reserveFailure = budget?.CanManage != true ? SWGlobalWarFinanceFailure.Denied :
            spendFailure != SWGlobalWarFinanceFailure.None ? spendFailure :
            _employee == null ? SWGlobalWarFinanceFailure.EmployeeChanged :
            string.IsNullOrWhiteSpace(Purpose.Text) || Purpose.Text.Length > 200 ? SWGlobalWarFinanceFailure.InvalidPurpose :
            SWGlobalWarFinanceFailure.None;
        Transfers.Visible = view.CanTransfer;
        transferProblem = transferFailure != SWGlobalWarFinanceFailure.None;
        foreach (var (account, column) in _columns)
        {
            var back = view.Budgets.FirstOrDefault(b => b.Account == account);
            column.Here.Disabled = _pending != null || transferFailure != SWGlobalWarFinanceFailure.None || account == _account;
            column.Back.Disabled = _pending != null || !amountValid || back == null || amount > back.Balance - back.Reserved;
        }

        Reserve.Disabled = _pending != null || reserveFailure != SWGlobalWarFinanceFailure.None;
        Reserve.Text = amountValid ? Loc.GetString("sw-global-war-finance-reserve-amount", ("amount", amount)) :
            Loc.GetString("sw-global-war-finance-reserve");
        Plain(TransferHint, _pending != null ? Loc.GetString("sw-global-war-finance-waiting") : FailureText(transferFailure));
        Plain(ReserveHint, _pending != null ? Loc.GetString("sw-global-war-finance-waiting") :
            _employee == null && budget?.CanManage == true && spendFailure == SWGlobalWarFinanceFailure.None
                ? Loc.GetString("sw-global-war-finance-select-employee") : FailureText(reserveFailure));
        Retry.Visible = _pending != null;
        TransferHint.Visible = view.CanTransfer && (_pending != null || transferProblem);
    }

    private void ClearPrivateData()
    {
        _pending = null;
        _ordersRequest = null;
        _journalRequest = null;
        _seenRevision = -1;
        _journalRevision = -1;
        _scope = null;
        _currentOrders = null;
        _currentJournal = null;
        _newerOrders.Clear();
        _newerJournal.Clear();
        _resultText = string.Empty;
        _latestOrders = _latestJournal = true;
        _orders.Clear();
        _employees.Clear();
        _accounts.Clear();
        _employee = null;
        _selectedOrder = null;
        Purpose.Text = string.Empty;
        AccountSelector.Clear();
        EmployeeSelector.Clear();
        ShowBalances([]);
        Journal.RemoveAllChildren();
        ShowOrders();
        Plain(Result, string.Empty);
        Plain(TransferHint, string.Empty);
        Plain(ReserveHint, string.Empty);
        OlderJournal.Disabled = OlderOrders.Disabled = true;
        NewerJournal.Disabled = NewerOrders.Disabled = true;
    }

    /// <summary>Stores only personal input and the exact request identity under the current authorized attachment.</summary>
    public void SaveDraft()
    {
        if (_scope is { } scope)
            _drafts.Save(SWGlobalWarGovernmentConsoleKind.Finance, scope, new EditingState(Amount.Text,
                Purpose.Text, _account, _destination, _employee, _selectedOrder, _pending, _resultText));
    }

    private static string AccountName(SWGlobalWarAccount account) => Loc.GetString("sw-global-war-account-" + account.ToString().ToLowerInvariant());
    private static string FailureText(SWGlobalWarFinanceFailure failure) => failure == SWGlobalWarFinanceFailure.None
        ? string.Empty : Loc.GetString("sw-global-war-finance-failure-" + failure.ToString().ToLowerInvariant());
    private static string Clock(TimeSpan time) => $"{Math.Max(0, (int)time.TotalMinutes):00}:{Math.Max(0, time.Seconds):00}";
    private static void Plain(RichTextLabel label, string text) => label.SetMessage(SWGlobalWarConsoleStyle.MoneyMessage(text));
}
