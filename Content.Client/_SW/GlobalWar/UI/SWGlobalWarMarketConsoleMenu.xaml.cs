        MapTitle.FontOverride = SWGlobalWarConsoleStyle.Strong;
        MapTitle.FontColorOverride = Color.White;
        TransitMark.PanelOverride = SWTerminalStyle.Fill(SWGlobalWarConsoleStyle.Brass);
        WaitingMark.PanelOverride = SWTerminalStyle.Fill(SWGlobalWarConsoleStyle.TextDim);
        DemandMark.PanelOverride = SWTerminalStyle.Fill(SWGlobalWarConsoleStyle.RepublicText);
        SupplyMark.PanelOverride = SWTerminalStyle.Fill(SWGlobalWarConsoleStyle.Good);
        foreach (var foot in new[] { TransitLegend, WaitingLegend, DemandLegend, SupplyLegend, PlanetCount })
        {
            foot.FontOverride = SWGlobalWarConsoleStyle.Small;
            foot.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        }

        CardSpace.Texture = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>()
            .Frame0(new SpriteSpecifier.Rsi(new ResPath("_SW/Interface/MegaMode/space_card.rsi"), "background"));
        CardKind.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        CardStateIcon.TextureScale = new Vector2(1f);
        CardState.FontOverride = SWGlobalWarConsoleStyle.Body;
        CardName.FontOverride = SWGlobalWarConsoleStyle.NameLarge;
        CardName.FontColorOverride = Color.White;
        MapStatsSlot.AddChild(_mapStats);
        WideStatsSlot.AddChild(_wideStats);
        GoodsHeaderSlot.AddChild(SWGlobalWarMarketGoodRow.Header());
        DeliveryLine.FontOverride = SWGlobalWarConsoleStyle.Body;
        DeliveryLine.FontColorOverride = SWGlobalWarConsoleStyle.Bad;
        Delivery.MainFont = SWGlobalWarConsoleStyle.MainButton;
        Delivery.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        Delivery.OnPressed += _ =>
        {
            if (_openGood is { } good)
                ConfigureDeliveryHere(good.Id);
        };
        TrafficToggle.SetAppearance(SWGlobalWarConsoleStyle.TextBright, selected: true);
        SupplyBuy.SetAppearance(SWGlobalWarConsoleStyle.TextBright, money: true);
        // Explanations wait under the control they explain, so that a form reads as a form.
        SupplySave.ToolTip = Loc.GetString("sw-global-war-supply-future-line");
        SupplyApproveArsenal.ToolTip = Loc.GetString("sw-global-war-supply-approve-help");
