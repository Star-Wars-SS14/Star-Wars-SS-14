using Content.Client._SW.UserInterface;
using Content.Shared._SW.GlobalWar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._SW.GlobalWar.UI;

/// <summary>Counts down the term after death and offers only the returns the server currently allows.</summary>
[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarRespawnWindow : SWGlobalWarWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;

    private SWGlobalWarRespawnStateEvent? _state;
    private int _shownSeconds = -1;

    public event Action<Guid, bool>? OnChoice;

    public SWGlobalWarRespawnWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        // Closing would hide the only way back; the window goes away by itself on return or revival.
        CloseButton.Visible = false;
        CloseButton.Parent!.Visible = false;
        ContentsContainer.Margin = new Thickness(0);
        HelpMark.ToolTip = Loc.GetString("sw-global-war-respawn-rules");
        Word.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        Timer.FontOverride = SWGlobalWarConsoleStyle.Bold(54);
        CitizenTitle.FontOverride = ForceTitle.FontOverride = SWGlobalWarConsoleStyle.Strong;
        CitizenTitle.FontColorOverride = ForceTitle.FontColorOverride = Color.White;
        CitizenCard.PanelOverride = SWGlobalWarConsoleStyle.RowBox(false);
        ForceStrip.PanelOverride = SWTerminalStyle.Box(Color.FromHex("#1A1530"), Color.FromHex("#9B7BE8"), 1);
        Force.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        Civilian.MainFont = SWGlobalWarConsoleStyle.MainButton;
        Civilian.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        Civilian.OnPressed += _ => Choose(false);
        Force.OnPressed += _ => Choose(true);
    }

    public void Update(SWGlobalWarRespawnStateEvent state)
    {
        _state = state;
        _shownSeconds = -1;
        var side = SWGlobalWarConsoleStyle.SideLetter(state.Faction);
        var faction = state.Faction == SWGlobalWarFaction.Empire ? "empire" : "republic";
        Scene.Scene = SWGlobalWarConsoleStyle.Picture("respawn_" + side);
        CitizenArt.Texture = SWGlobalWarConsoleStyle.Picture("card_citizen_" + side);
        CitizenNote.SetMessage(Loc.GetString(state.ForceCarrier ? "sw-global-war-respawn-citizen-note-force" : "sw-global-war-respawn-citizen-note", ("faction", faction)));
        ForceTitle.Text = Loc.GetString("sw-global-war-respawn-force-title", ("faction", faction));
        Force.Text = Loc.GetString("sw-global-war-respawn-force-back", ("faction", faction));
        // On a small screen the scene gives way to the choice.
        var small = IoCManager.Resolve<IUserInterfaceManager>().WindowRoot.Size.Y < 640;
        Scene.SetHeight = small ? 104 : 200;
        Timer.FontOverride = SWGlobalWarConsoleStyle.Bold(small ? 30 : 54);
        SetSize = new System.Numerics.Vector2(SetSize.X, (state.ForceCarrier ? 556 : 470) - (small ? 96 : 0));
        Civilian.Text = Loc.GetString("sw-global-war-respawn-civilian", ("faction", Loc.GetString(
            state.Faction == SWGlobalWarFaction.Republic ? "sw-global-war-republic" : "sw-global-war-empire")));
        ForceNote.SetMessage(Loc.GetString("sw-global-war-respawn-force-home", ("faction", faction)));
        Refresh();
    }

    public void ShowResult(string message)
    {
        Result.SetMessage(message);
        Result.Visible = true;
        Refresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        Refresh();
    }

    private void Choose(bool force)
    {
        if (_state == null)
            return;
        Result.Visible = false;
        OnChoice?.Invoke(_state.Life, force);
    }

    private void Refresh()
    {
        if (_state == null)
            return;
        var left = _state.ReadyAt - _timing.CurTime;
        var seconds = Math.Max(0, (int) Math.Ceiling(left.TotalSeconds));
        if (seconds == _shownSeconds)
            return;
        _shownSeconds = seconds;
        var ready = seconds == 0;
        Timer.Text = $"{seconds / 60:00}:{seconds % 60:00}";
        Timer.FontColorOverride = ready ? SWGlobalWarConsoleStyle.Good : Color.White;
        Word.Text = Loc.GetString(ready ? "sw-global-war-respawn-word-ready" : "sw-global-war-respawn-word-wait");
        Word.FontColorOverride = ready ? SWGlobalWarConsoleStyle.Good : SWGlobalWarConsoleStyle.EmpireText;
        Status.SetMessage(ready
            ? Loc.GetString("sw-global-war-respawn-ready")
            : Loc.GetString("sw-global-war-respawn-countdown", ("time", $"{seconds / 60}:{seconds % 60:00}")));
        Civilian.Disabled = !ready || _state.CivilianDenied != null;
        CivilianReason.Visible = ready && _state.CivilianDenied != null;
        if (_state.CivilianDenied != null)
            CivilianReason.SetMessage(_state.CivilianDenied);
        ForceStrip.Visible = _state.ForceCarrier;
        ForceArt.Texture = SWGlobalWarConsoleStyle.Picture((ready && _state.ForceDenied == null ? "card_force_" : "card_force_off_") + SWGlobalWarConsoleStyle.SideLetter(_state.Faction));
        Force.Disabled = !ready || _state.ForceDenied != null;
        ForceReason.Visible = ready && _state.ForceDenied != null;
        if (_state.ForceDenied != null)
            ForceReason.SetMessage(_state.ForceDenied);
    }
}
