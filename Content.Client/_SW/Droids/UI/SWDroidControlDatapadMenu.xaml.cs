using Content.Client._SW.TurretConsole.UI.TurretControl;
using Content.Shared._SW.Droids;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._SW.Droids.UI;

[GenerateTypedNameReferences]
public sealed partial class SWDroidControlDatapadMenu : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    public event Action<string>? OnJobButtonPressed;
    public event Action<string>? OnFactionAllowButtonPressed;
    public event Action<string>? OnFactionDisallowButtonPressed;

    public SWDroidControlDatapadMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Tabs.SetTabTitle(0, Loc.GetString("sw-droid-control-datapad-tab-droids"));
        Tabs.SetTabTitle(1, Loc.GetString("sw-droid-control-datapad-tab-targets"));
    }

    public void UpdateState(SWDroidControlDatapadBoundUserInterfaceState state)
    {
        UpdateDroids(state.Droids);
        UpdateJobs(state.JobsAllowed);
        UpdateFactions(state.AvailableFactions);
    }

    private void UpdateDroids(List<SWDroidControlDatapadDroidEntry> droids)
    {
        DroidsList.Children.Clear();
        DroidsSummary.Text = Loc.GetString("sw-droid-control-datapad-droids-count", ("count", droids.Count));

        if (droids.Count == 0)
        {
            DroidsList.AddChild(new Label
            {
                Text = Loc.GetString("sw-droid-control-datapad-no-linked-droids")
            });
            return;
        }

        foreach (var droid in droids)
        {
            DroidsList.AddChild(CreateDroidEntry(droid));
        }
    }

    private Control CreateDroidEntry(SWDroidControlDatapadDroidEntry droid)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true
        };

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(6)
        };

        box.AddChild(new Label
        {
            Text = droid.Name,
            StyleClasses = { "LabelHeading" }
        });

        box.AddChild(new Label
        {
            Text = Loc.GetString("sw-droid-control-datapad-droid-status", ("status", droid.Status))
        });

        box.AddChild(new Label
        {
            Text = Loc.GetString("sw-droid-control-datapad-droid-charge", ("charge", droid.Charge))
        });

        box.AddChild(new Label
        {
            Text = Loc.GetString("sw-droid-control-datapad-droid-coordinates", ("coordinates", droid.Coordinates))
        });

        panel.AddChild(box);
        return panel;
    }

    private void UpdateJobs(Dictionary<string, bool> jobs)
    {
        AllowedJobsList.Children.Clear();
        DisallowedJobsList.Children.Clear();

        foreach (var (job, isAllowed) in jobs)
        {
            if (!_prototype.TryIndex<JobPrototype>(job, out var proto))
                continue;

            var control = new SWTurretConsoleControl(job, proto.LocalizedName);
            control.SendJob += selectedJob => OnJobButtonPressed?.Invoke(selectedJob);

            if (isAllowed)
                AllowedJobsList.AddChild(control);
            else
                DisallowedJobsList.AddChild(control);
        }
    }

    private void UpdateFactions(Dictionary<string, string> factions)
    {
        AllowFactionsList.Children.Clear();
        DisallowFactionsList.Children.Clear();

        foreach (var (id, name) in factions)
        {
            var button = new Button
            {
                Text = Loc.GetString("sw-droid-control-datapad-faction-allow", ("faction", name)),
                HorizontalExpand = true
            };
            button.OnPressed += _ => OnFactionAllowButtonPressed?.Invoke(id);
            AllowFactionsList.AddChild(button);
        }

        foreach (var (id, name) in factions)
        {
            var button = new Button
            {
                Text = Loc.GetString("sw-droid-control-datapad-faction-disallow", ("faction", name)),
                HorizontalExpand = true
            };
            button.OnPressed += _ => OnFactionDisallowButtonPressed?.Invoke(id);
            DisallowFactionsList.AddChild(button);
        }
    }
}
