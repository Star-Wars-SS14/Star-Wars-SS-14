using System.Linq;
using System.Numerics;
using Content.Shared._SW.GlobalWar.Politics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface.CustomControls;
using Robust.Shared.Utility;

namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarCharacterPanel : PanelContainer
{
    private readonly SWGlobalWarCharacterSystem _state;
    private List<SWGlobalWarAppointmentOfferView> _offers = new();
    private List<SWGlobalWarPersonnelTargetView> _targets = new();
    private List<SWGlobalWarPersonnelRoleView> _roles = new();
    private string _offerKey = string.Empty;
    private string _targetKey = string.Empty;
    private string _roleKey = string.Empty;

    public SWGlobalWarCharacterPanel(SWGlobalWarCharacterSystem state)
    {
        _state = state;
        RobustXamlLoader.Load(this);
        Stylesheet = SWGlobalWarConsoleStyle.Sheet();
        foreach (var main in new[] { Claim, Accept, SendOffer, Confirm })
            main.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        foreach (var selector in new[] { OfferSelector, TargetSelector, RoleSelector })
            ClipSelectorLabels(selector);
        Search.Text = state.Search;
        Search.OnTextChanged += _ => { state.Search = Search.Text; Refresh(); };
        OfferSelector.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= _offers.Count)
                return;
            state.Offer = _offers[args.Id].Id;
            state.OfferOpen = true;
            state.MarkOfferViewed(state.Offer.Value);
            Refresh();
        };
        OpenOffer.OnPressed += _ =>
        {
            state.OfferOpen = true;
            if (state.Offer is { } offer)
                state.MarkOfferViewed(offer);
            Refresh();
        };
        NextNotice.OnPressed += _ => state.OpenNextNotice();
        CloseOffer.OnPressed += _ => { state.OfferOpen = false; Refresh(); };
        TargetSelector.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= _targets.Count)
                return;
            var target = _targets[args.Id];
            state.Target = target.User;
            state.TargetRevision = target.Revision;
            state.TargetLost = false;
            state.Job = null;
            state.Confirmation = null;
            Refresh();
        };
        RoleSelector.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= _roles.Count)
                return;
            state.Job = _roles[args.Id].Job;
            Refresh();
        };
        Accept.OnPressed += _ => state.Request(SWGlobalWarAppointmentAction.Accept);
        Decline.OnPressed += _ => state.Request(SWGlobalWarAppointmentAction.Decline);
        Claim.OnPressed += _ => state.Request(SWGlobalWarAppointmentAction.ClaimHead);
        DeclineSuccession.OnPressed += _ => state.Request(SWGlobalWarAppointmentAction.DeclineSuccession);
        SendOffer.OnPressed += _ => state.Request(SWGlobalWarAppointmentAction.Offer);
        Resign.OnPressed += _ => Ask(SWGlobalWarAppointmentAction.Resign);
        Dismiss.OnPressed += _ => Ask(SWGlobalWarAppointmentAction.Dismiss);
        Confirm.OnPressed += _ =>
        {
            if (state.Confirmation is { } action)
                state.Request(action);
        };
        Cancel.OnPressed += _ => { state.Confirmation = null; Refresh(); };
        Retry.OnPressed += _ => state.Retry();
        Refresh();
    }

    private void Ask(SWGlobalWarAppointmentAction action)
    {
        _state.Confirmation = action;
        Refresh();
        UserInterfaceManager.DeferAction(() =>
        {
            if (Disposed || !ConfirmPanel.Visible)
                return;
            for (var parent = Parent; parent != null; parent = parent.Parent)
                if (parent is ScrollContainer scroll)
                {
                    scroll.VScrollTarget = Position.Y + ConfirmPanel.Position.Y;
                    break;
                }
        });
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        var available = Vector2.Max(new Vector2(1), UserInterfaceManager.RootControl.Size - new Vector2(24));
        for (Control? parent = Parent; parent != null; parent = parent.Parent)
        {
            if (parent is ScrollContainer scroll)
                scroll.HScrollEnabled = false;
            if (parent is not BaseWindow window)
                continue;
            window.MinSize = Vector2.Min(window.MinSize, available);
            window.MaxSize = available;
            window.SetSize = Vector2.Min(Vector2.Max(window.Size, window.MinSize), available);
            break;
        }
    }

    private static void ClipSelectorLabels(Control control)
    {
        if (control is Label label)
            label.ClipText = true;
        foreach (var child in control.Children)
            ClipSelectorLabels(child);
    }

    public void Refresh()
    {
        var view = _state.View;
        Visible = view != null && view.Availability != SWGlobalWarViewAvailability.Unavailable;
        var pending = _state.Pending != null;
        NextNotice.Visible = _state.HasUnread;
        Retry.Visible = pending;
        Set(Result, pending ? Loc.GetString("sw-global-war-service-pending") :
            _state.Result.Length == 0 ? string.Empty :
                Loc.GetString("sw-global-war-service-result", ("result", _state.Result)));
        Service.Visible = view?.Availability == SWGlobalWarViewAvailability.Ready;
        Set(Status, view == null ? Loc.GetString("sw-global-war-government-loading") :
            view.Availability == SWGlobalWarViewAvailability.Ready ? string.Empty :
            Loc.GetString("sw-global-war-service-unavailable"));
        if (view is not { Availability: SWGlobalWarViewAvailability.Ready })
        {
            // Revocation also removes text from hidden controls and popup models.
            OfferSelector.Clear();
            TargetSelector.Clear();
            RoleSelector.Clear();
            _offers.Clear();
            _targets.Clear();
            _roles.Clear();
            _offerKey = _targetKey = _roleKey = string.Empty;
            foreach (var label in new[] { CurrentRole, Head, SuccessionText, OfferDescription, OfferFailure,
                         TargetHint, Proposal, ConfirmText, Outgoing, WithdrawalReason, WithdrawalState,
                         WithdrawalShip, WithdrawalCargo })
                Set(label, string.Empty);
            Search.Text = string.Empty;
            return;
        }
        if (Search.Text != _state.Search)
            Search.Text = _state.Search;
        Set(CurrentRole, Loc.GetString("sw-global-war-service-current", ("role", Role(view.Role))));
        Set(Head, view.HeadReserveRemaining is { } reserve
            ? Loc.GetString("sw-global-war-service-head-reserve", ("time", Clock(reserve)))
            : Loc.GetString("sw-global-war-service-head", ("name", view.Head.Length == 0
                ? Loc.GetString("sw-global-war-service-vacant") : view.Head)));
        Resign.Visible = view.Role != null;
        Withdrawal.Visible = view.Withdrawal != null;
        if (view.Withdrawal is { } withdrawal)
        {
            Set(WithdrawalReason, Loc.GetString("sw-global-war-service-withdrawal-reason-" +
                withdrawal.Reason.ToString().ToLowerInvariant(), ("sector", withdrawal.Sector)));
            Set(WithdrawalState, WithdrawalSummary(withdrawal));
            WithdrawalLimits.Visible = withdrawal.Active;
            Set(WithdrawalShip, Loc.GetString(withdrawal.ShipReturned
                ? "sw-global-war-service-ship-returned" : "sw-global-war-service-ship-unconfirmed"));
            Set(WithdrawalCargo, Loc.GetString(withdrawal.ShipReturned
                ? "sw-global-war-service-cargo-returned" : "sw-global-war-service-cargo-unconfirmed"));
        }
        Resign.Disabled = pending || !view.Living;
        Succession.Visible = view.Succession != null;
        if (view.Succession is { } succession)
        {
            Set(SuccessionText, Loc.GetString("sw-global-war-service-stage-" + succession.Stage,
                ("time", Clock(succession.Remaining))) + "\n" + Loc.GetString(succession.Eligible
                ? "sw-global-war-service-eligible" : "sw-global-war-service-wait-stage"));
            Claim.Disabled = pending || !view.Living || !succession.Eligible;
            DeclineSuccession.Visible = succession.Stage < 2 && succession.Eligible;
            DeclineSuccession.Disabled = pending || !view.Living;
        }
        Incoming.Visible = view.Offers.Count != 0;
        var offerKey = string.Join('|', view.Offers.Select(o => $"{o.Id}:{o.Sender}:{o.Role}"));
        if (_offerKey != offerKey || OfferSelector.ItemCount == 0)
        {
            _offerKey = offerKey;
            _offers = view.Offers.ToList();
            OfferSelector.Clear();
            OfferSelector.AddItem(Loc.GetString("sw-global-war-service-select-offer"), -1);
            for (var i = 0; i < _offers.Count; i++)
                OfferSelector.AddItem(Loc.GetString("sw-global-war-service-offer-option",
                    ("name", _offers[i].Sender), ("role", Role(_offers[i].Role))), i);
        }
        var selectedOffer = view.Offers.FirstOrDefault(o => o.Id == _state.Offer);
        OfferSelector.SelectId(_offers.FindIndex(o => o.Id == _state.Offer));
        OfferSelector.Disabled = pending;
        OpenOffer.Disabled = selectedOffer == null;
        OpenOffer.Visible = !_state.OfferOpen;
        OfferCard.Visible = _state.OfferOpen && selectedOffer != null;
        if (selectedOffer != null)
        {
            Set(OfferDescription, Loc.GetString("sw-global-war-service-offer-description", ("name", selectedOffer.Sender),
                ("senderRole", Role(selectedOffer.SenderRole)), ("current", Role(view.Role)),
                ("role", Role(selectedOffer.Role))));
            Set(OfferFailure, selectedOffer.Failure == SWGlobalWarAppointmentFailure.None ? string.Empty :
                selectedOffer.Failure == SWGlobalWarAppointmentFailure.LocationForbidden
                    ? Loc.GetString("sw-global-war-service-offer-location") :
                Loc.GetString("sw-global-war-service-offer-stale", ("reason", Failure(selectedOffer.Failure))));
            Accept.Disabled = pending || !view.Living || selectedOffer.Failure != SWGlobalWarAppointmentFailure.None;
            Decline.Disabled = pending || !view.Living;
        }
        RefreshPersonnel(view, pending);
        Set(Outgoing, string.Join('\n', view.Outgoing.Select(o => Loc.GetString("sw-global-war-service-outgoing-" +
                (o.Status == SWGlobalWarOfferStatus.Pending && o.Failure != SWGlobalWarAppointmentFailure.None
                    ? "unavailable" : o.Status.ToString().ToLowerInvariant()),
                ("name", o.Recipient), ("role", Role(o.Role))) +
            (o.Failure == SWGlobalWarAppointmentFailure.None ? string.Empty : "\n" + Failure(o.Failure)))));
    }

    private void RefreshPersonnel(SWGlobalWarCharacterView view, bool pending)
    {
        Personnel.Visible = view.Roles.Count != 0 || view.Targets.Any(t => t.CanDismiss);
        var targets = view.Targets.Where(t => t.Name.Contains(_state.Search, StringComparison.CurrentCultureIgnoreCase) ||
            t.User == _state.Target).OrderBy(t => t.Name).ThenBy(t => t.User.ToString()).ToList();
        var targetKey = string.Join('|', targets.Select(t => $"{t.User}:{t.Revision}:{t.Name}"));
        if (_targetKey != targetKey || TargetSelector.ItemCount == 0)
        {
            _targetKey = targetKey;
            _targets = targets;
            TargetSelector.Clear();
            TargetSelector.AddItem(Loc.GetString("sw-global-war-service-select-target"), -1);
            for (var i = 0; i < targets.Count; i++)
                TargetSelector.AddItem(Loc.GetString("sw-global-war-service-target-option", ("name", targets[i].Name),
                    ("role", Role(targets[i].Role))), i);
        }
        TargetSelector.SelectId(_targets.FindIndex(t => t.User == _state.Target && t.Revision == _state.TargetRevision));
        TargetSelector.Disabled = pending;
        Search.Editable = !pending;
        var target = view.Targets.FirstOrDefault(t => t.User == _state.Target && t.Revision == _state.TargetRevision);
        Set(TargetHint, _state.TargetLost ? Loc.GetString("sw-global-war-service-target-lost") :
            target == null ? Loc.GetString("sw-global-war-service-select-target") :
            Loc.GetString("sw-global-war-service-target-option", ("name", target.Name), ("role", Role(target.Role))));
        var roles = view.Roles.Where(r => target?.Jobs.Contains(r.Job) == true).ToList();
        var roleKey = string.Join('|', roles.Select(r => $"{r.Job}:{r.Available}"));
        if (_roleKey != roleKey || RoleSelector.ItemCount == 0)
        {
            _roleKey = roleKey;
            _roles = roles;
            RoleSelector.Clear();
            RoleSelector.AddItem(Loc.GetString("sw-global-war-service-select-role"), -1);
            for (var i = 0; i < roles.Count; i++)
                RoleSelector.AddItem(roles[i].Available ? Role(roles[i].Role) :
                    Loc.GetString("sw-global-war-service-role-full", ("role", Role(roles[i].Role))), i);
        }
        var role = roles.FirstOrDefault(r => r.Job == _state.Job);
        if (role == null)
            _state.Job = null;
        RoleSelector.SelectId(_roles.FindIndex(r => r.Job == _state.Job));
        RoleSelector.Disabled = pending || target == null;
        Set(Proposal, target != null && role != null ? Loc.GetString("sw-global-war-service-proposal",
            ("name", target.Name), ("role", Role(role.Role))) : string.Empty);
        SendOffer.Disabled = pending || !view.Living || target == null || role?.Available != true;
        Dismiss.Disabled = pending || !view.Living || target?.CanDismiss != true;
        ConfirmPanel.Visible = _state.Confirmation != null;
        Confirm.Disabled = pending || !view.Living ||
            (_state.Confirmation == SWGlobalWarAppointmentAction.Dismiss && target?.CanDismiss != true);
        Set(ConfirmText, _state.Confirmation == SWGlobalWarAppointmentAction.Dismiss && target != null
            ? Loc.GetString("sw-global-war-service-confirm-dismiss", ("name", target.Name), ("role", Role(target.Role)))
            : Loc.GetString("sw-global-war-service-confirm-resign", ("role", Role(view.Role))));
    }

    public static string Role(SWGlobalWarRole? role)
    {
        return Loc.GetString("sw-global-war-role-" + (role ?? SWGlobalWarRole.Civilian).ToString().ToLowerInvariant());
    }

    public static string Failure(SWGlobalWarAppointmentFailure failure)
    {
        return Loc.GetString("sw-global-war-service-failure-" + failure.ToString().ToLowerInvariant());
    }

    public static string WithdrawalSummary(SWGlobalWarWithdrawalView withdrawal)
    {
        var key = withdrawal.Status.ToString().ToLowerInvariant();
        if (withdrawal.Status == SWGlobalWarWithdrawalStatus.Countdown && withdrawal.Remaining <= TimeSpan.Zero)
            key = "checking";
        if (withdrawal.Status == SWGlobalWarWithdrawalStatus.Cancelled && withdrawal.WarResumed)
            key = "war";
        return Loc.GetString("sw-global-war-service-withdrawal-" + key, ("time", Clock(withdrawal.Remaining)),
            ("destination", withdrawal.Destination ?? Loc.GetString("sw-global-war-service-confirmed-point")));
    }

    public static string WithdrawalIndicator(SWGlobalWarWithdrawalView withdrawal)
    {
        var key = withdrawal.Status == SWGlobalWarWithdrawalStatus.Countdown && withdrawal.Remaining > TimeSpan.Zero
            ? "countdown" : withdrawal.Status.ToString().ToLowerInvariant();
        if (key == "countdown" && withdrawal.Remaining <= TimeSpan.Zero)
            key = "checking";
        return Loc.GetString("sw-global-war-service-indicator-" + key, ("time", Clock(withdrawal.Remaining)));
    }

    public static string Clock(TimeSpan remaining)
    {
        var seconds = (int) Math.Ceiling(Math.Max(0, remaining.TotalSeconds));
        return $"{seconds / 60:00}:{seconds % 60:00}";
    }

    public void ShowNotice(SWGlobalWarCharacterSystem.Notice notice)
    {
        Control target = notice.Kind switch
        {
            "offer" => OfferCard,
            "succession" => Succession,
            "withdrawal" => Withdrawal,
            _ => Outgoing,
        };
        if (notice.Kind == "offer" && _state.View?.Offers.Any(o => o.Id == notice.Id) == true)
        {
            _state.Offer = notice.Id;
            _state.OfferOpen = true;
        }
        Refresh();
        UserInterfaceManager.DeferAction(() =>
        {
            if (Disposed || !target.VisibleInTree)
                return;
            var y = 0f;
            for (Control? current = target; current?.Parent != null; current = current.Parent)
            {
                if (current.Parent is ScrollContainer scroll)
                {
                    scroll.VScrollTarget = y;
                    _state.MarkViewed(notice);
                    break;
                }
                y += current.Position.Y;
            }
        });
    }

    private static void Set(RichTextLabel label, string text)
    {
        label.Visible = text.Length != 0;
        var message = new FormattedMessage();
        message.AddText(text);
        label.SetMessage(message);
    }
}
