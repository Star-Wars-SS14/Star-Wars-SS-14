    private void ShowMoveConfirmation()
    {
        Details.RemoveAllChildren();
        _detailStatus = null;
        _detailTime = null;
        InspectorTitle.Text = "Перенос";
        Details.AddChild(SWConsoleStyle.Text($"Новое время: {SWPlannerSlots.Range(_slot, _moveDuration)}", SWConsoleStyle.TextBright, SWConsoleStyle.Strong));
        if (_selectedMeeting >= 0)
            Details.AddChild(SWConsoleStyle.Text("Участникам потребуется ответить заново.", SWConsoleStyle.Warn, SWConsoleStyle.Small));
        // The aggregate busy mask cannot distinguish this event from another event in
        // the same slots. Keep its bits: overlap may be the source itself, so warn
        // conservatively instead of hiding a real collision.
        (ulong Mask, bool Unknown) CurrentBusy()
        {
            if (_state == null) return (0UL, true);
            var mask = _draftDay == _state.Today ? _state.MyBusyToday : _state.MyBusyTomorrow;
            var meeting = _state.Meetings.FirstOrDefault(m => m.Id == _selectedMeeting && m.IsHost);
            if (_selectedMeeting >= 0 && meeting == null) return (mask, true);
            if (meeting == null) return (mask, false);
            var unknown = false;
            foreach (var name in meeting.InviteeNames)
            {
                var person = _state.Roster.FirstOrDefault(p => p.Name == name);
                if (person == null) { unknown = true; continue; }
                mask |= _draftDay == _state.Today ? person.BusyToday : person.BusyTomorrow;
            }
            return (mask, unknown);
        }
        var busy = CurrentBusy();
        var conflict = busy.Unknown || SWPlannerSlots.Overlaps(busy.Mask, _slot, _moveDuration);
        var conflictNotice = SWConsoleStyle.Wrap("В это время возможен конфликт с расписанием участников; проверьте события перед переносом.", SWConsoleStyle.Warn, 300);
        conflictNotice.Visible = conflict;
        Details.AddChild(conflictNotice);
        var armed = false;
        var armedBusy = (Mask: 0UL, Unknown: false);
        var confirm = SWConsoleStyle.Action("Перенести", SWConsoleStyle.Accent);
        _moveConfirm = confirm;
        confirm.Disabled = _slot + _moveDuration > SWPlannerSlots.PerDay;
        confirm.OnPressed += _ =>
        {
            if (_awaitingMove || _state == null || !_state.HasCard || _draftDay < _state.Today || _draftDay > _state.Today + 1) return;
            var latestBusy = CurrentBusy();
            var latestConflict = latestBusy.Unknown || SWPlannerSlots.Overlaps(latestBusy.Mask, _slot, _moveDuration);
            conflictNotice.Visible = latestConflict;
            if (latestConflict && (!armed || armedBusy != latestBusy))
            {
                armed = true;
                armedBusy = latestBusy;
                confirm.Text = "Всё равно перенести?";
                return;
            }
            _moveMeetingId = _selectedMeeting;
            _moveBlockId = _selectedBlock;
            _pendingMoveDay = _draftDay;
            _pendingMoveSlot = _slot;
            _pendingMoveDuration = _moveDuration;
            if (_selectedMeeting >= 0) _owner.Reschedule(_selectedMeeting, _draftDay, _slot, _moveDuration);
            else if (_selectedBlock >= 0) _owner.RescheduleBlock(_selectedBlock, _draftDay, _slot, _moveDuration);
            confirm.Disabled = true;
            _awaitingMove = true;
        };
        Details.AddChild(confirm);
        var cancel = SWConsoleStyle.Action("Отмена", SWConsoleStyle.TextDim);
        cancel.OnPressed += _ => { _moving = false; Details.RemoveAllChildren(); InspectorTitle.Text = "Выберите время или событие"; };
        Details.AddChild(cancel);
    }

    private void AddDeleteButton(bool meeting)
    {
        var button = SWConsoleStyle.Action(meeting ? "Отменить встречу" : "Удалить запись", SWConsoleStyle.Bad);
        _deleteButton = button;
        button.OnPressed += _ =>
        {
            if (!_confirmDelete) { _confirmDelete = true; button.Text = "Подтвердить удаление"; return; }
            if (meeting) _owner.Cancel(_selectedMeeting); else _owner.RemoveBlock(_selectedBlock);
            button.Disabled = true;
        };
        Details.AddChild(button);
    }

    private static string ResponseText(SWInviteStatus status) => "Ваш ответ: " + (status switch
    {
        SWInviteStatus.Accepted => "принято",
        SWInviteStatus.Declined => "отклонено",
        _ => "ожидает ответа",
    });

    private void AddResponse(SWPlannerMeetingEntry meeting)
    {
        _responseStatus = SWConsoleStyle.Text(ResponseText(meeting.MyStatus), SWConsoleStyle.TextDim, SWConsoleStyle.Small);
        Details.AddChild(_responseStatus);
        var reason = new LineEdit { PlaceHolder = "Причина отказа (необязательно)" };
        if (_reasons.TryGetValue(meeting.Id, out var saved)) reason.Text = saved;
        reason.OnTextChanged += args => _reasons[meeting.Id] = args.Text;
        Details.AddChild(reason);
        var accept = SWConsoleStyle.Action("Принять", SWConsoleStyle.Good);
        accept.OnPressed += _ => _owner.Respond(meeting.Id, true, string.Empty);
        Details.AddChild(accept);
        var decline = SWConsoleStyle.Action("Отказаться", SWConsoleStyle.Bad);
        decline.OnPressed += _ => _owner.Respond(meeting.Id, false, reason.Text);
        Details.AddChild(decline);
    }

    private void ShowInvitations()
    {
        SaveDraftPosition();
        _mode = "invitations";
        _deleteButton = null;
        _moving = false;
