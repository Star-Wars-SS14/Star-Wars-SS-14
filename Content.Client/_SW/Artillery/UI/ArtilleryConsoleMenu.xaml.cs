using Content.Client.UserInterface.Controls;
using System.Threading;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Utility;
using Timer = Robust.Shared.Timing.Timer;

namespace Content.Client._SW.Artillery.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class ArtilleryConsoleMenu : FancyWindow
    {
        private ArtilleryConsoleBoundUserInterface Owner { get; set; }
        private readonly CancellationTokenSource _timerCancelTokenSource = new();

        [Dependency] private readonly IConfigurationManager _cfg = default!;

        public ArtilleryConsoleMenu(ArtilleryConsoleBoundUserInterface owner)
        {
            IoCManager.InjectDependencies(this);
            RobustXamlLoader.Load(this);

            Owner = owner;
            ArtilleryButton.OnPressed += (_) => Owner.CallArtileryButtonPressed(Rope.Collapse(CoordsX.TextRope), Rope.Collapse(CoordsY.TextRope));
            UpdateCountdown();
            Timer.SpawnRepeating(1000, UpdateCountdown, _timerCancelTokenSource.Token);
        }
        public void UpdateCountdown()
        {

        }

        public override void Close()
        {
            base.Close();

            _timerCancelTokenSource.Cancel();
        }

        protected override void Dispose(bool disposing)
        {
            base.Dispose(disposing);

            if (disposing)
                _timerCancelTokenSource.Cancel();
        }
    }
}
