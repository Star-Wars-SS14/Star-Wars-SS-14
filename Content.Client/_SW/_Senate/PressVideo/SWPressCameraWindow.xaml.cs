using Content.Shared._SW._Senate.PressVideo;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._SW._Senate.PressVideo;

[GenerateTypedNameReferences]
public sealed partial class SWPressCameraWindow : FancyWindow
{
    public event Action<string>? Start;
    public event Action? Stop;

    public SWPressCameraWindow()
    {
        RobustXamlLoader.Load(this);
        SWConsoleStyle.StyleRoot(RootPanel);
        SWConsoleStyle.StyleHeader(HeaderPanel);
        StartButton.OnPressed += _ =>
        {
            SetError(string.Empty);
            Start?.Invoke(Topic.Text);
        };
        StopButton.OnPressed += _ =>
        {
            SetError(string.Empty);
            Stop?.Invoke();
        };
    }

    public void SetError(string text)
    {
        var message = new FormattedMessage();
        message.AddText(text);
        Error.SetMessage(message);
        Error.Visible = !string.IsNullOrEmpty(text);
    }

    public void SetState(SWPressVideoState state)
    {
        var live = state.Camera != null;
        if (live)
            SetError(string.Empty);
        Status.Text = !live ? "Эфир выключен" : state.IsSource ? "Идёт эфир с этой камеры" : "Идёт эфир с другой камеры";
        StartButton.Disabled = live;
        StopButton.Disabled = !state.IsSource;
    }
}
