using Content.Shared._SW.Droids;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.Droids.UI;

[GenerateTypedNameReferences]
public sealed partial class SWDroidControlConsoleMenu : DefaultWindow
{
    public event Action<NetEntity>? OnDatapadTogglePressed;

    public SWDroidControlConsoleMenu()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(SWDroidControlConsoleBoundUserInterfaceState state)
    {
        DatapadsList.Children.Clear();
        Summary.Text = Loc.GetString("sw-droid-control-console-datapads-count", ("count", state.Datapads.Count));

        if (state.Datapads.Count == 0)
        {
            DatapadsList.AddChild(new Label
            {
                Text = Loc.GetString("sw-droid-control-console-no-datapads")
            });
            return;
        }

        foreach (var datapad in state.Datapads)
        {
            var control = new SWDroidControlConsoleDatapadControl(datapad);
            control.OnTogglePressed += uid => OnDatapadTogglePressed?.Invoke(uid);
            DatapadsList.AddChild(control);
        }
    }
}
