using Content.Shared._SW.Lathe;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using System.Linq;

namespace Content.Client._SW.Lathe.SWLathe.UI;

[GenerateTypedNameReferences]
public sealed partial class SWLatheMenu : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    public event Action<string?>? OnRecipeSelected;

    private readonly List<string> _recipeIds = new();
    private SWLatheBoundUserInterfaceState? _state;
    private bool _updatingMode;

    public SWLatheMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ModeOption.OnItemSelected += OnModeSelected;
    }

    public void Populate(SWLatheBoundUserInterfaceState state)
    {
        _state = state;
        PopulateModeSelector(state);
        PopulateRecipes(state);
        PopulateMaterials(state);

        CurrentProductionLabel.Text = state.CurrentRecipe == null
            ? Loc.GetString("sw-lathe-menu-current-production-none")
            : GetRecipeDisplayName(state.Recipes.FirstOrDefault(recipe => recipe.Id == state.CurrentRecipe));
    }

    private void PopulateModeSelector(SWLatheBoundUserInterfaceState state)
    {
        _updatingMode = true;
        _recipeIds.Clear();
        ModeOption.Clear();
        ModeOption.AddItem(Loc.GetString("sw-lathe-menu-mode-auto"), 0);

        for (var i = 0; i < state.Recipes.Count; i++)
        {
            var recipe = state.Recipes[i];
            _recipeIds.Add(recipe.Id);
            ModeOption.AddItem(GetRecipeDisplayName(recipe), i + 1);
        }

        var selectedId = 0;
        if (state.SelectedRecipe != null)
        {
            var index = _recipeIds.IndexOf(state.SelectedRecipe);
            if (index >= 0)
                selectedId = index + 1;
        }

        ModeOption.SelectId(selectedId);
        _updatingMode = false;
    }

    private void PopulateRecipes(SWLatheBoundUserInterfaceState state)
    {
        RecipeList.RemoveAllChildren();

        foreach (var recipe in state.Recipes)
        {
            var selected = state.SelectedRecipe == recipe.Id;
            var ready = CanProduce(recipe, state.StashedMaterials);
            var container = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(4, 4),
            };

            container.AddChild(new Label
            {
                Text = GetRecipeDisplayName(recipe),
                StyleClasses = { "LabelKeyText" },
            });

            container.AddChild(new Label
            {
                Text = Loc.GetString("sw-lathe-menu-recipe-inputs", ("materials", FormatItemList(recipe.Materials))),
            });

            container.AddChild(new Label
            {
                Text = Loc.GetString("sw-lathe-menu-recipe-outputs", ("results", FormatItemList(recipe.Result))),
            });

            container.AddChild(new Label
            {
                Text = Loc.GetString("sw-lathe-menu-recipe-time", ("time", Math.Round(recipe.ProduceTime, 3))),
            });

            container.AddChild(new Label
            {
                Text = ready
                    ? Loc.GetString("sw-lathe-menu-recipe-ready")
                    : Loc.GetString("sw-lathe-menu-recipe-missing"),
            });

            var button = new Button
            {
                Text = selected
                    ? Loc.GetString("sw-lathe-menu-selected-button")
                    : Loc.GetString("sw-lathe-menu-select-button"),
                Disabled = selected,
                HorizontalExpand = true,
            };

            var recipeId = recipe.Id;
            button.OnPressed += _ => OnRecipeSelected?.Invoke(recipeId);
            container.AddChild(button);

            RecipeList.AddChild(container);
        }
    }

    private void PopulateMaterials(SWLatheBoundUserInterfaceState state)
    {
        MaterialsList.RemoveAllChildren();

        if (state.StashedMaterials.Count == 0)
        {
            MaterialsList.AddChild(new Label { Text = Loc.GetString("sw-lathe-menu-no-materials") });
            return;
        }

        foreach (var (id, amount) in state.StashedMaterials.OrderBy(pair => GetEntityName(pair.Key)))
        {
            MaterialsList.AddChild(new Label
            {
                Text = Loc.GetString(
                    "sw-lathe-menu-material-entry",
                    ("material", GetEntityName(id)),
                    ("amount", amount),
                    ("limit", state.MaxMaterialAmount)),
            });
        }
    }

    private void OnModeSelected(OptionButton.ItemSelectedEventArgs args)
    {
        if (_updatingMode)
            return;

        ModeOption.SelectId(args.Id);

        if (args.Id == 0)
        {
            OnRecipeSelected?.Invoke(null);
            return;
        }

        var index = args.Id - 1;
        if (index >= 0 && index < _recipeIds.Count)
            OnRecipeSelected?.Invoke(_recipeIds[index]);
    }

    private bool CanProduce(SWLatheRecipeInfo recipe, Dictionary<string, int> stashedMaterials)
    {
        foreach (var (id, amount) in recipe.Materials)
        {
            if (!stashedMaterials.TryGetValue(id, out var stashed) || stashed < amount)
                return false;
        }

        return true;
    }

    private string GetRecipeDisplayName(SWLatheRecipeInfo? recipe)
    {
        if (recipe == null)
            return Loc.GetString("sw-lathe-menu-unknown-recipe");

        return recipe.Result.Count > 0
            ? FormatItemList(recipe.Result)
            : recipe.Id;
    }

    private string FormatItemList(Dictionary<string, int> items)
    {
        if (items.Count == 0)
            return Loc.GetString("sw-lathe-menu-empty-list");

        return string.Join(
            Loc.GetString("sw-lathe-menu-list-separator"),
            items.Select(pair => Loc.GetString(
                "sw-lathe-menu-item-amount",
                ("item", GetEntityName(pair.Key)),
                ("amount", pair.Value))));
    }

    private string GetEntityName(string id)
    {
        if (Loc.TryGetString($"ent-{id}", out var localized))
            return localized;

        return _prototype.TryIndex<EntityPrototype>(id, out var prototype)
            ? prototype.Name
            : id;
    }
}
