using Content.Client._SW.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarServiceNotice : PanelContainer
{
    private string _accent = SWTerminalStyle.NeutralAccent;

    public SWGlobalWarServiceNotice(Action open)
    {
        RobustXamlLoader.Load(this);
        Stylesheet = SWGlobalWarConsoleStyle.Sheet();
        Details.OnPressed += _ => open();
    }

    public void SetText(string text)
    {
        var message = new FormattedMessage();
        message.AddText(text);
        Message.SetMessage(message);

        // The faction arrives after the body, and this runs every frame.
        var accent = SWTerminalStyle.AccentOf(SWGlobalWarConsoleStyle.LocalFaction());
        if (accent == _accent)
            return;

        _accent = accent;
        var side = SWGlobalWarConsoleStyle.LocalSide();
        SideMark.Visible = side != Content.Shared._SW.GlobalWar.SWGlobalWarFaction.Neutral;
        if (SideMark.Visible)
        {
            SideMark.Texture = SWGlobalWarConsoleStyle.SideIcon(side);
            SideMark.TextureScale = new System.Numerics.Vector2(4);
        }

        AccentLine.SetOnlyStyleClass(SWTerminalStyle.AccentLine + accent);
    }
}
