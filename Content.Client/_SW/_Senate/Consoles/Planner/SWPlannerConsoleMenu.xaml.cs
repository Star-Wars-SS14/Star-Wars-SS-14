    public void SetState(SWPlannerConsoleState state)
    {
        var identity = state.HasCard ? state.Me : string.Empty;
        var identityChanged = _identity != identity;
        if (identityChanged)
        {
            Calendar.CancelDrag();
            _identity = identity;
            _person = null;
            _rosterSignature = string.Empty;
            _invitees.Clear();
            _reasons.Clear();
            _moving = false;
            _deleteButton = null;
            _private = false;
            PrivateButton.Text = "Приватная: нет";
            SearchEdit.Text = string.Empty;
            _awaitingCreate = false;
            _awaitingMove = false;
            _draftDay = -1;
            _meetingDraftDay = _blockDraftDay = -1;
            _mode = string.Empty;
            TitleEdit.Text = string.Empty;
            LocationEdit.Text = string.Empty;
            AgendaEdit.Text = string.Empty;
            BlockLabel.Text = string.Empty;
            _selectedMeeting = -1;
            _selectedBlock = -1;
            ShowMode();
        }
        var dayChanged = _state != null && _state.Today != state.Today;
        _state = state;
        if (dayChanged) { Calendar.CancelDrag(); RequestView(); }
        if (_awaitingCreate)
        {
            var confirmed = _pendingMode == "meeting"
                ? state.Meetings.Any(m => m.IsHost && !_knownIds.Contains(m.Id) && m.Day == _pendingDay && m.StartSlot == _pendingSlot && m.Duration == _pendingDuration && m.Title == _pendingLabel)
                : (_pendingDay == state.Today ? state.MyItemsToday : state.MyItemsTomorrow).Any(i => i.BlockId >= 0 && !_knownIds.Contains(i.BlockId) && i.StartSlot == _pendingSlot && i.Duration == _pendingDuration && i.Label == _pendingLabel);
            if (confirmed)
            {
                _awaitingCreate = false;
                DraftStatus.Text = "Создание подтверждено расписанием.";
            }
            else if (++_pendingUpdates >= 2)
            {
                _awaitingCreate = false;
                DraftStatus.Text = "Нет подтверждения. Проверьте расписание и повторите.";
            }
        }
        if (_awaitingMove)
        {
            var moved = _moveMeetingId >= 0
                ? state.Meetings.Any(m => m.Id == _moveMeetingId && m.Day == _pendingMoveDay && m.StartSlot == _pendingMoveSlot && m.Duration == _pendingMoveDuration)
                : (_pendingMoveDay == state.Today ? state.MyItemsToday : state.MyItemsTomorrow).Any(i => i.BlockId == _moveBlockId && i.StartSlot == _pendingMoveSlot && i.Duration == _pendingMoveDuration);
            if (moved)
            {
                _moving = false;
                DraftStatus.Text = "Перенос подтверждён расписанием.";
            }
            else if (_moveConfirm != null)
                _moveConfirm.Disabled = false;
            _awaitingMove = false;
        }
        RefreshDetails();
        HeaderClock.Text = state.GameTime;
        PrimaryButton.Disabled = _awaitingCreate;
        InvitationsButton.Text = $"Приглашения: {state.Meetings.Count(m => m.Invited && !m.IsHost && m.MyStatus == SWInviteStatus.Pending)}";
        var signature = string.Join("|", state.Roster.Select(r => r.Name + ":" + r.Role));
        if (signature != _rosterSignature)
        {
            _rosterSignature = signature;
            if (_person != null && state.Roster.All(person => person.Name != _person)) { Calendar.CancelDrag(); _person = null; ResetConflictConfirmation(); }
            PersonOption.Clear();
            PersonOption.AddItem("Мой график", 0);
            var index = 0;
            foreach (var person in state.Roster)
            {
                PersonOption.AddItem($"{person.Name} — {person.Role}", ++index);
                if (person.Name == _person) PersonOption.SelectId(index);
            }
            if (_person == null) PersonOption.SelectId(0);
            if (_invitees.RemoveWhere(name => state.Roster.All(person => person.Name != name)) > 0)
                ResetConflictConfirmation();
            BuildInvitees();
        }
        SWConsoleStyle.StyleTabButton(TodayButton, _day == 0);
        SWConsoleStyle.StyleTabButton(TomorrowButton, _day == 1);
        if (identityChanged && state.HasCard) BeginDraft("meeting");
        BuildCalendar();
        if (!_awaitingCreate) RefreshHint();
    }

    private void ChangeDay(int offset)
    {
        if (_day != offset) { Calendar.CancelDrag(); ResetConflictConfirmation(); }
        _day = offset;
        RequestView();
        if (_state != null)
        {
            SWConsoleStyle.StyleTabButton(TodayButton, offset == 0);
            SWConsoleStyle.StyleTabButton(TomorrowButton, offset == 1);
        }
        BuildCalendar();
        RefreshHint();
    }

    private void RequestView()
    {
        if (_state != null && _person != null) _owner.View(_person, _state.Today + _day);
    }

    private void BeginDraft(string mode)
    {
        if (_state == null || !_state.HasCard) return;
        SaveDraftPosition();
        _mode = mode;
        _deleteButton = null;
        _moving = false;
        _draftDay = mode == "meeting" ? _meetingDraftDay : _blockDraftDay;
        _slot = mode == "meeting" ? _meetingDraftSlot : _blockDraftSlot;
        DraftStatus.Text = string.Empty;
        if (_draftDay < 0) _draftDay = _state.Today + _day;
        MeetingSlot.SelectId(_slot);
        BlockSlot.SelectId(_slot);
        if (mode == "meeting" && _person != null && _person != _state.Me && _invitees.Count < 8) _invitees.Add(_person);
        _confirmConflict = false;
        ShowMode();
        BuildInvitees();
        RefreshHint();
    }

    private void ResetConflictConfirmation()
    {
        _confirmConflict = false;
        RefreshHint();
    }

    private void SaveDraftPosition()
    {
        if (_mode == "meeting") { _meetingDraftDay = _draftDay; _meetingDraftSlot = _slot; }
        else if (_mode == "block") { _blockDraftDay = _draftDay; _blockDraftSlot = _slot; }
    }

    private void ShowMode()
    {
        MeetingForm.Visible = _mode == "meeting";
        BlockForm.Visible = _mode == "block";
        Details.Visible = _mode == "details" || _mode == "invitations" || _mode == string.Empty;
        PrimaryButton.Visible = _mode == "meeting" || _mode == "block";
        InspectorTitle.Text = _mode switch { "meeting" => "Новая встреча", "block" => "Новая запись", "invitations" => "Приглашения", _ => "Выберите время или событие" };
        PrimaryButton.Text = _mode == "block" ? "Добавить запись" : "Создать встречу";
    }

    private void SelectSlot(int slot)
    {
        if (_state == null || !_state.HasCard) return;
        if (!_moving && _mode != "meeting" && _mode != "block") BeginDraft("meeting");
        _slot = slot;
        _draftDay = _state.Today + _day;
        _confirmConflict = false;
        SaveDraftPosition();
        if (_moving)
        {
            ShowMoveConfirmation();
            return;
        }
        MeetingSlot.SelectId(slot);
        BlockSlot.SelectId(slot);
        if (_mode == "meeting" && _person != null && _person != _state.Me)
        {
            if (_invitees.Count < 8) _invitees.Add(_person);
            else if (!_invitees.Contains(_person)) DraftStatus.Text = "Не более 8 приглашённых: удалите участника, чтобы добавить выбранного человека.";
            BuildInvitees();
        }
        RefreshHint();
    }

    private void OnFormKey(GUIBoundKeyEventArgs args)
    {
        if (args.Handled) return;
        if (args.Function == EngineKeyFunctions.TextReleaseFocus && PrimaryButton.Visible)
        {
            SaveDraftPosition();
            _mode = string.Empty;
            Details.RemoveAllChildren();
            ShowMode();
            args.Handle();
            return;
        }
        if (args.Function != EngineKeyFunctions.MultilineTextSubmit || !PrimaryButton.Visible || PrimaryButton.Disabled) return;
        SubmitDraft();
        args.Handle();
    }

    private void OnCalendarKey(GUIBoundKeyEventArgs args)
    {
        if (args.Handled || !Calendar.HasKeyboardFocus()) return;
        if (args.Function == EngineKeyFunctions.TextReleaseFocus || args.Function == EngineKeyFunctions.CloseModals)
        {
            if (!Calendar.CancelDrag())
            {
                _moving = false;
                _mode = string.Empty;
                _deleteButton = null;
                Details.RemoveAllChildren();
                ShowMode();
            }
            args.Handle();
            return;
        }
        if (args.Function == EngineKeyFunctions.TextDelete && _deleteButton != null)
        {
            _confirmDelete = true;
            _deleteButton.Text = "Подтвердить удаление";
            args.Handle();
            return;
        }
        var delta = args.Function == EngineKeyFunctions.TextCursorUp || args.Function == EngineKeyFunctions.TextCursorSelectUp ? -1
            : args.Function == EngineKeyFunctions.TextCursorDown || args.Function == EngineKeyFunctions.TextCursorSelectDown ? 1 : 0;
        if (delta == 0) return;
        if (args.Function == EngineKeyFunctions.TextCursorSelectUp || args.Function == EngineKeyFunctions.TextCursorSelectDown)
        {
            if (_mode == "block") { _blockDuration = Math.Clamp(_blockDuration + delta, 1, Math.Min(16, SWPlannerSlots.PerDay - _slot)); BlockDuration.SelectId(_blockDuration); }
            else { _meetingDuration = Math.Clamp(_meetingDuration + delta, 1, Math.Min(4, SWPlannerSlots.PerDay - _slot)); MeetingDuration.SelectId(_meetingDuration); }
        }
        else SelectSlot(Math.Clamp(_slot + delta, 0, SWPlannerSlots.PerDay - 1));
        Calendar.ScrollToSlot(_slot);
        BuildCalendar();
        RefreshHint();
        args.Handle();
    }

    private void BuildCalendar()
    {
        if (_state == null) return;
        var matchingView = _person == null || (_state.ViewPerson == _person && _state.ViewDay == _state.Today + _day);
        var items = !_state.HasCard || !matchingView ? new List<SWPlannerItemEntry>()
            : _person != null ? _state.ViewItems : _day == 0 ? _state.MyItemsToday : _state.MyItemsTomorrow;
        if (_person == null && _state.HasCard)
        {
            items = items.Select(i => new SWPlannerItemEntry
            {
                StartSlot = i.StartSlot, Duration = i.Duration, Kind = i.Kind, Label = i.Label,
                Sub = i.Sub, MeetingId = i.MeetingId, BlockId = i.BlockId, Confirmed = i.Confirmed,
            }).ToList();
            foreach (var meeting in _state.Meetings.Where(m => m.Day == _state.Today + _day && m.Invited && !m.IsHost))
            {
                var status = meeting.MyStatus switch { SWInviteStatus.Accepted => "принято", SWInviteStatus.Declined => "отклонено", _ => "ожидает ответа" };
                var existing = items.FirstOrDefault(i => i.MeetingId == meeting.Id);
                if (existing != null) { existing.Label += $" — {status}"; existing.Sub = $"{existing.Sub} • {status}"; }
                else items.Add(new SWPlannerItemEntry { Kind = 2, MeetingId = meeting.Id, Label = $"{meeting.Title} — {status}",
                    StartSlot = meeting.StartSlot, Duration = meeting.Duration, Sub = status, Confirmed = meeting.Confirmed });
            }
        }
        var movable = new HashSet<int>(_state.Meetings.Where(m => m.IsHost).Select(m => m.Id));
        var selected = (_mode == "meeting" || _mode == "block") && _draftDay == _state.Today + _day ? _slot : -1;
        Calendar.SetData(items, _day == 0 ? _state.NowSlot : -1, _person == null && _state.HasCard,
            selected, _mode == "block" && _person == null ? _blockDuration : _meetingDuration, _mode == "block" && _person == null ? 16 : 4, movable);
        if (!_state.HasCard) DraftStatus.Text = _state.CardInserted ? "Карта не опознана" : "Вставьте ID-карту";
        else if (!matchingView) DraftStatus.Text = "Загрузка расписания…";
    }

    private void OnRangeSelected(int slot, int duration)
    {
        if (_person != null && _mode == "block") BeginDraft("meeting");
        if (_mode == "block")
        {
            _blockDuration = duration;
            BlockDuration.SelectId(duration);
        }
        else
        {
            _meetingDuration = Math.Clamp(duration, 1, 4);
            MeetingDuration.SelectId(_meetingDuration);
        }
        SelectSlot(slot);
        BuildCalendar();
    }

    private void OnItemMoved(SWPlannerItemEntry item, int slot)
    {
        if (_person != null || _state == null || !_state.HasCard) return;
        ShowItem(item);
        _moving = true;
        _moveDuration = item.Duration;
        _slot = slot;
        _draftDay = _state.Today + _day;
        ShowMoveConfirmation();
    }

    private void ShowItem(SWPlannerItemEntry item)
    {
        SaveDraftPosition();
        _mode = "details";
        _moving = false;
        _selectedMeeting = item.MeetingId;
        _selectedBlock = _person == null ? item.BlockId : -1;
        _moveOriginDay = _state == null ? -1 : _state.Today + _day;
        _moveOriginSlot = item.StartSlot;
        _confirmDelete = false;
        _deleteButton = null;
        ShowMode();
        InspectorTitle.Text = item.Label;
        InspectorTitle.ToolTip = item.Label;
        Details.RemoveAllChildren();
        _detailStatus = null;
        _responseStatus = null;
        _detailTime = SWConsoleStyle.Text(SWPlannerSlots.Range(item.StartSlot, item.Duration), SWConsoleStyle.TextBright, SWConsoleStyle.Strong);
        Details.AddChild(_detailTime);
        if (item.Sub.Length > 0) Details.AddChild(SWConsoleStyle.Wrap(item.Sub, SWConsoleStyle.TextDim, 300));
        var meeting = _state?.Meetings.FirstOrDefault(m => m.Id == item.MeetingId);
        if (meeting != null)
        {
            if (meeting.Description.Length > 0) Details.AddChild(SWConsoleStyle.Wrap(meeting.Description, SWConsoleStyle.TextDim, 300));
            _detailStatus = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            Details.AddChild(_detailStatus);
            UpdateMeetingStatus(meeting);
            if (meeting.Invited && !meeting.IsHost) AddResponse(meeting);
            if (meeting.IsHost && _person == null) { AddMoveButton(meeting.Duration); AddDeleteButton(true); }
        }
        if (_selectedBlock >= 0) { AddMoveButton(item.Duration); AddDeleteButton(false); }
    }

    private void UpdateMeetingStatus(SWPlannerMeetingEntry meeting)
    {
        if (_detailStatus == null) return;
        _detailStatus.RemoveAllChildren();
        foreach (var line in meeting.ParticipantLines) _detailStatus.AddChild(SWConsoleStyle.Wrap(line, SWConsoleStyle.TextDim, 300));
        if (meeting.Warning.Length > 0) _detailStatus.AddChild(SWConsoleStyle.Wrap(meeting.Warning, SWConsoleStyle.Bad, 300));
    }

    private void RefreshDetails()
    {
        if (_state == null || _mode != "details" || _moving) return;
        if (_selectedMeeting >= 0)
        {
            var meeting = _state.Meetings.FirstOrDefault(m => m.Id == _selectedMeeting);
            if (meeting != null)
            {
                if (_detailTime != null) _detailTime.Text = SWPlannerSlots.Range(meeting.StartSlot, meeting.Duration);
                UpdateMeetingStatus(meeting);
                if (_responseStatus != null) _responseStatus.Text = ResponseText(meeting.MyStatus);
            }
            else if (_person == null)
            {
                Details.RemoveAllChildren();
                InspectorTitle.Text = "Встреча больше недоступна";
                _selectedMeeting = -1;
                _deleteButton = null;
            }
        }
        else if (_selectedBlock >= 0)
        {
            var item = _state.MyItemsToday.Concat(_state.MyItemsTomorrow).FirstOrDefault(i => i.BlockId == _selectedBlock);
            if (item == null)
            {
                Details.RemoveAllChildren();
                InspectorTitle.Text = "Запись больше недоступна";
                _selectedBlock = -1;
                _deleteButton = null;
            }
            else if (_detailTime != null) _detailTime.Text = SWPlannerSlots.Range(item.StartSlot, item.Duration);
        }
    }

    private void AddMoveButton(int duration)
    {
        var button = SWConsoleStyle.Action("Перенести: выбрать время", SWConsoleStyle.Accent);
        button.OnPressed += _ =>
        {
            _moving = true;
            _moveDuration = duration;
            InspectorTitle.Text = "Выберите новое время в календаре";
