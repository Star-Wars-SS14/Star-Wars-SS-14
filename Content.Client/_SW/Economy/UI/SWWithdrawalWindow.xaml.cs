using Content.Shared._SW.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Content.Client._SW.Economy.UI;
[GenerateTypedNameReferences]
public sealed partial class SWWithdrawalWindow : DefaultWindow
{
    public event Action? OnCloseButtonPressed;
    public event Action<Dictionary<ProtoId<SWCurrencyPrototype>, float>>? OnConfirmButtonPressedAction;
    public SWWithdrawalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CloseWithdrawalButton.OnPressed += (_) => OnCloseButtonPressed?.Invoke();
        ConfirmButton.OnPressed += OnConfirmButtonPressed;
    }
    private void OnConfirmButtonPressed(BaseButton.ButtonEventArgs args)
    {
        Dictionary<ProtoId<SWCurrencyPrototype>, float> dict = new Dictionary<ProtoId<SWCurrencyPrototype>, float>();

        foreach (var cntrl in RequestsList.Children)
        {
            if (cntrl is SWWithdrawalControl withdrawalControl) {
                var amount = withdrawalControl.GetAmount();
                if (amount > 0)
                {
                    dict[withdrawalControl.Currency] = amount;
                }
            }
        }
        OnConfirmButtonPressedAction?.Invoke(dict);
    }
    public void PopulateCurrencies (List<ProtoId<SWCurrencyPrototype>> currencies)
    {
        RequestsList.Children.Clear();
        foreach (var currency in currencies)
        {
            var cntrl = new SWWithdrawalControl(currency);
            RequestsList.AddChild(cntrl);
        }
    }

    public override void Close()
    {
        if (Parent == null)
        {
            return;
        }

        Parent.RemoveChild(this);

        //Dont Invoke OnClosed To Avoid Closing FinanceConsoleMenuWindow
    }
}
