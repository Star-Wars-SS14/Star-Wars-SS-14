    private void BuildInvitees()
    {
        SelectedInvitees.RemoveAllChildren();
        InviteeList.RemoveAllChildren();
        if (_state == null) return;
        foreach (var name in _invitees.ToList())
        {
            var selected = name;
            var remove = SWConsoleStyle.Action($"{name} — убрать", SWConsoleStyle.Accent);
            remove.Label.ClipText = true;
            remove.ToolTip = name;
            remove.OnPressed += _ => { _invitees.Remove(selected); _confirmConflict = false; BuildInvitees(); RefreshHint(); };
            SelectedInvitees.AddChild(remove);
        }
        var search = SearchEdit.Text.Trim();
        if (search.Length == 0) return;
        foreach (var person in _state.Roster.Where(p => p.Name != _state.Me && !_invitees.Contains(p.Name) && (p.Name.Contains(search, StringComparison.OrdinalIgnoreCase) || p.Role.Contains(search, StringComparison.OrdinalIgnoreCase))).Take(8))
        {
            var name = person.Name;
            var add = SWConsoleStyle.Action($"{person.Name} — {person.Role}", SWConsoleStyle.TextBright);
            add.Label.ClipText = true;
            add.ToolTip = $"{person.Name} — {person.Role}";
            add.OnPressed += _ => { if (_invitees.Count < 8) _invitees.Add(name); _confirmConflict = false; BuildInvitees(); RefreshHint(); };
            InviteeList.AddChild(add);
        }
    }

    private ulong CombinedBusy(int day)
    {
        if (_state == null) return 0;
        var busy = day == _state.Today ? _state.MyBusyToday : _state.MyBusyTomorrow;
        foreach (var person in _state.Roster.Where(p => _invitees.Contains(p.Name)))
            busy |= day == _state.Today ? person.BusyToday : person.BusyTomorrow;
        return busy;
    }

    private void FindTime()
    {
        if (_state == null) return;
        var searchDay = _state.Today + _day;
        if (_day == 0 && (_state.EarliestStartSlot < 0 || _state.EarliestStartSlot >= SWPlannerSlots.PerDay))
        {
            TimeHint.Text = "Сегодня рабочий день закончился. Попробуйте завтра.";
            return;
        }
        var first = _day == 0 ? _state.EarliestStartSlot : 0;
        var busy = CombinedBusy(searchDay);
        for (var slot = first; slot <= SWPlannerSlots.PerDay - _meetingDuration; slot++)
        {
            if (SWPlannerSlots.Overlaps(busy, slot, _meetingDuration)) continue;
            SelectSlot(slot);
            return;
        }
        TimeHint.Text = "Общего свободного времени нет. Попробуйте завтра.";
    }

    private void RefreshHint()
    {
        if (_state == null || _draftDay < 0) return;
        BlockTimeHint.Text = _draftDay < _state.Today || _draftDay > _state.Today + 1
            ? "День черновика устарел"
            : $"{(_draftDay == _state.Today ? "Сегодня" : "Завтра")}, {SWPlannerSlots.Range(_slot, _blockDuration)}";
        BlockTimeHint.ToolTip = BlockTimeHint.Text;
        if (!_awaitingCreate && (_draftDay < _state.Today || _draftDay > _state.Today + 1))
            DraftStatus.Text = "День черновика устарел. Выберите новое время.";
        if (_draftDay < _state.Today || _draftDay > _state.Today + 1)
            TimeHint.Text = "День черновика устарел. Выберите новое время в календаре.";
        else if (_slot + _meetingDuration > SWPlannerSlots.PerDay)
            TimeHint.Text = "Встреча заканчивается после 21:00.";
        else
            TimeHint.Text = $"{(_draftDay == _state.Today ? "Сегодня" : "Завтра")}, {SWPlannerSlots.Range(_slot, _meetingDuration)}: " + (SWPlannerSlots.Overlaps(CombinedBusy(_draftDay), _slot, _meetingDuration) ? "есть пересечение" : "все свободны");
        TimeHint.ToolTip = TimeHint.Text;
        if (_mode == "meeting") PrimaryButton.Text = _confirmConflict ? "Всё равно создать?" : "Создать встречу";
    }

    private void StartPending(string mode, string label, int duration)
    {
        _pendingMode = mode;
        _pendingLabel = label;
        _pendingDay = _draftDay;
        _pendingSlot = _slot;
        _pendingDuration = duration;
        _pendingUpdates = 0;
        _awaitingCreate = true;
        PrimaryButton.Disabled = true;
        DraftStatus.Text = "Ожидаем подтверждения расписания…";
    }

    private void SubmitDraft()
    {
        if (_state == null || !_state.HasCard || _awaitingCreate || _draftDay < _state.Today || _draftDay > _state.Today + 1) return;
        if (_mode == "meeting")
        {
            if (string.IsNullOrWhiteSpace(TitleEdit.Text) || _slot + _meetingDuration > SWPlannerSlots.PerDay) return;
            var busy = CombinedBusy(_draftDay);
            if (SWPlannerSlots.Overlaps(busy, _slot, _meetingDuration) && (!_confirmConflict || _confirmedBusy != busy))
            {
                _confirmedBusy = busy;
                _confirmConflict = true;
                RefreshHint();
                return;
            }
            _knownIds.Clear();
            foreach (var meeting in _state.Meetings) _knownIds.Add(meeting.Id);
            var title = TitleEdit.Text.Trim();
            StartPending("meeting", title, _meetingDuration);
            _owner.CreateMeeting(_draftDay, _slot, _meetingDuration, title, AgendaEdit.Text, LocationEdit.Text, _private, _invitees.ToList());
        }
        else if (_mode == "block" && !string.IsNullOrWhiteSpace(BlockLabel.Text) && _slot + _blockDuration <= SWPlannerSlots.PerDay)
        {
            _knownIds.Clear();
            foreach (var item in _state.MyItemsToday.Concat(_state.MyItemsTomorrow)) if (item.BlockId >= 0) _knownIds.Add(item.BlockId);
            var label = BlockLabel.Text.Trim();
            StartPending("block", label, _blockDuration);
            _owner.AddBlock(_draftDay, _slot, _blockDuration, label);
        }
    }
