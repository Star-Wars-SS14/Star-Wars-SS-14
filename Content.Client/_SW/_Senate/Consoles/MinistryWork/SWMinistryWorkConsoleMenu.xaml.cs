    {
        var panel = SWConsoleStyle.Row(SWConsoleStyle.BgPanel);
        panel.Margin = new Thickness(0, 0, 0, 4);

        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
