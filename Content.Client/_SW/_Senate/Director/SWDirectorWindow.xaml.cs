namespace Content.Client._SW._Senate.Director;

[GenerateTypedNameReferences]
public sealed partial class SWDirectorWindow : FancyWindow
{
    public event Action<SWDirectorMode>? OnSetMode;
    public event Action<SWDirectorActionKind, string, string, string>? OnAction;
    public event Action<string, bool>? OnSendNote;
    public event Action<SWDefenseDirectorEventMessage>? OnDefenseEvent;
    private readonly SWDefenseDirectorWindow _defenseEditor = new();

    private readonly OptionButton _economyKindPicker = new() { Name = "DirectorEconomyKind", MinWidth = 210 };
    private readonly OptionButton _economyTargetPicker = new() { Name = "DirectorEconomyTarget", Filterable = true, HorizontalExpand = true, MinWidth = 210 };
    private readonly Button _economyCreate = SWConsoleStyle.Action("Создать", SWConsoleStyle.Accent);
    private static readonly (string Id, string Name)[] EconomyKinds = { ("production", "Авария производства"), ("transit", "Повреждение грузового узла"), ("demand", "Повышенный спрос на воду") };
    private (string Id, string Name)[] _economyTargets = Array.Empty<(string, string)>();
    private SWDirectorEuiState? _economyState;
    private string? _economyTargetsKey;
    private string _economyEventKind = "production";
    private string _economyEventTarget = string.Empty;
    private string _strikeTask = string.Empty;
    private string _strikeTarget = string.Empty;
    private string _mercKind = "kill";
    private string _mercTarget = string.Empty;

    public SWDirectorWindow()
    {
        RobustXamlLoader.Load(this);
        InitializeEconomyEvents();
        _defenseEditor.Submitted += message => OnDefenseEvent?.Invoke(message);
        OnClose += () => _defenseEditor.Close();

        NoteSend.OnPressed += _ =>
        {
            if (string.IsNullOrWhiteSpace(NoteEdit.Text))
                return;

            OnSendNote?.Invoke(NoteEdit.Text, NotePublic.Pressed);
            NoteEdit.Text = string.Empty;
        };

        SWConsoleStyle.StyleRoot(RootPanel);
        SWConsoleStyle.StyleHeader(HeaderPanel);
        HeaderTitle.Text = "ИМПЕРСКИЙ ШТАБ";
        HeaderTitle.FontOverride = SWConsoleStyle.MonoBold;
        HeaderTitle.FontColorOverride = Color.FromHex("#E0556B");
        ModeLabel.FontOverride = SWConsoleStyle.MonoBold;
        InfluenceLabel.FontOverride = SWConsoleStyle.MonoBold;
        InfluenceLabel.FontColorOverride = SWConsoleStyle.TextBright;
        IncomeLabel.FontOverride = SWConsoleStyle.MonoSmall;
        BorderLabel.FontOverride = SWConsoleStyle.Mono;
        BorderLabel.FontColorOverride = SWConsoleStyle.TextBright;
        NoticeLabel.FontOverride = SWConsoleStyle.MonoSmall;
        NoticeLabel.FontColorOverride = Color.FromHex("#E0A23B");
    }

    public void SetState(SWDirectorEuiState state)
    {
        var canAct = state.Mode == SWDirectorMode.Manual && state.IAmController;

        ModeLabel.Text = state.Mode switch
        {
            SWDirectorMode.Off => "Империя отключена — спокойный раунд",
            SWDirectorMode.Autopilot => "Автопилот — Империя действует сама",
            _ => $"Ручное управление: {state.ControllerName}",
        };
        ModeLabel.FontColorOverride = state.Mode switch
        {
            SWDirectorMode.Off => SWConsoleStyle.TextBright,
            SWDirectorMode.Autopilot => Color.FromHex("#E0A23B"),
            _ => Color.FromHex("#E0556B"),
        };

        ModeButtons.RemoveAllChildren();
        if (state.Mode != SWDirectorMode.Manual || !state.IAmController)
        {
            var take = SWConsoleStyle.Action("ВЗЯТЬ УПРАВЛЕНИЕ", Color.FromHex("#E0556B"));
            take.OnPressed += _ => OnSetMode?.Invoke(SWDirectorMode.Manual);
            ModeButtons.AddChild(take);
        }
        if (state.Mode != SWDirectorMode.Autopilot)
        {
            var auto = SWConsoleStyle.Action("АВТОПИЛОТ", Color.FromHex("#E0A23B"));
            auto.OnPressed += _ => OnSetMode?.Invoke(SWDirectorMode.Autopilot);
            ModeButtons.AddChild(auto);
        }
        if (state.Mode != SWDirectorMode.Off)
        {
            var off = SWConsoleStyle.Action("ОТКЛЮЧИТЬ ИМПЕРИЮ", SWConsoleStyle.TextBright);
            off.OnPressed += _ => OnSetMode?.Invoke(SWDirectorMode.Off);
            ModeButtons.AddChild(off);
        }

        InfluenceLabel.Text = $"Имперское влияние: {state.Influence}/{state.InfluenceCap}";
        IncomeLabel.Text = state.Mode == SWDirectorMode.Off ? "приток остановлен" : state.IncomeLine;
        BorderLabel.Text = $"Граница: {state.BorderPressure}/100 — {state.BorderStatus}"
            + (state.BlockadeActive ? $"   ·   блокада: {state.BlockadeLabel}" : "");

        NoticeLabel.Visible = state.Notice.Length > 0;
        NoticeLabel.Text = state.Notice;

        Body.RemoveAllChildren();

        if (state.DefenseMap is { } defenseMap)
        {
            _defenseEditor.SetState(defenseMap, canAct, state.Notice);
            var editor = SWConsoleStyle.Action("Тактические события", SWConsoleStyle.Accent);
            editor.OnPressed += _ => _defenseEditor.OpenCentered();
            Body.AddChild(editor);
        }

        Body.AddChild(SWConsoleStyle.Section("ОБЩИЕ ОПЕРАЦИИ"));
        var global = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 4) };

        var maneuvers = SWConsoleStyle.Action($"МАНЁВРЫ У ГРАНИЦЫ — {state.CostManeuvers}", Color.FromHex("#E0556B"),
            !canAct || state.Influence < state.CostManeuvers);
        maneuvers.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.Maneuvers, "", "", "");
        global.AddChild(maneuvers);

        var blockade = SWConsoleStyle.Action($"ТОРГОВАЯ БЛОКАДА — {state.CostBlockade}", Color.FromHex("#E0556B"),
            !canAct || state.BlockadeActive || state.Influence < state.CostBlockade);
        blockade.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.Blockade, "", "", "");
        global.AddChild(blockade);
        Body.AddChild(global);

        var covert = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 0, 0, 8) };

        var repCrisis = SWConsoleStyle.Action($"КРИЗИС РЕСПУБЛИКИ — {state.CostRepublicCrisis}", Color.FromHex("#E0A23B"),
            !canAct || state.Influence < state.CostRepublicCrisis);
        repCrisis.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.RepublicCrisis, "", "", "");
        covert.AddChild(repCrisis);

        var repDilemma = SWConsoleStyle.Action($"ДИЛЕММА КАНЦЛЕРУ — {state.CostDilemma}", Color.FromHex("#E0A23B"),
            !canAct || state.Influence < state.CostDilemma);
        repDilemma.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.RepublicDilemma, "", "", "");
        covert.AddChild(repDilemma);
        Body.AddChild(covert);

        UpdateEconomyEvents(state, canAct);
        BuildAgents(state, canAct);

        Body.AddChild(SWConsoleStyle.Section("СЕКТОРА"));
        if (state.Sectors.Count == 0)
            Body.AddChild(SWConsoleStyle.Text("Нет занятых секторов.", SWConsoleStyle.TextBright, SWConsoleStyle.MonoSmall));

        foreach (var sector in state.Sectors)
        {
            var row = SWConsoleStyle.Row(SWConsoleStyle.BgPanel, sector.Sanctioned ? Color.FromHex("#E0556B") : null);
            row.Margin = new Thickness(0, 0, 0, 5);
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };

            var info = sector.Sanctioned
                ? $"{sector.Name} — {sector.Holder} · {sector.SanctionLabel}"
                : $"{sector.Name} — {sector.Holder}";
            var label = SWConsoleStyle.Text(info, sector.Sanctioned ? Color.FromHex("#E0556B") : SWConsoleStyle.TextBright, SWConsoleStyle.Mono);
            label.HorizontalExpand = true;
            box.AddChild(label);

            var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 0) };

            var provoke = SWConsoleStyle.Action($"ПРОВОКАЦИЯ {state.CostProvocation}", Color.FromHex("#E0A23B"),
                !canAct || state.Influence < state.CostProvocation);
            provoke.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.Provocation, sector.Id, "", "");
            buttons.AddChild(provoke);

            if (!sector.Sanctioned)
            {
                var sanction = SWConsoleStyle.Action($"САНКЦИИ {state.CostSanction}", Color.FromHex("#E0556B"),
                    !canAct || state.Influence < state.CostSanction);
                sanction.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.Sanction, sector.Id, "", "");
                buttons.AddChild(sanction);
            }
            else
            {
                var lift = SWConsoleStyle.Action("СНЯТЬ", SWConsoleStyle.Good, !canAct);
                lift.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.LiftSanction, sector.Id, "", "");
                buttons.AddChild(lift);
            }

            var crisis = SWConsoleStyle.Action($"КРИЗИС {state.CostCrisis}", Color.FromHex("#E0556B"),
                !canAct || state.Influence < state.CostCrisis);
            crisis.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.Crisis, sector.Id, "", "");
            buttons.AddChild(crisis);

            var dilemma = SWConsoleStyle.Action($"ДИЛЕММА {state.CostDilemma}", Color.FromHex("#E0A23B"),
                !canAct || state.Influence < state.CostDilemma);
            dilemma.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.Dilemma, sector.Id, "", "");
            buttons.AddChild(dilemma);

            box.AddChild(buttons);
            row.AddChild(box);
            Body.AddChild(row);
        }

        Body.AddChild(SWConsoleStyle.Section("ДИПЛОМАТИЯ"));
        if (state.Diplomacy.Count == 0)
            Body.AddChild(SWConsoleStyle.Text("Переписки нет.", SWConsoleStyle.TextBright, SWConsoleStyle.MonoSmall));
        foreach (var entry in state.Diplomacy)
        {
            var accent = entry.FromEmpire ? Color.FromHex("#E0556B") : SWConsoleStyle.Accent;
            var header = entry.FromEmpire
                ? $"Империя · {entry.Stamp}" + (entry.Public ? " · публично" : "")
                : $"Республика · {entry.Stamp}";
            Body.AddChild(SWConsoleStyle.Text(header, accent, SWConsoleStyle.MonoBold));
            Body.AddChild(SWConsoleStyle.Text(entry.Text, SWConsoleStyle.TextBright, SWConsoleStyle.MonoSmall));
            Body.AddChild(new Control { MinHeight = 6 });
        }

        NoteBox.Visible = canAct;

        Body.AddChild(SWConsoleStyle.Section("ХРОНИКА"));
        if (state.Chronicle.Count == 0)
            Body.AddChild(SWConsoleStyle.Text("Пока пусто.", SWConsoleStyle.TextBright, SWConsoleStyle.MonoSmall));
        foreach (var line in state.Chronicle)
            Body.AddChild(SWConsoleStyle.Text(line, SWConsoleStyle.TextBright, SWConsoleStyle.MonoSmall));
    }

    private void InitializeEconomyEvents()
    {
        EconomyDirectorControls.AddChild(SWConsoleStyle.Section("ЭКОНОМИЧЕСКИЕ СОБЫТИЯ"));
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        for (var i = 0; i < EconomyKinds.Length; i++) _economyKindPicker.AddItem(EconomyKinds[i].Name, i);
        _economyKindPicker.SelectId(0);
        _economyKindPicker.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= EconomyKinds.Length) return;
            _economyKindPicker.SelectId(args.Id);
            _economyEventKind = EconomyKinds[args.Id].Id;
            _economyEventTarget = string.Empty;
            _economyTargetsKey = null;
            if (_economyState != null) UpdateEconomyEvents(_economyState, _economyState.Mode == SWDirectorMode.Manual && _economyState.IAmController);
        };
        _economyTargetPicker.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id > _economyTargets.Length) return;
            _economyTargetPicker.SelectId(args.Id);
            _economyEventTarget = args.Id == 0 ? string.Empty : _economyTargets[args.Id - 1].Id;
        };
        _economyCreate.Name = "DirectorEconomyCreate";
        _economyCreate.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.EconomyIncident, "", _economyEventKind, _economyEventTarget);
        row.AddChild(_economyKindPicker);
        row.AddChild(_economyTargetPicker);
        row.AddChild(_economyCreate);
        EconomyDirectorControls.AddChild(row);
        EconomyDirectorControls.AddChild(SWConsoleStyle.Wrap("Если министр экономики отсутствует, событие будет постепенно устранено службами.", SWConsoleStyle.TextDim));
    }

    private void UpdateEconomyEvents(SWDirectorEuiState state, bool canAct)
    {
        _economyState = state;
        EconomyDirectorControls.Visible = state.DefenseMap != null;
        _economyCreate.Disabled = !canAct;
        if (state.DefenseMap is not { } map) return;
        var worlds = map.Worlds.Where(w => w.Faction == "republic").ToDictionary(w => w.Id, w => w.Name);
        var targets = _economyEventKind == "transit"
            ? map.Links.Where(l => l.Traversable && worlds.ContainsKey(l.From) && worlds.ContainsKey(l.To))
                .Select(l => (Id: l.Id, Name: $"{worlds[l.From]} — {worlds[l.To]}"))
                .OrderBy(v => v.Name).ToArray()
            : map.Worlds.Where(w => w.Faction == "republic" && !string.IsNullOrWhiteSpace(w.Name))
                .Select(w => (Id: w.Id, Name: w.Name)).OrderBy(v => v.Name).ToArray();
        var key = _economyEventKind + "|" + string.Join("|", targets.Select(t => t.Id + "=" + t.Name));
        if (_economyTargetsKey == key) return;
        // Keep an open list stable; a later state refresh applies catalogue changes after it closes.
        if (_economyTargetPicker.OptionsScroll.Parent?.Parent != null) return;
        _economyTargetsKey = key;
        _economyTargets = targets;
        _economyTargetPicker.Clear();
        _economyTargetPicker.AddItem(_economyEventKind == "transit" ? "Случайный подходящий маршрут" : "Случайный подходящий мир", 0);
        for (var i = 0; i < targets.Length; i++) _economyTargetPicker.AddItem(targets[i].Name, i + 1);
        var selected = Array.FindIndex(targets, t => t.Id == _economyEventTarget);
        if (selected < 0) _economyEventTarget = string.Empty;
        _economyTargetPicker.SelectId(selected + 1);
    }

    private void BuildAgents(SWDirectorEuiState state, bool canAct)
    {
        Body.AddChild(SWConsoleStyle.Section("АГЕНТУРА"));

        if (!state.Targets.Contains(_strikeTarget))
            _strikeTarget = string.Empty;
        if (!state.Targets.Contains(_mercTarget))
            _mercTarget = state.Targets.Count > 0 ? state.Targets[0] : string.Empty;

        var strikeRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 4) };

        var taskOption = new OptionButton();
        taskOption.AddItem("Случайная задача", 0);
        taskOption.AddItem("Похищение", 1);
        taskOption.AddItem("Убийство", 2);
        taskOption.AddItem("Захват здания", 3);
        taskOption.SelectId(_strikeTask switch { "kidnap" => 1, "kill" => 2, "capture" => 3, _ => 0 });
        taskOption.OnItemSelected += args =>
        {
            taskOption.SelectId(args.Id);
            _strikeTask = args.Id switch { 1 => "kidnap", 2 => "kill", 3 => "capture", _ => "" };
        };
        strikeRow.AddChild(taskOption);

        var strikeTargetOption = new OptionButton();
        strikeTargetOption.AddItem("Случайная цель", 0);
        for (var i = 0; i < state.Targets.Count; i++)
            strikeTargetOption.AddItem(state.Targets[i], i + 1);
        strikeTargetOption.SelectId(_strikeTarget.Length > 0 ? state.Targets.IndexOf(_strikeTarget) + 1 : 0);
        strikeTargetOption.OnItemSelected += args =>
        {
            strikeTargetOption.SelectId(args.Id);
            _strikeTarget = args.Id > 0 ? state.Targets[args.Id - 1] : string.Empty;
        };
        strikeRow.AddChild(strikeTargetOption);

        var strike = SWConsoleStyle.Action($"ОТРЯД — {state.CostStrike}", Color.FromHex("#E0556B"),
            !canAct || !state.StrikeAvailable || state.Influence < state.CostStrike);
        strike.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.Strike, "", _strikeTask, _strikeTarget);
        strikeRow.AddChild(strike);
        Body.AddChild(strikeRow);

        if (state.StrikeLabel.Length > 0)
            Body.AddChild(SWConsoleStyle.Text(state.StrikeLabel, SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));

        var mercRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 4) };

        var kindOption = new OptionButton();
        kindOption.AddItem("Убийство", 0);
        kindOption.AddItem("Похищение", 1);
        kindOption.SelectId(_mercKind == "kidnap" ? 1 : 0);
        kindOption.OnItemSelected += args =>
        {
            kindOption.SelectId(args.Id);
            _mercKind = args.Id == 1 ? "kidnap" : "kill";
        };
        mercRow.AddChild(kindOption);

        var mercTargetOption = new OptionButton();
        for (var i = 0; i < state.Targets.Count; i++)
            mercTargetOption.AddItem(state.Targets[i], i);
        if (state.Targets.Count > 0)
            mercTargetOption.SelectId(Math.Max(0, state.Targets.IndexOf(_mercTarget)));
        mercTargetOption.OnItemSelected += args =>
        {
            mercTargetOption.SelectId(args.Id);
            _mercTarget = state.Targets[args.Id];
        };
        mercRow.AddChild(mercTargetOption);

        var merc = SWConsoleStyle.Action($"НАЁМНИК — {state.CostMerc}", Color.FromHex("#E0556B"),
            !canAct || !state.MercAvailable || state.Targets.Count == 0 || state.Influence < state.CostMerc);
        merc.OnPressed += _ => OnAction?.Invoke(SWDirectorActionKind.Merc, "", _mercKind, _mercTarget);
        mercRow.AddChild(merc);
        Body.AddChild(mercRow);

        if (state.MercLabel.Length > 0)
            Body.AddChild(SWConsoleStyle.Text(state.MercLabel, SWConsoleStyle.TextDim, SWConsoleStyle.MonoSmall));
    }
}
