/// <summary>
/// One window for production lines, drills, recruitment and the arsenal. The band on top says the line's state from
/// across the room; below it the products, the chosen one and the stock. Explanations live in tooltips.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarFactoryMenu : SWGlobalWarWindow
{
    private const float StockCell = 82;
    private const int NameLine = 16;

    public event Action<SWGlobalWarFactoryAction, SWGlobalWarSupplyKind, NetEntity?, string>? Requested;
    private List<SWGlobalWarFactoryChoice> _materials = new();
    private SWGlobalWarFactoryProduct? _selected;
    private List<SWGlobalWarFactoryProduct> _products = new();
    private string _productsKey = string.Empty;
    private string _itemsKey = string.Empty;
    private readonly Dictionary<SWGlobalWarFactoryProduct, ContainerButton> _productRows = new();
    private SWGlobalWarSupplyKind _lineKind = SWGlobalWarSupplyKind.T1;
    private bool _lineEnabled;
    private bool _operate;
    private bool _sized;
    private SWGlobalWarFactoryCargoWork? _cargoWork;

    public SWGlobalWarFactoryMenu()
    {
        RobustXamlLoader.Load(this);
        ContentsContainer.Margin = new Thickness(0);
        CornerBrackets = false;
        foreach (var quiet in new[] { PreviousPage, NextPage })
            quiet.SetAppearance(SWGlobalWarConsoleStyle.TextBright, quiet: true);
        foreach (var main in new[] { Start, Produce, Recruit, CargoWork })
        {
            main.MainFont = SWGlobalWarConsoleStyle.MainButton;
            main.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        }

        BandArt.Texture = SWGlobalWarConsoleStyle.Art("capture_scene", "off");
        MachineIcon.Texture = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>().Frame0(
            new SpriteSpecifier.Rsi(new ResPath("_SW/Structures/Machines/lathe.rsi"), "lathe_base"));
        MachineIcon.TextureScale = new Vector2(3);

        StateWord.FontOverride = SWGlobalWarConsoleStyle.Bold(22);
        Timer.FontOverride = SWGlobalWarConsoleStyle.Bold(36);
        CurrentProduct.FontOverride = SWGlobalWarConsoleStyle.Small;
        CurrentProduct.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        Progress.MinHeight = Progress.MaxHeight = 14;
        ProductName.FontOverride = ProductNameSecond.FontOverride = SWGlobalWarConsoleStyle.Bold(17);
        ProductName.FontColorOverride = ProductNameSecond.FontColorOverride = Color.White;

        Start.OnPressed += _ => Request(SWGlobalWarFactoryAction.Start);
        Stop.OnPressed += _ => Request(SWGlobalWarFactoryAction.Stop);
        Insert.OnPressed += _ => Request(SWGlobalWarFactoryAction.Insert);
        Recruit.OnPressed += _ => Request(SWGlobalWarFactoryAction.Recruit);
        CargoWork.OnPressed += _ =>
        {
            if (_cargoWork is { Carrier: { } carrier } work)
                Request(SWGlobalWarFactoryAction.CargoWork, carrier, work.Work.ToString());
        };
        Material.OnItemSelected += args => Material.SelectId(args.Id);
        Materialize.OnPressed += _ => Request(SWGlobalWarFactoryAction.Materialize, selection:
            _materials.ElementAtOrDefault(Material.SelectedId)?.Id ?? "");
        Produce.OnPressed += _ => Request(SWGlobalWarFactoryAction.Produce, selection: _selected?.Recipe ?? "");
        PreviousPage.OnPressed += _ => Request(SWGlobalWarFactoryAction.PreviousPage);
        NextPage.OnPressed += _ => Request(SWGlobalWarFactoryAction.NextPage);
    }

    private void Request(SWGlobalWarFactoryAction action, NetEntity? item = null, string selection = "")
    {
        Requested?.Invoke(action, _selected?.Kind ?? _lineKind, item, selection);
    }

    public void UpdateState(SWGlobalWarFactoryState state)
    {
        SetCampaignTitle(Loc.GetString(state.Recruitment ? "sw-global-war-factory-title-recruit" :
            state.Arsenal ? "sw-global-war-factory-title-arsenal" : "sw-global-war-factory-title"));
        _lineKind = state.Kind;
        _lineEnabled = state.Enabled;
        _operate = state.Operate;
        if (!_sized)
        {
            // Recruitment is one button and the arsenal one grid: a production line's size would be mostly empty.
            _sized = true;
            if (state.Recruitment)
                SetSize = new Vector2(600, 170);
            else if (state.Arsenal)
                SetSize = new Vector2(660, 420);
        }

        var line = state.Factory || state.Mining;
        var details = line && state.Operate;
        LineStrip.Visible = details;
        UpdateStrip(state);
        Status.SetMessage(SWGlobalWarConsoleStyle.MoneyMessage(state.Status));
        Status.Visible = !details && state.Status.Length > 0;

        Recruit.Visible = state.Recruitment;
        Recruit.Disabled = !state.Operate;
        UpdateCargoWork(state.CargoWork);
        Insert.Disabled = !state.Operate;
        Stop.Visible = line;
        Stop.Disabled = !state.Operate || !state.Enabled;

        UpdateProducts(state);
        UpdateMaterials(state);
        UpdateItems(state);

        ProductDetails.Visible = details;
        ProductColumn.Visible = details && _products.Count > 0;
        StockColumn.Visible = !state.Recruitment;
        EmptyStock.Visible = !state.Recruitment && state.Items.Count == 0;
        Pager.Visible = !state.Recruitment;
        Page.Text = Loc.GetString("sw-global-war-factory-page", ("page", state.Page + 1), ("pages", state.Pages));
        PreviousPage.Disabled = state.Page <= 0;
        NextPage.Disabled = state.Page >= state.Pages - 1;
    }

    private void UpdateCargoWork(SWGlobalWarFactoryCargoWork? work)
    {
        _cargoWork = work;
        var ready = work is { Carrier: not null, InReach: true };
        CargoWork.Visible = work != null;
        CargoWork.Disabled = !ready;
        CargoWorkHint.Visible = work != null && !ready;
        if (work == null)
            return;
        CargoWork.Text = Loc.GetString(work.Accept ? "sw-global-war-factory-cargo-accept" : "sw-global-war-factory-cargo-collect",
            ("item", work.Item), ("count", work.Count));
        CargoWorkHint.Text = Loc.GetString(work.Carrier == null ? "sw-global-war-factory-cargo-no-carrier" :
            "sw-global-war-factory-cargo-too-far");
    }

    private void UpdateStrip(SWGlobalWarFactoryState state)
    {
        var working = state.Powered && state.Enabled && state.RemainingSeconds > 0;
        var (word, color) = !state.Powered
            ? ("sw-global-war-factory-state-unpowered", SWGlobalWarConsoleStyle.Bad)
            : working ? ("sw-global-war-factory-state-working", SWGlobalWarConsoleStyle.Good)
            : ("sw-global-war-factory-state-idle", SWGlobalWarConsoleStyle.TextDim);
        StateWord.Text = Loc.GetString(word).ToUpperInvariant();
        StateWord.FontColorOverride = color;
        HelpMark.ToolTip = Loc.GetString("sw-global-war-factory-help")
            + (state.Detail.Length > 0 ? "\n" + state.Detail : string.Empty);

        PowerChip.Set(Loc.GetString("sw-global-war-factory-chip-" + (state.Powered ? "power-on" : "power-off")), state.Powered ? "good" : "bad");
        LineChip.Set(Loc.GetString("sw-global-war-factory-chip-" + (state.Enabled ? "line-on" : "line-off")), state.Enabled && state.Powered ? "good" : "off");

        Progress.Maximum = Math.Max(1, state.TotalSeconds);
        Progress.Value = state.TotalSeconds - state.RemainingSeconds;
        Progress.Fill = working ? SWGlobalWarConsoleStyle.Good : SWTerminalStyle.TextDim;
        Timer.Text = $"{state.RemainingSeconds / 60:00}:{state.RemainingSeconds % 60:00}";
        Timer.FontColorOverride = working ? Color.White : SWTerminalStyle.TextDim;

        var product = Loc.TryGetString($"sw-global-war-factory-kind-{(int) state.Kind}", out var name) ? name : string.Empty;
        CurrentProduct.Visible = state.Enabled && product.Length > 0;
        CurrentProduct.Text = state.Powered ? product : Loc.GetString("sw-global-war-factory-paused", ("product", product));
    }

    private void UpdateProducts(SWGlobalWarFactoryState state)
    {
        _products = state.Products;
        var key = string.Join('|', _products.Select(p => $"{p.Kind}/{p.Recipe}/{p.Ready}"));
        if (key != _productsKey)
        {
            _productsKey = key;
            Products.DisposeAllChildren();
            _productRows.Clear();
            foreach (var product in _products)
            {
                var row = ProductRow(product);
                _productRows[product] = row;
                Products.AddChild(row);
            }
        }

        // Records compare by value, so a new snapshot keeps the player's choice.
        _selected = _products.FirstOrDefault(p => p.Kind == _selected?.Kind && p.Recipe == _selected?.Recipe)
            ?? _products.FirstOrDefault(p => p.Kind == state.Kind)
            ?? _products.FirstOrDefault();
        ShowSelected();
    }

    private ContainerButton ProductRow(SWGlobalWarFactoryProduct product)
    {
        var row = new ContainerButton { HorizontalExpand = true, ToolTip = product.Name, MinHeight = 46 };
        row.ModulateSelfOverride = Color.White;
        var body = new BoxContainer { SeparationOverride = 8, Margin = new Thickness(6, 2) };
        var icon = new EntityPrototypeView { SetSize = new Vector2(52, 58), Margin = new Thickness(0, -7), Stretch = SpriteView.StretchMode.Fill, VerticalAlignment = VAlignment.Center };
        if (product.Entity != null)
            icon.SetPrototype(product.Entity);
        body.AddChild(icon);

        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
        text.AddChild(new Label { Text = product.Name, ClipText = true, FontOverride = SWGlobalWarConsoleStyle.Strong, FontColorOverride = Color.White });
        text.AddChild(new Label
        {
            Text = Loc.GetString(product.Ready ? "sw-global-war-factory-ready" : "sw-global-war-factory-short"),
            FontOverride = SWGlobalWarConsoleStyle.Small,
            FontColorOverride = product.Ready ? SWGlobalWarConsoleStyle.Good : SWGlobalWarConsoleStyle.Bad,
        });
        body.AddChild(text);
        row.AddChild(body);
        row.OnPressed += _ =>
        {
            _selected = product;
            ShowSelected();
        };
        return row;
    }

    private void ShowSelected()
    {
        foreach (var (product, row) in _productRows)
        {
            row.StyleBoxOverride = SWGlobalWarConsoleStyle.RowBox(product == _selected);
        }

        var kind = _selected?.Kind != null;
        Start.Visible = kind || _selected == null;
        Produce.Visible = !kind && _selected != null;

        // The chosen product starts here; a line already making it has nothing to start.
        var running = _lineEnabled && (_selected?.Kind == null || _selected.Kind == _lineKind);
        Start.Disabled = !_operate || running;
        Produce.Disabled = !_operate;

        SetProductName(_selected?.Name ?? string.Empty);
        ProductYield.Visible = _selected != null;
        ProductIcon.Visible = _selected?.Entity != null;
        if (_selected?.Entity != null)
            ProductIcon.SetPrototype(_selected.Entity);
        if (_selected != null)
            ProductYield.Text = Loc.GetString("sw-global-war-factory-yield", ("count", _selected.Output), ("seconds", _selected.Seconds));

        Costs.DisposeAllChildren();
        if (_selected == null)
            return;
        foreach (var cost in _selected.Costs)
            Costs.AddChild(CostRow(cost));

        // The first thing missing, in one line. The rest shows in the rows above it.
        if (_selected.Costs.FirstOrDefault(cost => cost.Have < cost.Need) is { } missing)
        {
            Costs.AddChild(new Label
            {
                Text = Loc.GetString("sw-global-war-factory-missing", ("name", missing.Name), ("count", missing.Need - missing.Have)),
                FontOverride = SWGlobalWarConsoleStyle.Small,
                FontColorOverride = SWGlobalWarConsoleStyle.Bad,
                ClipText = true,
            });
        }
    }

    /// <summary>Labels do not wrap, so a long name is split by hand at the last space that fits.</summary>
    private void SetProductName(string name)
    {
        var split = name.Length > NameLine ? name.LastIndexOf(' ', NameLine) : -1;
        ProductName.Text = split > 0 ? name[..split] : name;
        ProductNameSecond.Text = split > 0 ? name[(split + 1)..] : string.Empty;
        ProductNameSecond.Visible = split > 0;
        ProductName.ToolTip = name;
    }

    private static Control CostRow(SWGlobalWarFactoryCost cost)
    {
        var enough = cost.Have >= cost.Need;
        var row = new BoxContainer { SeparationOverride = 8, MinHeight = 38 };
        var icon = new EntityPrototypeView { SetSize = new Vector2(44, 50), Margin = new Thickness(0, -7), Stretch = SpriteView.StretchMode.Fill, VerticalAlignment = VAlignment.Center };
        icon.SetPrototype(cost.Entity);
        row.AddChild(icon);

        var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, VerticalAlignment = VAlignment.Center, SeparationOverride = 3 };
        var words = new BoxContainer { SeparationOverride = 8 };
        words.AddChild(new Label { Text = cost.Name, HorizontalExpand = true, ClipText = true, FontOverride = SWGlobalWarConsoleStyle.Small });
        words.AddChild(new Label
        {
            Text = Loc.GetString("sw-global-war-factory-cost", ("have", cost.Have), ("need", cost.Need)),
            FontOverride = SWGlobalWarConsoleStyle.Strong,
            FontColorOverride = enough ? Color.White : SWGlobalWarConsoleStyle.Bad,
        });
        body.AddChild(words);
        var bar = new SWGlobalWarMarketBar
        {
            Value = cost.Have,
            Maximum = Math.Max(1, cost.Need),
            Fill = enough ? SWGlobalWarConsoleStyle.Good : SWGlobalWarConsoleStyle.Bad,
            MinHeight = 5,
            MaxHeight = 5,
        };
        body.AddChild(bar);
        row.AddChild(body);
        return row;
    }

    private void UpdateMaterials(SWGlobalWarFactoryState state)
    {
        MaterialRow.Visible = state.Materials.Count > 0;
        if (_materials.SequenceEqual(state.Materials))
            return;

        _materials = state.Materials;
        Material.Clear();
        for (var i = 0; i < _materials.Count; i++)
            Material.AddItem(_materials[i].Name, i);
    }

    /// <summary>Same goods share a cell: a sprite and a number, the name in its tooltip.</summary>
    private void UpdateItems(SWGlobalWarFactoryState state)
    {
        var groups = state.Items
            .GroupBy(item => (item.Name, item.Prototype, item.CanTake))
            .Select(group => (group.Key.Name, group.Key.Prototype, group.Key.CanTake,
                First: group.First().Entity, Count: group.Sum(item => item.Count)))
            // A fixed order: the server lists taken goods last, and the cells used to jump under the cursor.
            // StringComparer is not on the client sandbox whitelist, so the comparers are built by hand.
            .OrderBy(group => group.Name, Comparer<string>.Create((a, b) => string.Compare(a, b, StringComparison.CurrentCulture)))
            .ThenBy(group => group.Prototype?.ToString(), Comparer<string?>.Create((a, b) => string.CompareOrdinal(a, b)))
            .ThenByDescending(group => group.CanTake)
            .ToList();
        var key = $"{state.Arsenal}|" + string.Join('|', groups.Select(group => $"{group.Name}/{group.CanTake}/{group.Count}/{group.First}"));
        if (key == _itemsKey)
            return;

        _itemsKey = key;
        Items.DisposeAllChildren();
        var columns = state.Arsenal ? 6 : 3;
        BoxContainer? row = null;
        foreach (var group in groups)
        {
            if (row == null || row.ChildCount >= columns)
            {
                row = new BoxContainer { SeparationOverride = 8 };
                Items.AddChild(row);
            }

            var cell = new ContainerButton
            {
                SetSize = new Vector2(StockCell),
                Disabled = !group.CanTake,
                ToolTip = Loc.GetString("sw-global-war-factory-arsenal-row", ("name", group.Name), ("count", group.Count)),
                ModulateSelfOverride = Color.White,
                StyleBoxOverride = SWTerminalStyle.Box(group.CanTake ? Color.FromHex("#23262C") : SWGlobalWarConsoleStyle.RowFill,
                    group.CanTake ? SWTerminalStyle.ButtonBorder : SWTerminalStyle.DividerColor, 1),
            };
            var icon = new EntityPrototypeView
            {
                SetSize = new Vector2(78),
                Stretch = SpriteView.StretchMode.Fill,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                Modulate = group.CanTake ? Color.White : Color.White.WithAlpha(.35f),
            };
            if (group.Prototype != null)
                icon.SetPrototype(group.Prototype);
            cell.AddChild(icon);
            cell.AddChild(new Label
            {
                Text = $"×{group.Count}",
                HorizontalAlignment = HAlignment.Left,
                VerticalAlignment = VAlignment.Bottom,
                Margin = new Thickness(6, 0, 0, 4),
                FontOverride = SWGlobalWarConsoleStyle.SmallStrong,
                FontColorOverride = group.CanTake ? Color.White : SWTerminalStyle.TextOff,
            });

            var entity = group.First;
            cell.OnPressed += _ => Request(SWGlobalWarFactoryAction.Take, entity);
            row.AddChild(cell);
        }
    }
}
