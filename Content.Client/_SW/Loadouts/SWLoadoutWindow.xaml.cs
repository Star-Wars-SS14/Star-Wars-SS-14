namespace Content.Client._SW.Loadouts;

/// <summary>
/// Chooses a job's loadout. It knows nothing of where an item comes from: a closed item is closed by one of the item's
/// own effects, and the text of the effect is shown. It owns the rules of a click, and tells its owner what came of it,
/// so the profile editor and the join window each only decide when to save.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SWLoadoutWindow : SWTerminalWindow
{
    private static readonly Dictionary<string, string> DepartmentAccents = new()
    {
        ["SWEmpire"] = "Empire",
        ["SWSobrik"] = "Empire",
        ["SWRPIntelligence"] = "Empire",
        ["SWPepublic"] = "Republic",
        ["SWRPCommander"] = "Republic",
        ["SWMandalorians"] = "Mandalorian",
        ["SWBlacksun"] = "BlackSun",
        ["SWExchange"] = "Exchange",
    };

    private readonly IDependencyCollection _collection;
    private readonly IEntityManager _entMan;
    private readonly IPrototypeManager _proto;
    private readonly ICommonSession _session;
    private readonly LoadoutSystem _loadouts;
    private readonly LobbyUIController _lobby;

    private readonly RoleLoadout _loadout;
    private readonly RoleLoadoutPrototype _role;
    private readonly JobPrototype? _job;
    private readonly List<LoadoutGroupPrototype> _groups = new();

    /// <summary>
    /// Groups with the same text share a tab. A costume from the season and the job's own uniforms are one choice to a
    /// player, and a tab each would not fit the window.
    /// </summary>
    private readonly List<List<LoadoutGroupPrototype>> _tabs = new();

    /// <summary>
    /// Choices that stopped being allowed since they were made, for example with another species, and why.
    /// </summary>
    private readonly Dictionary<string, string> _notApplied = new();

    private HumanoidCharacterProfile _profile;
    private List<LoadoutGroupPrototype>? _activeTab;
    private RoleLoadout? _beforeReset;
    private EntityUid _dummy;

    /// <summary>
    /// Raised after each change, with the loadout already checked. The loadout stays this window's: copy it to keep it.
    /// </summary>
    public event Action<RoleLoadout>? OnLoadoutChanged;

    public SWLoadoutWindow(
        HumanoidCharacterProfile profile,
        RoleLoadout loadout,
        RoleLoadoutPrototype role,
        JobPrototype? job,
        LocId saveHint,
        ICommonSession session,
        IDependencyCollection collection)
    {
        RobustXamlLoader.Load(this);

        _collection = collection;
        _entMan = collection.Resolve<IEntityManager>();
        _proto = collection.Resolve<IPrototypeManager>();
        _session = session;
        _loadouts = _entMan.System<LoadoutSystem>();
        _lobby = collection.Resolve<IUserInterfaceManager>().GetUIController<LobbyUIController>();

        _profile = profile;
        _loadout = loadout;
        _role = role;
        _job = job;

        Title = Loc.GetString("sw-loadout-window-title", ("job", job?.LocalizedName ?? string.Empty));
        SaveHintLabel.Text = Loc.GetString(saveHint);
        SetAccent(AccentOf(job));
        SetUpName(collection.Resolve<IConfigurationManager>());

        foreach (var group in role.Groups)
        {
            if (!_proto.TryIndex(group, out var groupProto) || groupProto.Hidden || groupProto.Loadouts.Count == 0)
                continue;

            _groups.Add(groupProto);

            var tab = _tabs.Find(t => Loc.GetString(t[0].Name) == Loc.GetString(groupProto.Name));
            if (tab != null)
                tab.Add(groupProto);
            else
                _tabs.Add(new List<LoadoutGroupPrototype> { groupProto });
        }

        _activeTab = _tabs.FirstOrDefault();

        RotateLeft.OnPressed += _ => Turn(1);
        RotateRight.OnPressed += _ => Turn(-1);
        ResetButton.OnPressed += _ => PressReset();
        Preview.OverrideDirection = Direction.South;

        NoteWhatStoppedWorking();
        _loadout.EnsureValid(_profile, _session, _collection);
        Rebuild();
        UpdatePreview(_profile);
    }

    private string AccentOf(JobPrototype? job)
    {
        if (job == null)
            return SWTerminalStyle.NeutralAccent;

        foreach (var department in _proto.EnumeratePrototypes<DepartmentPrototype>())
        {
            if (department.Roles.Contains(job.ID) && DepartmentAccents.TryGetValue(department.ID, out var accent))
                return accent;
        }

        return SWTerminalStyle.NeutralAccent;
    }

    private void SetUpName(IConfigurationManager cfg)
    {
        if (!_role.CanCustomizeName)
            return;

        var max = cfg.GetCVar(CCVars.MaxLoadoutNameLength);
        NameBox.Visible = true;
        NameLabel.Text = Loc.GetString(_role.NameDataset == null ? "loadout-name-edit-label" : "loadout-name-edit-label-dataset");
        NameEdit.ToolTip = Loc.GetString("loadout-name-edit-tooltip", ("max", max));
        NameEdit.IsValid = text => text.Length <= max;
        NameEdit.Text = _loadout.EntityName ?? string.Empty;
        NameEdit.OnTextChanged += args =>
        {
            _loadout.EntityName = args.Text;
            Changed();
        };
    }

    /// <summary>
    /// The check below would drop such a choice in silence, and the player would spawn in the wrong gear not knowing why.
    /// </summary>
    private void NoteWhatStoppedWorking()
    {
        foreach (var (group, selected) in _loadout.SelectedLoadouts)
        {
            foreach (var choice in selected)
            {
                if (_proto.TryIndex(choice.Prototype, out var item) && LongTermReason(item) is { } reason)
                    _notApplied[group] = reason.ToString();
            }
        }
    }

    private void Rebuild()
    {
        BuildTabs();
        BuildRows();
        ShowSelectedDetail();

        var hasBudget = _role.Points != null;
        PointsLabel.Visible = hasBudget;
        if (hasBudget)
            PointsLabel.Text = Loc.GetString("sw-loadout-points", ("left", _loadout.Points ?? 0), ("max", _role.Points ?? 0));

        ResetButton.Text = Loc.GetString(_beforeReset != null ? "sw-loadout-undo-reset" : "sw-loadout-reset");
        ResetButton.Disabled = _beforeReset == null && _groups.All(g => !IsChanged(g));
    }

    private void BuildTabs()
    {
        Tabs.RemoveAllChildren();

        foreach (var tab in _tabs)
        {
            var name = Loc.GetString(tab[0].Name);
            var button = new Button
            {
                // A mark on what differs from the job's own gear, so that a choice is not forgotten on a closed tab.
                Text = tab.Any(g => IsChanged(g) || _notApplied.ContainsKey(g.ID))
                    ? Loc.GetString("sw-loadout-tab-changed", ("name", name))
                    : name,
                StyleClasses = { tab == _activeTab ? SWTerminalStyle.TabActive : SWTerminalStyle.Tab },
            };
            button.OnPressed += _ =>
            {
                _activeTab = tab;
                Rebuild();
            };
            Tabs.AddChild(button);
        }
    }

    private bool IsChanged(LoadoutGroupPrototype group)
    {
        return _loadout.SelectedLoadouts.TryGetValue(group.ID, out var selected)
            && (group.MinLimit == 0
                ? selected.Count > 0
                : selected.Count > 0 && selected[0].Prototype != group.Loadouts[0]);
    }

    private void BuildRows()
    {
        Rows.RemoveAllChildren();

        if (_activeTab is not { } tab)
            return;

        foreach (var group in tab)
        {
            if (!_notApplied.TryGetValue(group.ID, out var stopped))
                continue;

            var line = new RichTextLabel { StyleClasses = { SWTerminalStyle.Text } };
            line.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("sw-loadout-not-applied", ("reason", stopped))));
            Rows.AddChild(line);
        }

        AddStandardRow(tab);

        // Short of points stays in its place, so that the list does not jump at each click. What the player cannot
        // change right now goes under a line, or a long list of rewards would bury what can be worn today.
        var closed = new List<(int Order, SWLoadoutRow Row)>();
        foreach (var (group, id) in tab.SelectMany(g => g.Loadouts.Select(l => (g, l))))
        {
            if (!_proto.TryIndex(id, out var item) || !_loadout.SelectedLoadouts.TryGetValue(group.ID, out var selected))
                continue;

            var isSelected = selected.Any(s => s.Prototype == id);
            var longTerm = isSelected ? null : LongTermReason(item);
            var reason = longTerm ?? (isSelected ? null : PointsReason(group, item));

            var order = 0;
            if (longTerm != null)
            {
                var hint = new SWLoadoutLockHintEvent(id);
                _entMan.EventBus.RaiseEvent(EventSource.Local, ref hint);
                reason = hint.Hint ?? reason;
                order = hint.Order;
            }

            var row = new SWLoadoutRow(IconOf(item), _loadouts.GetName(item), CostOf(item), isSelected, Accent, reason);
            SetUpHover(row, group, item, reason != null);
            row.OnPressed += _ => Press(group, item, isSelected);

            if (longTerm != null)
                closed.Add((order, row));
            else
                Rows.AddChild(row);
        }

        if (closed.Count == 0)
            return;

        Rows.AddChild(new Label
        {
            Text = Loc.GetString("sw-loadout-closed-divider", ("count", closed.Count)),
            StyleClasses = { SWTerminalStyle.Text },
            Margin = new Thickness(0, 6, 0, 0),
        });

        foreach (var (_, row) in closed.OrderBy(c => c.Order))
        {
            Rows.AddChild(row);
        }
    }

    /// <summary>
    /// A group that can stay empty has one more choice, shown like any other: what the job gives on its own.
    /// </summary>
    private void AddStandardRow(List<LoadoutGroupPrototype> tab)
    {
        if (tab.Any(g => g.MinLimit > 0 || g.MaxLimit != 1))
            return;

        EntProtoId? jobItem = null;
        if (_job != null
            && _proto.TryIndex(_job.StartingGear, out var gear)
            && SlotOf(tab[0]) is { } slot
            && gear.Equipment.TryGetValue(slot, out var item))
        {
            jobItem = item;
        }

        var name = jobItem is { } known && _proto.TryIndex(known, out var itemProto)
            ? Loc.GetString("sw-loadout-standard", ("item", itemProto.Name))
            : Loc.GetString("sw-loadout-standard-none");

        var row = new SWLoadoutRow(jobItem, name, 0, tab.All(g => !IsChanged(g)), Accent, null);
        row.OnPressed += _ =>
        {
            foreach (var group in tab)
            {
                _loadout.SelectedLoadouts[group.ID].Clear();
                _notApplied.Remove(group.ID);
            }

            _beforeReset = null;
            Changed();
        };
        Rows.AddChild(row);
    }

    private string? SlotOf(LoadoutGroupPrototype group)
    {
        foreach (var id in group.Loadouts)
        {
            if (_proto.TryIndex(id, out var item) && item.Equipment.Count > 0)
                return item.Equipment.Keys.First();
        }

        return null;
    }

    private static int CostOf(LoadoutPrototype item)
    {
        return item.Effects.OfType<PointsCostLoadoutEffect>().Sum(e => e.Cost);
    }

    private string DescriptionOf(LoadoutPrototype item)
    {
        return IconOf(item) is { } entity && _proto.TryIndex(entity, out var entityProto)
            ? entityProto.Description
            : string.Empty;
    }

    /// <summary>
    /// The entity shown for a loadout: its <see cref="LoadoutPrototype.DummyEntity"/>, which <c>GetName</c> already uses,
    /// or its only item. A set of several items without a dummy, like a Mandalorian armour with its helmet, shows its
    /// suit, or else its first item; the dummy would also replace the set's own name, so these sets keep none.
    /// </summary>
    private EntProtoId? IconOf(LoadoutPrototype item)
    {
        if ((item.DummyEntity ?? _loadouts.GetFirstOrNull(item)) is { } icon)
            return icon;

        if (item.Equipment.TryGetValue("outerClothing", out var suit))
            return suit;

        return item.Equipment.Values.Cast<EntProtoId?>().FirstOrDefault();
    }

    private void SetUpHover(SWLoadoutRow row, LoadoutGroupPrototype group, LoadoutPrototype item, bool closed)
    {
        var description = DescriptionOf(item);
        row.ToolTip = description;
        row.OnMouseEntered += _ =>
        {
            DetailLabel.SetMessage(FormattedMessage.FromUnformatted(description));

            // Closed, so the click does nothing, but the player can still see what the item would look like.
            if (closed)
                TryOn(group, item);
        };
        row.OnMouseExited += _ =>
        {
            ShowSelectedDetail();

            if (closed)
                UpdatePreview(_profile);
        };
    }

    private void ShowSelectedDetail()
    {
        var text = string.Empty;
        foreach (var group in _activeTab ?? new List<LoadoutGroupPrototype>())
        {
            if (_loadout.SelectedLoadouts.TryGetValue(group.ID, out var selected)
                && selected.Count > 0
                && _proto.TryIndex(selected[0].Prototype, out var item))
            {
                text = DescriptionOf(item);
                break;
            }
        }

        DetailLabel.SetMessage(FormattedMessage.FromUnformatted(text));
    }

    private void TryOn(LoadoutGroupPrototype group, LoadoutPrototype item)
    {
        var tried = _loadout.Clone();
        RemoveSlotRivals(tried, group, item);
        tried.SelectedLoadouts[group.ID] = new List<Loadout> { new() { Prototype = item.ID } };
        UpdatePreview(_profile.WithLoadout(tried), tryOn: true);
    }

    /// <summary>
    /// What the player cannot fix from this window: species, hours, ownership. It asks the item's own effects.
    /// </summary>
    private FormattedMessage? LongTermReason(LoadoutPrototype item)
    {
        if (!BodyHasSlotsFor(item))
            return FormattedMessage.FromUnformatted(Loc.GetString("sw-loadout-species-blocked"));

        foreach (var effect in item.Effects)
        {
            if (effect is PointsCostLoadoutEffect)
                continue;

            if (!effect.Validate(_profile, _loadout, item, _session, _collection, out var reason))
                return reason;
        }

        return null;
    }

    /// <summary>
    /// Species differ in their slots. The server would simply not put the item on, so the player must hear it here.
    /// </summary>
    private bool BodyHasSlotsFor(LoadoutPrototype item)
    {
        var factory = _entMan.ComponentFactory;
        return item.Equipment.Keys.All(slot => SWSpeciesSlots.CanWear(_profile.Species, slot, _proto, factory));
    }

    /// <summary>
    /// Whether the budget allows an item, on the loadout as it would be after the swap: the points of what this choice
    /// replaces count as free.
    /// </summary>
    private FormattedMessage? PointsReason(LoadoutGroupPrototype group, LoadoutPrototype item)
    {
        if (_role.Points == null)
            return null;

        var after = _loadout.Clone();
        if (group.MaxLimit == 1)
            after.SelectedLoadouts[group.ID] = new List<Loadout>();

        RemoveSlotRivals(after, group, item);
        after.EnsureValid(_profile, _session, _collection);

        foreach (var effect in item.Effects.OfType<PointsCostLoadoutEffect>())
        {
            if (!effect.Validate(_profile, after, item, _session, _collection, out var reason))
                return reason;
        }

        return null;
    }

    private void Press(LoadoutGroupPrototype group, LoadoutPrototype item, bool isSelected)
    {
        if (isSelected)
        {
            // A required group keeps its one choice: pick another instead.
            if (_loadout.SelectedLoadouts[group.ID].Count > group.MinLimit)
                _loadout.RemoveLoadout(group.ID, item.ID, _proto);
        }
        else
        {
            RemoveSlotRivals(_loadout, group, item);
            _loadout.AddLoadout(group.ID, item.ID, _proto);
        }

        _notApplied.Remove(group.ID);
        _beforeReset = null;
        Changed();
    }

    /// <summary>
    /// Two groups can fill one slot, and only the last one would be worn. The new choice takes it.
    /// </summary>
    private void RemoveSlotRivals(RoleLoadout loadout, LoadoutGroupPrototype group, LoadoutPrototype item)
    {
        foreach (var (otherGroup, selected) in loadout.SelectedLoadouts)
        {
            if (otherGroup == group.ID)
                continue;

            selected.RemoveAll(other =>
                _proto.TryIndex(other.Prototype, out var otherItem)
                && otherItem.Equipment.Keys.Any(item.Equipment.ContainsKey));
        }
    }

    /// <summary>
    /// There is no undo anywhere else and no dialog here, so the button itself takes the choices back until the next click.
    /// </summary>
    private void PressReset()
    {
        if (_beforeReset is { } before)
        {
            _loadout.SelectedLoadouts = before.SelectedLoadouts;
            _beforeReset = null;
        }
        else
        {
            _beforeReset = _loadout.Clone();
            _notApplied.Clear();
            foreach (var selected in _loadout.SelectedLoadouts.Values)
            {
                selected.Clear();
            }
        }

        Changed();
    }

    private void Changed()
    {
        _loadout.EnsureValid(_profile, _session, _collection);
        _profile = _profile.WithLoadout(_loadout);
        OnLoadoutChanged?.Invoke(_loadout);
        Rebuild();
        UpdatePreview(_profile);
    }

    private void UpdatePreview(HumanoidCharacterProfile profile, bool tryOn = false)
    {
        TryOnLabel.Visible = tryOn;
        _entMan.DeleteEntity(_dummy);
        _dummy = _lobby.LoadProfileEntity(profile, _job, true);
        Preview.SetEntity(_dummy);
    }

    private void Turn(int steps)
    {
        var direction = (int) (Preview.OverrideDirection ?? Direction.South) / 2;
        Preview.OverrideDirection = (Direction) ((direction + steps + 4) % 4 * 2);
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _entMan.DeleteEntity(_dummy);
    }
}
