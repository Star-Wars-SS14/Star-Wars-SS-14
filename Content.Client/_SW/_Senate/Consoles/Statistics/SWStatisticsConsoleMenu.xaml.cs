using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate.Consoles.Statistics;

[GenerateTypedNameReferences]
public sealed partial class SWStatisticsConsoleMenu : FancyWindow
{
    public SWStatisticsConsoleMenu()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(0, "Республика");
        Tabs.SetTabTitle(1, "Сектора");
    }

    public void SetState(SWStatisticsConsoleState state)
    {
        RepublicStats.RemoveAllChildren();
        foreach (var global in state.Globals)
        {
            RepublicStats.AddChild(MakeGlobalBlock(global));
        }

        SectorGrid.RemoveAllChildren();
        SectorGrid.Columns = 1 + state.Globals.Count;

        SectorGrid.AddChild(new Label { Text = "Сектор", StyleClasses = { "LabelKeyText" } });
        foreach (var global in state.Globals)
        {
            SectorGrid.AddChild(new Label
            {
                Text = global.ShortName,
                FontColorOverride = global.Color,
                HorizontalAlignment = Control.HAlignment.Center,
                StyleClasses = { "LabelKeyText" },
            });
        }

        foreach (var sector in state.Sectors)
        {
            SectorGrid.AddChild(new Label
            {
                Text = sector.Name,
                FontColorOverride = sector.Color,
            });

            foreach (var stat in sector.Stats)
            {
                SectorGrid.AddChild(new Label
                {
                    Text = $"{stat.Value:0}",
                    HorizontalAlignment = Control.HAlignment.Center,
                });
            }
        }
    }

    private static Control MakeGlobalBlock(SWGlobalStatEntry global)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(0, 2, 0, 6),
        };

        var head = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };
        head.AddChild(new Label { Text = global.Name, FontColorOverride = global.Color, HorizontalExpand = true });
        head.AddChild(new Label { Text = $"факт {global.Actual:0}", MinWidth = 76, HorizontalAlignment = Control.HAlignment.Right });
        head.AddChild(new Label { Text = $"полит. {global.Policy:0}", MinWidth = 88, FontColorOverride = Color.Gray, HorizontalAlignment = Control.HAlignment.Right });
        box.AddChild(head);

        box.AddChild(new ProgressBar
        {
            MinValue = global.Min,
            MaxValue = global.Max <= global.Min ? global.Min + 1 : global.Max,
            Value = global.Actual,
            HorizontalExpand = true,
            MinHeight = 14,
            Margin = new Thickness(0, 2, 0, 0),
            ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = global.Color },
        });

        var subText = string.Join("    ", global.Subs.Select(s => $"{s.ShortName} {s.Value:0}"));
        box.AddChild(new Label { Text = subText, FontColorOverride = Color.DarkGray, Margin = new Thickness(8, 1, 0, 0) });

        return box;
    }
}
