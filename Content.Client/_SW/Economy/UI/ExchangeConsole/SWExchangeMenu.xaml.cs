using Content.Client._SW.UserInterface;
using Content.Shared._SW.Economy.BankSystem;
using Content.Shared._SW.Economy.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Content.Client._SW.Economy.UI.ExchangeConsole;
[GenerateTypedNameReferences]
public sealed partial class SWExchangeMenu : SWTerminalWindow
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    public SWSharedBankSystem? SharedBankSystem;

    public event Action? OnWithdrawalButtonPressed;
    public event Action? OnAddMoneyButtonPressed;
    public event Action<SWCurrencyPrototype, SWCurrencyPrototype, int>? OnConfirmButtonPressed;

    public Dictionary<ProtoId<SWCurrencyPrototype>, float> Balance = new();
    public List<SWCurrencyPrototype> Currencies = new();
    public SWExchangeMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CurrencyExchangeFrom.OptionStyleClasses.Add(SWTerminalStyle.OptionItem);
        CurrencyExchangeTo.OptionStyleClasses.Add(SWTerminalStyle.OptionItem);
        MoneyOutButton.OnPressed += (_) => OnWithdrawalButtonPressed?.Invoke();
        MoneyInButton.OnPressed += (_) => OnAddMoneyButtonPressed?.Invoke();
        CurrencyExchangeFrom.OnItemSelected += OnFromSelected;
        CurrencyExchangeTo.OnItemSelected += OnToSelected;
        ConfirmButton.OnPressed += (_) => OnExchange();
        AmountEdit.OnTextChanged += (_) => UpdateExchange();
    }

    public void OnExchange()
    {
        if (Currencies.Count == 0)
        {
            return;
        }
        var from = Currencies[CurrencyExchangeFrom.SelectedId];
        var to = Currencies[CurrencyExchangeTo.SelectedId];
        int amount = 0;
        if (int.TryParse(AmountEdit.Text, out var quantity) && quantity > 0)
        {
            amount = quantity;
        }
        OnConfirmButtonPressed?.Invoke(from, to, amount);
    }

    private void OnFromSelected(OptionButton.ItemSelectedEventArgs obj) {
        CurrencyExchangeFrom.SelectId(obj.Id);
        UpdateExchange();
    }

    private void OnToSelected(OptionButton.ItemSelectedEventArgs obj) {
        CurrencyExchangeTo.SelectId(obj.Id);
        UpdateExchange();
    }

    public void UpdateExchange()
    {
        if (SharedBankSystem == null || Currencies.Count == 0)
        {
            return;
        }
        var from = Currencies[CurrencyExchangeFrom.SelectedId];
        var to = Currencies[CurrencyExchangeTo.SelectedId];
        int amount = 0;
        if (int.TryParse(AmountEdit.Text, out var quantity) && quantity > 0)
        {
            amount = quantity;
        }
        SharedBankSystem.TransferCurrency(amount, from, to, out int resultAmount);
        ResultAmountLabel.Text = resultAmount.ToString();
    }

    public void PopulateBalance(Dictionary<ProtoId<SWCurrencyPrototype>, float> balance)
    {
        Balance = balance;
        BalanceContainer.Children.Clear();
        foreach (var (currency, amount) in Balance)
        {
            if (BalanceContainer.ChildCount > 0)
                BalanceContainer.AddChild(CreateDivider());

            var name = Loc.GetString(_prototypeManager.Index(currency).LocalizedName);
            BalanceContainer.AddChild(CreateValueRow(name, amount.ToString("0.##")));
        }
    }

    public void PopulateCurrencies(List<SWCurrencyPrototype> currencies)
    {
        // Clearing resets both dropdowns to one currency, and the next exchange would be refused.
        if (Currencies.SequenceEqual(currencies))
        {
            return;
        }
        Currencies = currencies;
        CurrencyExchangeFrom.Clear();
        CurrencyExchangeTo.Clear();
        for (int i = 0; i < Currencies.Count; i++) {
            CurrencyExchangeFrom.AddItem(Loc.GetString(Currencies[i].LocalizedName), i);
            CurrencyExchangeTo.AddItem(Loc.GetString(Currencies[i].LocalizedName), i);
        }
        if (Currencies.Count > 1)
        {
            CurrencyExchangeTo.SelectId(1);
        }
    }
}
