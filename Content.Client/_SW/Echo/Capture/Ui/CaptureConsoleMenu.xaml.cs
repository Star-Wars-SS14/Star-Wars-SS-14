using Content.Client.UserInterface.Controls;
using Content.Shared.Echo.CaptureConsole;
using Content.Shared.Echo.GameTicking.Components;
using Content.Shared.Xenoarchaeology.Equipment;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._SW.Echo.Capture.Ui;

[GenerateTypedNameReferences]
public sealed partial class CaptureConsoleMenu : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    public event Action? OnCaptureButtonPressed;

    private CaptureConsoleUpdateState? _lastState;
    private string? _lastUserFraction;

    public CaptureConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CaptureButton.OnPressed += _ =>
        {
            OnCaptureButtonPressed?.Invoke();
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_lastState == null)
            return;

        // A null start time is a paused timer; retain the server's remaining active time.
        var remaining = _lastState.StartTime is { } start
            ? _lastState.CaptureDuration - (_timing.CurTime - start)
            : _lastState.TimeRemain;

        if (_lastState is not { Capturing: true })
        {
            ProgressBar.Visible = false;
            return;
        }

        _lastState.TimeRemain = remaining;
        ProgressBar.Value = Math.Clamp(1.0f - (float) remaining.Divide(_lastState.CaptureDuration), 0.0f, 1.0f);

        UpdateInformationDisplay(_lastState);
    }

    public void UpdateInformationDisplay(CaptureConsoleUpdateState state)
    {
        _lastState = state;
        if (state.UserFraction != null)
        {
            _lastUserFraction = state.UserFraction;
        }
        else
        {
            state.UserFraction = _lastUserFraction;
        }
        var message = new FormattedMessage();

        message.TryAddMarkup($"[color=white]{Loc.GetString("capture-console-message-station-active")}[/color]",
            out _);
        message.PushNewline();
        message.PushNewline();
        message.TryAddMarkup(
            $"[color=white]{state.StationFraction}[/color]",
            out _);
        message.PushNewline();
        message.PushNewline();
        message.TryAddMarkup(
            $"[color=yellow]{Loc.GetString("capture-console-capturing-status",
                ("state", state.Capturing ? Loc.GetString("capture-console-capturing-status-true") :
                    Loc.GetString("capture-console-capturing-status-false")))}[/color]",
            out _);
        message.PushNewline();
        message.PushNewline();
        message.TryAddMarkup(
            $"[color=red]{Loc.GetString("capture-console-eta", ("time",
                state.TimeRemain.TotalSeconds))}[/color]",
            out _);
        message.PushNewline();
        Information.SetMessage(message);

        var leftInfoMessage = new FormattedMessage();

        leftInfoMessage.TryAddMarkup(
            $"[color=white]{Loc.GetString("capture-console-message-user-fraction",
            ("fraction", state.UserFraction == null ? "unknown" : state.UserFraction))}[/color]", out _);
        leftInfoMessage.PushNewline();
        leftInfoMessage.PushNewline();
        leftInfoMessage.TryAddMarkup(
            $"[color=red]{Loc.GetString("capture-console-message-current-station",
                ("name", state.StationName))}[/color]",
            out _);
        leftInfoMessage.PushNewline();
        LeftInfoLabel.SetMessage(leftInfoMessage);
        CaptureButton.Text = state.Capturing
            ? Loc.GetString("capture-console-cancel-button")
            : Loc.GetString("capture-console-capture-button");

        if (state.UserFraction == state.StationFraction && !state.Capturing)
        {
            CaptureButton.Disabled = true;
        }
        else
        {
            CaptureButton.Disabled = false;
        }

        if (!state.HasAccess)
        {
            CaptureButton.Disabled = true;
            CaptureButton.Text = Loc.GetString("capture-console-no-access");
        }

        if (state.IsTimeout)
        {
            CaptureButton.Disabled = true;
        }

        if (!state.Capturing)
            return;

        ProgressBar.Visible = true;
    }
}
