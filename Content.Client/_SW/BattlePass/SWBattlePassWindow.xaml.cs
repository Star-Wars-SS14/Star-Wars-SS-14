        HideHeader();
        BannerClose.OnPressed += _ => Close();
        StripClose.OnPressed += _ => Close();
        GoalCaption.FontColorOverride = IceColor;

        // A section of its own across the whole window. It says what it is and asks for nothing.
        // The bar is only there for the mouse: it is a quiet line under the band.
