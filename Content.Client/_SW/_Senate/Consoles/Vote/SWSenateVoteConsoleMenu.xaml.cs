using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate.Consoles.Vote;

[GenerateTypedNameReferences]
public sealed partial class SWSenateVoteConsoleMenu : FancyWindow
{
    private const int FloorTabIndex = 2;

    private readonly SWSenateVoteConsoleBoundUserInterface _owner;

    public SWSenateVoteConsoleMenu(SWSenateVoteConsoleBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        _owner = owner;

        Tabs.SetTabTitle(0, "Повестка");
        Tabs.SetTabTitle(1, "Текущий законопроект");
        Tabs.SetTabTitle(FloorTabIndex, "Трибуна");

        VoteForButton.OnPressed += _ => _owner.Vote(SWVoteChoice.For);
        VoteAgainstButton.OnPressed += _ => _owner.Vote(SWVoteChoice.Against);
        VoteAbstainButton.OnPressed += _ => _owner.Vote(SWVoteChoice.Abstain);
        EndVoteButton.OnPressed += _ => _owner.EndVote();
        TiebreakForButton.OnPressed += _ => _owner.Tiebreak(SWVoteChoice.For);
        TiebreakAgainstButton.OnPressed += _ => _owner.Tiebreak(SWVoteChoice.Against);
        RevokeFloorButton.OnPressed += _ => _owner.RevokeFloor();
        GrantChancellorButton.OnPressed += _ => _owner.GrantChancellor();
    }

    public void SetState(SWSenateVoteConsoleState state)
    {
        Title = string.IsNullOrEmpty(state.GameTime)
            ? "Консоль голосования Сената"
            : $"Консоль голосования Сената — {state.GameTime}";

        Tabs.SetTabVisible(FloorTabIndex, state.CanControlFloor);

        BuildAgenda(state);
        BuildCurrent(state);
        BuildFloor(state);
    }

    private void BuildFloor(SWSenateVoteConsoleState state)
    {
        FloorHolderLabel.SetMessage(state.FloorHolderName != null
            ? $"Слово у: {state.FloorHolderName}"
            : "Слово сейчас ни у кого.");

        RevokeFloorButton.Disabled = state.FloorHolderName == null;

        FloorQueueList.RemoveAllChildren();
        if (state.FloorQueue.Count == 0)
        {
            FloorQueueList.AddChild(new Label { Text = "Очередь пуста.", FontColorOverride = Color.Gray });
            return;
        }

        var position = 1;
        foreach (var entry in state.FloorQueue)
        {
            var rowBox = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(0, 1, 0, 1),
            };

            rowBox.AddChild(new Label
            {
                Text = entry.IsChancellor ? $"{position}. {entry.Name} (Канцлер)" : $"{position}. {entry.Name}",
                FontColorOverride = entry.IsChancellor ? Color.Gold : Color.White,
                HorizontalExpand = true,
            });

            var target = entry.Target;
            var grant = new Button { Text = "Дать слово" };
            grant.OnPressed += _ => _owner.GrantFloor(target);
            rowBox.AddChild(grant);

            FloorQueueList.AddChild(rowBox);
            position++;
        }
    }

    private void BuildAgenda(SWSenateVoteConsoleState state)
    {
        AgendaList.RemoveAllChildren();
        if (state.Bills.Count == 0)
        {
            AgendaList.AddChild(new Label { Text = "Повестка пуста." });
            return;
        }

        foreach (var bill in state.Bills)
        {
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 2, 0, 6) };
            box.AddChild(new Label { Text = $"#{bill.Id}  {bill.Name}", StyleClasses = { "LabelKeyText" } });
            box.AddChild(new Label { Text = $"Автор: {bill.Author}    Стадия: {bill.Stage}", FontColorOverride = Color.Gray });

            if (!string.IsNullOrWhiteSpace(bill.Description))
            {
                var desc = new RichTextLabel { Margin = new Thickness(0, 2, 0, 2) };
                desc.SetMessage(bill.Description);
                box.AddChild(desc);
            }

            var effects = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            foreach (var effect in bill.Effects)
            {
                effects.AddChild(new Label
                {
                    Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                    FontColorOverride = effect.Color,
                    Margin = new Thickness(0, 0, 12, 0),
                });
            }

            box.AddChild(effects);
            AgendaList.AddChild(box);
        }
    }

    private void BuildCurrent(SWSenateVoteConsoleState state)
    {
        SessionLabel.SetMessage(string.IsNullOrEmpty(state.SessionInfo)
            ? "Нет активного заседания."
            : state.SessionInfo);

        var canVote = state.CanVote && state.HasCurrent;
        VoteForButton.Disabled = !canVote;
        VoteAgainstButton.Disabled = !canVote;
        VoteAbstainButton.Disabled = !canVote;

        EndVoteButton.Visible = state.CanEndVote;
        TiebreakPanel.Visible = state.CanTiebreak;
        if (state.CanTiebreak)
            TiebreakLabel.SetMessage("Ничья. Ваш решающий голос как Канцлера:");

        if (!state.HasCurrent)
        {
            BillTitle.SetMessage("Нет активного голосования.");
            BillAuthor.SetMessage(string.Empty);
            BillDescription.SetMessage(string.Empty);
            BillEffects.RemoveAllChildren();
            TallyLabel.SetMessage(string.Empty);
            SectorVotes.RemoveAllChildren();
            return;
        }

        BillTitle.SetMessage(state.AwaitingTiebreak
            ? $"#{state.CurrentId}  {state.CurrentName}  — ничья, ожидание Канцлера"
            : $"#{state.CurrentId}  {state.CurrentName}");

        var mine = state.HasVoted ? $"    Ваш голос: {VoteLabel(state.MyVote)}" : string.Empty;
        BillAuthor.SetMessage($"Автор: {state.CurrentAuthor}{mine}");

        BillDescription.SetMessage(string.IsNullOrWhiteSpace(state.CurrentDescription)
            ? "Без описания."
            : state.CurrentDescription);

        BillEffects.RemoveAllChildren();
        foreach (var effect in state.CurrentEffects)
        {
            BillEffects.AddChild(new Label
            {
                Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                FontColorOverride = effect.Color,
                Margin = new Thickness(0, 0, 12, 0),
            });
        }

        TallyLabel.SetMessage($"За: {state.VotesFor}    Против: {state.VotesAgainst}    Воздержались: {state.VotesAbstain}");

        SectorVotes.RemoveAllChildren();
        foreach (var sector in state.SectorVotes)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 1, 0, 1) };
            row.AddChild(new Label { Text = sector.Name, FontColorOverride = sector.Color, MinWidth = 200 });
            row.AddChild(new Label { Text = sector.VoteLabel });
            SectorVotes.AddChild(row);
        }
    }

    private static string VoteLabel(SWVoteChoice choice) => choice switch
    {
        SWVoteChoice.For => "За",
        SWVoteChoice.Against => "Против",
        SWVoteChoice.Abstain => "Воздержался",
        _ => "—",
    };
}
