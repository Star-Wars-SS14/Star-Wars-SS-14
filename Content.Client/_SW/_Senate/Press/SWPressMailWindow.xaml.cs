using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate.Press;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW._Senate.Press;

[GenerateTypedNameReferences]
public sealed partial class SWPressMailWindow : FancyWindow
{
    public event Action<SWPressActionMessage>? Action;
    private SWPressEuiState _state = new();
    private string _targetKey = string.Empty;
    private int _selectedId;
    private SWPressMailEntry? _selected;

    public SWPressMailWindow()
    {
        RobustXamlLoader.Load(this);
        NewMail.OnPressed += _ => Clear();
        Refresh.OnPressed += _ => Send(SWPressAction.Refresh);
        SendNew.OnPressed += _ => Send(SWPressAction.MailCreate);
        Reply.OnPressed += _ => Send(SWPressAction.MailReply);
        CopyDraft.OnPressed += _ => Send(SWPressAction.MailCopyToDraft);
        UpdateControls();
    }

    public void SetState(SWPressEuiState state)
    {
        _state = state; Notice.Text = state.Notice;
        Targets.RemoveAllChildren();
        if (state.MailTargets.Count == 0) Targets.AddChild(new Label { Text = "Нет доступных адресатов." });
        foreach (var target in state.MailTargets)
        {
            var button = new Button { Text = Short(target.Label), HorizontalExpand = true };
            button.OnPressed += _ => { Clear(); _targetKey = target.Key; Context.Text = "Адресат: " + Short(target.Label); UpdateControls(); };
            Targets.AddChild(button);
        }
        Threads.RemoveAllChildren();
        if (state.Mail.Count == 0) Threads.AddChild(new Label { Text = "Обращений пока нет." });
        foreach (var thread in state.Mail)
        {
            var button = new Button { Text = Short(thread.Subject), HorizontalExpand = true };
            button.OnPressed += _ => Select(thread);
            Threads.AddChild(button);
        }
        if (_selectedId != 0)
        {
            _selected = state.Mail.FirstOrDefault(t => t.Id == _selectedId);
            if (_selected == null) Clear(); else RenderMessages(_selected);
        }
        if (!state.CanMail) Clear();
        UpdateControls();
    }

    private void Clear()
    {
        _selectedId = 0; _selected = null; _targetKey = ""; Subject.Text = ""; Body.Text = "";
        Context.Text = "Выберите адресата."; Messages.RemoveAllChildren(); UpdateControls();
    }

    private void Select(SWPressMailEntry thread)
    {
        _selectedId = thread.Id; _selected = thread; _targetKey = ""; Subject.Text = thread.Subject; Body.Text = "";
        Context.Text = Short(thread.FirstName + " ↔ " + thread.SecondName);
        RenderMessages(thread); UpdateControls();
    }

    private void RenderMessages(SWPressMailEntry thread)
    {
        Messages.RemoveAllChildren();
        foreach (var message in thread.Messages)
        {
            var label = new RichTextLabel { HorizontalExpand = true };
            label.SetMessage($"{message.Author} · {message.Time}\n{message.Text}\n");
            Messages.AddChild(label);
        }
    }

    private void UpdateControls()
    {
        SendNew.Disabled = !_state.CanMail || _selectedId != 0 || string.IsNullOrEmpty(_targetKey);
        Reply.Disabled = !_state.CanMail || _selected == null || _selected.Messages.Count >= 6;
        CopyDraft.Disabled = !_state.CanWrite || _selected == null;
    }

    private void Send(SWPressAction action) => Action?.Invoke(new SWPressActionMessage
    {
        Action = action, Id = _selectedId, TargetKey = _targetKey, Title = Subject.Text, Body = Body.Text,
    });

    private static string Short(string value) => value.Length > 32 ? value[..32] + "…" : value;
}
