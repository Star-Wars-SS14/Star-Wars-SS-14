using System.Linq;
using System.Numerics;
using Content.Shared._SW.GlobalWar;
using Content.Shared._SW.GlobalWar.Combat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarReconMenu : SWGlobalWarWindow
{
    private const int StaleSeconds = 300;
    private const int FreshSeconds = 60;

    private readonly Dictionary<string, ProtoId<SWGlobalWarPlanetPrototype>> _planets = new();

    public SWGlobalWarReconMenu()
    {
        RobustXamlLoader.Load(this);
        ContentsContainer.Margin = new Thickness(0);
        HelpMark.ToolTip = Loc.GetString("sw-global-war-recon-instructions");
        CountValue.FontOverride = SWGlobalWarConsoleStyle.Bold(36);
        CountValue.FontColorOverride = Color.White;
        Scene.Scene = SWGlobalWarConsoleStyle.Picture("recon");
        foreach (var planet in IoCManager.Resolve<IPrototypeManager>().EnumeratePrototypes<SWGlobalWarPlanetPrototype>())
            _planets[Loc.GetString(planet.Name)] = planet.ID;
    }

    public void UpdateState(SWGlobalWarReconSnapshot snapshot)
    {
        Reports.RemoveAllChildren();
        StatusText.SetMessage(Loc.GetString(snapshot.Authorized ? "sw-global-war-recon-dated" : "sw-global-war-recon-denied"));
        CountValue.Text = snapshot.Reports.Length.ToString();
        foreach (var report in snapshot.Reports)
        {
            var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(10, 6), SeparationOverride = 4, HorizontalExpand = true };
            var head = new BoxContainer { SeparationOverride = 8 };
            head.AddChild(new Label { Text = report.Sector, FontOverride = SWGlobalWarConsoleStyle.Strong, FontColorOverride = Color.White, VAlign = Label.VAlignMode.Center });
            head.AddChild(new Label
            {
                Text = report.Device,
                HorizontalExpand = true,
                ClipText = true,
                VAlign = Label.VAlignMode.Center,
                FontOverride = SWGlobalWarConsoleStyle.Small,
                FontColorOverride = SWGlobalWarConsoleStyle.TextDim,
            });
            var age = (int) Math.Max(0, (snapshot.Now - report.ObservedAt).TotalSeconds);
            var chip = new SWGlobalWarChip();
            chip.Set(Loc.GetString("sw-global-war-recon-age", ("age", age)), age < FreshSeconds ? "good" : age < StaleSeconds ? "wait" : "off", age >= StaleSeconds ? "stale" : null);
            chip.ToolTip = Loc.GetString("sw-global-war-recon-heading", ("sector", report.Sector),
                ("device", report.Device), ("minute", (int) report.ObservedAt.TotalMinutes),
                ("second", report.ObservedAt.Seconds), ("age", age));
            chip.MouseFilter = MouseFilterMode.Stop;
            head.AddChild(chip);
            body.AddChild(head);
            var lines = new RichTextLabel();
            lines.SetMessage(string.Join("\n", report.Observations));
            body.AddChild(lines);
            var card = new PanelContainer { HorizontalExpand = true, PanelOverride = SWGlobalWarConsoleStyle.RowBox(false) };
            var line = new BoxContainer { SeparationOverride = 4 };
            // The report names a place: where that is a world on the chart, the chart's picture shows it.
            if (_planets.TryGetValue(report.Sector, out var world))
            {
                line.AddChild(new TextureRect
                {
                    Texture = SWGlobalWarMapControl.PlanetTexture(world, "planets_small"),
                    TextureScale = new Vector2(2),
                    Stretch = TextureRect.StretchMode.KeepCentered,
                    SetSize = new Vector2(60),
                    VerticalAlignment = VAlignment.Center,
                    Margin = new Thickness(4, 0, 0, 0),
                });
            }

            line.AddChild(body);
            card.AddChild(line);
            Reports.AddChild(card);
        }
    }
}
