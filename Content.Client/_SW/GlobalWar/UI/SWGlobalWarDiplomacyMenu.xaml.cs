[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarDiplomacyMenu : SWGlobalWarWindow
{
    public event Action<BoundUserInterfaceMessage>? Send;
    private readonly IPrototypeManager _prototypes = IoCManager.Resolve<IPrototypeManager>();
    private readonly Dictionary<SWGlobalWarPoliticalAction, Button> _actions = new();
    private readonly List<ProtoId<SWGlobalWarPlanetPrototype>> _neutrals = new();
    private readonly List<ProtoId<SWGlobalWarCommodityPrototype>> _commodities = new();
    private readonly HashSet<Guid> _retiredGenerations = new();
    private SWGlobalWarDiplomacyView? _view;
    private SWGlobalWarPoliticalRequest? _pending;
    private SWGlobalWarPoliticalAction? _confirmAction;
    private ProtoId<SWGlobalWarPlanetPrototype>? _neutral;
    private ProtoId<SWGlobalWarCommodityPrototype>? _commodity;
    private Guid? _historyRequest;
    private Guid _oldestMessage;
    private Guid _seenLatest;
    private bool _readingLatest = true;
    private readonly Stack<(SWGlobalWarHistoryPage Page, float Scroll)> _newerPages = new();
    private SWGlobalWarHistoryPage? _currentPage;
    private string? _confirmedPublicText;
    private readonly SWGlobalWarGovernmentDraftSystem _drafts = IoCManager.Resolve<IEntityManager>().System<SWGlobalWarGovernmentDraftSystem>();
    private SWGlobalWarGovernmentDraftSystem.Scope? _scope;
    private sealed record EditingState(string Text, string Amount, ProtoId<SWGlobalWarPlanetPrototype>? Neutral,
        ProtoId<SWGlobalWarCommodityPrototype>? Commodity, SWGlobalWarPoliticalRequest? Pending, string Result);
    private string _resultText = string.Empty;

    /// <summary>What to press next to declare war: the confirmation once it has been asked.</summary>
    public Robust.Client.UserInterface.Control DeclareWarControl => Confirm.VisibleInTree ? Confirm : _actions[SWGlobalWarPoliticalAction.DeclareWar];

    public SWGlobalWarDiplomacyMenu()
    {
        RobustXamlLoader.Load(this);
        Sponsor.SetAppearance(SWGlobalWarConsoleStyle.TextBright, money: true);
        Confirm.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        ProposalIcon.Texture = SWGlobalWarConsoleStyle.GovernmentIcon("diplomacy", "truce_pending");
        RelationIcon.TextureScale = new System.Numerics.Vector2(3);
        RelationWord.FontOverride = SWGlobalWarConsoleStyle.Bold(26);
        NeutralCard.PanelOverride = SWGlobalWarConsoleStyle.RowBox(false);
        NeutralPlanet.TextureScale = new System.Numerics.Vector2(2);
        SanctionIcon.Texture = SWGlobalWarConsoleStyle.GovernmentIcon("diplomacy", "sanction");
        foreach (var action in new[] { SWGlobalWarPoliticalAction.DeclareWar, SWGlobalWarPoliticalAction.OfferTruce,
                     SWGlobalWarPoliticalAction.WithdrawTruce, SWGlobalWarPoliticalAction.BreakTruce,
                     SWGlobalWarPoliticalAction.PrepareSurrender })
        {
            var button = new SWGlobalWarConsoleButton { Text = ActionName(action), MinHeight = 40 };
            if (action is SWGlobalWarPoliticalAction.DeclareWar or SWGlobalWarPoliticalAction.BreakTruce)
                button.SetAppearance(SWGlobalWarConsoleStyle.TextBright, danger: true);
            button.OnPressed += _ =>
            {
                if (action is SWGlobalWarPoliticalAction.DeclareWar or SWGlobalWarPoliticalAction.BreakTruce)
                    AskConfirmation(action);
                else
                    Request(action);
            };
            Actions.AddChild(button);
            _actions.Add(action, button);
        }
        NeutralSelector.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= _neutrals.Count)
                return;
            NeutralSelector.SelectId(args.Id);
            _neutral = _neutrals[args.Id];
            RefreshControls();
        };
        foreach (var commodity in _prototypes.EnumeratePrototypes<SWGlobalWarCommodityPrototype>().OrderBy(p => p.ID))
        {
            CommoditySelector.AddItem(Loc.GetString(commodity.Name), _commodities.Count);
            _commodities.Add(commodity.ID);
        }
        if (_commodities.Count != 0)
            _commodity = _commodities[0];
        CommoditySelector.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= _commodities.Count)
                return;
            CommoditySelector.SelectId(args.Id);
            _commodity = _commodities[args.Id];
            RefreshControls();
        };
        Amount.OnTextChanged += _ => RefreshControls();
        Draft.OnTextChanged += _ => RefreshControls();
        Sponsor.OnPressed += _ => Request(SWGlobalWarPoliticalAction.Sponsor);
        Contest.OnPressed += _ => Request(SWGlobalWarPoliticalAction.OpenBorderConflict);
        Impose.OnPressed += _ => Request(SWGlobalWarPoliticalAction.SetSanction, true);
        Lift.OnPressed += _ => Request(SWGlobalWarPoliticalAction.SetSanction, false);
        SendPrivate.OnPressed += _ => Request(SWGlobalWarPoliticalAction.StateMessage);
        SendPublic.OnPressed += _ =>
        {
            _confirmedPublicText = Rope.Collapse(Draft.TextRope);
            AskConfirmation(SWGlobalWarPoliticalAction.PublicAddress);
        };
        Confirm.OnPressed += _ =>
        {
            if (_confirmAction is { } action)
                Request(action);
            _confirmAction = null;
            ConfirmationPanel.Visible = false;
        };
        Cancel.OnPressed += _ => { _confirmAction = null; _confirmedPublicText = null; ConfirmationPanel.Visible = false; };
        Retry.OnPressed += _ => { if (_pending != null) Send?.Invoke(_pending); };
        Latest.OnPressed += _ => { _newerPages.Clear(); LoadHistory(Guid.Empty); };
        Older.OnPressed += _ =>
        {
            if (_currentPage != null)
                _newerPages.Push((_currentPage, HistoryScroll.VScroll));
            LoadHistory(_oldestMessage);
        };
        Newer.OnPressed += _ =>
        {
            if (!_newerPages.TryPop(out var saved))
                return;
            _historyRequest = saved.Page.Before;
            UpdateHistory(saved.Page);
            UserInterfaceManager.DeferAction(() =>
            {
                if (!Disposed && _currentPage == saved.Page)
                    HistoryScroll.VScrollTarget = saved.Scroll;
            });
        };
    }

    public void UpdateView(SWGlobalWarDiplomacyView view)
    {
        if (view.Generation != Guid.Empty && _retiredGenerations.Contains(view.Generation) ||
            _view is { } previous && previous.Generation == view.Generation && previous.Revision > view.Revision)
            return;
        if (_view is { } old && old.Generation != Guid.Empty && view.Generation != old.Generation)
            _retiredGenerations.Add(old.Generation);
        var authorityChanged = _view?.Generation != view.Generation || _view?.Assignment != view.Assignment ||
                               _view?.AssignmentRevision != view.AssignmentRevision || !view.CanReadMessages;
        if (authorityChanged)
            ClearPrivateData();
        _view = view;
        if (view.Availability == SWGlobalWarViewAvailability.Ready && view.CanReadMessages)
        {
            var scope = _drafts.Authorize(SWGlobalWarGovernmentConsoleKind.Diplomacy,
                view.Generation, view.Assignment, view.AssignmentRevision);
            if (_scope == null && scope is { } authorized &&
                _drafts.Restore<EditingState>(SWGlobalWarGovernmentConsoleKind.Diplomacy, authorized) is { } saved)
            {
                Draft.TextRope = new Rope.Leaf(saved.Text);
                Amount.Text = saved.Amount;
                _neutral = saved.Neutral;
                _commodity = saved.Commodity;
                _pending = saved.Pending;
                _resultText = saved.Result;
                Plain(Result, _resultText);
                if (_commodity is { } good && _commodities.Contains(good))
                    CommoditySelector.SelectId(_commodities.IndexOf(good));
            }
            _scope = scope;
        }
        else
        {
            _scope = null;
            _drafts.Revoke(SWGlobalWarGovernmentConsoleKind.Diplomacy);
        }
        Content.Visible = SectorScroll.Visible = view.Availability == SWGlobalWarViewAvailability.Ready;
        Plain(Status, Loc.GetString(view.Availability switch
        {
            SWGlobalWarViewAvailability.Ready => view.CanReadMessages
                ? "sw-global-war-government-authorized" : "sw-global-war-government-public-only",
            SWGlobalWarViewAvailability.Forbidden => "sw-global-war-government-forbidden",
            _ => "sw-global-war-government-unavailable",
        }));
        if (!Content.Visible)
            return;
        Plain(Relations, Loc.GetString("sw-global-war-relation-" + view.Relations.ToString().ToLowerInvariant()));
        RelationWord.Text = Loc.GetString("sw-global-war-relation-" + view.Relations.ToString().ToLowerInvariant()).ToUpperInvariant();
        RelationWord.FontColorOverride = view.Relations == SWGlobalWarRelations.War ? SWGlobalWarConsoleStyle.EmpireText : SWGlobalWarConsoleStyle.Good;
        RelationIcon.Texture = SWGlobalWarConsoleStyle.GovernmentIcon("diplomacy", view.Relations.ToString().ToLowerInvariant());
        Scene.Scene = SWGlobalWarConsoleStyle.Picture(view.Relations == SWGlobalWarRelations.War ? "diplomacy_war" : "diplomacy_peace");
        ProposalIcon.Visible = view.OwnTruceProposal || view.OpponentTruceProposal;
        ProposalRow.Visible = view.Relations == SWGlobalWarRelations.War;
        SanctionIcon.Visible = view.Sanctions.Count != 0;
        Plain(Proposals, Loc.GetString("sw-global-war-diplomacy-proposals",
            ("own", YesNo(view.OwnTruceProposal)), ("other", YesNo(view.OpponentTruceProposal))));
        WarTime.Visible = view.Relations == SWGlobalWarRelations.Peace &&
                          (view.Time < view.WarAvailableAt || view.Actions.Contains(SWGlobalWarPoliticalAction.DeclareWar));
        Plain(WarTime, view.Time < view.WarAvailableAt
            ? Loc.GetString("sw-global-war-diplomacy-war-time", ("time", Clock(view.WarAvailableAt - view.Time)))
            : Loc.GetString("sw-global-war-diplomacy-war-ready"));
        var ids = view.Neutrals.Select(n => n.Planet).ToList();
        if (!_neutrals.SequenceEqual(ids))
        {
            _neutrals.Clear();
            NeutralSelector.Clear();
            foreach (var id in ids)
            {
                NeutralSelector.AddItem(_prototypes.Index(id).Name, _neutrals.Count);
                _neutrals.Add(id);
            }
            if (_neutral == null || !_neutrals.Contains(_neutral.Value))
                _neutral = _neutrals.Count != 0 ? _neutrals[0] : (ProtoId<SWGlobalWarPlanetPrototype>?) null;
            if (_neutral is { } selected)
                NeutralSelector.SelectId(_neutrals.IndexOf(selected));
        }
        Plain(Sanctions, view.Sanctions.Count == 0 ? Loc.GetString("sw-global-war-government-none") :
            string.Join("\n", view.Sanctions.Select(s => FactionName(s.Faction) + ": " + Loc.GetString(_prototypes.Index(s.Commodity).Name))));
        Correspondence.Visible = view.CanReadMessages;
        if (view.CanReadMessages && authorityChanged && _historyRequest == null)
            LoadHistory(Guid.Empty);
        NewMessages.Visible = view.CanReadMessages && view.LatestMessage != _seenLatest;
        if (_pending is { } pending)
        {
            var result = view.RecentResults.FirstOrDefault(r => r.Request == pending.Request);
            if (result != null)
                UpdateResult(result);
        }
        RefreshControls();
    }

    public void UpdateResult(SWGlobalWarPoliticalResultView result)
    {
        if (_pending is not { } pending || result.Request != pending.Request)
            return;
        _pending = null;
        _resultText = result.Accepted ? AcceptedText(pending) : Loc.GetString(
            string.IsNullOrEmpty(result.Reason) ? "sw-global-war-politics-denied" : result.Reason,
            ("seconds", Math.Max(1, (int) Math.Ceiling(result.RetryAfter.TotalSeconds))));
        Plain(Result, _resultText);
        if (result.Accepted && pending.Action is SWGlobalWarPoliticalAction.StateMessage or SWGlobalWarPoliticalAction.PublicAddress &&
            Rope.Collapse(Draft.TextRope) == pending.Text)
            Draft.TextRope = Rope.Leaf.Empty;
        if (result.Accepted && pending.Action == SWGlobalWarPoliticalAction.PrepareSurrender)
            AskConfirmation(SWGlobalWarPoliticalAction.ConfirmSurrender);
        RefreshControls();
    }

    public void UpdateHistory(SWGlobalWarHistoryPage page)
    {
        if (_view is not { CanReadMessages: true } view || page.Generation != view.Generation ||
            page.AssignmentRevision != view.AssignmentRevision || _historyRequest != page.Before)
            return;
        _historyRequest = null;
        _readingLatest = page.Before == Guid.Empty;
        _currentPage = page;
        Newer.Disabled = _newerPages.Count == 0;
        _oldestMessage = page.Messages.Count == 0 ? Guid.Empty : page.Messages[0].Id;
        Older.Disabled = !page.Allowed || !page.HasOlder;
        Plain(History, !page.Allowed ? Loc.GetString("sw-global-war-government-forbidden") :
            page.Messages.Count == 0 ? Loc.GetString("sw-global-war-government-none") :
            string.Join("\n\n", page.Messages.Select(m =>
                $"{Clock(m.At)} · {FactionName(m.Faction)} · {m.Author}\n{m.Text}")));
    }

    private void LoadHistory(Guid before)
    {
        if (_view is not { CanReadMessages: true } view)
            return;
        _historyRequest = before;
        if (before == Guid.Empty)
        {
            _seenLatest = view.LatestMessage;
            NewMessages.Visible = false;
        }
        Send?.Invoke(new SWGlobalWarHistoryRequest(view.Generation, view.AssignmentRevision, before));
    }

    private void ClearPrivateData()
    {
        Draft.TextRope = Rope.Leaf.Empty;
        Plain(History, string.Empty);
        NeutralPlanet.Texture = _neutral is { } shownWorld ? SWGlobalWarMapControl.PlanetTexture(shownWorld, "planets_small") : null;
        Plain(NeutralDetails, string.Empty);
        Plain(ConfirmationText, string.Empty);
        Plain(Result, string.Empty);
        _pending = null;
        _confirmAction = null;
        _historyRequest = null;
        _oldestMessage = Guid.Empty;
        _seenLatest = Guid.Empty;
        _readingLatest = true;
        _scope = null;
        _newerPages.Clear();
        _currentPage = null;
        _confirmedPublicText = null;
        _resultText = string.Empty;
        ConfirmationPanel.Visible = false;
        Older.Disabled = true;
        Newer.Disabled = true;
    }

    private void AskConfirmation(SWGlobalWarPoliticalAction action)
    {
        _confirmAction = action;
        ConfirmationPanel.Visible = true;
        Plain(ConfirmationText, action == SWGlobalWarPoliticalAction.PublicAddress
            ? Loc.GetString("sw-global-war-diplomacy-confirm-public", ("text", _confirmedPublicText ?? string.Empty))
            : Loc.GetString(action == SWGlobalWarPoliticalAction.ConfirmSurrender
                ? "sw-global-war-diplomacy-confirm-surrender" : "sw-global-war-diplomacy-confirm-war"));
        RefreshControls();
        UserInterfaceManager.DeferAction(() =>
        {
            if (!Disposed && ConfirmationPanel.Visible)
                Scroll.VScrollTarget = ConfirmationPanel.Position.Y;
        });
    }

    private void Request(SWGlobalWarPoliticalAction action, bool enabled = false)
    {
        if (_view is not { Availability: SWGlobalWarViewAvailability.Ready } view || _pending != null)
            return;
        long.TryParse(Amount.Text, NumberStyles.None, CultureInfo.InvariantCulture, out var amount);
        _pending = new SWGlobalWarPoliticalRequest(view.Generation, Guid.NewGuid(), view.AssignmentRevision,
            action, view.RelationsRevision, _neutral, _commodity, enabled, amount,
            action == SWGlobalWarPoliticalAction.PublicAddress ? _confirmedPublicText ?? string.Empty :
                action == SWGlobalWarPoliticalAction.StateMessage ? Rope.Collapse(Draft.TextRope) : string.Empty,
            view.SurrenderConfirmation);
        Plain(Result, Loc.GetString("sw-global-war-government-pending"));
        Send?.Invoke(_pending);
        RefreshControls();
    }

    private void RefreshControls()
    {
        if (_view is not { } view)
            return;
        bool Allowed(SWGlobalWarPoliticalAction action) => _pending == null && view.Actions.Contains(action);
        foreach (var (action, button) in _actions)
            button.Disabled = !Allowed(action);
        Retry.Visible = _pending != null;
        Confirm.Disabled = _confirmAction is not { } confirm || !Allowed(confirm);
        if (_confirmAction == SWGlobalWarPoliticalAction.ConfirmSurrender &&
            (view.ConfirmationExpires == null || view.Time >= view.ConfirmationExpires))
        {
            _confirmAction = null;
            ConfirmationPanel.Visible = false;
            _resultText = Loc.GetString("sw-global-war-politics-confirmation-expired");
            Plain(Result, _resultText);
        }
        var neutral = view.Neutrals.FirstOrDefault(n => n.Planet == _neutral);
        var validAmount = long.TryParse(Amount.Text, NumberStyles.None, CultureInfo.InvariantCulture, out var amount) && amount > 0;
        Sponsor.Disabled = _pending != null || neutral?.CanSponsor != true || !validAmount ||
                           amount > neutral.ContributionLimit - neutral.OwnContribution || amount > view.Treasury;
        Contest.Disabled = _pending != null || neutral?.CanContest != true;
        Plain(NeutralDetails, NeutralDescription(neutral, view));
        var sanction = _commodity is { } good && view.Sanctions.Any(s => s.Faction == view.Faction && s.Commodity == good);
        Impose.Disabled = !Allowed(SWGlobalWarPoliticalAction.SetSanction) || _commodity == null || sanction;
        Lift.Disabled = !Allowed(SWGlobalWarPoliticalAction.SetSanction) || !sanction;
        var message = Rope.Collapse(Draft.TextRope).Trim();
        SendPrivate.Disabled = !Allowed(SWGlobalWarPoliticalAction.StateMessage) || message.Length is < 1 or > 1000;
        SendPublic.Disabled = !Allowed(SWGlobalWarPoliticalAction.PublicAddress) || message.Length is < 1 or > 1000;
    }

    private static string NeutralDescription(SWGlobalWarNeutralView? neutral, SWGlobalWarDiplomacyView view)
    {
        if (neutral == null)
            return Loc.GetString("sw-global-war-government-none");

        var text = neutral.Phase switch
        {
            SWGlobalWarNeutralPhase.CivilWar => Loc.GetString("sw-global-war-diplomacy-neutral-civilwar"),
            SWGlobalWarNeutralPhase.Annexing => Loc.GetString("sw-global-war-diplomacy-neutral-annexing",
                ("faction", FactionName(neutral.Claimant)), ("time", Clock(neutral.Remaining))),
            _ => Loc.GetString("sw-global-war-diplomacy-neutral-integrated"),
        };
        if (neutral.Phase == SWGlobalWarNeutralPhase.Annexing && neutral.Paused)
            text += "\n" + Loc.GetString("sw-global-war-diplomacy-paused");
        if (neutral.OwnContribution is { } paid)
        {
            text += "\n" + Loc.GetString("sw-global-war-diplomacy-contribution",
                ("paid", paid), ("limit", neutral.ContributionLimit!.Value), ("treasury", view.Treasury ?? 0));
            if (neutral.Phase == SWGlobalWarNeutralPhase.CivilWar && view.Time < neutral.FundingEndsAt)
                text += "\n" + Loc.GetString("sw-global-war-diplomacy-funding-time",
                    ("time", Clock(neutral.FundingEndsAt - view.Time)));
        }
        return text;
    }

    /// <summary>Preserves only this player's own editing state; received pages are discarded with the window.</summary>
    public void SaveDraft()
    {
        if (_scope is { } scope)
            _drafts.Save(SWGlobalWarGovernmentConsoleKind.Diplomacy, scope, new EditingState(
                Rope.Collapse(Draft.TextRope), Amount.Text, _neutral, _commodity, _pending, _resultText));
    }

    private string AcceptedText(SWGlobalWarPoliticalRequest request) => request.Action switch
    {
        SWGlobalWarPoliticalAction.StateMessage => Loc.GetString("sw-global-war-diplomacy-sent-private"),
        SWGlobalWarPoliticalAction.PublicAddress => Loc.GetString("sw-global-war-diplomacy-sent-public"),
        SWGlobalWarPoliticalAction.Sponsor when request.Sector is { } sector =>
            Loc.GetString("sw-global-war-diplomacy-funded", ("sector", _prototypes.Index(sector).Name), ("amount", request.Amount)),
        _ => Loc.GetString("sw-global-war-diplomacy-action-accepted", ("action", ActionName(request.Action))),
    };

    private static string ActionName(SWGlobalWarPoliticalAction action) => Loc.GetString("sw-global-war-action-" + action.ToString().ToLowerInvariant());
    private static string YesNo(bool value) => Loc.GetString(value ? "sw-global-war-government-yes" : "sw-global-war-government-no");
    private static string FactionName(SWGlobalWarFaction faction) => Loc.GetString("sw-global-war-" + faction.ToString().ToLowerInvariant());
    private static string Clock(TimeSpan time) => $"{Math.Max(0, (int)time.TotalMinutes):00}:{Math.Max(0, time.Seconds):00}";
    private static void Plain(RichTextLabel label, string text) => label.SetMessage(SWGlobalWarConsoleStyle.MoneyMessage(text));
}
