using System;
using System.Collections.Generic;
using System.Linq;
using Content.Client._SW._Senate.Consoles.Economy;
using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using static Content.Client._SW._Senate.Consoles.Statistics.SWStatisticsWidgets;

namespace Content.Client._SW._Senate.Consoles.Statistics;

[GenerateTypedNameReferences]
public sealed partial class SWStatisticsConsoleMenu : FancyWindow
{
    private readonly Control[] _panels;
    private readonly Button[] _tabs;
    private SWStatisticsConsoleState? _state;
    private int _active;
    private string? _metricId;
    private string? _sectorId;
    private int _operation;
    private string _metricSignature = string.Empty;
    private readonly BoxContainer _metrics = VerticalStack(4);
    private readonly Dictionary<string, (SWConsoleButton Button, Label Status)> _metricButtons = new();
    private readonly BoxContainer _operationDetail = VerticalStack(12);
    private readonly Button[] _operationButtons;
    private readonly SWConsoleDocuments _crises = new();
    private readonly SWConsoleDocuments _laws = new();
    private readonly RichTextLabel _crisisSummary = SWConsoleStyle.Wrap(string.Empty, SWConsoleStyle.TextDim);
    public string? SelectedMetricId => _metricId;
    public string? SelectedSectorId => _sectorId;
    public const int CommoditiesTab = 6;
    public SWRepublicCommodityBrowser Commodities { get; private set; } = default!;

    public SWStatisticsConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        TitleClass = "LabelKeyText";
        SWConsoleStyle.StyleRoot(RootPanel);
        SWConsoleStyle.StyleHeader(HeaderPanel);
        SWConsoleStyle.StyleTabBar(TabBarPanel);
        HeaderNetwork.FontOverride = SWConsoleStyle.Small;
        HeaderNetwork.FontColorOverride = SWConsoleStyle.Brass;
        HeaderTitle.FontOverride = SWConsoleStyle.Header;
        HeaderTitle.FontColorOverride = SWConsoleStyle.TextBright;
        HeaderClock.FontOverride = SWConsoleStyle.Small;
        HeaderClock.FontColorOverride = SWConsoleStyle.TextDim;
        _panels = new Control[] { RepublicPanel, SectorsPanel, OperationsPanel, CrisesPanel, LawsPanel, GalaxyPanel, CommoditiesPanel };
        var names = new[] { "Обзор", "Сектора", "Обстановка", "Кризисы", "Законы", "Галактика", "Товары" };
        _tabs = new Button[names.Length];
        for (var i = 0; i < names.Length; i++)
        {
            var index = i;
            _tabs[i] = SWConsoleStyle.TabButton(names[i]);
            _tabs[i].OnPressed += _ => ShowTab(index);
            TabBar.AddChild(_tabs[i]);
        }
        InitializeOverview();
        InitializeSectors();
        InitializeGalaxy();
        Commodities = new SWRepublicCommodityBrowser();
        Commodities.WorldRequested += id =>
        {
            _galaxy.ShowGalaxy();
            _galaxy.SelectWorld(id, true);
            if (Commodities.InspectedCommodityId is { } good) _galaxy.SelectCommodity(good);
            _galaxy.ShowEconomyPage(1);
            ShowTab(GalaxyTab);
        };
        CommoditiesPanel.AddChild(Commodities);
        _tabs[GalaxyTab].SetPositionInParent(1);
        var operationNav = VerticalStack(4);
        var operationNames = new[] { "Границы и оборона", "Безопасность", "Здравоохранение", "Экономика", "Финансы", "Правосудие", "Полномочия" };
        _operationButtons = new Button[operationNames.Length];
        for (var i = 0; i < operationNames.Length; i++)
        {
            var index = i;
            var button = SWConsoleStyle.TabButton(operationNames[i]);
            button.TextAlign = Label.AlignMode.Left;
            button.Label.HorizontalAlignment = HAlignment.Stretch;
            button.OnPressed += _ => { _operation = index; RefreshOperations(); };
            _operationButtons[i] = button;
            operationNav.AddChild(button);
        }
        OperationsContent.AddChild(new SWConsoleColumns(operationNav, _operationDetail, 215, 700, fixedFirst: true));
        CrisesList.AddChild(_crisisSummary);
        CrisesList.AddChild(_crises);
        LawsList.AddChild(_laws);
        ShowTab(0);
    }

    public void ShowTab(int index)
    {
        if (index < 0 || index >= _panels.Length) return;
        _active = index;
        for (var i = 0; i < _panels.Length; i++)
        {
            _panels[i].Visible = i == index;
            SWConsoleStyle.StyleTabButton(_tabs[i], i == index);
        }
        RefreshActive();
    }

    public void SetState(SWStatisticsConsoleState state)
    {
        _state = state;
        HeaderClock.Text = state.GameTime.Length > 0 ? state.GameTime : "—";
        if (!state.Globals.Any(g => g.Id == _metricId)) _metricId = state.Globals.FirstOrDefault()?.Id;
        UpdateMetricNavigation();
        _tabs[3].Text = state.Crises.Count > 0 ? $"Кризисы ({state.Crises.Count})" : "Кризисы";
        RefreshActive();
    }

    public void SelectMetric(string id)
    {
        if (_state?.Globals.All(g => g.Id != id) != false) return;
        _metricId = id;
        UpdateMetricNavigation();
        RefreshActive();
    }

    public void SelectSector(string id)
    {
        if (_state?.Sectors.All(s => s.Id != id) != false) return;
        _sectorId = id;
        RefreshSectors();
    }

    private void RefreshActive()
    {
        if (_state == null) return;
        switch (_active)
        {
            case 0: RefreshOverview(); break;
            case 1: RefreshSectors(); break;
            case 2: RefreshOperations(); break;
            case 3: RefreshCrises(); break;
            case 4: RefreshLaws(); break;
            case GalaxyTab: RefreshGalaxy(); break;
        }
    }

    private void UpdateMetricNavigation()
    {
        if (_state == null) return;
        var signature = string.Join("|", _state.Globals.Select(g => $"{g.Id}:{g.Name}"));
        if (signature != _metricSignature)
        {
            _metricSignature = signature;
            _metrics.RemoveAllChildren();
            _metricButtons.Clear();
            _sectorMetric.Clear();
            foreach (var (g, index) in _state.Globals.Select((g, i) => (g, i)))
            {
                var button = new SWConsoleButton { HorizontalExpand = true };
                button.Label.Visible = false;
                var text = VerticalStack(3);
                text.AddChild(SWConsoleStyle.Wrap(g.Name, SWConsoleStyle.TextBright));
                var status = SWConsoleStyle.Text(string.Empty, SWConsoleStyle.TextDim, SWConsoleStyle.Small);
                text.AddChild(status);
                button.AddChild(text);
                button.OnPressed += _ => SelectMetric(g.Id);
                _metrics.AddChild(button);
                _metricButtons.Add(g.Id, (button, status));
                _sectorMetric.AddItem(g.Name, index);
            }
        }
        _sectorMetric.Disabled = _state.Globals.Count == 0;
        for (var i = 0; i < _state.Globals.Count; i++)
        {
            var g = _state.Globals[i];
            var row = _metricButtons[g.Id];
            row.Button.SetAppearance(SWConsoleStyle.TextBright, selected: g.Id == _metricId, quiet: true);
            row.Button.ToolTip = $"Факт: {SWStatisticsPresentation.Number(g.Actual)}, политика: {SWStatisticsPresentation.Number(g.Policy)}";
            row.Status.Text = SWStatisticsPresentation.Level(g.Actual, g.Min, g.Max);
            row.Status.FontColorOverride = SWStatisticsPresentation.LevelColor(g.Actual, g.Min, g.Max);
            if (g.Id == _metricId) _sectorMetric.SelectId(i);
        }
    }

    private void RefreshOperations()
    {
        if (_state == null) return;
        for (var i = 0; i < _operationButtons.Length; i++) SWConsoleStyle.StyleTabButton(_operationButtons[i], i == _operation);
        _operationDetail.RemoveAllChildren();
        _operationDetail.AddChild(SWConsoleDocument.Body(_operationButtons[_operation].Text ?? string.Empty, ""));
        _operationDetail.AddChild(Operations(_state, _operation));
    }

    private void RefreshCrises()
    {
        if (_state == null) return;
        var severe = _state.Crises.Count(c => c.Severity >= 70);
        _crisisSummary.Visible = severe > 0 || _state.Crises.Count == 0;
        _crisisSummary.SetMessage(_state.Crises.Count == 0 ? "Кризисов нет" : $"Высокая тяжесть: {severe}", defaultColor: severe > 0 ? SWConsoleStyle.Bad : SWConsoleStyle.TextDim);
        _crises.SetDocuments(_state.Crises.OrderByDescending(c => c.Severity).Select(c => new SWConsoleDocumentEntry(
            c.Id, c.Name, $"{c.TypeLabel}, {c.AffectedLabel}",
            $"{c.Name}|{c.Description}|{c.TypeLabel}|{c.AffectedLabel}|{c.Severity}|{c.SeverityLabel}|{c.EscalationThreat}|{c.ExitProgress}|" + string.Join(";", c.Impact.Select(e => $"{e.StatName}:{e.Delta}:{e.Color}")),
            () =>
            {
                var body = SWConsoleDocument.Body(c.Name, c.Description);
                body.AddChild(Metric("Тяжесть кризиса", c.Severity, color: SWConsoleStyle.SeverityColor(c.Severity)));
                body.AddChild(SWConsoleStyle.Wrap(c.SeverityLabel, SWConsoleStyle.TextDim));
                body.AddChild(SWConsoleStyle.Wrap($"{c.TypeLabel}, {c.AffectedLabel}", SWConsoleStyle.TextDim));
                if (c.EscalationThreat.Length > 0) body.AddChild(SWConsoleStyle.Wrap(c.EscalationThreat, SWConsoleStyle.Warn));
                if (c.ExitProgress.Length > 0) body.AddChild(SWConsoleStyle.Wrap(c.ExitProgress, SWConsoleStyle.Good));
                StatEffects(body, c.Impact);
                return body;
            })));
    }

    private void RefreshLaws()
    {
        if (_state == null) return;
        _laws.SetDocuments(_state.ActiveLaws.Select(law => new SWConsoleDocumentEntry(law.Id, law.Name,
            $"№ {law.Id}, {law.Author}", SWConsoleDocument.Revision(law), () => SWConsoleDocument.Bill(law))));
    }
}
