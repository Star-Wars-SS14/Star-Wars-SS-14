using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._SW.GlobalWar;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarTravelConsoleMenu : FancyWindow
{
    public event Action<ProtoId<SWGlobalWarPlanetPrototype>>? OnTravelPressed;

    private readonly IPrototypeManager _prototypes;
    private readonly Dictionary<RichTextLabel, string> _displayedText = new();
    private SWGlobalWarTravelConsoleState? _state;
    private ProtoId<SWGlobalWarPlanetPrototype>? _selected;
    private readonly List<ProtoId<SWGlobalWarPlanetPrototype>> _searchPlanets = new();

    public SWGlobalWarTravelConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        _prototypes = IoCManager.Resolve<IPrototypeManager>();
        StyleInterface();
        Map.PlanetSelected += id =>
        {
            _selected = id;
            UpdatePlanetInfo();
        };
        Map.ViewChanged += () => Zoom.Text = $"{Map.Zoom * 100:0}%";
        ZoomOut.OnPressed += _ => Map.ChangeZoom(1 / 1.2f);
        ZoomIn.OnPressed += _ => Map.ChangeZoom(1.2f);
        ResetView.OnPressed += _ => Map.ResetView();
        FocusPlanet.OnPressed += _ =>
        {
            if (_selected is { } selected)
                Map.SelectPlanet(selected, focus: true);
        };
        PlanetSearch.OnItemSelected += args =>
        {
            if (args.Id >= 0 && args.Id < _searchPlanets.Count)
                Map.SelectPlanet(_searchPlanets[args.Id], focus: true);
        };
        Travel.OnPressed += _ =>
        {
            if (_selected is not { } selected ||
                _state?.Destinations.Any(entry => entry.Id == selected && entry.Available) != true)
                return;

            Travel.Disabled = true;
            OnTravelPressed?.Invoke(selected);
        };
    }

    public void UpdateState(SWGlobalWarTravelConsoleState state)
    {
        _state = state;
        SetText(Status, string.IsNullOrEmpty(state.Status)
            ? Loc.GetString("sw-global-war-travel-location", ("planet", state.CurrentPlanet))
            : state.Status);
        // Update availability without rebuilding the map, preserving selection, zoom and an active drag.
        Map.SetState(state.Destinations, state.CurrentPlanetId);
        UpdateSearch(state.Destinations);
        UpdatePlanetInfo();
    }

    /// <summary>Updates the selected planet's details and server-provided travel availability in place.</summary>
    private void UpdatePlanetInfo()
    {
        var entry = _state?.Destinations.FirstOrDefault(destination => destination.Id == _selected);
        if (entry == null || !_prototypes.TryIndex(entry.Id, out var planet))
        {
            _selected = null;
            SelectionHint.Visible = true;
            PlanetInfo.Visible = false;
            Travel.Disabled = true;
            Travel.Visible = false;
            FocusPlanet.Disabled = true;
            return;
        }

        SelectionHint.Visible = false;
        PlanetInfo.Visible = true;
        Travel.Visible = true;
        FocusPlanet.Disabled = false;
        SetText(PlanetName, entry.Name);
        SetText(PlanetDescription, planet.Description);
        PlanetDescription.Visible = !string.IsNullOrEmpty(planet.Description);
        SetText(HyperspaceTime, planet.HyperspaceTime is { } seconds
            ? Loc.GetString("sw-global-war-travel-time", ("seconds", seconds))
            : Loc.GetString("sw-global-war-travel-time-default"));
        var connections = _state!.Destinations.Where(destination => planet.Connections.Contains(destination.Id))
            .Select(destination => destination.Name);
        var names = string.Join(", ", connections);
        SetText(Connections, Loc.GetString("sw-global-war-travel-connections", ("planets",
            string.IsNullOrEmpty(names) ? Loc.GetString("sw-global-war-travel-no-connections") : names)));
        var availability = entry.Available ? Loc.GetString("sw-global-war-travel-ready") : entry.Reason;
        if (!_displayedText.TryGetValue(Availability, out var previous) || previous != availability)
        {
            _displayedText[Availability] = availability;
            Availability.SetMessage(availability, defaultColor: entry.Available
                ? SWGlobalWarConsoleStyle.Good : SWGlobalWarConsoleStyle.Bad);
        }
        Availability.Visible = entry.Available || !string.IsNullOrEmpty(entry.Reason);
        Travel.Disabled = !entry.Available;
    }

    private void UpdateSearch(IReadOnlyList<SWGlobalWarTravelDestination> destinations)
    {
        if (PlanetSearch.ItemCount > 0 && _searchPlanets.Count == destinations.Count &&
            destinations.All(entry => _searchPlanets.Contains(entry.Id)))
            return;

        _searchPlanets.Clear();
        PlanetSearch.Clear();
        PlanetSearch.AddItem(Loc.GetString("sw-global-war-travel-search"), -1);
        PlanetSearch.SetItemDisabled(0, true);
        foreach (var entry in destinations.OrderBy(entry => entry.Name))
        {
            PlanetSearch.AddItem(entry.Name, _searchPlanets.Count);
            _searchPlanets.Add(entry.Id);
        }
        PlanetCount.Text = Loc.GetString("sw-global-war-travel-planet-count", ("count", destinations.Count));
    }

    /// <summary>Applies the Senate console palette and datapad controls to the XAML-defined navigation layout.</summary>
    private void StyleInterface()
    {
        SWGlobalWarConsoleStyle.StyleRoot(RootPanel);
        HeaderPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = SWGlobalWarConsoleStyle.Navigation,
            BorderColor = SWGlobalWarConsoleStyle.Brass,
            BorderThickness = new Thickness(0, 0, 0, 1),
        };
        StatusPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = SWGlobalWarConsoleStyle.BgPanel };
        MapPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = SWGlobalWarConsoleStyle.Navigation };
        DetailsPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = SWGlobalWarConsoleStyle.BgPanel };
        TravelInfoPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = SWGlobalWarConsoleStyle.Navigation };
        HeaderNetwork.FontOverride = SWGlobalWarConsoleStyle.Small;
        HeaderNetwork.FontColorOverride = SWGlobalWarConsoleStyle.Brass;
        HeaderTitle.FontOverride = SWGlobalWarConsoleStyle.Title;
        HeaderTitle.FontColorOverride = SWGlobalWarConsoleStyle.TextBright;
        InfoTitle.FontOverride = MapTitle.FontOverride = SWGlobalWarConsoleStyle.Strong;
        InfoTitle.FontColorOverride = SWGlobalWarConsoleStyle.Brass;
        MapTitle.FontColorOverride = SWGlobalWarConsoleStyle.TextBright;
        PlanetCount.FontOverride = SWGlobalWarConsoleStyle.Small;
        CurrentLegend.FontColorOverride = SWGlobalWarConsoleStyle.Brass;
        AvailableLegend.FontColorOverride = SWGlobalWarConsoleStyle.Good;
        UnavailableLegend.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        foreach (var button in new[] { ZoomOut, ZoomIn, ResetView, FocusPlanet })
            button.SetAppearance(SWGlobalWarConsoleStyle.TextBright, quiet: true);
        Travel.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        PlanetSearch.ModulateSelfOverride = Color.White;
        PlanetSearch.StyleBoxOverride = new SWGlobalWarConsoleSurface
        {
            Background = SWGlobalWarConsoleStyle.PillDim,
            ContentMarginLeftOverride = 10, ContentMarginRightOverride = 10,
            ContentMarginTopOverride = 6, ContentMarginBottomOverride = 6,
        };
    }

    private void SetText(RichTextLabel label, string text)
    {
        if (_displayedText.TryGetValue(label, out var previous) && previous == text)
            return;

        _displayedText[label] = text;
        label.SetMessage(text);
    }
}
