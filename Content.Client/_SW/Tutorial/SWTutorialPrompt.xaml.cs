using Content.Client._SW.UserInterface;
using Content.Client.Stylesheets;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.Tutorial;

/// <summary>
/// One line of what to do now, a line on what just went wrong, and the exit button that is always there.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SWTutorialPrompt : UIWidget
{
    private const int TextSize = 14;
    private const int BigTextSize = 18;

    private readonly Font _font;
    private readonly Font _bigFont;

    public event Action? OnExitPressed;
    public event Action? OnReturnPressed;

    public Control ReturnControl => ReturnButton;

    public string PromptText => PromptLabel.Text ?? string.Empty;

    public string NoteText => NoteLabel.Text ?? string.Empty;

    public SWTutorialPrompt()
    {
        RobustXamlLoader.Load(this);

        var resources = IoCManager.Resolve<IResourceCache>();
        _font = resources.NotoStack(size: TextSize);
        _bigFont = resources.NotoStack(variation: "Bold", size: BigTextSize);

        PromptLabel.FontOverride = _font;
        PromptLabel.FontColorOverride = SWTerminalStyle.TextBright;
        NoteLabel.FontOverride = _font;
        NoteLabel.FontColorOverride = SWTerminalStyle.TextBright;

        ExitButton.OnPressed += _ => OnExitPressed?.Invoke();
        ReturnButton.OnPressed += _ => OnReturnPressed?.Invoke();
    }

    /// <param name="text">The line. Null leaves only the exit button.</param>
    /// <param name="big">Large letters, for when the player seems not to see it.</param>
    /// <param name="note">What just went wrong, if anything.</param>
    public void SetText(string? text, bool big, string? note)
    {
        PromptLabel.Visible = text != null;
        PromptLabel.Text = text ?? string.Empty;
        PromptLabel.FontOverride = big ? _bigFont : _font;

        NoteLabel.Visible = note != null;
        NoteLabel.Text = note ?? string.Empty;
    }

    public void SetReturnButton(bool visible)
    {
        ReturnButton.Visible = visible;
    }
}
