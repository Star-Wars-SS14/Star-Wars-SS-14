using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate;

[GenerateTypedNameReferences]
public sealed partial class SWSectorSelectConsoleMenu : FancyWindow
{
    private readonly SWSectorSelectConsoleBoundUserInterface _owner;

    public SWSectorSelectConsoleMenu(SWSectorSelectConsoleBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        _owner = owner;
    }

    public void SetState(SWSectorSelectConsoleState state)
    {
        SectorButtons.RemoveAllChildren();

        if (!state.HasCard)
        {
            StatusLabel.SetMessage("Вставьте ID-карту, чтобы выбрать сектор.");
            return;
        }

        if (!state.IsSenatorCard)
        {
            StatusLabel.SetMessage("Сектор может закрепить только карта сенатора.");
            return;
        }

        if (state.CurrentSector != null)
        {
            StatusLabel.SetMessage($"Сектор закреплён: {state.CurrentSectorName}");
            return;
        }

        StatusLabel.SetMessage("Выберите сектор для представительства:");

        foreach (var sector in state.Sectors)
        {
            var button = new Button
            {
                Text = sector.Claimed ? $"{sector.Name} (Занято)" : sector.Name,
                Modulate = sector.Color,
                Disabled = sector.Claimed,
                Margin = new Thickness(0, 1, 0, 1),
            };

            if (!sector.Claimed)
            {
                var id = sector.Id;
                button.OnPressed += _ => _owner.SelectSector(id);
            }

            SectorButtons.AddChild(button);
        }
    }
}
