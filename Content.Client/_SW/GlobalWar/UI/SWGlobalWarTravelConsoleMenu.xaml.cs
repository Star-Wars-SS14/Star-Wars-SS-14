namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarTravelConsoleMenu : SWGlobalWarWindow
{
    public event Action<ProtoId<SWGlobalWarPlanetPrototype>>? OnTravelPressed;

    private readonly IPrototypeManager _prototypes;
    private readonly Dictionary<RichTextLabel, string> _displayedText = new();
    private SWGlobalWarTravelConsoleState? _state;
    private ProtoId<SWGlobalWarPlanetPrototype>? _selected;
    private string? _destinationsKey;
    private readonly Dictionary<ProtoId<SWGlobalWarPlanetPrototype>, ContainerButton> _destinationRows = new();

    public SWGlobalWarTravelConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        UseChartSize();
        _prototypes = IoCManager.Resolve<IPrototypeManager>();
        StyleInterface();
        Map.PlanetSelected += id =>
        {
            _selected = id;
            UpdatePlanetInfo();
        };
        Travel.OnPressed += _ =>
        {
            if (_selected is not { } selected ||
                _state?.Destinations.Any(entry => entry.Id == selected && entry.Available) != true)
                return;

            Travel.Disabled = true;
            OnTravelPressed?.Invoke(selected);
        };
    }

    /// <summary>The market shows whole rows: a row cut by the panel's edge reads as a broken window.</summary>
    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!MarketInfo.Visible || MarketGoods.ChildCount == 0)
            return;

        var gap = MarketGoods.SeparationOverride ?? 0;
        var row = MarketGoods.GetChild(0).DesiredSize.Y + gap;
        if (row <= gap)
            return;

        var rows = Math.Max(1, MathF.Floor((MarketInfo.Height - MarketTitle.Height - (MarketInfo.SeparationOverride ?? 0) + gap) / row));
        MarketScroll.MaxHeight = rows * row - gap;
    }

    /// <summary>The same choice as the map, for a player who only wants to get somewhere. A row only selects.</summary>
    private void UpdateDestinations(SWGlobalWarTravelConsoleState state)
    {
        var open = state.Destinations.Where(entry => entry.Available && entry.Id != state.CurrentPlanetId).OrderBy(entry => entry.Name).ToList();
        var key = state.CurrentPlanetId + "|" + string.Join('|', open.Select(entry => entry.Id.Id));
        NoDestinations.Visible = open.Count == 0;
        if (key == _destinationsKey)
        {
            MarkSelectedDestination();
            return;
        }

        _destinationsKey = key;
        Destinations.DisposeAllChildren();
        _destinationRows.Clear();
        foreach (var entry in open)
        {
            var row = new ContainerButton { HorizontalExpand = true, ModulateSelfOverride = Color.White, MinHeight = (18 * SWGlobalWarConsoleStyle.ArtScale + 6 * UIScale) / UIScale };
            var body = new BoxContainer { SeparationOverride = 8, Margin = new Thickness(5, 2, 9, 2) };
            var art = SWGlobalWarConsoleStyle.ArtScale / UIScale;
            body.AddChild(new TextureRect
            {
                Texture = SWGlobalWarMapControl.PlanetTexture(entry.Id, "planets_small"),
                TextureScale = new Vector2(art),
                Stretch = TextureRect.StretchMode.KeepCentered,
                VerticalAlignment = VAlignment.Center,
                // The picture has empty space around the planet: it takes 18 of its 28 pixels in the row.
                SetSize = new Vector2(28 * art),
                Margin = new Thickness(-5 * art),
            });
            body.AddChild(new Label { Text = entry.Name, HorizontalExpand = true, ClipText = true, VAlign = Label.VAlignMode.Center, FontColorOverride = SWGlobalWarConsoleStyle.TextBright });
            if (TravelSeconds(state.CurrentPlanetId, entry.Id) is { } seconds)
            {
                body.AddChild(new Label
                {
                    Text = Loc.GetString("sw-global-war-travel-time-short", ("seconds", seconds)),
                    FontOverride = SWGlobalWarConsoleStyle.Small,
                    FontColorOverride = SWGlobalWarConsoleStyle.TextDim,
                    VAlign = Label.VAlignMode.Center,
                });
            }

            row.AddChild(body);
            row.OnPressed += _ => Map.SelectPlanet(entry.Id);
            _destinationRows[entry.Id] = row;
            Destinations.AddChild(row);
        }

        // Up to five rows without a scrollbar, which is what a capital has. The market takes the rest.
        var rowHeight = (18 * SWGlobalWarConsoleStyle.ArtScale + 6 * UIScale) / UIScale + 2;
        DestinationScroll.SetHeight = Math.Min(open.Count, 5) * rowHeight;
        MarkSelectedDestination();
    }

    private void MarkSelectedDestination()
    {
        foreach (var (id, row) in _destinationRows)
        {
            var selected = id == _selected;
            row.StyleBoxOverride = SWTerminalStyle.Box(selected ? Color.FromHex("#1E2836") : Color.FromHex("#121418"),
                selected ? Color.White : SWTerminalStyle.DividerColor, 1);
        }
    }

    /// <summary>A pair's own time when the map has one, or the planet's. Null when neither is set: the default is not news.</summary>
    private int? TravelSeconds(ProtoId<SWGlobalWarPlanetPrototype>? from, ProtoId<SWGlobalWarPlanetPrototype> to)
    {
        if (from is { } origin && _prototypes.TryIndex(origin, out var source) && source.TravelTimes.TryGetValue(to, out var time))
            return (int) time.TotalSeconds;

        return _prototypes.TryIndex(to, out var target) && target.HyperspaceTime is { } seconds ? (int) seconds : null;
    }

    public void UpdateState(SWGlobalWarTravelConsoleState state)
    {
        _state = state;
        // Where the player is reads off the map. This line is only for what the map cannot say, like a jump under way.
        SetText(Status, state.Status);
        Status.Visible = !string.IsNullOrEmpty(state.Status);
        // Update availability without rebuilding the map, preserving selection, zoom and an active drag.
        Map.SetState(state.Destinations, state.CurrentPlanetId);
        PlanetCount.Text = Loc.GetString("sw-global-war-travel-planet-count", ("count", state.Destinations.Count));
        UpdateDestinations(state);
        UpdatePlanetInfo();
    }

    /// <summary>Updates the selected planet's details and server-provided travel availability in place.</summary>
    private void UpdatePlanetInfo()
    {
        var entry = _state?.Destinations.FirstOrDefault(destination => destination.Id == _selected);
        var shown = entry != null && _prototypes.TryIndex(entry.Id, out _);
        foreach (var part in new Control[] { PlanetKind, PlanetName, Availability, HyperspaceTime, Connections })
            part.Visible = shown;
        SelectionHint.Visible = !shown;
        CardPlanet.Visible = shown;
        Travel.Visible = shown;
        MarketInfo.Visible = shown;
        if (!shown)
        {
            _selected = null;
            Travel.Disabled = true;
            MarkSelectedDestination();
            return;
        }

        var planet = _prototypes.Index(entry!.Id);
        Travel.Text = Loc.GetString("sw-global-war-travel-jump-to", ("planet", entry.Name));
        Travel.Disabled = !entry.Available;
        MarkSelectedDestination();
        PlanetCard.ToolTip = string.IsNullOrEmpty(planet.Description) ? null : planet.Description;
        PlanetKind.Text = Loc.GetString("sw-global-war-travel-kind-" + planet.Kind.ToString().ToLowerInvariant());
        PlanetName.Text = entry.Name;
        CardPlanet.Texture = SWGlobalWarMapControl.PlanetTexture(entry.Id, "planets_large");
        CardPlanet.TextureScale = new Vector2(SWGlobalWarConsoleStyle.ArtScale / UIScale);
        // The planet leaves the card by a fifth of its width. The art canvas is wider than the planet.
        var art = SWGlobalWarConsoleStyle.ArtScale / UIScale;
        CardPlanet.Margin = new Thickness(0, 0, -24 * art, 0);
        CardPlanet.SetSize = new Vector2(80 * art);
        Availability.Text = entry.Available ? Loc.GetString("sw-global-war-travel-ready-short") : entry.Reason;
        Availability.ToolTip = entry.Reason;
        Availability.FontColorOverride = entry.Available ? SWGlobalWarConsoleStyle.Good : SWGlobalWarConsoleStyle.Bad;
        HyperspaceTime.Text = TravelSeconds(_state!.CurrentPlanetId, entry.Id) is { } seconds
            ? Loc.GetString("sw-global-war-travel-time-card", ("seconds", seconds))
            : Loc.GetString("sw-global-war-travel-time-card-default");
        var names = string.Join(", ", _state.Destinations.Where(destination => planet.Connections.Contains(destination.Id)).Select(destination => destination.Name));
        SetText(Connections, Loc.GetString("sw-global-war-travel-routes-card", ("planets",
            string.IsNullOrEmpty(names) ? Loc.GetString("sw-global-war-travel-no-connections") : names)));

        MarketGoods.DisposeAllChildren();
        var ready = entry.MarketAvailability == SWGlobalWarMarketAvailability.Ready;
        MarketNote.Visible = !ready;
        if (!ready)
        {
            SetText(MarketNote, SWGlobalWarMarketPresentation.Availability(entry.MarketAvailability));
            return;
        }

        foreach (var good in entry.Market ?? [])
            MarketGoods.AddChild(GoodRow(good));
    }

    private BoxContainer GoodRow(SWGlobalWarMarketGoodView good)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 2, HorizontalExpand = true };
        var words = new BoxContainer { SeparationOverride = 8 };
        words.AddChild(new Label { Text = Loc.GetString(_prototypes.Index(good.Commodity).Name), HorizontalExpand = true, ClipText = true, FontOverride = SWGlobalWarConsoleStyle.Small });
        words.AddChild(new Label { Text = $"{good.Stock:0.###} / {good.TargetStock:0.###}", FontOverride = SWGlobalWarConsoleStyle.Small, FontColorOverride = SWGlobalWarConsoleStyle.TextBright });
        row.AddChild(words);
        row.AddChild(new SWGlobalWarMarketBar
        {
            Value = good.Stock,
            Maximum = Math.Max(1, good.TargetStock),
            Fill = SWGlobalWarMarketPresentation.CommodityColor(good.Commodity),
        });
        return row;
    }

    /// <summary>Applies the terminal panels and button roles to the XAML-defined navigation layout.</summary>
    private void StyleInterface()
    {
        MapPanel.PanelOverride = SWGlobalWarConsoleStyle.CardBox();
        CardSpace.Texture = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>()
            .Frame0(new SpriteSpecifier.Rsi(new ResPath("_SW/Interface/MegaMode/space_card.rsi"), "background"));
        PlanetKind.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        PlanetKind.FontColorOverride = Color.FromHex("#6FB7FF");
        PlanetName.FontOverride = SWGlobalWarConsoleStyle.NameLarge;
        PlanetName.FontColorOverride = Color.White;
        Availability.FontOverride = SWGlobalWarConsoleStyle.Strong;
        HyperspaceTime.FontOverride = SWGlobalWarConsoleStyle.Small;
        HyperspaceTime.FontColorOverride = SWGlobalWarConsoleStyle.TextBright;
        PlanetCount.FontOverride = SWGlobalWarConsoleStyle.Small;
        PlanetCount.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        foreach (var word in new[] { SelectedLegend, AvailableLegend, UnavailableLegend })
            word.FontOverride = SWGlobalWarConsoleStyle.Small;
        SelectedMark.Color = Color.White;
        AvailableMark.Color = SWGlobalWarConsoleStyle.Good;
        UnavailableMark.Color = Color.FromHex("#464A56");
        UnavailableMark.Disc = true;
        Travel.MainFont = SWGlobalWarConsoleStyle.MainButton;
        Travel.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        PlanetCard.SetHeight = SetSize.Y * .235f;
        // The mock's column runs almost to the frame, which gives the market its fourth row.
        var margin = ContentsContainer.Margin;
        ContentsContainer.Margin = new Thickness(margin.Left, margin.Top, margin.Right, 4);
    }

    private void SetText(RichTextLabel label, string text)
    {
        if (_displayedText.TryGetValue(label, out var previous) && previous == text)
            return;

        _displayedText[label] = text;
        label.SetMessage(text);
    }
}
