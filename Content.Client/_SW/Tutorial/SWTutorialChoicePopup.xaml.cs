using Content.Shared._SW.Tutorial;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.Tutorial;

[GenerateTypedNameReferences]
public sealed partial class SWTutorialChoicePopup : Control
{
    /// <summary>
    /// The player's answer. Null means going back to the lobby without an answer.
    /// </summary>
    public event Action<SWTutorialChoice?>? OnChoice;

    /// <param name="isOffer">
    /// True when the server offers the tutorial on entry, where the last answer is final.
    /// False when the player opened this from the lobby button, where it only goes back.
    /// </param>
    /// <param name="newToServerReady">
    /// The second mode depends on the visible score and has no scenario yet. Until it does, the button says so and
    /// does nothing, because the first mode would not be what its text promises.
    /// </param>
    public SWTutorialChoicePopup(bool isOffer, bool newToServerReady)
    {
        RobustXamlLoader.Load(this);

        SkipButton.Text = Loc.GetString(isOffer ? "sw-tutorial-choice-skip" : "sw-tutorial-choice-back");
        NewToServerButton.Disabled = !newToServerReady;
        NewToServerButton.Text = Loc.GetString(newToServerReady
            ? "sw-tutorial-choice-new-to-server"
            : "sw-tutorial-choice-new-to-server-soon");

        NewToGameButton.OnPressed += _ => OnChoice?.Invoke(SWTutorialChoice.NewToGame);
        NewToServerButton.OnPressed += _ => OnChoice?.Invoke(SWTutorialChoice.NewToServer);
        SkipButton.OnPressed += _ => OnChoice?.Invoke(isOffer ? SWTutorialChoice.Skip : null);
    }
}
