using Content.Shared._SW.Droids;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.Droids.UI;

[GenerateTypedNameReferences]
public sealed partial class SWDroidControlConsoleDatapadControl : PanelContainer
{
    public event Action<NetEntity>? OnTogglePressed;

    private readonly NetEntity _datapadUid;

    public SWDroidControlConsoleDatapadControl(SWDroidControlConsoleDatapadEntry datapad)
    {
        RobustXamlLoader.Load(this);

        _datapadUid = datapad.DatapadUid;
        Heading.Text = Loc.GetString("sw-droid-control-console-datapad-heading",
            ("id", datapad.ControlId),
            ("name", datapad.Name));
        Details.Text = Loc.GetString("sw-droid-control-console-datapad-details",
            ("status", datapad.Status),
            ("count", datapad.LinkedDroids));
        ToggleButton.Text = Loc.GetString(datapad.Enabled
            ? "sw-droid-control-console-disable"
            : "sw-droid-control-console-enable");
        ToggleButton.OnPressed += _ => OnTogglePressed?.Invoke(_datapadUid);
    }
}
