    private static string GetDateText(SWBattlePassSeasonPrototype season, SWBattlePassState state)
    {
        var ru = CultureInfo.GetCultureInfo("ru-RU");
        var end = (season.EndUtc.AddDays(-1) + SWBattlePassRules.MoscowOffset).ToString("d MMMM", ru);
        if (!state.Started)
        {
            var start = (season.StartUtc + SWBattlePassRules.MoscowOffset).ToString("d MMMM", ru);
            return Loc.GetString("sw-battlepass-starts", ("date", start));
        }

        return Loc.GetString(state.Ended ? "sw-battlepass-ended" : "sw-battlepass-until", ("date", end));
    }

    /// <summary>
    /// What the bar cannot say. The usual way to the next tier needs no words: the number is on the bar.
    /// </summary>
    private static string? GetNotice(SWBattlePassSeasonPrototype season, SWBattlePassState state, int tier)
    {
        if (!state.XpOpen)
            return Loc.GetString("sw-battlepass-next-closed");

        return tier >= season.Tiers.Count
            ? Loc.GetString("sw-battlepass-next-overtime", ("xp", season.XpPerTier))
            : null;
    }

    private static int CountClaimable(SWBattlePassSeasonPrototype season, SWBattlePassState state)
    {
        var count = state.ClaimsOpen ? SWBattlePassRules.CountClaimable(season, state.Xp, state.Paid, state.Claimed) : 0;
        return count + Math.Max(0, SWBattlePassRules.OvertimeEarned(season, state.Xp) - state.OvertimeClaimed);
    }

    private void UpdateMainButton(SWBattlePassSeasonPrototype season, SWBattlePassState state)
    {
        // Leaving is the cross and Esc. The loudest button of the window only ever means there is something to take.
        var claimable = CountClaimable(season, state);
        MainButton.Visible = claimable > 0 || _controller.InLobby;
        MainButton.SetOnlyStyleClass(claimable > 0 ? SWTerminalStyle.ClaimButton : SWTerminalStyle.Button);
        MainButton.Text = claimable > 0
            ? Loc.GetString("sw-battlepass-claim-all", ("count", claimable))
            : Loc.GetString("sw-battlepass-go-fight");
    }

    private void OnMainPressed()
    {
        if (_state == null || _season == null)
            return;

        if (CountClaimable(_season, _state) == 0)
        {
            Close();
            return;
        }

        if (_state.ClaimsOpen && SWBattlePassRules.CountClaimable(_season, _state.Xp, _state.Paid, _state.Claimed) > 0)
            _controller.ClaimAll();
        else if (SWBattlePassRules.OvertimeEarned(_season, _state.Xp) > _state.OvertimeClaimed)
            _controller.ClaimOvertime();
    }

    private void BuildTrack(SWBattlePassSeasonPrototype season, SWBattlePassState state, int tier)
    {
        Ruler.RemoveAllChildren();
        FreeRow.RemoveAllChildren();
        PaidRow.RemoveAllChildren();

        var next = tier + 1;

        for (var i = 1; i <= season.Tiers.Count; i++)
        {
            Ruler.AddChild(new Label
            {
                Text = i.ToString(),
                Align = Label.AlignMode.Center,
                MinWidth = SWBattlePassCell.CellWidth,
                StyleClasses = { i == next ? SWTerminalStyle.Value : SWTerminalStyle.Text },
            });
            FreeRow.AddChild(BuildCell(season, state, i, SWBattlePassTrack.Free, next));
            PaidRow.AddChild(BuildCell(season, state, i, SWBattlePassTrack.Paid, next));
        }

        var total = (float) SWBattlePassRules.XpForTier(season, season.Tiers.Count);
        RulerBar.Value = Math.Min(1f, state.Xp / total);

        // Two rewards behind, everything else ahead.
        if (_scrollPending)
            _scrollWanted = Math.Max(0, next - 3) * CellStep;

        _scrollPending = false;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // The scroll bar only knows its range after a layout pass.
        if (_scrollWanted is { } wanted && TrackScroll.Size.X > 0)
        {
            TrackScroll.SetScrollValue(new Vector2(wanted, 0));
            _scrollWanted = null;
        }

        if (_preview != null && _controller.Timing.RealTime > _previewTurnAt)
        {
            _previewDirection = _previewDirection switch
            {
                Direction.South => Direction.East,
                Direction.East => Direction.North,
                Direction.North => Direction.West,
                _ => Direction.South,
            };

            // The front shows the item best, so it stays longest.
            _previewTurnAt = _controller.Timing.RealTime + (_previewDirection == Direction.South ? PreviewFront : PreviewTurn);
            BigPreview.OverrideDirection = _previewDirection;
        }

        if (_statusUntil is { } until && _controller.Timing.RealTime > until)
        {
            _statusUntil = null;
            StatusLabel.Text = string.Empty;
            StatusLabel.ToolTip = null;
        }

        UpdateCaseMotion(args.DeltaSeconds);
    }

    private Control BuildCell(SWBattlePassSeasonPrototype season, SWBattlePassState state, int tier, SWBattlePassTrack track, int next)
    {
        var reward = SWBattlePassRules.GetReward(season, tier, track);
        var claimed = state.Claimed.Contains(SWBattlePassRules.RewardKey(tier, track));
        var canClaim = state.ClaimsOpen && SWBattlePassRules.CanClaim(season, state.Xp, state.Paid, state.Claimed, tier, track);
        var locked = track == SWBattlePassTrack.Paid && !state.Paid;

        var cellState = reward == null ? SWBattlePassCellState.Empty
            : claimed ? SWBattlePassCellState.Claimed
            : canClaim ? SWBattlePassCellState.Claimable
            : tier == next && !locked ? SWBattlePassCellState.Next
            : SWBattlePassCellState.Future;

        var weight = reward == null ? SWBattlePassCellWeight.Minor
            : track == SWBattlePassTrack.Paid && tier % MilestoneEvery == 0 ? SWBattlePassCellWeight.PaidMilestone
            : track == SWBattlePassTrack.Paid ? SWBattlePassCellWeight.Paid
            : reward.Cosmetic != null && tier % MilestoneEvery == 0 ? SWBattlePassCellWeight.Milestone
            : reward.Snowflakes > 0 ? SWBattlePassCellWeight.Minor
            : SWBattlePassCellWeight.Item;

        var cell = new SWBattlePassCell();
        cell.Set(reward == null ? null : RewardIcon(reward),
            reward == null ? string.Empty : RewardName(reward),
            reward == null ? 0 : reward.Snowflakes,
            cellState,
            weight,
            RewardEntity(reward));

        if (reward != null)
        {
            cell.OnPressed += _ =>
            {
                if (canClaim)
                {
                    _controller.Claim(tier, track);
                    return;
                }

                _inspected = _inspected == (tier, track) ? null : (tier, track);
                if (_state != null && _season != null)
                    UpdateGoal(_season, _state, SWBattlePassRules.TierOf(_season, _state.Xp));
            };
        }

        return cell;
    }

    private static Color RarityColor(SWCosmeticRarity rarity)
    {
        return rarity switch
        {
            SWCosmeticRarity.Legendary => LegendaryColor,
            SWCosmeticRarity.Rare => RareColor,
            _ => CommonColor,
        };
    }

    /// <summary>
    /// The entity shown for a cosmetic. Everything else has a plain icon.
    /// </summary>
    private string? RewardEntity(SWBattlePassReward? reward)
    {
        return reward?.Cosmetic != null ? LoadoutEntity(_controller.ItemsForCharacter(reward)[0]) : null;
    }

    private string? LoadoutEntity(ProtoId<LoadoutPrototype> id)
    {
        if (!_proto.TryIndex(id, out var loadout))
            return null;

        // A costume makes no item of its own, and its dummy stands for it in lists.
        return loadout.Equipment.Count > 0 ? loadout.Equipment.Values.First().Id : loadout.DummyEntity?.Id;
    }

    private Texture? RewardIcon(SWBattlePassReward reward)
    {
        if (reward.Cosmetic != null)
            return null;

        if (reward.Case is { } caseId)
            return _sprite.Frame0(_proto.Index(caseId).Icon);

        return _sprite.Frame0(reward.Title != null ? TitleIcon : SnowflakeIcon);
    }

    private string RewardName(SWBattlePassReward reward)
    {
        if (reward.Cosmetic != null)
            return LoadoutName(_controller.ItemsForCharacter(reward)[0]);

        if (reward.Case is { } caseId)
            return Loc.GetString(_proto.Index(caseId).Name);

        if (reward.Title is { } title)
            return Loc.GetString("sw-battlepass-reward-title", ("name", Loc.GetString(title)));

        return Loc.GetString("sw-battlepass-reward-snowflakes", ("count", reward.Snowflakes));
    }

    private string LoadoutName(ProtoId<LoadoutPrototype> id)
    {
        var entity = LoadoutEntity(id);
        return entity != null && _proto.TryIndex<EntityPrototype>(entity, out var proto) ? proto.Name : id.Id;
    }

    /// <summary>
    /// The left column: what the player is working towards, or the cell they clicked on.
    /// </summary>
    private void UpdateGoal(SWBattlePassSeasonPrototype season, SWBattlePassState state, int tier)
    {
        SWBattlePassReward? reward = null;
        var goalTier = 0;

        if (_inspected is var (inspectTier, inspectTrack))
        {
            reward = SWBattlePassRules.GetReward(season, inspectTier, inspectTrack);
            goalTier = inspectTier;
            GoalCaption.Text = Loc.GetString(inspectTrack == SWBattlePassTrack.Paid
                ? "sw-battlepass-inspect-paid"
                : "sw-battlepass-inspect-free",
                ("tier", inspectTier));
        }
        else
        {
            for (var i = tier + 1; i <= season.Tiers.Count && reward == null; i++)
            {
                var free = season.Tiers[i - 1].Free;
                var paid = season.Tiers[i - 1].Paid;
                reward = free?.Cosmetic != null ? free : state.Paid && paid?.Cosmetic != null ? paid : null;
                goalTier = i;
            }
        }

        if (_inspected == null && reward != null)
            GoalCaption.Text = Loc.GetString("sw-battlepass-next-big", ("tier", goalTier));

        if (reward == null)
        {
            GoalCaption.Text = string.Empty;
            BigName.Text = Loc.GetString("sw-battlepass-big-none");
            BigLeft.Text = string.Empty;
            DeletePreview();
            BigPreview.Visible = false;
            BigIcon.Visible = false;
            return;
        }

        var bigName = RewardName(reward);
        BigName.Text = Capitalized(bigName);
        BigLeft.Text = goalTier > tier
            ? Loc.GetString("sw-battlepass-big-left", ("left", goalTier - tier))
            : Loc.GetString("sw-battlepass-big-tier");

        if (reward.Cosmetic != null)
        {
            BigPreview.Visible = true;
            BigIcon.Visible = false;
            ShowPreview(_controller.ItemsForCharacter(reward));
        }
        else
        {
            DeletePreview();
            BigPreview.Visible = false;
            BigIcon.Visible = true;
            BigIcon.Texture = RewardIcon(reward);
        }
    }

    /// <summary>
    /// Puts the player's own character on show wearing the item, turning slowly.
    /// </summary>
    private void ShowPreview(List<ProtoId<LoadoutPrototype>> items)
    {
        var key = string.Join(",", items);
        if (_previewLoadout == key && _preview != null)
            return;

        DeletePreview();
        _preview = _controller.SpawnPreview(items);
        _previewLoadout = key;
        if (_preview != null)
            BigPreview.SetEntity(_preview);
    }

    private void DeletePreview()
    {
        if (_preview != null)
            _entMan.DeleteEntity(_preview);

        _preview = null;
        _previewLoadout = null;
        BigPreview.SetEntity(null);
    }

