using System.Numerics;
using Content.Client._SW.UserInterface;
using Content.Shared._SW.GlobalWar;
using Content.Shared._SW.GlobalWar.Politics;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._SW.GlobalWar.UI;

/// <summary>States who won, why the campaign ended and what the map looked like at that moment.</summary>
[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarRoundEndWindow : SWGlobalWarWindow
{
    private const float LargeRootHeight = 1000;
    private const float SceneSeconds = .3f;
    private const float CellSeconds = .03f;
    private const float TicksSeconds = .3f;
    private const float StampSeconds = .15f;
    private static readonly Vector2 BannerCenter = new(.058f, .66f);

    private readonly List<PanelContainer> _cells = new();
    private float _reveal;
    private bool _revealed;

    public SWGlobalWarRoundEndWindow(SWGlobalWarRoundEndEvent result)
    {
        RobustXamlLoader.Load(this);
        HideHeader();
        Close.OnPressed += _ => base.Close();
        Cross.OnPressed += _ => base.Close();
        var summary = IoCManager.Resolve<IUserInterfaceManager>().GetUIController<Content.Client.RoundEnd.RoundEndSummaryUIController>();
        summary.SWHideWindow();
        Summary.OnPressed += _ => summary.SWShowWindow();

        // The mock's two sizes: a full window on a big screen and three quarters of it on a small one.
        var big = IoCManager.Resolve<IUserInterfaceManager>().WindowRoot.Size.Y >= LargeRootHeight;
        var window = big ? new Vector2(1240, 720) : new Vector2(950, 541);
        var scale = window.X / 1240;
        SetSize = window;
        Hero.SetHeight = window.Y * .55f;
        ScoreBand.SetHeight = window.Y * .22f;
        HeroWords.Margin = new Thickness(368 * scale, 28 * scale, 0, 0);

        var key = result.Outcome switch
        {
            SWGlobalWarOutcome.RepublicVictory => "republic",
            SWGlobalWarOutcome.EmpireVictory => "empire",
            SWGlobalWarOutcome.MutualSurrender => "mutual",
            SWGlobalWarOutcome.TimeLimit => "time",
            SWGlobalWarOutcome.InsufficientParticipants => "participants",
            _ => "stopped",
        };
        Verdict.Text = Loc.GetString($"sw-global-war-round-end-verdict-{key}").ToUpperInvariant();
        // Wraps before the planet, so the whole reason is read at any window size.
        Reason.MaxWidth = big ? 570 : 520;
        var reason = result.LimitRepublic is { } limitRepublic && result.LimitEmpire is { } limitEmpire
            ? Loc.GetString("sw-global-war-round-end-reason-limit", ("republic", limitRepublic), ("empire", limitEmpire))
            : Loc.GetString($"sw-global-war-round-end-reason-{key}");
        Reason.SetMessage(FormattedMessage.FromUnformatted(reason), defaultColor: Color.White);

        var winner = result.Outcome switch
        {
            SWGlobalWarOutcome.RepublicVictory => SWGlobalWarFaction.Republic,
            SWGlobalWarOutcome.EmpireVictory => SWGlobalWarFaction.Empire,
            _ => SWGlobalWarFaction.Neutral,
        };
        var lost = result.Side != SWGlobalWarFaction.Neutral && winner != SWGlobalWarFaction.Neutral && result.Side != winner;

        // A defeat shows the player's own side, dimmed and drained of colour.
        var scene = lost ? result.Side : winner;
        var player = result.Side == SWGlobalWarFaction.Republic ? "r" : "e";
        var winnerState = winner switch
        {
            SWGlobalWarFaction.Republic => "r",
            SWGlobalWarFaction.Empire => "e",
            _ => "n",
        };
        // The small window has its own bake: the mock's smaller planet and whole pixels at 1280x720.
        var art = big ? "verdict_hero" : "verdict_hero_small";
        HeroScene.Texture = SWGlobalWarConsoleStyle.Art(art, lost ? "bg_lost_" + player : "bg_" + winnerState);
        HeroTroops.Texture = SWGlobalWarConsoleStyle.Art(art, "troops_" + (lost ? player : winnerState));

        // Only a victory gets the rays. The player who lost stands in the ashes without them.
        HeroRays.Effect = lost ? null : winner switch
        {
            SWGlobalWarFaction.Republic => SWGlobalWarFx.SunburstRepublic,
            SWGlobalWarFaction.Empire => SWGlobalWarFx.SunburstEmpire,
            _ => null,
        };
        HeroRays.Center = BannerCenter;
        HeroRays.ArtScale = big ? 3 : 2;

        HeroLine.PanelOverride = SWTerminalStyle.Fill(scene == SWGlobalWarFaction.Neutral ? SWTerminalStyle.DividerColor : SWGlobalWarConsoleStyle.SideText(scene));

        Heading.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        Heading.FontColorOverride = SWGlobalWarConsoleStyle.SideText(scene);
        Verdict.FontOverride = SWGlobalWarConsoleStyle.Bold(big ? 36 : 30);
        Verdict.FontColorOverride = Color.White;

        var personal = PersonalKey(result);
        Personal.Text = Loc.GetString("sw-global-war-round-end-stamp-" + personal[(personal.LastIndexOf('-') + 1)..]);
        StampPlate.ToolTip = Loc.GetString(personal);
        Personal.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        Personal.FontColorOverride = Color.White;
        StampPlate.Visible = result.Side != SWGlobalWarFaction.Neutral;
        // A lost war is red on either side.
        var (fill, _, border) = SWTerminalStyle.AccentFills(lost ? "Empire" : winner switch
        {
            SWGlobalWarFaction.Republic => "Republic",
            SWGlobalWarFaction.Empire => "Empire",
            _ => SWTerminalStyle.NeutralAccent,
        });
        StampPlate.PanelOverride = SWTerminalStyle.Box(fill, border, 1);

        ScoreBand.PanelOverride = SWTerminalStyle.Fill(Color.FromHex("#101216"));
        RepublicIcon.Texture = SWGlobalWarConsoleStyle.SideIcon(SWGlobalWarFaction.Republic);
        EmpireIcon.Texture = SWGlobalWarConsoleStyle.SideIcon(SWGlobalWarFaction.Empire);
        RepublicIcon.TextureScale = EmpireIcon.TextureScale = new Vector2(big ? 6 : 4);
        RepublicCount.Text = result.RepublicWorlds.ToString();
        EmpireCount.Text = result.EmpireWorlds.ToString();
        RepublicCount.FontOverride = EmpireCount.FontOverride = SWGlobalWarConsoleStyle.Bold(46);
        RepublicCount.FontColorOverride = SWGlobalWarConsoleStyle.RepublicText;
        EmpireCount.FontColorOverride = SWGlobalWarConsoleStyle.EmpireText;
        RepublicWord.FontOverride = EmpireWord.FontOverride = OtherCount.FontOverride = SWGlobalWarConsoleStyle.Small;
        OtherCount.Text = Loc.GetString("sw-global-war-round-end-stat-other-count", ("count", result.OtherWorlds));

        // One cell per world, in the order of the score.
        for (var i = 0; i < result.RepublicWorlds + result.OtherWorlds + result.EmpireWorlds; i++)
        {
            var side = i < result.RepublicWorlds ? "Republic" : i < result.RepublicWorlds + result.OtherWorlds ? SWTerminalStyle.NeutralAccent : "Empire";
            var (cellFill, _, cellBorder) = SWTerminalStyle.AccentFills(side);
            var cell = new PanelContainer
            {
                HorizontalExpand = true,
                MinHeight = 32,
                PanelOverride = SWTerminalStyle.Box(cellFill, cellBorder, 1),
            };
            _cells.Add(cell);
            ScoreCells.AddChild(cell);
        }

        Details.Text = Loc.GetString("sw-global-war-round-end-changes", ("changes", result.OwnershipChanges));
        Details.FontOverride = SWGlobalWarConsoleStyle.Small;
        TimelineTitle.FontOverride = SWGlobalWarConsoleStyle.Strong;
        TimelineTitle.FontColorOverride = Color.White;
        Timeline.Duration = result.Duration;
        Timeline.Ticks = result.Timeline;
        TimelineEnd.Text = Loc.GetString("sw-global-war-round-end-minutes", ("minutes", (int) result.Duration.TotalMinutes));
        ApplyReveal(IoCManager.Resolve<IConfigurationManager>().GetCVar(CCVars.ReducedMotion) ? float.MaxValue : 0);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_revealed)
            return;
        _reveal += args.DeltaSeconds;
        ApplyReveal(_reveal);
    }

    /// <summary>The scene fades in, the cells light one by one, then the ticks, then the stamp.</summary>
    private void ApplyReveal(float time)
    {
        var scene = Color.White.WithAlpha(Math.Clamp(time / SceneSeconds, 0, 1));
        HeroScene.Modulate = HeroTroops.Modulate = scene;
        for (var i = 0; i < _cells.Count; i++)
            _cells[i].Modulate = Color.White.WithAlpha(time >= SceneSeconds + i * CellSeconds ? 1 : 0);

        var cellsEnd = SceneSeconds + _cells.Count * CellSeconds;
        Timeline.Reveal = Math.Clamp((time - cellsEnd) / TicksSeconds, 0, 1);
        var stamp = Math.Clamp((time - cellsEnd - TicksSeconds) / StampSeconds, 0, 1);
        StampPlate.Modulate = Color.White.WithAlpha(stamp);
        _revealed = stamp >= 1;
    }

    private static string PersonalKey(SWGlobalWarRoundEndEvent result)
    {
        var side = result.Side == SWGlobalWarFaction.Republic ? "republic" : "empire";
        var won = result.Outcome == SWGlobalWarOutcome.RepublicVictory && result.Side == SWGlobalWarFaction.Republic ||
                  result.Outcome == SWGlobalWarOutcome.EmpireVictory && result.Side == SWGlobalWarFaction.Empire;
        var lost = result.Outcome == SWGlobalWarOutcome.RepublicVictory && result.Side == SWGlobalWarFaction.Empire ||
                   result.Outcome == SWGlobalWarOutcome.EmpireVictory && result.Side == SWGlobalWarFaction.Republic;
        var verdict = won ? "won" : lost ? "lost" : "open";
        return $"sw-global-war-round-end-personal-{side}-{verdict}";
    }
}
