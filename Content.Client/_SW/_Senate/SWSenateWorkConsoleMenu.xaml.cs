[GenerateTypedNameReferences]
public sealed partial class SWSenateWorkConsoleMenu : FancyWindow
{
    private const float MaxEffect = 10f;

    private readonly SWSenateWorkConsoleBoundUserInterface _owner;
    private (Button Nav, Control Panel)[] _sections = System.Array.Empty<(Button, Control)>();
    private readonly Dictionary<string, Slider> _draftSliders = new();
    private readonly Dictionary<string, Label> _draftValueLabels = new();
    private readonly HashSet<int> _expandedDilemmas = new();
    private bool _draftBuilt;
    private int _draftBudget;

    private int _selectedBillId = -1;
    private int _selectedStartHour = -1;
    private int _selectedDuration = 1;

    public SWSenateWorkConsoleMenu(SWSenateWorkConsoleBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        _owner = owner;

        _sections = new (Button, Control)[]
        {
            (NavOffice, OfficeTab),
            (NavRoster, RosterScroll),
            (NavSummary, DashScroll),
            (NavDraft, DraftTab),
            (NavAgenda, AgendaScroll),
            (NavSchedule, ScheduleTab),
            (NavDilemmas, DilemmaTab),
            (NavAnnounce, AnnounceTab),
        };
        foreach (var (nav, panel) in _sections)
        {
            var target = panel;
            nav.OnPressed += _ => ShowSection(target);
        }

        DraftModeCustom.OnPressed += _ => ShowDraftMode(true);
        DraftModePreset.OnPressed += _ => ShowDraftMode(false);

        DilemmaModeActive.OnPressed += _ => ShowDilemmaMode(0);
        DilemmaModeBudget.OnPressed += _ => ShowDilemmaMode(1);
        DilemmaModeSummary.OnPressed += _ => ShowDilemmaMode(2);

        ShowSection(OfficeTab);
        ShowDraftMode(true);
        ShowDilemmaMode(0);

        AnnounceButton.OnPressed += _ =>
        {
            if (!string.IsNullOrWhiteSpace(AnnounceEdit.Text))
            {
                _owner.Announce(AnnounceEdit.Text);
                AnnounceEdit.Text = string.Empty;
            }
        };

        TakeButton.OnPressed += _ => _owner.TakeOffice();
        ResignButton.OnPressed += _ => _owner.Resign();
        SubmitBillButton.OnPressed += _ => OnSubmitPressed();

        for (var d = 1; d <= 4; d++)
            DurationOption.AddItem($"{d}ч", d);
        DurationOption.SelectId(_selectedDuration);

        BillOption.OnItemSelected += args =>
        {
            BillOption.SelectId(args.Id);
            _selectedBillId = args.Id;
        };
        StartHourOption.OnItemSelected += args =>
        {
            StartHourOption.SelectId(args.Id);
            _selectedStartHour = args.Id;
        };
        DurationOption.OnItemSelected += args =>
        {
            DurationOption.SelectId(args.Id);
            _selectedDuration = args.Id;
        };
        ScheduleButton.OnPressed += _ =>
        {
            if (_selectedBillId >= 0 && _selectedStartHour >= 0)
                _owner.ScheduleSession(_selectedBillId, _selectedStartHour, _selectedDuration);
        };
    }

    public void SetState(SWSenateWorkConsoleState state)
    {
        Title = string.IsNullOrEmpty(state.GameTime)
            ? "Сенатская рабочая консоль"
            : $"Сенатская рабочая консоль — {state.GameTime}";

        if (!state.HasCard)
            PositionLabel.SetMessage("Вставьте ID-карту в консоль.");
        else if (!state.IsSenateCard)
            PositionLabel.SetMessage("Это не сенатская карта.");
        else
            PositionLabel.SetMessage(state.PositionLabel);

        StatusLabel.SetMessage(state.InOffice ? "Статус: в должности" : "Статус: не в должности");

        TakeButton.Visible = state.CanTake;
        ResignButton.Visible = state.CanResign;

        var isSenator = state.IsSenateCard && state.Position == SWSenatePosition.Senator;
        var isLeader = state.IsSenateCard
            && (state.Position == SWSenatePosition.Speaker || state.Position == SWSenatePosition.Chancellor);
        NavDraft.Visible = isSenator && state.InOffice;
        NavAgenda.Visible = state.IsSenateCard && state.InOffice;
        NavSchedule.Visible = state.IsSenateCard && state.InOffice;
        NavDilemmas.Visible = state.CanDilemmas && state.InOffice;
        NavAnnounce.Visible = isLeader && state.InOffice;

        foreach (var (nav, panel) in _sections)
        {
            if (panel.Visible && !nav.Visible)
            {
                ShowSection(OfficeTab);
                break;
            }
        }

        if (!_draftBuilt && state.Globals.Count > 0)
            BuildDraft(state);

        BuildRoster(state);
        BuildDashboard(state);
        BuildAgenda(state);
        BuildSchedule(state);
        BuildPresets(state);
        BuildDilemmas(state);
    }

    private void ShowDilemmaMode(int mode)
    {
        DilemmaActivePanel.Visible = mode == 0;
        DilemmaBudgetPanel.Visible = mode == 1;
        DilemmaSummaryPanel.Visible = mode == 2;
        DilemmaModeActive.Disabled = mode == 0;
        DilemmaModeBudget.Disabled = mode == 1;
        DilemmaModeSummary.Disabled = mode == 2;
    }

    private void BuildDilemmas(SWSenateWorkConsoleState state)
    {
        DilemmaActiveList.RemoveAllChildren();
        if (state.MyDilemmas.Count == 0)
        {
            DilemmaActiveList.AddChild(new Label { Text = "Активных дилемм нет.", FontColorOverride = Color.Gray });
        }
        else
        {
            foreach (var dilemma in state.MyDilemmas)
                DilemmaActiveList.AddChild(MakeDilemmaCard(dilemma));
        }

        DilemmaSummaryList.RemoveAllChildren();
        if (state.AllDilemmas.Count == 0)
        {
            DilemmaSummaryList.AddChild(new Label { Text = "Дилемм пока нет.", FontColorOverride = Color.Gray });
            return;
        }

        foreach (var dilemma in state.AllDilemmas)
            DilemmaSummaryList.AddChild(MakeSummaryEntry(dilemma));
    }

    private Control MakeDilemmaCard(SWDilemmaEntry dilemma)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(0, 2, 0, 10),
        };

        var head = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        head.AddChild(new Label { Text = dilemma.Name, StyleClasses = { "LabelKeyText" }, HorizontalExpand = true });
        head.AddChild(new Label { Text = dilemma.TimeLabel, FontColorOverride = Color.Goldenrod });
        box.AddChild(head);

        if (!string.IsNullOrWhiteSpace(dilemma.Description))
        {
            var desc = new RichTextLabel { Margin = new Thickness(0, 2, 0, 4) };
            desc.SetMessage(dilemma.Description);
            box.AddChild(desc);
        }

        for (var i = 0; i < dilemma.Options.Count; i++)
        {
            var option = dilemma.Options[i];
            var optionBox = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 1, 0, 4) };

            var optionRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            var index = i;
            var id = dilemma.Id;
            var button = new Button
            {
                Text = option.Label,
                Disabled = !dilemma.CanResolve,
                HorizontalExpand = true,
                HorizontalAlignment = Control.HAlignment.Left,
            };
            if (dilemma.ChosenOption == i)
                button.Text = $"{option.Label} (выбрано)";
            button.OnPressed += _ => _owner.ResolveDilemma(id, index);
            optionRow.AddChild(button);
            optionBox.AddChild(optionRow);

            var effects = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(8, 0, 0, 0) };
            foreach (var effect in option.Effects)
            {
                effects.AddChild(new Label
                {
                    Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                    FontColorOverride = effect.Color,
                    Margin = new Thickness(0, 0, 10, 0),
                });
            }
            optionBox.AddChild(effects);

            box.AddChild(optionBox);
        }

        if (dilemma.ChosenOption < 0 && (dilemma.FailEffects.Count > 0 || !string.IsNullOrWhiteSpace(dilemma.FailText)))
        {
            box.AddChild(new Label
            {
                Text = "Срочно! При отсутствии решения наступит провал:",
                FontColorOverride = Color.IndianRed,
                Margin = new Thickness(0, 4, 0, 0),
            });
            if (!string.IsNullOrWhiteSpace(dilemma.FailText))
                box.AddChild(new Label { Text = dilemma.FailText, FontColorOverride = Color.IndianRed, Margin = new Thickness(8, 0, 0, 0) });
            if (dilemma.FailEffects.Count > 0)
                box.AddChild(MakeEffectsRow(dilemma.FailEffects));
        }

        return box;
    }

    private static Control MakeEffectsRow(List<SWBillEffectEntry> effects)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(8, 0, 0, 0) };
        foreach (var effect in effects)
        {
            row.AddChild(new Label
            {
                Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                FontColorOverride = effect.Color,
                Margin = new Thickness(0, 0, 10, 0),
            });
        }

        return row;
    }

    private Control MakeSummaryEntry(SWDilemmaEntry dilemma)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 1, 0, 2) };

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        header.AddChild(new Label
        {
            Text = $"{dilemma.OwnerLabel}: {dilemma.Name}",
            FontColorOverride = dilemma.IsRepublic ? Color.Gold : Color.White,
            HorizontalExpand = true,
        });
        header.AddChild(new Label { Text = dilemma.Status, FontColorOverride = Color.Gray, Margin = new Thickness(0, 0, 8, 0) });

        var expanded = _expandedDilemmas.Contains(dilemma.Id);
        var details = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(12, 2, 0, 6), Visible = expanded };

        var id = dilemma.Id;
        var toggle = new Button { Text = expanded ? "Скрыть" : "Подробнее" };
        toggle.OnPressed += _ =>
        {
            if (!_expandedDilemmas.Add(id))
                _expandedDilemmas.Remove(id);
            var now = _expandedDilemmas.Contains(id);
            details.Visible = now;
            toggle.Text = now ? "Скрыть" : "Подробнее";
        };
        header.AddChild(toggle);
        box.AddChild(header);

        if (!string.IsNullOrWhiteSpace(dilemma.Description))
        {
            var desc = new RichTextLabel { Margin = new Thickness(0, 0, 0, 4) };
            desc.SetMessage(dilemma.Description);
            details.AddChild(desc);
        }

        for (var i = 0; i < dilemma.Options.Count; i++)
        {
            var option = dilemma.Options[i];
            details.AddChild(new Label
            {
                Text = dilemma.ChosenOption == i ? $"{option.Label} (выбрано)" : option.Label,
                FontColorOverride = dilemma.ChosenOption == i ? Color.LightGreen : Color.LightGray,
                Margin = new Thickness(0, 1, 0, 0),
            });
            details.AddChild(MakeEffectsRow(option.Effects));
        }

        if (dilemma.FailEffects.Count > 0 || !string.IsNullOrWhiteSpace(dilemma.FailText))
        {
            var failHeader = string.IsNullOrWhiteSpace(dilemma.FailText) ? "При провале:" : $"При провале: {dilemma.FailText}";
            details.AddChild(new Label { Text = failHeader, FontColorOverride = Color.IndianRed, Margin = new Thickness(0, 2, 0, 0) });
            if (dilemma.FailEffects.Count > 0)
                details.AddChild(MakeEffectsRow(dilemma.FailEffects));
        }

        box.AddChild(details);
        return box;
    }

    private void ShowSection(Control target)
    {
        foreach (var (nav, panel) in _sections)
        {
            panel.Visible = panel == target;
            nav.Disabled = panel == target;
        }
    }

    private void ShowDraftMode(bool custom)
    {
        CustomDraftPanel.Visible = custom;
        PresetPanel.Visible = !custom;
        DraftModeCustom.Disabled = custom;
        DraftModePreset.Disabled = !custom;
    }

    private void BuildPresets(SWSenateWorkConsoleState state)
    {
        PresetsList.RemoveAllChildren();
        if (state.Presets.Count == 0)
        {
            PresetsList.AddChild(new Label { Text = "Шаблонов нет." });
            return;
        }

        foreach (var preset in state.Presets)
        {
            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(0, 2, 0, 8),
            };

            box.AddChild(new Label { Text = preset.Name, StyleClasses = { "LabelKeyText" } });

            if (!string.IsNullOrWhiteSpace(preset.Description))
            {
                var desc = new RichTextLabel { Margin = new Thickness(0, 1, 0, 2) };
                desc.SetMessage(preset.Description);
                box.AddChild(desc);
            }

            var effectsRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            foreach (var effect in preset.Effects)
            {
                effectsRow.AddChild(new Label
                {
                    Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                    FontColorOverride = effect.Color,
                    Margin = new Thickness(0, 0, 10, 0),
                });
            }
            box.AddChild(effectsRow);

            var id = preset.Id;
            var submit = new Button { Text = "Внести", Margin = new Thickness(0, 2, 0, 0), HorizontalAlignment = Control.HAlignment.Left };
            submit.OnPressed += _ => _owner.SubmitPreset(id);
            box.AddChild(submit);

            PresetsList.AddChild(box);
        }
    }

    private void BuildRoster(SWSenateWorkConsoleState state)
    {
        RosterList.RemoveAllChildren();
        if (state.Roster.Count == 0)
        {
            RosterList.AddChild(new Label { Text = "Должности пока никем не заняты." });
            return;
        }

        foreach (var entry in state.Roster)
        {
            RosterList.AddChild(new Label
            {
                Text = $"{entry.Position}: {entry.Holder}",
                FontColorOverride = entry.Color,
                Margin = new Thickness(0, 1, 0, 1),
            });
        }
    }

    private void BuildDraft(SWSenateWorkConsoleState state)
    {
        _draftBudget = state.DraftBudget;
        DraftStatList.RemoveAllChildren();
        _draftSliders.Clear();
        _draftValueLabels.Clear();

        foreach (var global in state.Globals)
        {
            var subPanel = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(16, 0, 0, 6),
                Visible = false,
            };

            var header = new Button
            {
                Text = $"[+] {global.Name}",
                HorizontalExpand = true,
                Margin = new Thickness(0, 2, 0, 0),
            };
            header.OnPressed += _ =>
            {
                subPanel.Visible = !subPanel.Visible;
                header.Text = (subPanel.Visible ? "[-] " : "[+] ") + global.Name;
            };
            DraftStatList.AddChild(header);

            foreach (var sub in global.Subs)
            {
                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    HorizontalExpand = true,
                    Margin = new Thickness(0, 1, 0, 1),
                };

                row.AddChild(new Label { Text = sub.Name, FontColorOverride = global.Color, MinWidth = 150 });

                var slider = new Slider
                {
                    MinValue = -MaxEffect,
                    MaxValue = MaxEffect,
                    Value = 0,
                    HorizontalExpand = true,
                    MinWidth = 180,
                };

                var valueLabel = new Label { Text = "0", MinWidth = 40, HorizontalAlignment = Control.HAlignment.Right };

                slider.OnValueChanged += _ =>
                {
                    valueLabel.Text = $"{MathF.Round(slider.Value):+0;-0;0}";
                    RecomputeBudget();
                };

                row.AddChild(slider);
                row.AddChild(valueLabel);
                subPanel.AddChild(row);

                _draftSliders[sub.Id] = slider;
                _draftValueLabels[sub.Id] = valueLabel;
            }

            DraftStatList.AddChild(subPanel);
        }

        RecomputeBudget();
        _draftBuilt = true;
    }

    private void RecomputeBudget()
    {
        var net = 0f;
        foreach (var slider in _draftSliders.Values)
            net += MathF.Round(slider.Value);

        var remaining = _draftBudget - net;
        BudgetLabel.SetMessage($"Очки: {remaining:0} из бюджета {_draftBudget}");
        SubmitBillButton.Disabled = remaining < 0;
    }

    private void OnSubmitPressed()
    {
        var effects = new Dictionary<string, float>();
        foreach (var (id, slider) in _draftSliders)
        {
            var delta = MathF.Round(slider.Value);
            if (delta != 0)
                effects[id] = delta;
        }

        _owner.SubmitBill(BillNameEdit.Text, BillDescEdit.Text, effects);

        BillNameEdit.Text = string.Empty;
        BillDescEdit.Text = string.Empty;
        foreach (var slider in _draftSliders.Values)
            slider.Value = 0;
        RecomputeBudget();
    }

    private void BuildAgenda(SWSenateWorkConsoleState state)
    {
        AgendaList.RemoveAllChildren();
        if (state.Bills.Count == 0)
        {
            AgendaList.AddChild(new Label { Text = "Повестка пуста." });
            return;
        }

        foreach (var bill in state.Bills)
        {
            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(0, 2, 0, 6),
            };

            box.AddChild(new Label
            {
                Text = $"#{bill.Id}  {bill.Name}",
                StyleClasses = { "LabelKeyText" },
            });

            box.AddChild(new Label
            {
                Text = $"Автор: {bill.Author}    Стадия: {bill.Stage}",
                FontColorOverride = Color.Gray,
            });

            if (!string.IsNullOrWhiteSpace(bill.Description))
            {
                var desc = new RichTextLabel { Margin = new Thickness(0, 2, 0, 2) };
                desc.SetMessage(bill.Description);
                box.AddChild(desc);
            }

            var effectsRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            foreach (var effect in bill.Effects)
            {
                effectsRow.AddChild(new Label
                {
                    Text = $"{effect.StatName} {effect.Delta:+0;-0}",
                    FontColorOverride = effect.Color,
                    Margin = new Thickness(0, 0, 12, 0),
                });
            }

            box.AddChild(effectsRow);
            AgendaList.AddChild(box);
        }
    }

    private void BuildSchedule(SWSenateWorkConsoleState state)
    {
        ScheduleGrid.RemoveAllChildren();
        foreach (var row in state.Schedule)
        {
            var rowBox = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(0, 1, 0, 1),
            };

            rowBox.AddChild(new Label
            {
                Text = row.IsNow ? $"> {row.TimeLabel}" : row.TimeLabel,
                FontColorOverride = row.IsNow ? Color.White : Color.Gray,
                MinWidth = 70,
            });
            rowBox.AddChild(new Label { Text = row.Text, FontColorOverride = row.Color });
            ScheduleGrid.AddChild(rowBox);
        }

        var isSpeaker = state.IsSenateCard && state.Position == SWSenatePosition.Speaker && state.InOffice;
        var isChancellor = state.IsSenateCard && state.Position == SWSenatePosition.Chancellor && state.InOffice;
        SpeakerPanel.Visible = isSpeaker;
        ChancellorPanel.Visible = isChancellor;

        if (isSpeaker)
        {
            PopulateBillOption(state.SchedulableBills);
            PopulateHourOption(state.FreeStartHours);
            ScheduleButton.Disabled = state.SchedulableBills.Count == 0 || state.FreeStartHours.Count == 0;

            SpeakerPendingList.RemoveAllChildren();
            foreach (var session in state.PendingSessions)
            {
                var rowBox = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 1, 0, 1) };
                rowBox.AddChild(new Label { Text = $"{session.TimeRange}  {session.BillName}", HorizontalExpand = true });
                var remove = new Button { Text = "Удалить" };
                var id = session.Id;
                remove.OnPressed += _ => _owner.RemoveSession(id);
                rowBox.AddChild(remove);
                SpeakerPendingList.AddChild(rowBox);
            }
        }

        if (isChancellor)
        {
            ChancellorPendingList.RemoveAllChildren();
            if (state.PendingSessions.Count == 0)
            {
                ChancellorPendingList.AddChild(new Label { Text = "Нет заседаний на подтверждение." });
            }
            else
            {
                foreach (var session in state.PendingSessions)
                {
                    var rowBox = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 1, 0, 1) };
                    rowBox.AddChild(new Label { Text = $"{session.TimeRange}  {session.BillName}", HorizontalExpand = true });

                    var id = session.Id;
                    var confirm = new Button { Text = "Подтвердить" };
                    confirm.OnPressed += _ => _owner.ConfirmSession(id);
                    var reject = new Button { Text = "Отклонить", Margin = new Thickness(6, 0, 0, 0) };
                    reject.OnPressed += _ => _owner.RejectSession(id);

                    rowBox.AddChild(confirm);
                    rowBox.AddChild(reject);
                    ChancellorPendingList.AddChild(rowBox);
                }
            }
        }
    }

    private void PopulateBillOption(List<SWBillOption> bills)
    {
        BillOption.Clear();
        var hasSelected = false;
        var first = -1;
        foreach (var bill in bills)
        {
            BillOption.AddItem(bill.Name, bill.Id);
            if (first < 0)
                first = bill.Id;
            if (bill.Id == _selectedBillId)
                hasSelected = true;
        }

        if (bills.Count == 0)
        {
            _selectedBillId = -1;
            return;
        }

        if (!hasSelected)
            _selectedBillId = first;
        BillOption.SelectId(_selectedBillId);
    }

    private void PopulateHourOption(List<int> hours)
    {
        StartHourOption.Clear();
        var hasSelected = false;
        var first = -1;
        foreach (var hour in hours)
        {
            StartHourOption.AddItem($"{hour:00}:00", hour);
            if (first < 0)
                first = hour;
            if (hour == _selectedStartHour)
                hasSelected = true;
        }

        if (hours.Count == 0)
        {
            _selectedStartHour = -1;
            return;
        }

        if (!hasSelected)
            _selectedStartHour = first;
        StartHourOption.SelectId(_selectedStartHour);
    }

    private void BuildDashboard(SWSenateWorkConsoleState state)
    {
        Dashboard.RemoveAllChildren();

        if (state.SectorStats.Count > 0)
        {
            Dashboard.AddChild(new Label
            {
                Text = $"Сектор: {state.SectorName}",
                StyleClasses = { "LabelHeading" },
            });

            for (var i = 0; i < state.SectorStats.Count; i++)
            {
                var stat = state.SectorStats[i];
                var trend = i < state.SectorTrends.Count ? state.SectorTrends[i] : 0;

                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new Thickness(0, 1, 0, 1),
                };

                row.AddChild(new Label { Text = stat.Name, FontColorOverride = stat.Color, MinWidth = 170 });
                row.AddChild(new Label { Text = $"{stat.Value:0}", MinWidth = 44, HorizontalAlignment = Control.HAlignment.Right });
                row.AddChild(new Label
                {
                    Text = trend > 0 ? "  ↑" : trend < 0 ? "  ↓" : "  →",
                    FontColorOverride = trend > 0 ? Color.LightGreen : trend < 0 ? Color.IndianRed : Color.Gray,
                });

                Dashboard.AddChild(row);
            }

            Dashboard.AddChild(new Control { MinHeight = 12 });
        }

        Dashboard.AddChild(new Label { Text = "Республика (факт / политика)", StyleClasses = { "LabelHeading" } });
        foreach (var global in state.Globals)
        {
            Dashboard.AddChild(MakeGlobalBar(global));
        }
    }

    private static Control MakeGlobalBar(SWGlobalStatEntry global)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(0, 1, 0, 4),
        };

        var head = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };
        head.AddChild(new Label { Text = global.Name, FontColorOverride = global.Color, HorizontalExpand = true });
        head.AddChild(new Label { Text = $"{global.Actual:0}", MinWidth = 40, HorizontalAlignment = Control.HAlignment.Right });
        head.AddChild(new Label { Text = $"/ {global.Policy:0}", MinWidth = 48, FontColorOverride = Color.Gray, HorizontalAlignment = Control.HAlignment.Right });
        box.AddChild(head);

        box.AddChild(new ProgressBar
        {
            MinValue = global.Min,
            MaxValue = global.Max <= global.Min ? global.Min + 1 : global.Max,
            Value = global.Actual,
            HorizontalExpand = true,
            MinHeight = 14,
            Margin = new Thickness(0, 2, 0, 0),
            ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = global.Color },
        });

        return box;
    }
