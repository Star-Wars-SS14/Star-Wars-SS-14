using Content.Client._SW.TurretConsole.UI.TurretControl;
using Content.Client.Pinpointer.UI;
using Content.Client.Stylesheets;
using Content.Shared._SW.Droids;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._SW.Droids.UI;

[GenerateTypedNameReferences]
public sealed partial class SWDroidControlDatapadMenu : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly SharedTransformSystem _transform;
    private readonly SpriteSystem _sprite;
    private readonly Texture _blipTexture;
    private NetEntity? _trackedDroid;

    public event Action<string>? OnJobButtonPressed;
    public event Action<string>? OnFactionAllowButtonPressed;
    public event Action<string>? OnFactionDisallowButtonPressed;
    public event Action? OnTargetHumanoidsWithoutIdToggled;
    public event Action? OnTargetAnimalsToggled;

    public SWDroidControlDatapadMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _transform = _entManager.System<SharedTransformSystem>();
        _sprite = _entManager.System<SpriteSystem>();
        _blipTexture = _sprite.Frame0(new SpriteSpecifier.Texture(new ResPath("/Textures/Interface/NavMap/beveled_circle.png")));

        Tabs.SetTabTitle(0, Loc.GetString("sw-droid-control-datapad-tab-droids"));
        Tabs.SetTabTitle(1, Loc.GetString("sw-droid-control-datapad-tab-targets"));
        Tabs.SetTabTitle(2, Loc.GetString("sw-droid-control-datapad-tab-map"));

        DisabledOverlayLabel.FontColorOverride = Color.Red;

        TargetHumanoidsWithoutIdCheckBox.OnToggled += _ => OnTargetHumanoidsWithoutIdToggled?.Invoke();
        TargetAnimalsCheckBox.OnToggled += _ => OnTargetAnimalsToggled?.Invoke();
        DroidNavMap.TrackedEntitySelectedAction += SetTrackedDroidFromMap;
    }

    public void UpdateState(SWDroidControlDatapadBoundUserInterfaceState state)
    {
        MainContent.Visible = state.Enabled;
        DisabledOverlay.Visible = !state.Enabled;

        UpdateDroids(state.Droids);
        UpdateJobs(state.JobsAllowed);
        UpdateFactions(state.AvailableFactions);
        UpdateTargetOptions(state.TargetHumanoidsWithoutId, state.TargetAnimals);
        UpdateMap(state);
    }

    private void UpdateDroids(List<SWDroidControlDatapadDroidEntry> droids)
    {
        DroidsList.Children.Clear();
        DroidsSummary.Text = Loc.GetString("sw-droid-control-datapad-droids-count", ("count", droids.Count));

        if (droids.Count == 0)
        {
            DroidsList.AddChild(new Label
            {
                Text = Loc.GetString("sw-droid-control-datapad-no-linked-droids")
            });
            return;
        }

        foreach (var droid in droids)
        {
            DroidsList.AddChild(CreateDroidEntry(droid));
        }
    }

    private Control CreateDroidEntry(SWDroidControlDatapadDroidEntry droid)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true
        };

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(6)
        };

        box.AddChild(new Label
        {
            Text = droid.Name,
            StyleClasses = { "LabelHeading" }
        });

        box.AddChild(new Label
        {
            Text = Loc.GetString("sw-droid-control-datapad-droid-status", ("status", droid.Status))
        });

        box.AddChild(new Label
        {
            Text = Loc.GetString("sw-droid-control-datapad-droid-charge", ("charge", droid.Charge))
        });

        box.AddChild(new Label
        {
            Text = Loc.GetString("sw-droid-control-datapad-droid-coordinates", ("coordinates", droid.CoordinatesText))
        });

        panel.AddChild(box);
        return panel;
    }

    private void UpdateMap(SWDroidControlDatapadBoundUserInterfaceState state)
    {
        MapDroidsList.Children.Clear();
        DroidNavMap.TrackedCoordinates.Clear();
        DroidNavMap.TrackedEntities.Clear();
        DroidNavMap.LocalizedNames.Clear();

        MapDroidsSummary.Text = Loc.GetString("sw-droid-control-datapad-map-droids-count", ("count", state.MapDroids.Count));

        if (state.MapUid == null)
        {
            DroidNavMap.MapUid = null;
            DroidNavMap.Visible = false;
            MapDroidsList.AddChild(new Label
            {
                Text = Loc.GetString("sw-droid-control-datapad-map-unavailable")
            });
            return;
        }

        var mapUid = _entManager.GetEntity(state.MapUid.Value);
        if (DroidNavMap.MapUid != mapUid)
        {
            DroidNavMap.MapUid = mapUid;
            DroidNavMap.Visible = true;
            DroidNavMap.ForceNavMapUpdate();
        }

        if (state.MapDroids.Count == 0)
        {
            MapDroidsList.AddChild(new Label
            {
                Text = Loc.GetString("sw-droid-control-datapad-no-map-droids")
            });
            DroidNavMap.Focus = null;
            return;
        }

        var trackedStillExists = false;
        foreach (var droid in state.MapDroids)
        {
            var coordinates = _entManager.GetCoordinates(droid.Coordinates);

            if (droid.DroidUid == _trackedDroid)
                trackedStillExists = true;

            MapDroidsList.AddChild(CreateMapDroidEntry(droid, coordinates));
            DroidNavMap.LocalizedNames[droid.DroidUid] =
                Loc.GetString("sw-droid-control-datapad-map-selected",
                    ("name", droid.Name),
                    ("status", droid.Status),
                    ("charge", droid.Charge));
        }

        if (!trackedStillExists)
            _trackedDroid = null;

        RefreshMapBlips(state.MapDroids);
    }

    private Control CreateMapDroidEntry(SWDroidControlDatapadDroidEntry droid, EntityCoordinates coordinates)
    {
        var button = new Button
        {
            HorizontalExpand = true,
        };

        if (droid.DroidUid == _trackedDroid)
            button.AddStyleClass(StyleClass.Positive);

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(4)
        };

        box.AddChild(new Label
        {
            Text = droid.Name,
            ClipText = true
        });
        box.AddChild(new Label
        {
            Text = Loc.GetString("sw-droid-control-datapad-map-entry-details",
                ("status", droid.Status),
                ("charge", droid.Charge)),
            ClipText = true
        });

        button.AddChild(box);
        button.OnButtonUp += _ =>
        {
            SetTrackedDroid(droid.DroidUid);
            DroidNavMap.CenterToCoordinates(coordinates);
        };

        return button;
    }

    private void RefreshMapBlips(List<SWDroidControlDatapadDroidEntry> droids)
    {
        DroidNavMap.TrackedEntities.Clear();

        foreach (var droid in droids)
        {
            var coordinates = _entManager.GetCoordinates(droid.Coordinates);

            var selected = droid.DroidUid == _trackedDroid;
            var color = selected || _trackedDroid == null
                ? Color.LimeGreen
                : Color.LimeGreen * Color.DimGray;

            DroidNavMap.TrackedEntities[droid.DroidUid] = new NavMapBlip(
                CoordinatesToLocal(coordinates),
                _blipTexture,
                color,
                selected);
        }

        DroidNavMap.Focus = _trackedDroid;
    }

    private EntityCoordinates CoordinatesToLocal(EntityCoordinates coordinates)
    {
        return DroidNavMap.MapUid == null
            ? coordinates
            : _transform.WithEntityId(coordinates, DroidNavMap.MapUid.Value);
    }

    private void SetTrackedDroidFromMap(NetEntity? netEntity)
    {
        SetTrackedDroid(netEntity);
    }

    private void SetTrackedDroid(NetEntity? netEntity)
    {
        _trackedDroid = _trackedDroid == netEntity ? null : netEntity;
        DroidNavMap.Focus = _trackedDroid;
    }

    private void UpdateJobs(Dictionary<string, bool> jobs)
    {
        AllowedJobsList.Children.Clear();
        DisallowedJobsList.Children.Clear();

        foreach (var (job, isAllowed) in jobs)
        {
            if (!_prototype.TryIndex<JobPrototype>(job, out var proto))
                continue;

            var control = new SWTurretConsoleControl(job, proto.LocalizedName);
            control.SendJob += selectedJob => OnJobButtonPressed?.Invoke(selectedJob);

            if (isAllowed)
                AllowedJobsList.AddChild(control);
            else
                DisallowedJobsList.AddChild(control);
        }
    }

    private void UpdateFactions(Dictionary<string, string> factions)
    {
        AllowFactionsList.Children.Clear();
        DisallowFactionsList.Children.Clear();

        foreach (var (id, name) in factions)
        {
            var button = new Button
            {
                Text = Loc.GetString("sw-droid-control-datapad-faction-allow", ("faction", name)),
                HorizontalExpand = true
            };
            button.OnPressed += _ => OnFactionAllowButtonPressed?.Invoke(id);
            AllowFactionsList.AddChild(button);
        }

        foreach (var (id, name) in factions)
        {
            var button = new Button
            {
                Text = Loc.GetString("sw-droid-control-datapad-faction-disallow", ("faction", name)),
                HorizontalExpand = true
            };
            button.OnPressed += _ => OnFactionDisallowButtonPressed?.Invoke(id);
            DisallowFactionsList.AddChild(button);
        }
    }

    private void UpdateTargetOptions(bool targetHumanoidsWithoutId, bool targetAnimals)
    {
        TargetHumanoidsWithoutIdCheckBox.Pressed = targetHumanoidsWithoutId;
        TargetAnimalsCheckBox.Pressed = targetAnimals;
    }
}
