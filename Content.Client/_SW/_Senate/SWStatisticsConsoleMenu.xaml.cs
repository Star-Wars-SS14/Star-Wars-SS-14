using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate;

[GenerateTypedNameReferences]
public sealed partial class SWStatisticsConsoleMenu : FancyWindow
{
    public SWStatisticsConsoleMenu()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetState(SWStatisticsConsoleState state)
    {
        RepublicStats.RemoveAllChildren();
        foreach (var stat in state.RepublicStats)
        {
            RepublicStats.AddChild(MakeStatBar(stat));
        }

        SectorGrid.RemoveAllChildren();
        SectorGrid.Columns = 1 + state.RepublicStats.Count;

        SectorGrid.AddChild(new Label { Text = "Сектор", StyleClasses = { "LabelKeyText" } });
        foreach (var stat in state.RepublicStats)
        {
            SectorGrid.AddChild(new Label
            {
                Text = stat.ShortName,
                FontColorOverride = stat.Color,
                HorizontalAlignment = Control.HAlignment.Center,
                StyleClasses = { "LabelKeyText" },
            });
        }

        foreach (var sector in state.Sectors)
        {
            SectorGrid.AddChild(new Label
            {
                Text = sector.Name,
                FontColorOverride = sector.Color,
            });

            foreach (var stat in sector.Stats)
            {
                SectorGrid.AddChild(new Label
                {
                    Text = $"{stat.Value:0}",
                    HorizontalAlignment = Control.HAlignment.Center,
                });
            }
        }
    }

    private static Control MakeStatBar(SWStatEntry stat)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 1, 0, 1),
        };

        row.AddChild(new Label
        {
            Text = stat.Name,
            FontColorOverride = stat.Color,
            MinWidth = 160,
        });

        row.AddChild(new ProgressBar
        {
            MinValue = stat.Min,
            MaxValue = stat.Max <= stat.Min ? stat.Min + 1 : stat.Max,
            Value = stat.Value,
            HorizontalExpand = true,
            MinHeight = 16,
            ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = stat.Color },
        });

        row.AddChild(new Label
        {
            Text = $"{stat.Value:0}",
            MinWidth = 44,
            HorizontalAlignment = Control.HAlignment.Right,
        });

        return row;
    }
}
