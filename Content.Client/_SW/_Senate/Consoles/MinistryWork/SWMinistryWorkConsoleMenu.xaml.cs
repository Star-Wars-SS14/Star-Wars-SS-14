            dismiss.HorizontalExpand = true;
            dismiss.OnPressed += _ => _owner.Verdict(id, SWVerdict.Dismiss);
            actions.AddChild(dismiss);
        }

        box.AddChild(actions);
        card.AddChild(box);
        return card;
    }

