namespace Content.Client._SW.Economy;

[GenerateTypedNameReferences]
public sealed partial class SWFactionSpireWindow : SWTerminalWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;

    // EntitySystems are NOT registered in the IoC container: resolve via the
    // system manager after InjectDependencies, never via [Dependency] in a window.
    private SpriteSystem _sprite = default!;

    private readonly SWFactionSpireBoundUserInterface _owner;
    private readonly EntityUid _ownerUid;
    private TimeSpan _mascotTime;
    private bool _capturing;

    // Decorative client-only telemetry (random walk, refreshed periodically).
    private readonly Random _rng = new();
    private float _coreTemp = 42.0f;
    private float _signal = 87.0f;
    private float _capacitor = 91.0f;
    private TimeSpan _uptime;
    private float _telemetryAccumulator;
    private const float TelemetryInterval = 2.0f;

    // Seamless marquee: the Margin is applied to the BOX with two copies, never
    // to the measured label (Margin on the measured label shrinks DesiredSize and
    // causes an early reset). Step = first copy width + inter-copy gap.
    private const float TickerSpeed = 40.0f;
    private const float TickerGap = 60.0f;
    private float _tickerOffset;

    private static readonly Dictionary<string, string> FactionHex = new()
    {
        { "RepublicFaction", "#2e6bd6" },
        { "EmpireFaction", "#d63a3a" },
        { "ExchangeFaction", "#8a5a2b" },
        { "BlackSunFaction", "#8a3ad6" },
        { "MandalorianFaction", "#d6c23a" },
    };

    private const string NeutralHex = "#dfe4ee";

    public SWFactionSpireWindow(SWFactionSpireBoundUserInterface owner)
    {
        _owner = owner;
        _ownerUid = owner.Owner;
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _sysMan.GetEntitySystem<SpriteSystem>();

        var telemetryColor = Color.FromHex("#ff5555");
        TelemetryCoreLabel.FontColorOverride = telemetryColor;
        TelemetrySignalLabel.FontColorOverride = telemetryColor;
        TelemetryCapLabel.FontColorOverride = telemetryColor;
        TelemetryUptimeLabel.FontColorOverride = telemetryColor;
        RewriteTimerLabel.FontColorOverride = telemetryColor;
        PayoutTimerLabel.FontColorOverride = telemetryColor;

        CaptureButton.OnPressed += _ => _owner.SendCapture();
        EjectButton.OnPressed += _ => _owner.SendEject();
        Title = Loc.GetString("sw-spire-title");
        UpdateTelemetry();
        UpdateTimers(false, 0f, false, 0f);
    }

    public void UpdateState(SWFactionSpireBoundUserInterfaceState state)
    {
        SpireNameLabel.Text = _entMan.GetComponent<MetaDataComponent>(_ownerUid).EntityName;
        OwnerLabel.Text = Loc.GetString("sw-spire-owner", ("faction", state.OwnerName));
        OwnerLabel.FontColorOverride = Color.FromHex(FactionHex.GetValueOrDefault(state.OwnerFaction, NeutralHex));
        StatusLabel.Text = state.IsCapturing
            ? Loc.GetString("sw-spire-capturing", ("faction", state.CapturingName))
            : Loc.GetString("sw-spire-idle");

        _capturing = state.IsCapturing;
        CaptureBar.Value = state.CaptureProgress;
        PayoutBar.Value = state.PayoutProgress;

        UpdateTimers(state.IsCapturing, state.CaptureRemainingSeconds,
            state.OwnerFaction != string.Empty, state.PayoutRemainingSeconds);

        CardPanel.Visible = state.HasCard;
        EjectButton.Visible = state.HasCard;
        if (state.HasCard)
        {
            CardNameLabel.Text = state.CardName;
            CardJobLabel.Text = state.CardJob;
            if (_prototype.TryIndex<JobIconPrototype>(state.CardIcon, out var icon))
                CardIconRect.Texture = _sprite.GetFrame(icon.Icon, TimeSpan.Zero);
        }

        CaptureButton.Disabled = !state.HasCard || state.IsCapturing;
        SetAccent(FactionHex.GetValueOrDefault(state.OwnerFaction, "#8a8a8a"));

        SetTicker(Loc.GetString("sw-spire-ticker"));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // Mascot animation.
        _mascotTime += TimeSpan.FromSeconds(args.DeltaSeconds);
        var mascotState = _capturing ? "calicomp_lag" : "calicomp";
        MascotRect.Texture = _sprite.GetFrame(
            new SpriteSpecifier.Rsi(new ResPath("/Textures/_SW/Economy/control_spire/calicomp.rsi"), mascotState),
            _mascotTime);

        // Telemetry refresh.
        _uptime += TimeSpan.FromSeconds(args.DeltaSeconds);
        _telemetryAccumulator += args.DeltaSeconds;
        if (_telemetryAccumulator >= TelemetryInterval)
        {
            _telemetryAccumulator = 0f;
            UpdateTelemetry();
        }

        UpdateTicker(args.DeltaSeconds);
    }

    /// <summary>
    /// Countdown lines are always present (placeholder when idle) so their
    /// appearance never shifts the layout.
    /// </summary>
    private void UpdateTimers(bool capturing, float captureRemaining, bool owned, float payoutRemaining)
    {
        var rewriteValue = capturing
            ? FormatClock(captureRemaining)
            : Loc.GetString("sw-spire-none");
        RewriteTimerLabel.Text = Loc.GetString("sw-spire-rewrite-timer", ("value", rewriteValue));

        var payoutValue = owned
            ? FormatClock(payoutRemaining)
            : Loc.GetString("sw-spire-none");
        PayoutTimerLabel.Text = Loc.GetString("sw-spire-payout-timer", ("value", payoutValue));
    }

    private void UpdateTicker(float deltaSeconds)
    {
        // Measured label carries no Margin, so DesiredSize is the true text width.
        var copyWidth = TickerTextA.DesiredSize.X;
        if (copyWidth <= 0f)
            return;

        var step = copyWidth + TickerGap;
        _tickerOffset -= deltaSeconds * TickerSpeed;
        if (_tickerOffset <= -step)
            _tickerOffset += step;

        TickerBox.Margin = new Thickness(_tickerOffset, 0, 0, 0);
    }

    private void SetTicker(string text)
    {
        if (TickerTextA.Text == text)
            return;

        TickerTextA.Text = text;
        TickerTextB.Text = text;
        _tickerOffset = 0f;
    }

    private void UpdateTelemetry()
    {
        _coreTemp = Clamp(_coreTemp + (float) (_rng.NextDouble() - 0.5) * 0.8f, 38f, 47f);
        _signal = Clamp(_signal + (float) (_rng.NextDouble() - 0.5) * 4f, 70f, 99f);
        _capacitor = Clamp(_capacitor + (float) (_rng.NextDouble() - 0.5) * 3f, 60f, 100f);

        TelemetryCoreLabel.Text = Loc.GetString("sw-spire-telemetry-core",
            ("value", _coreTemp.ToString("F1", CultureInfo.InvariantCulture)));
        TelemetrySignalLabel.Text = Loc.GetString("sw-spire-telemetry-signal",
            ("value", _signal.ToString("F0", CultureInfo.InvariantCulture)));
        TelemetryCapLabel.Text = Loc.GetString("sw-spire-telemetry-cap",
            ("value", _capacitor.ToString("F0", CultureInfo.InvariantCulture)));
        TelemetryUptimeLabel.Text = Loc.GetString("sw-spire-telemetry-uptime",
            ("value", FormatUptime()));
    }

    private string FormatUptime()
    {
        var hours = (int) _uptime.TotalHours;
        return hours.ToString("D2") + ":" + _uptime.Minutes.ToString("D2") + ":" + _uptime.Seconds.ToString("D2");
    }

    private static string FormatClock(float seconds)
    {
        var span = TimeSpan.FromSeconds(seconds);
        return span.Minutes.ToString("D2") + ":" + span.Seconds.ToString("D2");
    }

    private static float Clamp(float value, float min, float max)
    {
        return value < min ? min : value > max ? max : value;
    }
}