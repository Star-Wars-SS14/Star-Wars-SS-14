    /// <summary>
    /// Takes a new state from the server and redraws everything from it.
    /// </summary>
    public void UpdateState(SWBattlePassState state, HashSet<string> owned)
    {
        _state = state;
        _owned = owned;

        if (state.Season == null || !_proto.TryIndex<SWBattlePassSeasonPrototype>(state.Season, out _season))
        {
            TierLabel.Text = Loc.GetString("sw-battlepass-no-season");
            return;
        }

        var season = _season;
        _case = season.OvertimeCase is { } caseId ? _proto.Index(caseId) : null;
        var xp = state.Xp;
        var tier = SWBattlePassRules.TierOf(season, xp);
        var last = season.Tiers.Count;
        var floor = SWBattlePassRules.XpForTier(season, tier);
        var into = xp - floor;

        BannerTitle.Text = Loc.GetString(season.Name).ToUpperInvariant();
        StripTitle.Text = BannerTitle.Text;
        if (season.Banner != null)
            BannerArt.Texture = _sprite.Frame0(season.Banner);

        TierNumber.Text = tier.ToString();
        EndLabel.Text = GetDateText(season, state);
        TierLabel.Text = Loc.GetString("sw-battlepass-tier", ("tier", tier));
        XpBar.Value = tier >= last ? 1f : (float) into / season.XpPerTier;
        XpLabel.Text = tier >= last
            ? Loc.GetString("sw-battlepass-xp-max", ("xp", xp))
            : Loc.GetString("sw-battlepass-xp", ("xp", into), ("max", season.XpPerTier));

        StripTier.Text = TierLabel.Text;
        StripXp.Text = XpLabel.Text;
        StripBar.Value = XpBar.Value;

        var notice = GetNotice(season, state, tier);
        NextLabel.Text = notice;
        NextLabel.Visible = notice != null;

        Chips.RemoveAllChildren();
        if (state.CatchUpBank > 0)
        {
            Chips.AddChild(new Label
            {
                Text = Loc.GetString("sw-battlepass-catchup", ("xp", state.CatchUpBank)),
                StyleClasses = { SWTerminalStyle.Text },
                FontColorOverride = IceColor,
                VAlign = Label.VAlignMode.Center,
            });
        }

        if (state.Evening)
            Chips.AddChild(new Label { Text = Loc.GetString("sw-battlepass-evening"), StyleClasses = { SWTerminalStyle.Text } });

        var cases = _case == null ? 0 : state.Cases.GetValueOrDefault(_case.ID);
        TabCases.Text = cases > 0
            ? Loc.GetString("sw-battlepass-tab-cases-count", ("count", cases))
            : Loc.GetString("sw-battlepass-tab-cases");

        UpdateMainButton(season, state);
        BuildTrack(season, state, tier);
        UpdateGoal(season, state, tier);
        BuildToday(state);
        BuildQuests(season, state);
        BuildCases(state);
        BuildItems(state);

        PremiumSoon.Visible = !state.Paid;
    }

