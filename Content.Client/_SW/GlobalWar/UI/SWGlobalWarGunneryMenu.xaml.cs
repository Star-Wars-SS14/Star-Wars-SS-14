using System.Linq;
using System.Numerics;
using Content.Shared._SW.GlobalWar.Combat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarGunneryMenu : SWGlobalWarWindow
{
    public event Action<NetEntity[], Vector2, bool>? Input;
    private readonly Dictionary<NetEntity, CheckBox> _weapons = new();
    private readonly Dictionary<NetEntity, WeaponRow> _rows = new();
    private SWGlobalWarGunnerySnapshot? _snapshot;
    private bool _firing;
    private float _sendDelay;

    public SWGlobalWarGunneryMenu()
    {
        RobustXamlLoader.Load(this);
        HelpMark.ToolTip = Loc.GetString("sw-global-war-gunnery-instructions");
        Fire.MainFont = SWGlobalWarConsoleStyle.Bold(17);
        Fire.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        Fire.OnButtonDown += _ => _firing = true;
        Fire.OnButtonUp += _ => _firing = false;
        Fire.OnMouseExited += _ => _firing = false;
    }

    public void UpdateState(SWGlobalWarGunnerySnapshot snapshot)
    {
        _snapshot = snapshot;
        Radar.Center = snapshot.Center;
        Radar.Guns = snapshot.Guns;
        Radar.Hulls = snapshot.Hulls;
        StatusText.SetMessage(Loc.GetString(snapshot.Authorized ? "sw-global-war-gunnery-ready" : "sw-global-war-gunnery-denied"));
        Fire.Disabled = !snapshot.Authorized;
        if (!snapshot.Authorized) _firing = false;
        foreach (var obsolete in _weapons.Keys.Where(id => !snapshot.Guns.Any(g => g.Gun == id)).ToArray())
        {
            _rows[obsolete].Root.Dispose();
            _rows.Remove(obsolete);
            _weapons.Remove(obsolete);
        }
        foreach (var gun in snapshot.Guns)
        {
            if (!_rows.TryGetValue(gun.Gun, out var row))
            {
                row = new WeaponRow();
                _rows.Add(gun.Gun, row);
                _weapons.Add(gun.Gun, row.Choice);
                Weapons.AddChild(row.Root);
            }

            var choice = row.Choice;
            choice.Disabled = !snapshot.Authorized || gun.Occupied;
            if (choice.Disabled) choice.Pressed = false;
            row.Name.Text = gun.Name;
            row.Ammo.Text = $"{gun.Ammunition}/{gun.Capacity}";
            row.Bar.Value = gun.Ammunition;
            row.Bar.Maximum = Math.Max(1, gun.Capacity);
            row.Bar.Fill = gun.Ammunition > 0 ? SWGlobalWarConsoleStyle.Good : SWGlobalWarConsoleStyle.Bad;
            row.State.Set(Loc.GetString(gun.Occupied ? "sw-global-war-gunnery-status-occupied" : $"sw-global-war-gunnery-status-{gun.Status}"),
                gun.Occupied ? "off" : gun.Status == "ready" ? "good" : gun.Status is "unpowered" or "broken" or "empty" ? "bad" : "wait");
        }
    }

    private sealed class WeaponRow
    {
        public readonly PanelContainer Root = new() { HorizontalExpand = true, PanelOverride = SWGlobalWarConsoleStyle.RowBox(false) };
        public readonly CheckBox Choice = new() { VerticalAlignment = Control.VAlignment.Center };
        public readonly Label Name = new() { HorizontalExpand = true, ClipText = true, FontOverride = SWGlobalWarConsoleStyle.Strong, FontColorOverride = Color.White };
        public readonly Label Ammo = new() { FontOverride = SWGlobalWarConsoleStyle.Strong, FontColorOverride = Color.White };
        public readonly SWGlobalWarMarketBar Bar = new() { MinHeight = 5, MaxHeight = 5 };
        public readonly SWGlobalWarChip State = new();

        public WeaponRow()
        {
            var line = new BoxContainer { SeparationOverride = 8, Margin = new Thickness(8, 4), MinHeight = 40 };
            line.AddChild(Choice);
            // The name has its own line, so that a long state never cuts it.
            var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, VerticalAlignment = Control.VAlignment.Center, SeparationOverride = 3 };
            body.AddChild(Name);
            var charge = new BoxContainer { SeparationOverride = 8 };
            Bar.HorizontalExpand = true;
            Bar.VerticalAlignment = Control.VAlignment.Center;
            charge.AddChild(Bar);
            charge.AddChild(Ammo);
            charge.AddChild(State);
            body.AddChild(charge);
            line.AddChild(body);
            Root.AddChild(line);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (Root?.Window?.IsFocused != true) _firing = false;
        _sendDelay -= args.DeltaSeconds;
        if (_sendDelay > 0 || _snapshot is not { Authorized: true } || Radar.Target is not { } target) return;
        _sendDelay = 0.1f;
        Input?.Invoke(_weapons.Where(w => w.Value.Pressed && !w.Value.Disabled).Select(w => w.Key).Take(16).ToArray(),
            target, _firing);
    }
}
