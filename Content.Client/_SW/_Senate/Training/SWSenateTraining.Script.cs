    public const float ChapterLength = 60f;

    /// <summary>Assumed unhurried reading pace. A shot with more text than the script's time allows stays longer.</summary>
    public const float ReadingCharsPerSecond = 14f;

    /// <summary>The script's own time for the shot, extended when its visible text needs longer to read.</summary>
    public static float ShotDuration(SWTrainingChapter chapter, SWTrainingShot shot)
    {
        var characters = shot.Title.Length + shot.Text.Length + shot.Note.Length;
        return MathF.Max(ChapterLength / chapter.Shots.Length, characters / ReadingCharsPerSecond);
    }

