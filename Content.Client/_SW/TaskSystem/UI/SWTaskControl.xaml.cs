using Content.Client._SW.UserInterface;
using Content.Shared._SW.TaskSystem;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW.TaskSystem.UI;

[GenerateTypedNameReferences]
public sealed partial class SWTaskControl : Control
{
    public SWTaskControl(TaskInfo task, string accent)
    {
        RobustXamlLoader.Load(this);

        var progress = task.Status.Float();
        var done = progress >= 1f;

        TaskName.Text = task.TaskName;
        TaskDescription.Text = task.TaskDesc;
        TaskPercent.Text = Loc.GetString("sw-task-console-percent", ("percent", MathF.Round(progress * 100f)));
        TaskDone.Visible = done;
        if (done)
            TaskDescription.SetOnlyStyleClass(SWTerminalStyle.TextDone);

        TaskProgress.Value = progress;
        TaskProgress.AddStyleClass(done ? SWTerminalStyle.BarDone : SWTerminalStyle.BarOpen + accent);

        foreach (var reward in task.Rewards)
        {
            RewardList.AddChild(SWTerminalWindow.CreateChip(reward, SWTerminalStyle.ChipMoney));
        }

        if (task.Score.Length > 0)
            RewardList.AddChild(SWTerminalWindow.CreateChip(task.Score, SWTerminalStyle.ChipScore + accent));
    }
}
