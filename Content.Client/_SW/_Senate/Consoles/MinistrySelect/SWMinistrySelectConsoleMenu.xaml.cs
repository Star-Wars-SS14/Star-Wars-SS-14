using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._SW._Senate.Consoles.MinistrySelect;

[GenerateTypedNameReferences]
public sealed partial class SWMinistrySelectConsoleMenu : FancyWindow
{
    private readonly SWMinistrySelectConsoleBoundUserInterface _owner;

    public SWMinistrySelectConsoleMenu(SWMinistrySelectConsoleBoundUserInterface owner)
    {
        RobustXamlLoader.Load(this);
        TitleClass = "LabelKeyText";
        _owner = owner;

        SWConsoleStyle.StyleRoot(RootPanel);
        SWConsoleStyle.StyleHeader(HeaderPanel);
        HeaderNetwork.FontOverride = SWConsoleStyle.Small;
        HeaderNetwork.FontColorOverride = SWConsoleStyle.Brass;
        HeaderTitle.FontOverride = SWConsoleStyle.Header;
        HeaderTitle.FontColorOverride = SWConsoleStyle.TextBright;
        HeaderTitle.Text = "Исполнительная власть";
        StatusLabel.FontOverride = SWConsoleStyle.Body;
    }

    public void SetState(SWMinistrySelectConsoleState state)
    {
        MinistryList.RemoveAllChildren();

        if (!state.HasCard)
        {
            SetStatus("ID-карта не установлена", SWConsoleStyle.TextDim);
            return;
        }

        if (!state.IsMinisterCard)
        {
            SetStatus("Портфель может занять только карта министра.", SWConsoleStyle.TextDim);
            return;
        }

        if (state.Current != null)
        {
            SetStatus($"Назначение закреплено: {state.CurrentName}", SWConsoleStyle.Good);
            return;
        }

        SetStatus("Назначение", SWConsoleStyle.TextBright);

        var currentGroup = -1;
        foreach (var ministry in state.Ministries)
        {
            if (ministry.KindGroup != currentGroup)
            {
                currentGroup = ministry.KindGroup;
                if (MinistryList.ChildCount > 0)
                    MinistryList.AddChild(new Control { MinHeight = 8 });
                MinistryList.AddChild(SWConsoleStyle.Section(ministry.KindLabel));
                MinistryList.AddChild(new Control { MinHeight = 4 });
            }

            MinistryList.AddChild(MakeMinistryCard(ministry));
        }
    }

    private void SetStatus(string text, Color color)
    {
        StatusLabel.Text = text;
        StatusLabel.FontColorOverride = color;
    }

    private Control MakeMinistryCard(SWMinistryEntry ministry)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 6),
        };

        var claimed = ministry.Claimed;
        var disabled = claimed || ministry.Locked;
        var suffix = claimed ? ", ЗАНЯТО" : ministry.Locked ? ", НЕДОСТУПНО" : string.Empty;
        var btn = new Button
        {
            Text = $"{ministry.Name}{suffix}",
            HorizontalExpand = true,
            Disabled = disabled,
            TextAlign = Label.AlignMode.Left,
        };

        btn.Label.FontOverride = SWConsoleStyle.Strong;
        btn.Label.FontColorOverride = disabled ? SWConsoleStyle.TextDim : ministry.Color;
        btn.StyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = disabled ? SWConsoleStyle.BgRowAlt : SWConsoleStyle.BgPanel,
            BorderColor = disabled ? SWConsoleStyle.TextDim : ministry.Color,
            BorderThickness = new Thickness(3, 0, 0, 0),
            ContentMarginLeftOverride = 10,
            ContentMarginRightOverride = 10,
            ContentMarginTopOverride = 8,
            ContentMarginBottomOverride = 8,
        };

        if (!disabled)
        {
            var id = ministry.Id;
            btn.OnPressed += _ => _owner.SelectMinistry(id);
        }

        box.AddChild(btn);

        var sub = claimed && ministry.Holder != null
            ? $"Занимает: {ministry.Holder}"
            : ministry.Locked
                ? ministry.LockedReason
                : ministry.ParentName != null
                    ? $"Подчинение: {ministry.ParentName}"
                    : string.Empty;

        if (!string.IsNullOrEmpty(sub))
        {
            var sl = SWConsoleStyle.Text(sub, SWConsoleStyle.TextDim, SWConsoleStyle.Small);
            sl.Margin = new Thickness(6, 1, 0, 0);
            box.AddChild(sl);
        }

        return box;
    }
}
