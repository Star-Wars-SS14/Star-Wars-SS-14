using Content.Shared._SW.GlobalWar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._SW.GlobalWar.UI;

[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarTravelConsoleMenu : DefaultWindow
{
    public event Action<ProtoId<SWGlobalWarPlanetPrototype>>? OnTravelPressed;

    private ProtoId<SWGlobalWarPlanetPrototype>? _selected;
    private readonly Dictionary<ProtoId<SWGlobalWarPlanetPrototype>, Button> _buttons = new();

    public SWGlobalWarTravelConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        Travel.OnPressed += _ =>
        {
            if (_selected is not { } selected)
                return;

            Travel.Disabled = true;
            OnTravelPressed?.Invoke(selected);
        };
    }

    public void UpdateState(SWGlobalWarTravelConsoleState state)
    {
        CurrentPlanet.Text = Loc.GetString("sw-global-war-travel-location", ("planet", state.CurrentPlanet));
        Status.Text = state.Status;
        Destinations.RemoveAllChildren();
        _buttons.Clear();
        var selectedAvailable = false;
        foreach (var entry in state.Destinations)
        {
            var button = new Button
            {
                Text = entry.Name,
                ToolTip = entry.Reason,
                Disabled = !entry.Available,
                ToggleMode = true,
                Pressed = _selected == entry.Id,
                HorizontalExpand = true,
            };
            _buttons.Add(entry.Id, button);
            Destinations.AddChild(button);
            if (!entry.Available)
                Destinations.AddChild(new Label { Text = entry.Reason, MaxWidth = 330, ClipText = true });

            if (_selected == entry.Id && entry.Available)
                selectedAvailable = true;

            button.OnPressed += _ =>
            {
                _selected = entry.Id;
                foreach (var (id, other) in _buttons)
                    other.Pressed = id == entry.Id;
                Travel.Disabled = false;
            };
        }

        Travel.Disabled = !selectedAvailable;
    }
}
