    private void OnAddBlockPressed()
    {
        if (_state == null || string.IsNullOrWhiteSpace(BlockLabelEdit.Text))
            return;

        _owner.AddBlock(_state.Today + _blockDay, _blockSlot, _blockDuration, BlockLabelEdit.Text);
        BlockLabelEdit.Text = string.Empty;
    }

    private void BuildBlocks(SWPlannerConsoleState state)
    {
        BlockList.RemoveAllChildren();
        BlockList.AddChild(SWConsoleStyle.Section("Мои блоки"));
        BlockList.AddChild(new Control { MinHeight = 4 });

        var any = false;
        foreach (var (items, dayLabel) in new[] { (state.MyItemsToday, "сегодня"), (state.MyItemsTomorrow, "завтра") })
        {
            foreach (var item in items)
            {
                if (item.Kind != 3 || item.BlockId < 0)
                    continue;

                any = true;
                var row = SWConsoleStyle.Row(SWConsoleStyle.BgPanel, SWConsoleStyle.Neutral);
                row.Margin = new Thickness(0, 0, 0, 3);
                var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
                var label = SWConsoleStyle.Text($"{dayLabel} {SWPlannerSlots.Range(item.StartSlot, item.Duration)}   {item.Label}",
                    SWConsoleStyle.TextBright, SWConsoleStyle.Small);
                label.HorizontalExpand = true;
                label.VerticalAlignment = Control.VAlignment.Center;
                line.AddChild(label);

                var blockId = item.BlockId;
                var remove = SWConsoleStyle.Action("Убрать", SWConsoleStyle.Bad);
                remove.OnPressed += _ => _owner.RemoveBlock(blockId);
                line.AddChild(remove);

                row.AddChild(line);
                BlockList.AddChild(row);
            }
        }

        if (!any)
            BlockList.AddChild(SWConsoleStyle.Text("Блоков нет", SWConsoleStyle.TextDim, SWConsoleStyle.Body));
    }
