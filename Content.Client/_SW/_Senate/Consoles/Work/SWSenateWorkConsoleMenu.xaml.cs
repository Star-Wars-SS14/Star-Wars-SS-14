            _selectedStartHour = args.Id;
        };
        DurationOption.OnItemSelected += args =>
        {
            DurationOption.SelectId(args.Id);
            _selectedDuration = args.Id;
        };
        ScheduleButton.OnPressed += _ =>
        {
            if (_selectedBillId >= 0 && _selectedStartHour >= 0)
                _owner.ScheduleSession(_selectedBillId, _selectedStartHour, _selectedDuration);
        };
    }

    public void SetState(SWSenateWorkConsoleState state)
    {
        HeaderClock.Text = string.IsNullOrEmpty(state.GameTime) ? "—" : state.GameTime;

        if (!state.HasCard)
            PositionLabel.SetMessage("Вставьте ID-карту в консоль.");
        else if (!state.IsSenateCard)
            PositionLabel.SetMessage("Это не сенатская карта.");
        else
            PositionLabel.SetMessage(state.PositionLabel);

        var statusColor = state.InOffice ? SWConsoleStyle.Good : SWConsoleStyle.TextDim;
        StatusLabel.SetMarkup($"[color={statusColor.ToHex()}]{(state.InOffice ? "Статус: в должности" : "Статус: не в должности")}[/color]");

        TakeButton.Visible = state.CanTake;
        ResignButton.Visible = state.CanResign;

        BuildWarApproval(state);

        var isSenator = state.IsSenateCard && state.Position == SWSenatePosition.Senator;
        var isLeader = state.IsSenateCard
            && (state.Position == SWSenatePosition.Speaker || state.Position == SWSenatePosition.Chancellor);
        NavDraft.Visible = isSenator && state.InOffice;
        NavAgenda.Visible = state.IsSenateCard && state.InOffice;
        NavSchedule.Visible = state.IsSenateCard && state.InOffice;
        NavDilemmas.Visible = state.CanDilemmas && state.InOffice;
        NavCrises.Visible = state.IsSenateCard;
        NavParties.Visible = state.IsSenateCard;
        NavAmbitions.Visible = state.CanAmbitions && state.InOffice;
        NavBudget.Visible = state.IsChancellorView;
        NavSignature.Visible = state.CanSignLaws;
        NavPowers.Visible = state.ShowPowers;
        NavAnnounce.Visible = isLeader && state.InOffice;

        foreach (var (header, buttons) in _navGroups)
            header.Visible = buttons.Any(b => b.Visible);

        foreach (var (nav, panel) in _sections)
        {
            if (panel.Visible && !nav.Visible)
            {
                ShowSection(OfficeTab);
                break;
            }
        }

        if (!_draftBuilt && state.Globals.Count > 0)
            BuildDraft(state);

        BuildRoster(state);
        BuildDashboard(state);
        BuildAgenda(state);
        BuildSchedule(state);
        BuildPresets(state);
        DilemmaModePrograms.Visible = state.CanPrograms;
        BuildDilemmas(state);
        BuildBudget(state);
        BuildPrograms(state);
        BuildAmbitions(state);
        BuildCrises(state);
        BuildParties(state);
        BuildBudgetSection(state);
        BuildSignature(state);
        BuildPowers(state);
    }

