using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface.Controls;
using Content.Client.Stylesheets;
using Robust.Shared.Prototypes;
using Content.Shared.Roles;

namespace Content.Client.UserInterface.Systems.Character.Windows;

[GenerateTypedNameReferences]
public sealed partial class CharacterWindow : DefaultWindow
{
    public Label JobDescriptionLabel { get; }
    private IPrototypeManager? _prototypeManager;

    public CharacterWindow()
    {
        RobustXamlLoader.Load(this);

        JobDescriptionLabel = new Label
        {
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Top,
            StyleClasses = { StyleNano.StyleClassLabelSubText },
            Visible = false
        };

        Contents.AddChild(JobDescriptionLabel);
    }

    public void SetPrototypeManager(IPrototypeManager prototypeManager)
    {
        _prototypeManager = prototypeManager;
    }

    public void UpdateJobDescription(string job)
    {
        if (_prototypeManager == null)
            return;

        if (_prototypeManager.TryIndex<JobPrototype>(job, out var jobPrototype))
        {
            var jobDescriptionKey = $"job-description-{jobPrototype.ID}";
            JobDescriptionLabel.Text = Loc.GetString(jobDescriptionKey);
            JobDescriptionLabel.Visible = !string.IsNullOrEmpty(JobDescriptionLabel.Text);
        }
        else
        {
            JobDescriptionLabel.Text = Loc.GetString("job-description-unknown");
            JobDescriptionLabel.Visible = true;
        }
    }
}