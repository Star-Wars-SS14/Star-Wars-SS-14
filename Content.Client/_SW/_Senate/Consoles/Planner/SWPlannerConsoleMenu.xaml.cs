    private void RebuildInviteeList(SWPlannerConsoleState state)
    {
        InviteeList.RemoveAllChildren();
        _inviteeButtons.Clear();
        _invitees.RemoveWhere(name => state.Roster.All(r => r.Name != name));

        foreach (var person in state.Roster)
        {
            if (person.Name == state.Me)
                continue;

            var name = person.Name;
            var btn = new Button
            {
                Text = $"{person.Name} - {person.Role}",
                ToggleMode = true,
                Pressed = _invitees.Contains(name),
                HorizontalExpand = true,
                Margin = new Thickness(0, 0, 0, 2),
            };
            btn.Label.FontOverride = SWConsoleStyle.Small;
            btn.OnToggled += args =>
            {
                if (args.Pressed)
                    _invitees.Add(name);
                else
                    _invitees.Remove(name);
                _confirmArmed = false;
                RefreshMeetHints();
            };
            InviteeList.AddChild(btn);
            _inviteeButtons[name] = btn;
        }
    }

    private void RefreshMeetTab()
    {
        StyleDayToggles();
        RefreshMeetHints();
    }

    private ulong MyBusy(SWPlannerConsoleState state, int day) =>
        day == state.Today ? state.MyBusyToday : state.MyBusyTomorrow;

    private ulong PersonBusy(SWPlannerConsoleState state, string name, int day)
    {
        var person = state.Roster.FirstOrDefault(r => r.Name == name);
        if (person == null)
            return 0;
        return day == state.Today ? person.BusyToday : person.BusyTomorrow;
    }

    private void RefreshMeetHints()
    {
        if (_state == null)
            return;

        var day = _state.Today + _meetDay;
        var combined = MyBusy(_state, day);
        foreach (var name in _invitees)
            combined |= PersonBusy(_state, name, day);

        var conflicts = new List<string>();
        if (SWPlannerSlots.Overlaps(MyBusy(_state, day), _meetSlot, _meetDuration))
            conflicts.Add("вы");
        foreach (var name in _invitees)
        {
            if (SWPlannerSlots.Overlaps(PersonBusy(_state, name, day), _meetSlot, _meetDuration))
                conflicts.Add(name);
        }

        if (conflicts.Count > 0)
        {
            SetMarkup(MeetHintLabel, $"[color=#E0556B]Слот {SWPlannerSlots.Range(_meetSlot, _meetDuration)} пересекается с расписанием: {string.Join(", ", conflicts)}.[/color]");
        }
        else
        {
            SetMarkup(MeetHintLabel, $"[color=#43D16A]Слот {SWPlannerSlots.Range(_meetSlot, _meetDuration)} свободен у всех участников.[/color]");
            _confirmArmed = false;
        }

        CreateMeetingButton.Text = _confirmArmed ? "Слоты пересекаются - всё равно создать?" : "Создать встречу";
        StyleButton(CreateMeetingButton, _confirmArmed ? SWConsoleStyle.Warn : SWConsoleStyle.Accent);

        var free = new List<string>();
        for (var slot = 0; slot <= SWPlannerSlots.PerDay - _meetDuration && free.Count < 8; slot++)
        {
            if (!SWPlannerSlots.Overlaps(combined, slot, _meetDuration))
                free.Add(SWPlannerSlots.Time(slot));
        }

        SetMarkup(CommonSlotsLabel, free.Count > 0
            ? $"[color=#8899AA]Все свободны в: {string.Join(", ", free)}[/color]"
            : "[color=#E0556B]Общих свободных окон такой длины нет.[/color]");
    }

    private static void SetMarkup(RichTextLabel label, string markup) =>
        label.SetMessage(FormattedMessage.FromMarkupPermissive(markup));

    private void OnCreatePressed()
    {
        if (_state == null || string.IsNullOrWhiteSpace(MeetTitleEdit.Text))
            return;

        var day = _state.Today + _meetDay;
        var combinedConflict = SWPlannerSlots.Overlaps(MyBusy(_state, day), _meetSlot, _meetDuration)
            || _invitees.Any(name => SWPlannerSlots.Overlaps(PersonBusy(_state, name, day), _meetSlot, _meetDuration));

        if (combinedConflict && !_confirmArmed)
        {
            _confirmArmed = true;
            RefreshMeetHints();
            return;
        }

        _confirmArmed = false;
        _owner.CreateMeeting(day, _meetSlot, _meetDuration, MeetTitleEdit.Text, MeetDescEdit.Text,
            MeetLocationEdit.Text, _meetPrivate, _invitees.ToList());

        MeetTitleEdit.Text = string.Empty;
        MeetDescEdit.Text = string.Empty;
        _invitees.Clear();
        foreach (var (_, btn) in _inviteeButtons)
            btn.Pressed = false;
        RefreshMeetHints();
    }

