using System.Numerics;
using Content.Client._SW.UserInterface;
using Content.Shared._SW.GlobalWar;
using Content.Shared._SW.GlobalWar.Combat;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Timing;

namespace Content.Client._SW.GlobalWar.UI;

/// <summary>Territory control: two sides, one timer, a bar of thirty cells. Read from across the room.</summary>
[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarCaptureMenu : SWGlobalWarWindow
{
    private static readonly Color Off = Color.FromHex("#8A91A0");

    private const float LastSeconds = 10;

    private bool _blink;
    private float _blinkTime;

    public event Action<bool>? Requested;

    public SWGlobalWarCaptureMenu()
    {
        RobustXamlLoader.Load(this);
        ContentsContainer.Margin = new Thickness(0);
        CornerBrackets = false;
        Start.MainFont = SWGlobalWarConsoleStyle.MainButton;
        Start.SetAppearance(SWGlobalWarConsoleStyle.TextBright, primary: true);
        Cancel.MainFont = SWGlobalWarConsoleStyle.MainButton;
        Place.FontOverride = LeftWord.FontOverride = RightWord.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        Place.FontColorOverride = LeftWord.FontColorOverride = RightWord.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        LeftName.FontOverride = RightName.FontOverride = SWGlobalWarConsoleStyle.Strong;
        StatusWord.FontOverride = SWGlobalWarConsoleStyle.Bold(22);
        Timer.FontOverride = SWGlobalWarConsoleStyle.Bold(64);
        Timing.FontOverride = SWGlobalWarConsoleStyle.Small;
        Timing.FontColorOverride = SWGlobalWarConsoleStyle.TextBright;
        ResetWord.FontOverride = SWGlobalWarConsoleStyle.SmallStrong;
        ResetWord.FontColorOverride = SWGlobalWarConsoleStyle.EmpireText;
        ResetWord.Text = Loc.GetString("sw-global-war-capture-before-reset");
        // Words that lie over the stars get a dark plate.
        PlacePlate.PanelOverride = TimingPlate.PanelOverride = SWTerminalStyle.Fill(Color.FromHex("#07090E").WithAlpha(.82f));
        HubMark.Texture = IoCManager.Resolve<IEntityManager>().System<Robust.Client.GameObjects.SpriteSystem>().Frame0(
            new Robust.Shared.Utility.SpriteSpecifier.Rsi(new Robust.Shared.Utility.ResPath("_SW/Structures/Machines/MegaMode/orbital_hub.rsi"), "base"));
        HubMark.TextureScale = new Vector2(3);
        HelpMark.ToolTip = Loc.GetString("sw-global-war-capture-instructions");
        Start.OnPressed += _ => Requested?.Invoke(false);
        Cancel.OnPressed += _ => Requested?.Invoke(true);
    }

    public void UpdateState(SWGlobalWarCaptureView state)
    {
        var idle = state.Status is SWGlobalWarCaptureStatus.Idle or SWGlobalWarCaptureStatus.Unavailable;
        // When it is over there is only one side left to name: the new owner.
        var finished = state.Status == SWGlobalWarCaptureStatus.Completed;
        var left = finished ? state.Owner : idle ? SWGlobalWarConsoleStyle.LocalSide() : state.Attacker;
        SetSide(LeftIcon, LeftName, BarLeftIcon, left);
        LeftWord.Text = Loc.GetString(finished ? "sw-global-war-capture-word-owner" : idle ? "sw-global-war-capture-word-you" : "sw-global-war-capture-word-attacker");
        SetSide(RightIcon, RightName, BarRightIcon, state.Owner);
        RightColumn.Visible = !finished;
        BarRightIcon.Modulate = finished ? Color.Transparent : Color.White;
        RightWord.Text = Loc.GetString("sw-global-war-capture-word-owner");
        Scene.Texture = SWGlobalWarConsoleStyle.Art("capture_scene", SceneState(state, left));

        // A ship has no sprite of its own yet, so its place is told in words only.
        HubMark.Visible = !state.Ship;
        Place.Text = Loc.GetString(state.Ship ? "sw-global-war-capture-ship" : state.Location == SWGlobalWarPlanetLocation.Orbit
            ? "sw-global-war-capture-orbit" : "sw-global-war-capture-surface").ToUpperInvariant();

        var (word, wordColor, timerColor) = state.Status switch
        {
            SWGlobalWarCaptureStatus.Capturing => ("capturing", SWGlobalWarConsoleStyle.SideText(state.Attacker), Color.White),
            SWGlobalWarCaptureStatus.Contested => ("contested", SWGlobalWarConsoleStyle.Amber, SWGlobalWarConsoleStyle.Amber),
            SWGlobalWarCaptureStatus.Abandoned => ("abandoned", SWGlobalWarConsoleStyle.EmpireText, SWGlobalWarConsoleStyle.EmpireText),
            SWGlobalWarCaptureStatus.Unpowered => ("unpowered", Off, Off),
            SWGlobalWarCaptureStatus.Unavailable => ("unavailable", Off, Off),
            SWGlobalWarCaptureStatus.Completed => ("completed", SWGlobalWarConsoleStyle.Good, SWGlobalWarConsoleStyle.Good),
            _ => ("idle", Off, state.CanStart ? SWGlobalWarConsoleStyle.TextBright : Off),
        };
        StatusWord.Text = Loc.GetString($"sw-global-war-capture-word-{word}");
        StatusWord.FontColorOverride = wordColor;

        var abandoned = state.Status == SWGlobalWarCaptureStatus.Abandoned;
        var seconds = abandoned ? state.AbandonmentRemaining
            : idle ? state.Duration
            : Math.Max(0, state.Duration - state.Progress);
        var whole = (int) MathF.Ceiling(seconds);
        Timer.Text = $"{whole / 60:00}:{whole % 60:00}";
        Timer.FontColorOverride = timerColor;
        _blink = abandoned || state.Status == SWGlobalWarCaptureStatus.Capturing && seconds <= LastSeconds;
        ResetWord.Visible = abandoned;
        Timing.Text = idle
            ? Loc.GetString("sw-global-war-capture-need", ("total", (int) state.Duration))
            : Loc.GetString("sw-global-war-capture-timing", ("done", (int) state.Progress), ("total", (int) state.Duration));

        Bar.Progress = state.Progress;
        Bar.Duration = Math.Max(1, state.Duration);
        Bar.Attacker = finished ? state.Owner : state.Attacker;
        Bar.Owner = state.Owner;
        Bar.Running = state.Status == SWGlobalWarCaptureStatus.Capturing;
        Bar.Contested = state.Status == SWGlobalWarCaptureStatus.Contested;
        Bar.Off = state.Status == SWGlobalWarCaptureStatus.Unpowered;
        Bar.Finished = finished;

        // One short line beside the buttons. The full text of a refusal waits under the question mark.
        var line = state.Status switch
        {
            SWGlobalWarCaptureStatus.Capturing => Loc.GetString("sw-global-war-capture-line-capturing"),
            SWGlobalWarCaptureStatus.Contested => Loc.GetString("sw-global-war-capture-line-contested"),
            SWGlobalWarCaptureStatus.Abandoned => Loc.GetString("sw-global-war-capture-line-abandoned"),
            SWGlobalWarCaptureStatus.Unpowered => Loc.GetString("sw-global-war-capture-line-unpowered"),
            SWGlobalWarCaptureStatus.Completed => Loc.GetString("sw-global-war-capture-line-completed",
                ("place", state.Ship ? "ship" : state.Location == SWGlobalWarPlanetLocation.Orbit ? "station" : "surface"),
                ("owner", state.Owner.ToString().ToLowerInvariant())),
            _ => state.CanStart ? string.Empty : Loc.TryGetString(state.Reason + "-short", out var brief) ? brief : Loc.GetString(state.Reason),
        };
        Reason.Text = line;
        Reason.FontOverride = SWGlobalWarConsoleStyle.Body;
        Reason.FontColorOverride = state.Status switch
        {
            SWGlobalWarCaptureStatus.Contested => SWGlobalWarConsoleStyle.Amber,
            SWGlobalWarCaptureStatus.Abandoned => SWGlobalWarConsoleStyle.EmpireText,
            SWGlobalWarCaptureStatus.Completed => SWGlobalWarConsoleStyle.Good,
            _ => SWGlobalWarConsoleStyle.TextBright,
        };
        HelpMark.ToolTip = Loc.GetString("sw-global-war-capture-instructions") + "\n" + Loc.GetString(state.Reason);
        Start.Disabled = !state.CanStart;
        Cancel.Disabled = !state.CanCancel;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        _blinkTime = (_blinkTime + args.DeltaSeconds) % 1;
        var off = _blink && _blinkTime >= .5f && !IoCManager.Resolve<IConfigurationManager>().GetCVar(CCVars.ReducedMotion);
        Timer.Modulate = Color.White.WithAlpha(off ? .35f : 1);
    }

    private static string SceneState(SWGlobalWarCaptureView state, SWGlobalWarFaction left)
    {
        if (state.Status is SWGlobalWarCaptureStatus.Unpowered or SWGlobalWarCaptureStatus.Unavailable)
            return "off";

        // The sky keeps both sides after the capture, with the new owner on the left.
        if (state.Status == SWGlobalWarCaptureStatus.Completed)
            return left == SWGlobalWarFaction.Empire ? "er" : "re";

        return (left, state.Owner) switch
        {
            (SWGlobalWarFaction.Republic, SWGlobalWarFaction.Empire) => "re",
            (SWGlobalWarFaction.Empire, SWGlobalWarFaction.Republic) => "er",
            (SWGlobalWarFaction.Republic, _) => "rn",
            _ => "off",
        };
    }

    private void SetSide(TextureRect icon, Label name, TextureRect barIcon, SWGlobalWarFaction side)
    {
        var texture = SWGlobalWarConsoleStyle.SideIcon(side);
        icon.Texture = barIcon.Texture = texture;
        icon.TextureScale = new Vector2(6);
        barIcon.TextureScale = new Vector2(4);
        name.Text = FactionName(side);
        name.FontColorOverride = SWGlobalWarConsoleStyle.SideText(side);
    }

    private static string FactionName(SWGlobalWarFaction faction)
    {
        return Loc.GetString(faction switch
        {
            SWGlobalWarFaction.Republic => "sw-global-war-capture-republic",
            SWGlobalWarFaction.Empire => "sw-global-war-capture-empire",
            _ => "sw-global-war-capture-neutral",
        });
    }
}
