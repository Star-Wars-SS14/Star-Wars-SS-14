using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._SW._Senate.Press;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._SW._Senate.Press;

[GenerateTypedNameReferences]
public sealed partial class SWPressHistoryWindow : FancyWindow
{
    private static readonly string[] Editions = { "Республиканский вестник", "Голос миров", "Корусантская трибуна", "Галактический обозреватель" };

    public SWPressHistoryWindow() => RobustXamlLoader.Load(this);

    public void SetState(SWPressEuiState state)
    {
        Versions.RemoveAllChildren();
        if (state.HistoryId == 0)
        {
            Heading.Text = "История недоступна или публикация отозвана.";
            return;
        }
        var edition = state.HistoryEdition >= 0 && state.HistoryEdition < Editions.Length ? Editions[state.HistoryEdition] : "Голонет";
        Heading.Text = edition + " · " + state.HistoryAuthor;
        foreach (var version in state.History)
        {
            var label = new RichTextLabel { HorizontalExpand = true };
            var quotes = string.Join("\n", version.Quotes.Select(q => $"Цитата: {q.DisplayName} ({q.Time})\n«{q.Text}»"));
            label.SetMessage($"Версия {version.Number} · {version.Time}\n{version.Title}\n{version.Body}\n{quotes}\n");
            Versions.AddChild(label);
        }
    }
}
