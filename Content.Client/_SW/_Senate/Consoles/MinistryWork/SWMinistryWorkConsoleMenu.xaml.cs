    private void BuildRepublic(SWMinistryWorkConsoleState state)
    {
        RepublicContent.RemoveAllChildren();
        RepublicContent.AddChild(SWConsoleStyle.Section("РЕСПУБЛИКА — ФАКТ / ПОЛИТИКА"));
