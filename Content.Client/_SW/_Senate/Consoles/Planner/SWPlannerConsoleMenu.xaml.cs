    private void RefreshRoster(SWPlannerConsoleState state)
    {
        var signature = string.Join("|", state.Roster.Select(r => r.Name + ":" + r.Role));
        if (signature == _rosterSignature)
            return;

        _rosterSignature = signature;
        PersonOption.Clear();
        for (var i = 0; i < state.Roster.Count; i++)
        {
            var person = state.Roster[i];
            PersonOption.AddItem($"{person.Name} - {person.Role}", i);
            if (person.Name == _selectedPerson)
                PersonOption.SelectId(i);
        }

        RebuildInviteeList(state);
    }

    private void BuildPeople(SWPlannerConsoleState state)
    {
        PeopleList.RemoveAllChildren();

        if (state.ViewPerson.Length == 0)
        {
            PeopleList.AddChild(SWConsoleStyle.Text("Сотрудник не выбран", SWConsoleStyle.TextDim, SWConsoleStyle.Body));
            return;
        }

        var busyNow = state.ViewDay == state.Today && state.NowSlot >= 0
            ? state.ViewItems.FirstOrDefault(i => i.Kind != 0 && state.NowSlot >= i.StartSlot && state.NowSlot < i.StartSlot + i.Duration)
            : null;

        PeopleList.AddChild(SWConsoleStyle.Text(
            $"{state.ViewPerson} - {(state.ViewDay == state.Today ? "сегодня" : "завтра")}"
            + (busyNow != null ? $", сейчас занят до {SWPlannerSlots.Time(busyNow.StartSlot + busyNow.Duration)}" : string.Empty),
            SWConsoleStyle.TextBright, SWConsoleStyle.Strong));
        PeopleList.AddChild(new Control { MinHeight = 4 });

        BuildTimeline(PeopleList, state.ViewItems, state.ViewDay == state.Today ? state.NowSlot : -1);
    }

