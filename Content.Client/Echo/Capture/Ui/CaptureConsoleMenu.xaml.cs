using Content.Client.UserInterface.Controls;
using Content.Shared.Echo.CaptureConsole;
using Content.Shared.Echo.GameTicking.Components;
using Content.Shared.Xenoarchaeology.Equipment;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.Echo.Capture.Ui;

[GenerateTypedNameReferences]
public sealed partial class CaptureConsoleMenu : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    public event Action? OnCaptureButtonPressed;

    // For rendering the progress bar, updated from BUI state
    private TimeSpan? _startTime;
    private TimeSpan? _totalTime;
    private TimeSpan? _accumulatedRunTime;

    public CaptureConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CaptureButton.OnPressed += _ => OnCaptureButtonPressed?.Invoke();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_startTime is not { } start || _totalTime is not { } total || _accumulatedRunTime is not { } accumulated)
            return;

        var remaining = total - accumulated;

        remaining += start - _timing.CurTime;

        var secsText = Math.Max((int)remaining.TotalSeconds, 0);

        ProgressLabel.Text = Loc.GetString("analysis-console-progress-text",
            ("seconds", secsText));

        ProgressBar.Value = Math.Clamp(1.0f - (float)remaining.Divide(total), 0.0f, 1.0f);
    }

    public void UpdateInformationDisplay(CaptureConsoleUpdateState state)
    {
        var message = new FormattedMessage();

        message.TryAddMarkup($"[color=green]{Loc.GetString("capture-console-message-station-active")}[/color]",
            out _);
        message.PushNewline();
        message.PushNewline();
        message.TryAddMarkup(
            $"[color=yellow]{Loc.GetString("capture-console-message-station-fraction",
                ("stationFraction", state.StationFraction == SectorFractions.Alliance ?
                    Loc.GetString("capture-console-message-fraction-alliance") :
                    Loc.GetString("capture-console-message-fraction-resistance")))}[/color]",
            out _);
        message.PushNewline();
        message.PushNewline();
        message.TryAddMarkup(
            $"[color=purple]{Loc.GetString("capture-console-capturing-status",
                ("state", state.Capturing ? Loc.GetString("capture-console-capturing-status-true") :
                    Loc.GetString("capture-console-capturing-status-false")))}[/color]",
            out _);
        message.PushNewline();
        message.PushNewline();
        message.TryAddMarkup(
            $"[color=blue]{Loc.GetString("capture-console-eta", ("time",
                state.TotalTime.ToString()))}[/color]",
            out _);
        message.PushNewline();
        Information.SetMessage(message);

        var leftInfoMessage = new FormattedMessage();

        leftInfoMessage.TryAddMarkup(
            $"[color=yellow]{Loc.GetString("capture-console-message-user-fraction", ("fraction",
                state.UserFraction switch
                {
                    SectorFractions.Alliance => Loc.GetString("capture-console-message-fraction-alliance"),
                    SectorFractions.Resistance => Loc.GetString("capture-console-message-fraction-resistance"),
                    _ => Loc.GetString("capture-console-message-user-no-fraction"),
                }))}[/color]",
            out _);
        leftInfoMessage.PushNewline();
        leftInfoMessage.PushNewline();
        leftInfoMessage.TryAddMarkup(
            $"[color=green]{Loc.GetString("capture-console-message-current-station",
                ("name", state.StationName))}[/color]",
            out _);
        leftInfoMessage.PushNewline();
        LeftInfoLabel.SetMessage(leftInfoMessage);
        CaptureButton.Text = state.Capturing
            ? Loc.GetString("capture-console-cancel-button")
            : Loc.GetString("capture-console-capture-button");
    }

    public void UpdateProgressBar(CaptureConsoleUpdateState state)
    {
        ProgressBar.Visible = state.Capturing;
        ProgressLabel.Visible = state.Capturing;

        _startTime = state.StartTime;
        _totalTime = state.TotalTime;
        _accumulatedRunTime = state.AccumulatedRunTime;
    }
}
