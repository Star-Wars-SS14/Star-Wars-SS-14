using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.AutoGenerated;
using Content.Client._SW.TurretConsole.UI.TurretControl;
using Robust.Shared.Prototypes;
using Content.Shared.Roles;

namespace Content.Client._SW.TurretConsole.UI;

[GenerateTypedNameReferences]
public sealed partial class SWTurretConsoleMenu : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    public event Action<string>? OnJobButtonPressed;

    public event Action<string>? OnFactionAllowBtnPressed;
    public event Action<string>? OnFactionDisallowBtnPressed;
    public event Action? OnTargetHumanoidsWithoutIdToggled;
    public event Action? OnTargetAnimalsToggled;

    public SWTurretConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TargetHumanoidsWithoutIdCheckBox.OnToggled += _ => OnTargetHumanoidsWithoutIdToggled?.Invoke();
        TargetAnimalsCheckBox.OnToggled += _ => OnTargetAnimalsToggled?.Invoke();
    }

    public void UpdateJobs(Dictionary<string, bool> jobs)
    {
        AllowedJobsList.Children.Clear();
        DisallowedJobsList.Children.Clear();
        foreach (var (job, isAllowed) in jobs)
        {
            var proto = _prototype.Index<JobPrototype>(job);
            var cntrl = new SWTurretConsoleControl(job, proto.LocalizedName);
            cntrl.SendJob += (s) => OnJobButtonPressed?.Invoke(s);
            if (isAllowed)
            {
                AllowedJobsList.AddChild(cntrl);
            }
            else
            {
                DisallowedJobsList.AddChild(cntrl);
            }
        }
    }

    public void UpdateFactions(Dictionary<string, string> factions)
    {
        AllowFactionsList.Children.Clear();
        DisallowFactionsList.Children.Clear();
        foreach (var (id, name) in factions)
        {
            var btn = new Button();
            btn.Text = Loc.GetString("sw-turret-console-faction-allow", ("faction", name));
            btn.OnPressed += (_) => OnFactionAllowBtnPressed?.Invoke(id);
            AllowFactionsList.AddChild(btn);
        }

        foreach (var (id, name) in factions)
        {
            var btn = new Button();
            btn.Text = Loc.GetString("sw-turret-console-faction-disallow", ("faction", name));
            btn.OnPressed += (_) => OnFactionDisallowBtnPressed?.Invoke(id);
            DisallowFactionsList.AddChild(btn);
        }
    }

    public void UpdateTargetOptions(bool targetHumanoidsWithoutId, bool targetAnimals)
    {
        TargetHumanoidsWithoutIdCheckBox.Pressed = targetHumanoidsWithoutId;
        TargetAnimalsCheckBox.Pressed = targetAnimals;
    }
}
