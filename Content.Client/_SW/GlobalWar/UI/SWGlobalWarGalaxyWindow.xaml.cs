using System.Linq;
using Content.Shared._SW.GlobalWar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._SW.GlobalWar.UI;

/// <summary>
/// The galaxy as it stands, for anyone in the campaign: the same chart as the navigation console, coloured by who holds
/// each station. A world whose surface belongs to another side is hatched. Nothing on it can be pressed into action.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SWGlobalWarGalaxyWindow : SWGlobalWarWindow
{
    private readonly IPrototypeManager _prototypes = IoCManager.Resolve<IPrototypeManager>();
    private List<SWGlobalWarGalaxyWorld> _worlds = new();
    private ProtoId<SWGlobalWarPlanetPrototype>? _selected;

    public SWGlobalWarGalaxyWindow()
    {
        RobustXamlLoader.Load(this);
        UseChartSize();
        Map.Overview = true;
        MapPanel.PanelOverride = SWGlobalWarConsoleStyle.CardBox();
        Card.PanelOverride = SWGlobalWarConsoleStyle.RowBox(false);
        PlanetName.FontOverride = SWGlobalWarConsoleStyle.NameLarge;
        PlanetName.FontColorOverride = Color.White;
        foreach (var label in new[] { Station, Surface, Split })
            label.FontOverride = SWGlobalWarConsoleStyle.Strong;
        foreach (var label in new[] { LegendRepublic, LegendEmpire, LegendSplit, Count })
            label.FontOverride = SWGlobalWarConsoleStyle.Small;
        LegendRepublic.Text = Loc.GetString("sw-global-war-galaxy-legend-republic");
        LegendRepublic.FontColorOverride = SWGlobalWarConsoleStyle.RepublicText;
        LegendEmpire.Text = Loc.GetString("sw-global-war-galaxy-legend-empire");
        LegendEmpire.FontColorOverride = SWGlobalWarConsoleStyle.EmpireText;
        LegendSplit.Text = Loc.GetString("sw-global-war-galaxy-legend-split");
        LegendSplit.FontColorOverride = SWGlobalWarConsoleStyle.TextBright;
        Count.FontColorOverride = SWGlobalWarConsoleStyle.TextDim;
        Hint.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("sw-global-war-galaxy-hint")), defaultColor: SWGlobalWarConsoleStyle.TextDim);
        Map.PlanetSelected += id =>
        {
            _selected = id;
            ShowCard();
        };
    }

    public void UpdateState(List<SWGlobalWarGalaxyWorld> worlds)
    {
        _worlds = worlds;
        Map.SetState(worlds.Select(world => new SWGlobalWarTravelDestination(world.Planet,
            _prototypes.Index(world.Planet).Name, false, string.Empty, Owner: world.Orbit)).ToList());
        Map.SetSplit(worlds.Where(world => world.Orbit != world.Surface).ToDictionary(world => world.Planet, world => world.Surface));
        var republic = worlds.Count(world => world.Orbit == SWGlobalWarFaction.Republic);
        var empire = worlds.Count(world => world.Orbit == SWGlobalWarFaction.Empire);
        Count.Text = Loc.GetString("sw-global-war-galaxy-count", ("republic", republic), ("empire", empire), ("split", worlds.Count(world => world.Orbit != world.Surface)));
        ShowCard();
    }

    private void ShowCard()
    {
        var world = _worlds.FirstOrDefault(w => w.Planet == _selected);
        Card.Visible = world != null;
        if (world == null)
            return;

        PlanetName.Text = _prototypes.Index(world.Planet).Name;
        Station.Text = Loc.GetString("sw-global-war-galaxy-station", ("side", Side(world.Orbit)));
        Station.FontColorOverride = SWGlobalWarConsoleStyle.SideText(world.Orbit);
        Surface.Text = Loc.GetString("sw-global-war-galaxy-surface", ("side", Side(world.Surface)));
        Surface.FontColorOverride = SWGlobalWarConsoleStyle.SideText(world.Surface);
        Split.Visible = world.Orbit != world.Surface;
        Split.Text = Loc.GetString("sw-global-war-galaxy-split");
        Split.FontColorOverride = SWGlobalWarConsoleStyle.Amber;
    }

    private static string Side(SWGlobalWarFaction side) => Loc.GetString(side switch
    {
        SWGlobalWarFaction.Republic => "sw-global-war-capture-republic",
        SWGlobalWarFaction.Empire => "sw-global-war-capture-empire",
        _ => "sw-global-war-capture-neutral",
    });
}
