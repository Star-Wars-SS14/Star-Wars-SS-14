    public override void Close()
    {
        // Closed in the middle of a shake: the next time it opens where it stood.
        if (_shakeLeft > 0)
            LayoutContainer.SetPosition(this, _shakeHome);

        _shakeLeft = 0;
        base.Close();
        DeletePreview();
    }

    private void SelectTab(Control tab)
    {
        foreach (var (panel, button) in new (Control, Button)[]
                 {
                     (TrackTab, TabTrack),
                     (QuestsTab, TabQuests),
                     (CasesTab, TabCases),
                     (ItemsTab, TabItems),
                 })
        {
            panel.Visible = panel == tab;
            button.SetOnlyStyleClass(panel == tab ? SWTerminalStyle.TabActive : SWTerminalStyle.Tab);
        }

        SetBannerFolded(tab != TrackTab);

        // Coming back to the tab means looking at the case again, unless the reel is still running.
        if (tab == CasesTab && !Reel.Spinning && _revealAt == null)
            SetCaseView(SWCaseView.Closed);
    }

